// A world's generation settings (docs/WORLD_GENERATION.md §9): the create-world screen's sliders and
// presets (data: shared/worldgen/settings.json, generated into worldgenSettings.gen.ts), and their
// encoding — the sliders off their defaults, in file order, as `id:value` joined by `,`, each value
// snapped to its step and written with the step's decimals, trailing zeros dropped. The Rust side
// (`dwell_worldgen::settings`) encodes the same way; the empty string is the default.
import { PRESETS, SLIDERS, type SettingsPreset, type SettingsSlider } from './worldgenSettings.gen';

export { CATEGORIES, PRESETS, SLIDERS } from './worldgenSettings.gen';
export type { SettingsCategory, SettingsPreset, SettingsSlider } from './worldgenSettings.gen';

/** Slider id → value. */
export type WorldgenValues = Record<string, number>;

/** The longest encoding a world may carry (bytes; the protocol's `worldgenSettingsMaxBytes`). */
export const MAX_ENCODED_BYTES = 512;

/** `v` as the encoding writes it: clamped, snapped to the step, trailing zeros off. */
export function formatValue(s: SettingsSlider, v: number): string {
  const x = Number.isFinite(v) ? v : s.default;
  const k = Math.round((Math.min(s.max, Math.max(s.min, x)) - s.min) / s.step);
  const t = (s.min + k * s.step).toFixed(s.decimals);
  return t.includes('.') ? t.replace(/0+$/, '').replace(/\.$/, '') : t;
}

/** `v` snapped as the encoding stores it. */
export function snap(s: SettingsSlider, v: number): number {
  return Number(formatValue(s, v));
}

export function sliderById(id: string): SettingsSlider | undefined {
  return SLIDERS.find((s) => s.id === id);
}

/** Every slider at its default. */
export function defaultValues(): WorldgenValues {
  return Object.fromEntries(SLIDERS.map((s) => [s.id, s.default]));
}

/** A preset's values (every slider), or null for an unknown id. */
export function presetValues(id: string): WorldgenValues | null {
  const p = PRESETS.find((q) => q.id === id);
  if (!p) return null;
  const v = defaultValues();
  for (const [k, x] of Object.entries(p.values)) {
    const s = sliderById(k);
    if (s) v[k] = snap(s, x);
  }
  return v;
}

/** The canonical encoding of values (unknown ids ignored; missing ones at their defaults). */
export function encodeWorldgen(values: WorldgenValues): string {
  const parts: string[] = [];
  for (const s of SLIDERS) {
    const v = values[s.id];
    if (v === undefined) continue;
    const t = formatValue(s, v);
    if (Number(t) !== s.default) parts.push(`${s.id}:${t}`);
  }
  return parts.join(',');
}

/**
 * Values from an encoding, every slider present (defaults for those not named), or null when it
 * names an unknown slider, repeats one or holds something that is not a number: such settings were
 * made by another version and can't be generated by this one.
 */
export function decodeWorldgen(text: string): WorldgenValues | null {
  if (text.length > MAX_ENCODED_BYTES) return null;
  const v = defaultValues();
  const seen = new Set<string>();
  for (const raw of text.split(',')) {
    const part = raw.trim();
    if (part === '') continue;
    const at = part.indexOf(':');
    if (at < 0) return null;
    const id = part.slice(0, at).trim();
    const n = Number(part.slice(at + 1).trim());
    const s = sliderById(id);
    if (!s || seen.has(id) || part.slice(at + 1).trim() === '' || !Number.isFinite(n)) return null;
    seen.add(id);
    v[id] = snap(s, n);
  }
  return v;
}

/** The encoding of an encoding: canonical, or null when it can't be read (above). */
export function canonicalWorldgen(text: string): string | null {
  const v = decodeWorldgen(text);
  return v ? encodeWorldgen(v) : null;
}

/** The preset whose values these are exactly, if any. */
export function presetOf(values: WorldgenValues): SettingsPreset | null {
  const e = encodeWorldgen(values);
  return PRESETS.find((p) => encodeWorldgen(presetValues(p.id) ?? {}) === e) ?? null;
}

/** A slider's readout ("×1.2", "1550 m", "On"). */
export function readout(s: SettingsSlider, v: number): string {
  if (s.toggle) return s.labels[v ? 1 : 0] ?? String(v);
  return s.format.replace('{v}', formatValue(s, v));
}

/** Whether values change the world map (the map preview, the maps' cache). */
export function changesMap(values: WorldgenValues): boolean {
  return SLIDERS.some(
    (s) => s.map && values[s.id] !== undefined && snap(s, values[s.id] ?? s.default) !== s.default,
  );
}

/** A short summary of an encoding for a world's details line: its preset's name, or "Custom". */
export function worldgenLabel(text: string | undefined): string {
  const v = decodeWorldgen(text ?? '');
  if (!v) return 'Custom';
  return presetOf(v)?.label ?? 'Custom';
}
