#!/usr/bin/env node
// Generates the explosives table (docs/EXPLOSIVES.md) for Rust (crates/dwell-world/src/explosives.gen.rs)
// from shared/explosives/explosives.json, after validating it against the block registry: an unknown,
// missing or out-of-range entry fails with its path named. The output is checked in; CI regenerates it
// and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/explosives/gen.mjs from shared/explosives/explosives.json. Do not edit.';

/** An explosive's numbers: field → [min, max]. */
export const EXPLOSIVE_RANGES = {
  fuseSeconds: [0, 60],
  radiusM: [0.5, 16],
  destroyRadiusM: [0, 16],
  loosenRadiusM: [0.5, 16],
  impulse: [0, 1e6],
  falloff: [0, 8],
  flingFalloff: [0, 8],
  lift: [0, 4],
  maxSpeedMs: [0, 100],
  reachM: [0, 32],
  knockbackMs: [0, 100],
  damage: [0, 1000],
  waterRadiusM: [0, 16],
  waveReachM: [0, 32],
  waveImpulse: [0, 20],
  waveFreeM: [0, 64],
  noPieceContactS: [0, 10],
  openSenseM: [0, 8],
  openBlend: [0, 1],
  openPathM: [0, 4],
  openSpreadMin: [0, 1],
};

/** Each effect's numbers (and its colour, if it has one): field → [min, max]; pairs are [lo, hi] ranges. */
export const EFFECT_RANGES = {
  flash: { strength: [0, 1000], lightRadiusM: [0, 200], seconds: [0, 10], sizeM: [0, 64] },
  smoke: { count: [0, 256], cpuCount: [0, 256], sizeM: [0, 32, 'pair'], seconds: [0, 60, 'pair'], spreadM: [0, 64], riseMs: [0, 50], opacity: [0, 1] },
  dust: { count: [0, 256], cpuCount: [0, 256], sizeM: [0, 32, 'pair'], seconds: [0, 60, 'pair'], speedMs: [0, 100, 'pair'], opacity: [0, 1] },
  boom: { fullM: [0, 1000], hearM: [0, 10000] },
  shake: { radiusM: [0, 1000], degrees: [0, 30], seconds: [0, 10], hz: [0, 120] },
};
const COLOURED = ['flash', 'smoke', 'dust'];
const COUNTS = ['count', 'cpuCount'];

/** The registry's block names (`dwell:stone`) with whether each is placeable, from shared/blocks/dwell.json. */
export function registryBlocks() {
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  return new Map(ns.blocks.map((b) => [`${ns.namespace}:${b.name}`, { placeable: !!b.placeable, properties: b.properties ?? {} }]));
}

/** Checks the table; returns it. Throws naming the entry. */
export function validateExplosives(data, blocks = registryBlocks()) {
  const bad = (m) => {
    throw new Error(`explosives.json: ${m}`);
  };
  const object = (v, at) => {
    if (typeof v !== 'object' || v === null || Array.isArray(v)) bad(`${at} must be an object`);
  };
  const keys = (v, at, allowed) => {
    for (const k of Object.keys(v)) if (k !== '$comment' && !allowed.includes(k)) bad(`unknown entry ${at}.${k}`);
  };
  const number = (v, at, lo, hi, int = false) => {
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi || (int && !Number.isInteger(v))) {
      bad(`${at} must be ${int ? 'a whole number' : 'a number'} in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  };
  const pair = (v, at, lo, hi) => {
    if (!Array.isArray(v) || v.length !== 2) bad(`${at} must be a [low, high] pair`);
    number(v[0], `${at}[0]`, lo, hi);
    number(v[1], `${at}[1]`, lo, hi);
    if (v[1] < v[0]) bad(`${at}: high below low`);
  };
  const block = (v, at) => {
    if (typeof v !== 'string' || !blocks.has(v)) bad(`${at}: ${JSON.stringify(v)} is not a block of the registry`);
    return blocks.get(v);
  };
  object(data, '(root)');
  keys(data, '(root)', ['limits', 'explosives']);
  object(data.limits, 'limits');
  keys(data.limits, 'limits', ['blastsPerTick', 'maxPieces']);
  number(data.limits.blastsPerTick, 'limits.blastsPerTick', 1, 64, true);
  number(data.limits.maxPieces, 'limits.maxPieces', 1, 65536, true);
  if (!Array.isArray(data.explosives) || data.explosives.length === 0) bad('explosives must be a non-empty list');
  const names = new Set();
  const used = new Map();
  data.explosives.forEach((e, i) => {
    const at = `explosives[${i}]`;
    object(e, at);
    keys(e, at, ['name', 'block', 'lit', 'ignitedBy', 'chainDelaySeconds', 'effects', ...Object.keys(EXPLOSIVE_RANGES)]);
    if (typeof e.name !== 'string' || !/^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$/.test(e.name)) bad(`${at}.name must be a namespaced name`);
    if (names.has(e.name)) bad(`${at}.name ${e.name} is listed twice`);
    names.add(e.name);
    const placed = block(e.block, `${at}.block`);
    if (!placed.placeable) bad(`${at}.block ${e.block} must be placeable (it is placed unlit)`);
    const lit = block(e.lit, `${at}.lit`);
    if (lit.placeable) bad(`${at}.lit ${e.lit} must not be placeable (only lighting makes it)`);
    if (e.lit === e.block) bad(`${at}.lit must differ from its block`);
    for (const [k, b] of [['block', e.block], ['lit', e.lit]]) {
      if (Object.keys(blocks.get(b).properties).length) bad(`${at}.${k} ${b}: an explosive's blocks have one state (no properties)`);
      if (used.has(b)) bad(`${at}.${k} ${b} is already ${used.get(b)}'s`);
      used.set(b, e.name);
    }
    if (!Array.isArray(e.ignitedBy)) bad(`${at}.ignitedBy must be a list of block names`);
    e.ignitedBy.forEach((b, k) => block(b, `${at}.ignitedBy[${k}]`));
    for (const [k, [lo, hi]] of Object.entries(EXPLOSIVE_RANGES)) number(e[k], `${at}.${k}`, lo, hi);
    if (e.destroyRadiusM > e.radiusM) bad(`${at}.destroyRadiusM must be at most its radiusM`);
    if (e.loosenRadiusM < e.radiusM) bad(`${at}.loosenRadiusM must be at least its radiusM`);
    pair(e.chainDelaySeconds, `${at}.chainDelaySeconds`, 0, 60);
    object(e.effects, `${at}.effects`);
    keys(e.effects, `${at}.effects`, Object.keys(EFFECT_RANGES));
    for (const [fx, ranges] of Object.entries(EFFECT_RANGES)) {
      const f = e.effects[fx];
      const fat = `${at}.effects.${fx}`;
      object(f, fat);
      keys(f, fat, [...Object.keys(ranges), ...(COLOURED.includes(fx) ? ['color'] : [])]);
      if (COLOURED.includes(fx) && !(typeof f.color === 'string' && /^#[0-9a-f]{6}$/i.test(f.color))) bad(`${fat}.color must be #rrggbb`);
      for (const [k, [lo, hi, kind]] of Object.entries(ranges)) {
        if (kind === 'pair') pair(f[k], `${fat}.${k}`, lo, hi);
        else number(f[k], `${fat}.${k}`, lo, hi, COUNTS.includes(k));
      }
    }
    if (e.effects.smoke.cpuCount > e.effects.smoke.count) bad(`${at}.effects.smoke.cpuCount must be at most its count`);
    if (e.effects.dust.cpuCount > e.effects.dust.count) bad(`${at}.effects.dust.cpuCount must be at most its count`);
    if (e.effects.boom.hearM < e.effects.boom.fullM) bad(`${at}.effects.boom.hearM must be at least fullM`);
  });
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rgb = (hex) => {
  const n = Number.parseInt(hex.slice(1), 16);
  return `[${[(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => rf(Math.round((c / 255) * 1e6) / 1e6)).join(', ')}]`;
};

/** The Rust source for a validated table. */
export function explosivesRust(data) {
  const lines = [`// ${header}`, ''];
  lines.push('/// The explosives table (shared/explosives/explosives.json).');
  lines.push(`pub const LIMITS: ExplosiveLimits = ExplosiveLimits { blasts_per_tick: ${data.limits.blastsPerTick}, max_pieces: ${data.limits.maxPieces} };`);
  lines.push('');
  lines.push('pub const EXPLOSIVES: &[ExplosiveData] = &[');
  for (const e of data.explosives) {
    lines.push('    ExplosiveData {');
    lines.push(`        name: ${JSON.stringify(e.name)},`);
    lines.push(`        block: ${JSON.stringify(e.block)},`);
    lines.push(`        lit: ${JSON.stringify(e.lit)},`);
    lines.push(`        ignited_by: &[${e.ignitedBy.map((b) => JSON.stringify(b)).join(', ')}],`);
    for (const k of Object.keys(EXPLOSIVE_RANGES)) lines.push(`        ${snake(k)}: ${rf(e[k])},`);
    lines.push(`        chain_delay_seconds: [${e.chainDelaySeconds.map(rf).join(', ')}],`);
    lines.push('        effects: BlastEffects {');
    for (const [fx, ranges] of Object.entries(EFFECT_RANGES)) {
      const f = e.effects[fx];
      const type = { flash: 'FlashLook', smoke: 'PuffLook', dust: 'PuffLook', boom: 'BoomLook', shake: 'ShakeLook' }[fx];
      const fields = [];
      if (COLOURED.includes(fx)) fields.push(`color: ${rgb(f.color)}`);
      for (const [k, [, , kind]] of Object.entries(ranges)) {
        const v = f[k];
        fields.push(`${snake(k)}: ${kind === 'pair' ? `[${v.map(rf).join(', ')}]` : COUNTS.includes(k) ? String(v) : rf(v)}`);
      }
      // Smoke rises and spreads; dust is thrown out: each puff kind carries every field.
      if (fx === 'smoke') fields.push('speed_ms: [0.0, 0.0]');
      if (fx === 'dust') fields.push('spread_m: 0.0', 'rise_ms: 0.0');
      lines.push(`            ${fx}: ${type} { ${fields.join(', ')} },`);
    }
    lines.push('        },');
    lines.push('    },');
  }
  lines.push('];', '');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateExplosives(JSON.parse(readFileSync(join(here, 'explosives.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-world/src/explosives.gen.rs'), explosivesRust(data));
  console.log('explosives: table generated');
}
