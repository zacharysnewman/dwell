#!/usr/bin/env node
// Validates the structure files (shared/structures/*.json, and the test fixtures in test/) against
// the block registry and emits their canonical form and hash as Rust tables for dwell-world
// (docs/STRUCTURES.md §3, ARCHITECTURE.md §6.3). The format's rules live in format.mjs, shared with
// the client's structures store. Outputs are checked in; CI regenerates and fails on any diff. Run
// after shared/blocks/gen.mjs: names resolve against its vectors.txt.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { canonicalText, registryFromVector, structureHash, validate } from './format.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/structures/gen.mjs from shared/structures/**/*.json. Do not edit.';

export {
  canonicalState,
  canonicalText,
  FORMAT,
  KINDS,
  MAX_EDGE,
  registryFromBlockDefs,
  registryFromVector,
  structureHash,
  TOP_LEVEL,
  validate,
  VARIANT_OPS,
} from './format.mjs';

// ---- Loading a directory and emitting Rust -------------------------------------------------------

/** Validates every `*.json` in `dir`; `namespace` checks (`"test"` only, or anything but). */
export function loadDir(dir, registry, { test }) {
  const out = [];
  for (const f of readdirSync(dir).filter((n) => n.endsWith('.json')).sort()) {
    const file = relative(root, join(dir, f));
    let json;
    try {
      json = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    } catch (e) {
      throw new Error(`${file}: (file): ${e.message}`);
    }
    const s = validate(json, file, registry);
    const [ns, local] = s.name.split(':');
    if (local !== basename(f, '.json')) throw new Error(`${file}: name: "${s.name}" must match the file name (${local}.json)`);
    if (test !== (ns === 'test')) {
      throw new Error(`${file}: name: ${test ? 'test fixtures use the "test" namespace' : '"test" is reserved for test/'}`);
    }
    if (out.some((o) => o.name === s.name)) throw new Error(`${file}: name: duplicate structure ${s.name}`);
    const text = canonicalText(s);
    out.push({ ...s, text, hash: structureHash(text) });
  }
  return out;
}

const rstr = (v) => JSON.stringify(v);
const rchar = (c) => (c === "'" || c === '\\' ? `'\\${c}'` : `'${c}'`);

/** Rust tables (types in dwell-world `structure.rs`, in scope where the file is included). */
export function rustTables(structures, staticName) {
  const rs = [`// ${header}`, ''];
  rs.push(`pub static ${staticName}: [StructureDef; ${structures.length}] = [`);
  for (const s of structures) {
    const palette = [...s.palette.keys()].sort().map((c) => {
      const st = s.palette.get(c);
      return `(${rchar(c)}, ${st === null ? 'None' : `Some(${rstr(st)})`})`;
    });
    const variants = s.variants.map((v) => {
      if (v.op === 'rotate') return `Variant::Rotate(&[${v.values.join(', ')}])`;
      if (v.op === 'mirror') return `Variant::Mirror(&[${v.values.map((a) => `Axis::${a.toUpperCase()}`).join(', ')}])`;
      const cs = v.choices.map(
        (c) => `Choice { key: ${rchar(c.key)}, options: &[${c.options.map(([n, w]) => `(${rstr(n)}, ${w})`).join(', ')}] }`,
      );
      return `Variant::Choices(&[${cs.join(', ')}])`;
    });
    rs.push('    StructureDef {');
    rs.push(`        name: ${rstr(s.name)},`);
    rs.push(`        hash: 0x${s.hash},`);
    rs.push('        body: Body::Voxels {');
    rs.push(`            size: [${s.size.join(', ')}],`);
    rs.push(`            anchor: [${s.anchor.join(', ')}],`);
    rs.push(`            palette: &[${palette.join(', ')}],`);
    rs.push(`            cells: ${rstr(s.cells)},`);
    rs.push('        },');
    rs.push(`        variants: &[${variants.join(', ')}],`);
    rs.push('    },');
  }
  rs.push('];', '');
  return rs.join('\n');
}

function main() {
  const registry = registryFromVector(readFileSync(join(root, 'shared/blocks/vectors.txt'), 'utf8'));
  const build = loadDir(here, registry, { test: false });
  const fixtures = loadDir(join(here, 'test'), registry, { test: true });
  writeFileSync(join(root, 'crates/dwell-world/src/structures.gen.rs'), rustTables(build, 'STRUCTURES'));
  writeFileSync(join(root, 'crates/dwell-world/tests/fixtures/structures.gen.rs'), rustTables(fixtures, 'TEST_STRUCTURES'));
  const list = (ss) => ss.map((s) => `${s.name} ${s.hash}`).join(', ');
  console.log(`structures: ${list(build)}; fixtures: ${list(fixtures)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    main();
  } catch (e) {
    console.error(`shared/structures: ${e.message}`);
    process.exit(1);
  }
}
