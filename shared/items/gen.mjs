#!/usr/bin/env node
// Generates the creative hotbar's items and the build modes (docs/ITEMS.md) for Rust
// (crates/dwell-game/src/items.gen.rs), and the build modes for the shell (client/src/ui/
// buildModes.gen.ts), from shared/items/items.json, after validating them against the block registry
// (shared/blocks/dwell.json): an unknown or malformed entry fails with its path named. The output is
// checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadNames, loadTools, validateTools } from '../tools/gen.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/items/gen.mjs from shared/items/items.json. Do not edit.';

/** The tallest piece (cells): the protocol's `MAX_PIECE_ROWS`. */
export const MAX_ROWS = 2;
const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
/** The build modes' kinds the engine knows (crates/dwell-game/src/build_drag.rs `DragKind`). */
export const DRAG_KINDS = { line: 'Line', level: 'Level' };
/** What holding Place does with an item (crates/dwell-game/src/items.rs `ItemDrag`). */
export const ITEM_DRAGS = { modes: 'Modes', vertical: 'Vertical', none: 'None' };
/** A `KeyboardEvent.code`. */
const KEY_CODE = /^[A-Z][A-Za-z0-9]*$/;

const fail = (m) => {
  throw new Error(`items.json: ${m}`);
};

/** The registry's blocks by id (`dwell:stone` → its definition). */
export function registryBlocks() {
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  return new Map(ns.blocks.map((b) => [`${ns.namespace}:${b.name}`, b]));
}

/** The registry's states (`dwell:stone_ramp[facing=east,…]` → placeable), from the generated table
 * (crates/dwell-blocks/src/blocks.gen.rs, itself checked by CI). */
export function registryStates() {
  const rs = readFileSync(join(root, 'crates/dwell-blocks/src/blocks.gen.rs'), 'utf8');
  const out = new Map();
  for (const m of rs.matchAll(/StateInfo \{ name: "([^"]+)",.*?placeable: (true|false)/g)) out.set(m[1], m[2] === 'true');
  return out;
}

/** The facings an item's `facing` turns its block to (the property `facing`). */
export const ITEM_FACINGS = { toward: 'Toward', away: 'Away' };
const COMPASS = ['north', 'east', 'south', 'west'];

/** A state's canonical name: `block[k=v,…]` with the properties in name order. */
export const stateName = (block, values) => {
  const keys = Object.keys(values).sort();
  return keys.length ? `${block}[${keys.map((k) => `${k}=${values[k]}`).join(',')}]` : block;
};

/** The tools' item names (shared/tools/tools.json, validated). */
export function toolNames() {
  const { items, blocks } = loadNames();
  return new Set(validateTools(loadTools(), items, blocks).tools.map((t) => t.name));
}

/** Checks the items against `blocks` (id → definition) and `tools` (the tools' item names); returns
 * them. */
export function validateItems(data, blocks, states = registryStates(), tools = toolNames()) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('must be an object');
  const extra = Object.keys(data).filter((k) => !['$comment', 'items', 'hotbar', 'buildModes'].includes(k));
  if (extra.length) fail(`unknown ${extra.join(', ')}`);
  if (!Array.isArray(data.items) || data.items.length === 0) fail('items must be a non-empty list');
  const names = new Set();
  data.items.forEach((it, i) => {
    const at = `items[${i}]`;
    if (typeof it !== 'object' || it === null) fail(`${at} must be an object`);
    const e = Object.keys(it).filter((k) => !['$comment', 'name', 'label', 'block', 'tool', 'rows', 'drag', 'state', 'facing', 'upper'].includes(k));
    if (e.length) fail(`${at}: unknown ${e.join(', ')}`);
    if (typeof it.name !== 'string' || !NAME.test(it.name)) fail(`${at}.name must be namespace:name`);
    if (names.has(it.name)) fail(`${at}.name ${it.name} is listed twice`);
    names.add(it.name);
    if (typeof it.label !== 'string' || it.label === '') fail(`${at}.label must be a name to show`);
    // A tool (ADR 0067; owner, 2026-11-08: the axe on the creative hotbar): held, it places
    // nothing; its item names a tool of shared/tools/tools.json.
    if (it.tool !== undefined) {
      if (it.block !== undefined) fail(`${at}: give block or tool (not both)`);
      const placing = ['rows', 'drag', 'state', 'facing', 'upper'].filter((k) => it[k] !== undefined);
      if (placing.length) fail(`${at}: a tool places nothing (${placing.join(', ')})`);
      if (typeof it.tool !== 'string' || !tools.has(it.tool)) fail(`${at}.tool ${JSON.stringify(it.tool)} is not a tool of shared/tools/tools.json`);
      return;
    }
    const b = blocks.get(it.block);
    if (!b) fail(`${at}.block ${JSON.stringify(it.block)} is not in the registry`);
    // Placeable: `placeable`, or states listed in its `palette` (a ladder's facings).
    const placeable = b.placeable === true || b.palette === 'all' || (Array.isArray(b.palette) && b.palette.length > 0);
    if (!placeable) fail(`${at}.block ${it.block} is not placeable`);
    if (!Number.isInteger(it.rows) || it.rows < 1 || it.rows > MAX_ROWS) fail(`${at}.rows must be 1..${MAX_ROWS} (½ m cells)`);
    if (it.rows > 1 && b.extends) fail(`${at}: ${it.block} brings its own other cells (extends): rows must be 1`);
    // A state (property values), turned to face along the look (`facing`), with a different upper
    // cell (`upper`: property values over its own, for a 2-row piece): every state it can place is
    // a placeable state of the registry.
    const isValues = (v) => typeof v === 'object' && v !== null && !Array.isArray(v) && Object.values(v).every((x) => typeof x === 'string');
    if (it.state !== undefined && !isValues(it.state)) fail(`${at}.state must be property values ({"shape": "ramp"})`);
    if (it.upper !== undefined && !isValues(it.upper)) fail(`${at}.upper must be property values ({"shape": "steep_upper"})`);
    if (it.upper !== undefined && it.rows !== 2) fail(`${at}.upper is a 2-row piece's upper cell: rows must be 2`);
    if (it.facing !== undefined && !Object.hasOwn(ITEM_FACINGS, it.facing)) fail(`${at}.facing must be one of ${Object.keys(ITEM_FACINGS).join(', ')}`);
    if (it.state !== undefined || it.facing !== undefined || it.upper !== undefined) {
      for (const facing of it.facing ? COMPASS : [null]) {
        const base = { ...(it.state ?? {}), ...(facing ? { facing } : {}) };
        for (const values of [base, ...(it.upper ? [{ ...base, ...it.upper }] : [])]) {
          const name = stateName(it.block, values);
          if (!states.has(name)) fail(`${at}: ${name} is not a state of the registry`);
          if (!states.get(name)) fail(`${at}: ${name} is not placeable`);
        }
      }
    }
    const drag = it.drag ?? 'modes';
    if (!Object.hasOwn(ITEM_DRAGS, drag)) fail(`${at}.drag ${JSON.stringify(drag)} must be one of ${Object.keys(ITEM_DRAGS).join(', ')}`);
    // A drag's pieces after the first are region fills, which run no place rules: building on in
    // the modes is for a plain block; one hung on a wall builds a vertical line, each piece held.
    // (`palette: "all"`, every state of a shaped family, is no rule.)
    const rules = ['palette', 'extends', 'placeOn', 'needsSupport'].filter((k) => b[k] !== undefined && !(k === 'palette' && b[k] === 'all'));
    if (drag === 'modes' && rules.length) fail(`${at}: ${it.block} has place rules (${rules.join(', ')}): drag must be vertical or none`);
    if (drag === 'vertical' && b.needsSupport !== 'behind') fail(`${at}: drag vertical is for a block hung on a wall (needsSupport behind)`);
  });
  validateHotbar(data.hotbar);
  validateBuildModes(data.buildModes);
  return data;
}

/** Checks the hotbar's step keys and the wheel's accumulator. */
function validateHotbar(h) {
  if (typeof h !== 'object' || h === null || Array.isArray(h)) fail('hotbar must be an object');
  const extra = Object.keys(h).filter((k) => !['$comment', 'prevKey', 'nextKey', 'wheelNotchPx', 'wheelGapMs'].includes(k));
  if (extra.length) fail(`hotbar: unknown ${extra.join(', ')}`);
  for (const k of ['prevKey', 'nextKey']) {
    if (typeof h[k] !== 'string' || !KEY_CODE.test(h[k])) fail(`hotbar.${k} must be a KeyboardEvent.code, e.g. ArrowLeft`);
  }
  if (h.prevKey === h.nextKey) fail('hotbar.prevKey and hotbar.nextKey must differ');
  if (typeof h.wheelNotchPx !== 'number' || !(h.wheelNotchPx >= 1 && h.wheelNotchPx <= 1000)) fail('hotbar.wheelNotchPx must be 1..1000 (px)');
  if (!Number.isInteger(h.wheelGapMs) || h.wheelGapMs < 0 || h.wheelGapMs > 2000) fail('hotbar.wheelGapMs must be 0..2000 (ms)');
}

/** Checks the build modes (what holding Place does). */
function validateBuildModes(m) {
  if (typeof m !== 'object' || m === null || Array.isArray(m)) fail('buildModes must be an object');
  const extra = Object.keys(m).filter((k) => !['$comment', 'key', 'clearance', 'holdMs', 'modes'].includes(k));
  if (extra.length) fail(`buildModes: unknown ${extra.join(', ')}`);
  if (typeof m.key !== 'string' || !KEY_CODE.test(m.key)) fail('buildModes.key must be a KeyboardEvent.code, e.g. KeyL');
  if (typeof m.clearance !== 'number' || !(m.clearance >= 0 && m.clearance <= 0.5)) fail('buildModes.clearance must be 0..0.5 (m)');
  if (!Number.isInteger(m.holdMs) || m.holdMs < 0 || m.holdMs > 2000) fail('buildModes.holdMs must be 0..2000 (ms)');
  if (!Array.isArray(m.modes) || m.modes.length === 0) fail('buildModes.modes must be a non-empty list');
  const names = new Set();
  m.modes.forEach((mode, i) => {
    const at = `buildModes.modes[${i}]`;
    if (typeof mode !== 'object' || mode === null) fail(`${at} must be an object`);
    const e = Object.keys(mode).filter((k) => !['$comment', 'name', 'label', 'kind'].includes(k));
    if (e.length) fail(`${at}: unknown ${e.join(', ')}`);
    if (typeof mode.name !== 'string' || !NAME.test(mode.name)) fail(`${at}.name must be namespace:name`);
    if (names.has(mode.name)) fail(`${at}.name ${mode.name} is listed twice`);
    names.add(mode.name);
    if (typeof mode.label !== 'string' || mode.label === '') fail(`${at}.label must be a name to show`);
    if (!Object.hasOwn(DRAG_KINDS, mode.kind)) fail(`${at}.kind ${JSON.stringify(mode.kind)} must be one of ${Object.keys(DRAG_KINDS).join(', ')}`);
  });
}

/** The Rust table. */
export function itemsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::build_drag::{BuildModeDef, DragKind};', 'use crate::items::{ItemDef, ItemDrag, ItemFacing};', ''];
  rs.push(`/// The creative hotbar's items, in its order (shared/items/items.json).`);
  rs.push(`pub const ITEMS: [ItemDef; ${data.items.length}] = [`);
  for (const it of data.items) {
    const pairs = (o) => `&[${Object.entries(o ?? {}).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `(${JSON.stringify(k)}, ${JSON.stringify(v)})`).join(', ')}]`;
    const facing = it.facing ? `ItemFacing::${ITEM_FACINGS[it.facing]}` : 'ItemFacing::None';
    const tool = it.tool ? `Some(${JSON.stringify(it.tool)})` : 'None';
    const drag = it.tool ? 'None' : ITEM_DRAGS[it.drag ?? 'modes'];
    rs.push(`    ItemDef { name: ${JSON.stringify(it.name)}, label: ${JSON.stringify(it.label)}, block: ${JSON.stringify(it.block ?? '')}, tool: ${tool}, rows: ${it.rows ?? 1}, drag: ItemDrag::${drag}, state: ${pairs(it.state)}, facing: ${facing}, upper: ${pairs(it.upper)} },`);
  }
  rs.push('];', '');
  const h = data.hotbar;
  const f = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
  rs.push('/// The keys that step the hotbar one slot left / right (`KeyboardEvent.code`).');
  rs.push(`pub const HOTBAR_PREV_KEY: &str = ${JSON.stringify(h.prevKey)};`);
  rs.push(`pub const HOTBAR_NEXT_KEY: &str = ${JSON.stringify(h.nextKey)};`, '');
  rs.push('/// The wheel\'s travel (px) in one gesture that steps the hotbar one more slot.');
  rs.push(`pub const WHEEL_NOTCH_PX: f64 = ${f(h.wheelNotchPx)};`, '');
  rs.push('/// The quiet (ms) after which a wheel event starts a new gesture, stepping at once.');
  rs.push(`pub const WHEEL_GAP_MS: f64 = ${f(h.wheelGapMs)};`, '');
  const m = data.buildModes;
  rs.push('/// The key that cycles the build modes (`KeyboardEvent.code`).');
  rs.push(`pub const BUILD_MODE_KEY: &str = ${JSON.stringify(m.key)};`, '');
  rs.push('/// How long (ms) Place is held before it builds on, so a click places one block.');
  rs.push(`pub const BUILD_HOLD_MS: f64 = ${m.holdMs}.0;`, '');
  rs.push('/// How far (m) the player\'s own body must be clear of a cell before a block goes in it.');
  rs.push(`pub const BUILD_CLEARANCE: f64 = ${Number.isInteger(m.clearance) ? `${m.clearance}.0` : m.clearance};`, '');
  rs.push('/// What holding Place does after the first block, in the order the key cycles them.');
  rs.push(`pub const BUILD_MODES: [BuildModeDef; ${m.modes.length}] = [`);
  for (const mode of m.modes) {
    rs.push(`    BuildModeDef { name: ${JSON.stringify(mode.name)}, label: ${JSON.stringify(mode.label)}, kind: DragKind::${DRAG_KINDS[mode.kind]} },`);
  }
  rs.push('];', '');
  return rs.join('\n');
}

/** A TS string literal, single-quoted as the client's Prettier writes it. */
const q = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** The shell's table: the build modes' key and labels (the controls list, the HUD). */
export function buildModesTs(data) {
  const m = data.buildModes;
  const ts = [`// ${header}`, ''];
  ts.push('/** What holding Place does after the first block (docs/ITEMS.md §5): the key that cycles the');
  ts.push(' * modes (`KeyboardEvent.code`) and the modes, the first the default. */');
  ts.push('export const BUILD_MODES = {');
  ts.push(`  key: ${q(m.key)},`);
  ts.push('  modes: [');
  for (const x of m.modes) ts.push(`    { name: ${q(x.name)}, label: ${q(x.label)}, kind: ${q(x.kind)} },`);
  ts.push('  ],');
  ts.push('} as const;', '');
  ts.push('/** The keys that step the hotbar one slot left / right (`KeyboardEvent.code`). */');
  ts.push(`export const HOTBAR_KEYS = { prev: ${q(data.hotbar.prevKey)}, next: ${q(data.hotbar.nextKey)} } as const;`, '');
  return ts.join('\n');
}

export function loadItems() {
  return JSON.parse(readFileSync(join(here, 'items.json'), 'utf8'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateItems(loadItems(), registryBlocks());
  writeFileSync(join(root, 'crates/dwell-game/src/items.gen.rs'), itemsRust(data));
  writeFileSync(join(root, 'client/src/ui/buildModes.gen.ts'), buildModesTs(data));
  console.log(`items: ${data.items.length} and ${data.buildModes.modes.length} build modes generated`);
}
