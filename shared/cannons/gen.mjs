#!/usr/bin/env node
// Generates the cannons table (docs/CANNONS.md) for Rust (crates/dwell-world/src/cannons.gen.rs) from
// shared/cannons/cannons.json, after validating it against the blocks and the explosives: an unknown,
// missing or out-of-range entry fails with its path named. CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/cannons/gen.mjs from shared/cannons/cannons.json. Do not edit.';

const fail = (m) => {
  throw new Error(`shared/cannons: ${m}`);
};
const known = (o, keys, at) => {
  if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`${at} must be an object`);
  for (const k of Object.keys(o)) if (k[0] !== '$' && !keys.includes(k)) fail(`${at}: unknown field ${k} (${keys.join(', ')})`);
};
const range = (o, k, lo, hi, at) => {
  const v = o[k];
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) fail(`${at}.${k} must be a number in [${lo}, ${hi}]`);
  return v;
};

/** The blocks (`id → def`) and the explosives' blocks, for the names the table may use. */
export function loadNames() {
  const blocks = new Map();
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  for (const b of ns.blocks) blocks.set(`${ns.namespace}:${b.name}`, b);
  const ex = JSON.parse(readFileSync(join(root, 'shared/explosives/explosives.json'), 'utf8'));
  const explosives = new Set(ex.explosives.map((e) => e.block));
  return { blocks, explosives };
}

/** Validates the table against `names` ({ blocks, explosives }); returns it normalised. */
export function validateCannons(data, names) {
  known(data, ['cannons', 'balls', 'helms'], 'cannons.json');
  if (!Array.isArray(data.balls) || data.balls.length === 0) fail('balls must be a non-empty list');
  const balls = data.balls.map((b, i) => {
    const at = `balls[${i}]`;
    known(b, ['name', 'radiusM', 'densityKgM3', 'rollDamping', 'impact'], at);
    if (typeof b.name !== 'string' || !/^[a-z]+:[a-z0-9_]+$/.test(b.name)) fail(`${at}.name must be a namespaced name`);
    if (names.blocks.get(b.name)?.look !== 'ball') fail(`${at}.name: ${b.name} must be a block of look ball (shared/blocks)`);
    range(b, 'radiusM', 0.02, 1, at);
    range(b, 'rollDamping', 0, 50, at);
    range(b, 'densityKgM3', 100, 30000, at);
    const im = b.impact;
    const keys = ['destroySpeedMs', 'energyPerKgJ', 'dragRadiusM', 'dragForcePerSpeedN', 'maxLooseCells', 'minSpeedMs'];
    known(im, keys, `${at}.impact`);
    range(im, 'destroySpeedMs', 0, 300, `${at}.impact`);
    range(im, 'energyPerKgJ', 0, 10000, `${at}.impact`);
    range(im, 'dragRadiusM', 0, 4, `${at}.impact`);
    range(im, 'dragForcePerSpeedN', 0, 1e6, `${at}.impact`);
    if (!Number.isInteger(im.maxLooseCells) || im.maxLooseCells < 0 || im.maxLooseCells > 256) fail(`${at}.impact.maxLooseCells must be a whole number in [0, 256]`);
    range(im, 'minSpeedMs', 0, 300, `${at}.impact`);
    if (im.minSpeedMs > im.destroySpeedMs) fail(`${at}.impact.minSpeedMs must not exceed destroySpeedMs`);
    return b;
  });
  const ballNames = new Set(balls.map((b) => b.name));
  if (ballNames.size !== balls.length) fail('balls: a name is listed twice');
  if (!Array.isArray(data.cannons)) fail('cannons must be a list');
  const seen = new Set();
  const cannons = data.cannons.map((c, i) => {
    const at = `cannons[${i}]`;
    known(c, ['block', 'ball', 'muzzleSpeedMs', 'muzzleUpM', 'muzzleForwardM', 'recoilShare', 'reloadS'], at);
    const def = names.blocks.get(c.block);
    if (!def) fail(`${at}.block: no block ${JSON.stringify(c.block)}`);
    if (def.use !== 'fire') fail(`${at}.block: ${c.block} must have use: fire`);
    if (seen.has(c.block)) fail(`${at}.block: ${c.block} is listed twice`);
    seen.add(c.block);
    if (!ballNames.has(c.ball)) fail(`${at}.ball: no ball ${JSON.stringify(c.ball)}`);
    range(c, 'muzzleSpeedMs', 1, 300, at);
    range(c, 'muzzleUpM', 0, 4, at);
    range(c, 'muzzleForwardM', 0, 8, at);
    range(c, 'reloadS', 0, 120, at);
    range(c, 'recoilShare', 0, 1, at);
    return c;
  });
  if (!Array.isArray(data.helms)) fail('helms must be a list');
  const helmSeen = new Set();
  const helms = data.helms.map((h, i) => {
    const at = `helms[${i}]`;
    known(h, ['block', 'thrustN', 'rudderNmPerMs', 'camera'], at);
    known(h.camera, ['backM', 'upM', 'easeS'], `${at}.camera`);
    range(h.camera, 'backM', 0, 30, `${at}.camera`);
    range(h.camera, 'upM', -5, 15, `${at}.camera`);
    range(h.camera, 'easeS', 0, 5, `${at}.camera`);
    const def = names.blocks.get(h.block);
    if (!def) fail(`${at}.block: no block ${JSON.stringify(h.block)}`);
    if (def.use !== 'helm') fail(`${at}.block: ${h.block} must have use: helm`);
    if (helmSeen.has(h.block)) fail(`${at}.block: ${h.block} is listed twice`);
    helmSeen.add(h.block);
    range(h, 'thrustN', 0, 1e7, at);
    range(h, 'rudderNmPerMs', 0, 1e7, at);
    return h;
  });
  return { cannons, balls, helms };
}

const f64 = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

export function cannonsRust(d) {
  const rs = [`// ${header}`, '', 'use crate::cannons::{BallDef, CannonDef, HelmCamera, HelmDef, Impact};', ''];
  rs.push('/// The cannons, by block (`cannons`).');
  rs.push('pub static CANNONS: &[CannonDef] = &[');
  for (const c of d.cannons) {
    rs.push(`    CannonDef { block: "${c.block}", ball: "${c.ball}", muzzle_speed_ms: ${f64(c.muzzleSpeedMs)}, muzzle_up_m: ${f64(c.muzzleUpM)}, muzzle_forward_m: ${f64(c.muzzleForwardM)}, recoil_share: ${f64(c.recoilShare)}, reload_s: ${f64(c.reloadS)} },`);
  }
  rs.push('];', '');
  rs.push('/// The cannonballs (`balls`).');
  rs.push('pub static BALLS: &[BallDef] = &[');
  for (const b of d.balls) {
    const im = b.impact;
    rs.push(`    BallDef { name: "${b.name}", radius_m: ${f64(b.radiusM)}, density_kg_m3: ${f64(b.densityKgM3)}, roll_damping: ${f64(b.rollDamping)}, impact: Impact { destroy_speed_ms: ${f64(im.destroySpeedMs)}, energy_per_kg_j: ${f64(im.energyPerKgJ)}, drag_radius_m: ${f64(im.dragRadiusM)}, drag_force_per_speed_n: ${f64(im.dragForcePerSpeedN)}, max_loose_cells: ${im.maxLooseCells}, min_speed_ms: ${f64(im.minSpeedMs)} } },`);
  }
  rs.push('];', '');
  rs.push('/// The ships\' helms, by block (`helms`).');
  rs.push('pub static HELMS: &[HelmDef] = &[');
  for (const h of d.helms) {
    rs.push(`    HelmDef { block: "${h.block}", thrust_n: ${f64(h.thrustN)}, rudder_nm_per_ms: ${f64(h.rudderNmPerMs)}, camera: HelmCamera { back_m: ${f64(h.camera.backM)}, up_m: ${f64(h.camera.upM)}, ease_s: ${f64(h.camera.easeS)} } },`);
  }
  rs.push('];', '');
  return rs.join('\n');
}

export function loadCannons() {
  return JSON.parse(readFileSync(join(here, 'cannons.json'), 'utf8'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const d = validateCannons(loadCannons(), loadNames());
  writeFileSync(join(root, 'crates/dwell-world/src/cannons.gen.rs'), cannonsRust(d));
  console.log(`cannons: ${d.cannons.length} cannon(s), ${d.balls.length} ball(s), ${d.helms.length} helm(s) generated`);
}
