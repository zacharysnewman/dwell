#!/usr/bin/env node
// Generates Play advanced's fields (docs/DEV_TOOLS.md, Play advanced) for the shell
// (client/src/ui/playOverrides.gen.ts) from shared/play/overrides.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. A choice's `optionsFrom` names a
// look data file whose entries' names become its options (shared/look/outline.json's modes,
// pixelart.json's presets), so a mode added there shows in the menu with no edit here. The output is
// checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/play/gen.mjs from shared/play/overrides.json. Do not edit.';

/** The look data files a choice may take its options from: the file and its list of named entries. */
export const OPTION_SOURCES = {
  outline: { file: 'shared/look/outline.json', list: 'modes', off: 'Off' },
  pixelart: { file: 'shared/look/pixelart.json', list: 'presets', off: 'Off' },
};

/**
 * Parameters Play advanced may not set: the routes the launcher and the shell read to choose what
 * the page opens (ui/launch.ts) other than the link world's own, and the launcher's.
 */
export const RESERVED = [
  'local',
  'join',
  'cert',
  'rtc',
  'ice',
  'code',
  'play',
  'v',
  'new',
  'name',
  'type',
  'regenerate',
  'say',
  'version',
  'versions',
];

const KINDS = {
  choice: ['options', 'optionsFrom'],
  integer: ['min', 'max'],
  number: ['min', 'max', 'step'],
  clock: [],
};

const fail = (m) => {
  throw new Error(`overrides.json: ${m}`);
};

function checkKeys(where, obj, required, optional = []) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !required.includes(k) && !optional.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of required) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkText(where, v) {
  if (typeof v !== 'string' || v.trim() === '') fail(`${where} must be non-empty text`);
}

function checkNumber(where, v) {
  if (typeof v !== 'number' || !Number.isFinite(v)) fail(`${where} must be a number, got ${JSON.stringify(v)}`);
}

const titled = (name) => name.charAt(0).toUpperCase() + name.slice(1);

/** A source's options: "" (off) first, then each named entry. */
export function sourceOptions(source, read = (p) => readFileSync(join(root, p), 'utf8')) {
  const s = OPTION_SOURCES[source];
  const entries = JSON.parse(read(s.file))[s.list];
  return [{ value: '', label: s.off }, ...entries.map((e) => ({ value: e.name, label: titled(e.name) }))];
}

/** Checks the overrides and resolves `optionsFrom`; returns the fields. Throws naming the entry. */
export function validateOverrides(data, read) {
  checkKeys('(root)', data, ['overrides']);
  if (!Array.isArray(data.overrides) || data.overrides.length === 0) fail('overrides must be a non-empty list');
  const seen = new Set();
  return data.overrides.map((o, i) => {
    const at = `overrides[${i}]`;
    if (typeof o !== 'object' || o === null) fail(`${at} must be an object`);
    if (!(o.kind in KINDS))
      fail(`${at}.kind must be one of ${Object.keys(KINDS).join(', ')}, got ${JSON.stringify(o.kind)}`);
    const extra = o.kind === 'number' ? ['min', 'max', 'step'] : o.kind === 'integer' ? ['min', 'max'] : [];
    const optional = ['hint', ...(o.kind === 'choice' ? KINDS.choice : [])];
    checkKeys(at, o, ['param', 'label', 'kind', ...extra], optional);
    if (typeof o.param !== 'string' || !/^[a-z][a-z0-9]*$/.test(o.param)) {
      fail(`${at}.param must be a lowercase URL parameter name, got ${JSON.stringify(o.param)}`);
    }
    if (RESERVED.includes(o.param))
      fail(`${at}.param ${o.param} chooses what the page opens (ui/launch.ts): not an override`);
    if (seen.has(o.param)) fail(`${at}.param ${o.param} is used twice`);
    seen.add(o.param);
    checkText(`${at}.label`, o.label);
    if ('hint' in o) checkText(`${at}.hint`, o.hint);
    const field = {
      param: o.param,
      label: o.label,
      kind: o.kind,
      ...(o.hint ? { hint: o.hint } : {}),
    };
    if (o.kind === 'integer' || o.kind === 'number') {
      checkNumber(`${at}.min`, o.min);
      checkNumber(`${at}.max`, o.max);
      if (o.max <= o.min) fail(`${at}.max must be greater than min`);
      if (o.kind === 'integer' && !(Number.isSafeInteger(o.min) && Number.isSafeInteger(o.max))) {
        fail(`${at}.min and max must be whole numbers`);
      }
      Object.assign(field, { min: o.min, max: o.max });
      if (o.kind === 'number') {
        checkNumber(`${at}.step`, o.step);
        if (o.step <= 0) fail(`${at}.step must be positive`);
        field.step = o.step;
      }
    }
    if (o.kind === 'choice') {
      if ('options' in o === 'optionsFrom' in o) fail(`${at} needs options or optionsFrom (one of them)`);
      let options;
      if ('optionsFrom' in o) {
        if (!(o.optionsFrom in OPTION_SOURCES)) {
          fail(
            `${at}.optionsFrom must be one of ${Object.keys(OPTION_SOURCES).join(', ')}, got ${JSON.stringify(o.optionsFrom)}`,
          );
        }
        options = sourceOptions(o.optionsFrom, read);
      } else {
        if (!Array.isArray(o.options) || o.options.length < 2) fail(`${at}.options must list at least two`);
        options = o.options.map((x, j) => {
          checkKeys(`${at}.options[${j}]`, x, ['value', 'label']);
          if (typeof x.value !== 'string' || !/^[a-z0-9-]*$/.test(x.value)) {
            fail(`${at}.options[${j}].value must be lowercase words joined by dashes, or ""`);
          }
          checkText(`${at}.options[${j}].label`, x.label);
          return { value: x.value, label: x.label };
        });
      }
      if (options[0].value !== '') fail(`${at}.options must start with the default, value ""`);
      const values = options.map((x) => x.value);
      if (new Set(values).size !== values.length) fail(`${at}.options has a value twice`);
      field.options = options;
    }
    return field;
  });
}

/** The TypeScript for validated fields. */
export function overridesTs(fields) {
  return [
    `// ${header}`,
    '',
    "import type { OverrideField } from './playAdvanced';",
    '',
    "/** Play advanced's fields, in order (shared/play/overrides.json). */",
    `export const OVERRIDE_FIELDS: readonly OverrideField[] = ${JSON.stringify(fields, null, 2)};`,
    '',
  ].join('\n');
}

export function loadOverrides(path = join(here, 'overrides.json')) {
  return validateOverrides(JSON.parse(readFileSync(path, 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'client/src/ui/playOverrides.gen.ts'), overridesTs(loadOverrides()));
  console.log('play: overrides generated');
}
