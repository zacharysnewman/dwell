#!/usr/bin/env node
// Generates tools and the woods they cut (docs/adr/0067-stone-axe-and-chopping.md) for Rust and
// TypeScript from shared/tools/tools.json: `crates/dwell-protocol/src/tools.gen.rs` (the server's
// chopping and the client's gouges, through `dwell_protocol::chopping`) and
// `client/src/ui/tools.gen.ts` (the shell's swing hint). It checks every name against the
// inventory's items and the block files. Outputs are checked in; CI regenerates them and fails on
// any diff. A bad entry fails with a message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadBlocks, loadInventory } from '../inventory/gen.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/tools/gen.mjs from shared/tools/tools.json. Do not edit.';

/** The tool kinds the engine understands (code; a new kind is code with its data). */
export const KINDS = ['axe'];
const TOP_FIELDS = ['formatVersion', 'tools', 'woods'];
const TOOL_FIELDS = ['name', 'kind', 'swingSeconds', 'biteM', 'bindM', 'across', 'along', 'sharpness', 'held'];
const WOOD_FIELDS = ['block', 'fellFraction', 'buckFraction', 'buckDrops', 'chips'];
const CHIP_FIELDS = ['count', 'color', 'speed', 'size'];
const COLOR = /^#[0-9a-f]{6}$/i;
const DROP_FIELDS = ['item', 'count', 'chance'];

const fail = (m) => {
  throw new Error(`shared/tools: ${m}`);
};
const num = (v) => typeof v === 'number' && Number.isFinite(v);
const known = (o, fields, at) => {
  if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`${at} must be an object`);
  for (const k of Object.keys(o)) {
    if (!fields.includes(k) && k[0] !== '$') fail(`${at}: unknown field ${k} (${fields.join(', ')})`);
  }
};
const inRange = (o, k, lo, hi, at, open = false) => {
  const v = o[k];
  if (!num(v) || v < lo || v > hi || (open && v <= lo)) fail(`${at}.${k} must be a number in ${open ? '(' : '['}${lo}, ${hi}]`);
};

/**
 * Checks the tools data. `items` are the names of every item (blocks and inventory items); `blocks`
 * maps a block's name to its definition (to check a wood has an `axis`). Returns the data with
 * defaults filled.
 */
export function validateTools(data, items, blocks, heldItems = loadHeldItems()) {
  known(data, [...TOP_FIELDS, '$comment'], 'the file');
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  if (!Array.isArray(data.tools) || data.tools.length === 0) fail('tools must be a non-empty list');
  const names = new Set();
  const tools = data.tools.map((t, i) => {
    const at = typeof t?.name === 'string' ? `tools.${t.name}` : `tools[${i}]`;
    known(t, TOOL_FIELDS, at);
    if (!items.has(t.name)) fail(`${at}: no item of that name (add it to shared/inventory/inventory.json's items)`);
    if (names.has(t.name)) fail(`${at}: listed twice`);
    names.add(t.name);
    if (!KINDS.includes(t.kind)) fail(`${at}.kind must be one of ${KINDS.join(', ')}`);
    inRange(t, 'swingSeconds', 0, 10, at, true);
    inRange(t, 'biteM', 0, 1, at, true);
    inRange(t, 'bindM', 0, 1, at, true);
    inRange(t, 'across', 0, 1, at);
    inRange(t, 'along', 0, 1, at);
    inRange(t, 'sharpness', 0, 8, at, true);
    if (t.along > t.across) fail(`${at}: along (${t.along}) must not be above across (${t.across})`);
    // What the hand shows holding it: an item of shared/characters/characters.json.
    if (t.held !== undefined && !heldItems.has(t.held)) fail(`${at}.held: no item ${JSON.stringify(t.held)} in shared/characters/characters.json`);
    return { ...t, held: t.held ?? null };
  });
  if (!Array.isArray(data.woods)) fail('woods must be a list');
  const woodNames = new Set();
  const woods = data.woods.map((w, i) => {
    const at = typeof w?.block === 'string' ? `woods.${w.block}` : `woods[${i}]`;
    known(w, WOOD_FIELDS, at);
    const def = blocks.get(w.block);
    if (!def) fail(`${at}: no block of that name`);
    if (!def.properties?.axis) fail(`${at}: the block has no axis property (its grain)`);
    if (woodNames.has(w.block)) fail(`${at}: listed twice`);
    woodNames.add(w.block);
    inRange(w, 'fellFraction', 0, 1, at, true);
    inRange(w, 'buckFraction', 0, 1, at, true);
    if (!Array.isArray(w.buckDrops)) fail(`${at}.buckDrops must be a list`);
    const buckDrops = w.buckDrops.map((d, j) => {
      const dat = `${at}.buckDrops[${j}]`;
      known(d, DROP_FIELDS, dat);
      if (!items.has(d.item)) fail(`${dat}: no item named ${d.item}`);
      const c = d.count ?? 1;
      const [min, max] = Array.isArray(c) ? c : [c, c];
      if (!Number.isInteger(min) || !Number.isInteger(max) || min < 1 || max < min || max > 64) fail(`${dat}.count must be n or [min, max] in 1..64`);
      const chance = d.chance ?? 1;
      if (!num(chance) || chance <= 0 || chance > 1) fail(`${dat}.chance must be in (0, 1]`);
      return { item: d.item, min, max, chance };
    });
    // The chips a swing knocks out of it (the client's particles).
    const c = w.chips ?? {};
    known(c, CHIP_FIELDS, `${at}.chips`);
    const chips = { count: c.count ?? 6, color: c.color ?? '#c8a070', speed: c.speed ?? 2.5, size: c.size ?? 0.05 };
    if (!Number.isInteger(chips.count) || chips.count < 0 || chips.count > 32) fail(`${at}.chips.count must be a whole number in [0, 32]`);
    if (typeof chips.color !== 'string' || !COLOR.test(chips.color)) fail(`${at}.chips.color must be #rrggbb`);
    inRange(chips, 'speed', 0, 10, `${at}.chips`, true);
    inRange(chips, 'size', 0, 0.2, `${at}.chips`, true);
    return { ...w, buckDrops, chips };
  });
  // Blocks a break needs a tool kind for where blocks are not unlimited (`breakWith` on the block;
  // owner, 2026-11-08: logs need an axe in adventure).
  const breakWith = [];
  for (const [name, def] of blocks) {
    if (def.breakWith === undefined) continue;
    if (!KINDS.includes(def.breakWith)) fail(`${name}.breakWith must be one of ${KINDS.join(', ')}`);
    breakWith.push({ block: name, kind: def.breakWith });
  }
  return { tools, woods, breakWith };
}

/** The items a hand can show (shared/characters/characters.json's `items`). */
export function loadHeldItems() {
  const c = JSON.parse(readFileSync(join(root, 'shared/characters/characters.json'), 'utf8'));
  return new Set(Object.keys(c.items ?? {}));
}

export function loadTools() {
  return JSON.parse(readFileSync(join(here, 'tools.json'), 'utf8'));
}

/** Every item's name (blocks are items of their own name) and the blocks by name. */
export function loadNames(fixture = false) {
  const blocks = new Map();
  for (const ns of loadBlocks(fixture)) for (const b of ns.blocks) blocks.set(`${ns.namespace}:${b.name}`, b);
  const items = new Set([...blocks.keys(), ...loadInventory().items.map((i) => i.name)]);
  return { items, blocks };
}

const rgb = (c) => [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
const f64 = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

export function toolsRust(d) {
  const rs = [`// ${header}`, '', 'use crate::chopping::{Chips, ToolDef, ToolKind, WoodDef};', 'use crate::inventory::{DropChoice, DropRule};', ''];
  rs.push('/// The tools, by item name.');
  rs.push('pub static TOOLS: &[ToolDef] = &[');
  for (const t of d.tools) {
    const kind = t.kind[0].toUpperCase() + t.kind.slice(1);
    rs.push(
      `    ToolDef { name: "${t.name}", kind: ToolKind::${kind}, held: ${t.held === null ? 'None' : `Some("${t.held}")`}, swing_seconds: ${f64(t.swingSeconds)}, bite_m: ${f64(t.biteM)}, bind_m: ${f64(t.bindM)}, across: ${f64(t.across)}, along: ${f64(t.along)}, sharpness: ${f64(t.sharpness)} },`,
    );
  }
  rs.push('];');
  rs.push('');
  rs.push('/// The blocks an axe cuts, by block name.');
  rs.push('pub static WOODS: &[WoodDef] = &[');
  for (const w of d.woods) {
    const drops = w.buckDrops.map(
      (x) => `DropRule { chance: ${f64(x.chance)}, choices: &[DropChoice { item: "${x.item}", min: ${x.min}, max: ${x.max}, weight: 1.0 }] }`,
    );
    rs.push(
      `    WoodDef { block: "${w.block}", fell_fraction: ${f64(w.fellFraction)}, buck_fraction: ${f64(w.buckFraction)}, buck_drops: &[${drops.join(', ')}], chips: Chips { count: ${w.chips.count}, color: [${rgb(w.chips.color).join(', ')}], speed: ${f64(w.chips.speed)}, size: ${f64(w.chips.size)} } },`,
    );
  }
  rs.push('];');
  rs.push('');
  rs.push('/// Blocks a break needs a tool of a kind for, where blocks are not unlimited.');
  rs.push('pub static BREAK_WITH: &[(&str, ToolKind)] = &[');
  for (const b of d.breakWith) rs.push(`    ("${b.block}", ToolKind::${b.kind[0].toUpperCase() + b.kind.slice(1)}),`);
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

export function toolsTs(d) {
  const ts = [`// ${header}`, ''];
  ts.push('/** A tool: its item name and kind (the swing hint shows for an axe). */');
  ts.push('export const TOOLS: readonly { name: string; kind: string }[] = [');
  for (const t of d.tools) ts.push(`  { name: ${JSON.stringify(t.name)}, kind: ${JSON.stringify(t.kind)} },`);
  ts.push('];');
  ts.push('');
  return ts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const { items, blocks } = loadNames();
  const d = validateTools(loadTools(), items, blocks);
  writeFileSync(join(root, 'crates/dwell-protocol/src/tools.gen.rs'), toolsRust(d));
  writeFileSync(join(root, 'client/src/ui/tools.gen.ts'), toolsTs(d));
}
