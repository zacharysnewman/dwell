/** Every item's name (blocks are items of their own name) and the blocks by name. */
export function loadNames(fixture = false) {
  const blocks = new Map();
  for (const ns of loadBlocks(fixture)) for (const b of ns.blocks) blocks.set(`${ns.namespace}:${b.name}`, b);
  const items = new Set([...blocks.keys(), ...loadInventory().items.map((i) => i.name)]);
  return { items, blocks };
}

const rgb = (c) => [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
const f64 = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const bladeRust = (b) => `RaisedBlade { grip: [${b.grip.map(f64).join(', ')}], tip: [${b.tip.map(f64).join(', ')}] }`;
const optStr = (v) => (v === null ? 'None' : `Some("${v}")`);
