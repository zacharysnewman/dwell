  rs.push('');
  rs.push('/// The tools, by item name.');
  rs.push('pub static TOOLS: &[ToolDef] = &[');
  for (const t of d.tools) {
    const kind = t.kind[0].toUpperCase() + t.kind.slice(1);
    rs.push(
      `    ToolDef { name: "${t.name}", kind: ToolKind::${kind}, held: ${t.held === null ? 'None' : `Some("${t.held}")`}, swing_seconds: ${f64(t.swingSeconds)}, bite_m: ${f64(t.biteM)}, bind_m: ${f64(t.bindM)}, across: ${f64(t.across)}, along: ${f64(t.along)}, sharpness: ${f64(t.sharpness)}, held_vertical: ${optStr(t.heldVertical)}, swing: ${swingRust(t.swing)}, clears: &[${t.clears.map((b) => `"${b}"`).join(', ')}], chop2_bite: ${f64(t.chop2.bite)} },`,
    );
  }
