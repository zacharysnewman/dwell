/** The tool kinds the engine understands (code; a new kind is code with its data). */
export const KINDS = ['axe'];
const TOP_FIELDS = ['formatVersion', 'tools', 'woods', 'breaking', 'durability', 'chop2'];
/** The chopping prototype (WORK_QUEUE item 7, `chop2`): a tool's bite, a wood's rules, the switch. */
const CHOP2_TOOL_FIELDS = ['bite'];
const CHOP2_WOOD_FIELDS = ['fellFraction', 'along', 'fellWedgeTrunk'];
const CHOP2_FIELDS = ['enabled'];
const TOOL_FIELDS = ['name', 'kind', 'swingSeconds', 'biteM', 'bindM', 'across', 'along', 'sharpness', 'held', 'heldVertical', 'swing', 'clears', 'chop2'];
const SWING_FIELDS = ['windupS', 'activeS', 'hitStopS', 'recoverHitS', 'recoverMissS', 'reachM', 'arcDeg', 'samples', 'camera', 'staminaCost', 'swish', 'bounce', 'rustle', 'rustleLeaves'];
/** A swing's defaults (a tool without `swing`): a short wind-up, a committed arc, a hit-stop. */
export const SWING_DEFAULTS = { windupS: 0.12, activeS: 0.14, hitStopS: 0.07, recoverHitS: 0.22, recoverMissS: 0.36, reachM: 2.2, arcDeg: 110, samples: 12, camera: {}, staminaCost: 0, swish: null, bounce: null, rustle: null, rustleLeaves: 4 };
/** A swing's camera sway (docs/CHARACTERS.md §5.2): per swing kind, keyed offsets and a kick. */
const CAMERA_KINDS = ['level', 'vertical'];
const CAMERA_FIELDS = ['keys', 'kick'];
const CAMERA_KEY_FIELDS = ['t', 'yaw', 'pitch', 'roll', 'bob'];
const CAMERA_KICK_FIELDS = ['yaw', 'pitch', 'roll', 'bob', 'decayS', 'miss', 'bounce'];
/** The sway's bounds: a few degrees and centimetres (it sells the swing; it must not sicken). */
const SWAY_MAX_DEG = 10;
const SWAY_MAX_BOB_M = 0.1;
const WOOD_FIELDS = ['block', 'fellFraction', 'buckFraction', 'buckDrops', 'chips', 'leaves', 'sway', 'sounds', 'cut', 'fellWedge', 'fellWedgeTrunk', 'fellTip', 'chop2'];
const CUT_FIELDS = ['tile', 'tint', 'open', 'kerfWidthM'];
const LEAF_FIELDS = ['block', 'count', 'color', 'radiusM', 'heightM'];
const SWAY_FIELDS = ['fromFraction', 'maxDeg'];
const CHIP_FIELDS = ['count', 'color', 'speed', 'size'];
const COLOR = /^#[0-9a-f]{6}$/i;
const DROP_FIELDS = ['item', 'count', 'chance'];

const fail = (m) => {
  throw new Error(`shared/tools: ${m}`);
};
const num = (v) => typeof v === 'number' && Number.isFinite(v);
const known = (o, fields, at) => {
  if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`${at} must be an object`);
  for (const k of Object.keys(o)) {
    if (!fields.includes(k) && k[0] !== '$') fail(`${at}: unknown field ${k} (${fields.join(', ')})`);
  }
};
const inRange = (o, k, lo, hi, at, open = false) => {
  const v = o[k];
  if (!num(v) || v < lo || v > hi || (open && v <= lo)) fail(`${at}.${k} must be a number in ${open ? '(' : '['}${lo}, ${hi}]`);
};
/** Chips (the client's particles): a wood's off a swing, a block's `damage.chips` off a hit. */
function validateChips(c, at) {
  if (c === null || typeof c !== 'object' || Array.isArray(c)) fail(`${at} must be an object`);
  known(c, CHIP_FIELDS, at);
  const chips = { count: c.count ?? 6, color: c.color ?? '#c8a070', speed: c.speed ?? 2.5, size: c.size ?? 0.05 };
  if (!Number.isInteger(chips.count) || chips.count < 0 || chips.count > 32) fail(`${at}.count must be a whole number in [0, 32]`);
  if (typeof chips.color !== 'string' || !COLOR.test(chips.color)) fail(`${at}.color must be #rrggbb`);
  inRange(chips, 'speed', 0, 10, at, true);
  inRange(chips, 'size', 0, 0.2, at, true);
  return chips;
}

/** An offset (a key's or the kick's): degrees of yaw, pitch and roll and a bob in metres. */
function validateOffset(o, at) {
  const v = { yaw: o.yaw ?? 0, pitch: o.pitch ?? 0, roll: o.roll ?? 0, bob: o.bob ?? [0, 0, 0] };
  for (const k of ['yaw', 'pitch', 'roll']) inRange(v, k, -SWAY_MAX_DEG, SWAY_MAX_DEG, at);
  if (!Array.isArray(v.bob) || v.bob.length !== 3 || v.bob.some((b) => !num(b) || Math.abs(b) > SWAY_MAX_BOB_M)) fail(`${at}.bob must be [right, up, back] metres, each in [-${SWAY_MAX_BOB_M}, ${SWAY_MAX_BOB_M}]`);
  return v;
}
const atRest = (k) => k.yaw === 0 && k.pitch === 0 && k.roll === 0 && k.bob.every((b) => b === 0);

/**
 * A swing's `camera`: for each swing kind (level, vertical) its `keys` over the phase time (0 the
 * start, 1 the wind-up's end, 2 the arc's end, 3 a miss's recovery's end), at rest at 0 and 3, in
 * order, and its `kick` at contact. A kind left out has no sway.
 */
export function validateCamera(c, at) {
  known(c, CAMERA_KINDS, at);
  const out = {};
  for (const kind of CAMERA_KINDS) {
    const kat = `${at}.${kind}`;
    const v = c[kind];
    if (v === undefined) {
      out[kind] = { keys: [], kick: { ...validateOffset({}, kat), decayS: 0.1, miss: 0, bounce: 0 } };
      continue;
    }
    known(v, CAMERA_FIELDS, kat);
    if (!Array.isArray(v.keys) || v.keys.length < 2) fail(`${kat}.keys must be a list of at least two keys`);
    const keys = v.keys.map((k, i) => {
      const kk = `${kat}.keys[${i}]`;
      known(k, CAMERA_KEY_FIELDS, kk);
      inRange(k, 't', 0, 3, kk);
      return { t: k.t, ...validateOffset(k, kk) };
    });
    keys.forEach((k, i) => {
      if (i > 0 && k.t <= keys[i - 1].t) fail(`${kat}.keys[${i}].t (${k.t}) must be after the key before (${keys[i - 1].t})`);
    });
    const first = keys[0];
    const last = keys[keys.length - 1];
    if (first.t !== 0 || !atRest(first)) fail(`${kat}.keys must start at rest at t 0 (every offset 0)`);
    if (last.t !== 3 || !atRest(last)) fail(`${kat}.keys must end at rest at t 3 (every offset 0)`);
    const kick = v.kick ?? {};
    known(kick, CAMERA_KICK_FIELDS, `${kat}.kick`);
    const kv = { ...validateOffset(kick, `${kat}.kick`), decayS: kick.decayS ?? 0.1, miss: kick.miss ?? 0.4, bounce: kick.bounce ?? 1.6 };
    inRange(kv, 'decayS', 0, 1, `${kat}.kick`, true);
    inRange(kv, 'miss', 0, 2, `${kat}.kick`);
    inRange(kv, 'bounce', 0, 4, `${kat}.kick`);
    out[kind] = { keys, kick: kv };
  }
  return out;
}

/**
 * Checks the tools data. `items` are the names of every item (blocks and inventory items); `blocks`
 * maps a block's name to its definition (to check a wood has an `axis`). Returns the data with
 * defaults filled.
 */
export function validateTools(data, items, blocks, heldItems = loadHeldItems(), soundEvents = loadSoundEvents(), tiles = loadTiles()) {
  const event = (v, at) => {
    if (v === undefined || v === null) return null;
    if (!soundEvents.has(v)) fail(`${at}: no sound event ${JSON.stringify(v)} in shared/sounds/dwell.json's events`);
    return v;
  };
  known(data, [...TOP_FIELDS, '$comment'], 'the file');
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  if (!Array.isArray(data.tools) || data.tools.length === 0) fail('tools must be a non-empty list');
  const names = new Set();
  const tools = data.tools.map((t, i) => {
    const at = typeof t?.name === 'string' ? `tools.${t.name}` : `tools[${i}]`;
    known(t, TOOL_FIELDS, at);
    if (!items.has(t.name)) fail(`${at}: no item of that name (add it to shared/inventory/inventory.json's items)`);
    if (names.has(t.name)) fail(`${at}: listed twice`);
    names.add(t.name);
    if (!KINDS.includes(t.kind)) fail(`${at}.kind must be one of ${KINDS.join(', ')}`);
    inRange(t, 'swingSeconds', 0, 10, at, true);
    inRange(t, 'biteM', 0, 1, at, true);
    inRange(t, 'bindM', 0, 1, at, true);
    inRange(t, 'across', 0, 1, at);
    inRange(t, 'along', 0, 1, at);
    inRange(t, 'sharpness', 0, 8, at, true);
    if (t.along > t.across) fail(`${at}: along (${t.along}) must not be above across (${t.across})`);
    // What the hand shows holding it: an item of shared/characters/characters.json.
    if (t.held !== undefined && !heldItems.has(t.held)) fail(`${at}.held: no item ${JSON.stringify(t.held)} in shared/characters/characters.json`);
    if (t.heldVertical !== undefined && !heldItems.has(t.heldVertical)) fail(`${at}.heldVertical: no item ${JSON.stringify(t.heldVertical)} in shared/characters/characters.json`);
    // The swing (the client's feel, the server's sweep): timings, the arc, the camera's kick, a
    // stamina cost for when stamina exists (unused until then), its sounds by event name.
    const sw = { ...SWING_DEFAULTS, ...(t.swing ?? {}) };
    known(t.swing ?? {}, SWING_FIELDS, `${at}.swing`);
    const sat = `${at}.swing`;
    inRange(sw, 'windupS', 0, 2, sat);
    inRange(sw, 'activeS', 0, 2, sat, true);
    inRange(sw, 'hitStopS', 0, 0.5, sat);
    inRange(sw, 'recoverHitS', 0, 3, sat);
    inRange(sw, 'recoverMissS', 0, 3, sat);
    inRange(sw, 'reachM', 0, 6, sat, true);
    inRange(sw, 'arcDeg', 0, 180, sat, true);
    sw.camera = validateCamera(sw.camera, `${sat}.camera`);
    inRange(sw, 'staminaCost', 0, 1000, sat);
    if (!Number.isInteger(sw.samples) || sw.samples < 2 || sw.samples > 64) fail(`${sat}.samples must be a whole number in [2, 64]`);
    if (sw.recoverMissS < sw.recoverHitS) fail(`${sat}: recoverMissS (${sw.recoverMissS}) must not be below recoverHitS (${sw.recoverHitS}): a miss follows through`);
    // The server holds swingSeconds between swings: no swing the client lets go may come sooner.
    if (sw.windupS + sw.activeS + sw.recoverMissS < t.swingSeconds - 1e-9) fail(`${sat}: a miss (${(sw.windupS + sw.activeS + sw.recoverMissS).toFixed(3)} s) must last at least swingSeconds (${t.swingSeconds})`);
    sw.swish = event(sw.swish, `${sat}.swish`);
    sw.bounce = event(sw.bounce, `${sat}.bounce`);
    sw.rustle = event(sw.rustle, `${sat}.rustle`);
    if (!Number.isInteger(sw.rustleLeaves) || sw.rustleLeaves < 0 || sw.rustleLeaves > 16) fail(`${sat}.rustleLeaves must be a whole number in [0, 16]`);
    // The blocks its swing clears on the way (owner, 2026-11-09: the axe clears leaves): by name,
    // each a block of the registry that is not a wood (a wood is chopped, not cleared).
    if (t.clears !== undefined && !Array.isArray(t.clears)) fail(`${at}.clears must be a list of block names`);
    const clears = t.clears ?? [];
    clears.forEach((b, j) => {
      if (typeof b !== 'string' || !blocks.has(b)) fail(`${at}.clears[${j}]: no block named ${JSON.stringify(b)}`);
      if (clears.indexOf(b) !== j) fail(`${at}.clears: ${b} listed twice`);
      if ((data.woods ?? []).some((w) => w.block === b)) fail(`${at}.clears: ${b} is a wood (chopped, not cleared)`);
    });
    // The chopping prototype's bite: the share of the cross-section a good chop across the grain
    // removes (WORK_QUEUE item 7: the stone axe about 12 chops to past half).
    const c2 = { bite: 0.045, ...(t.chop2 ?? {}) };
    known(t.chop2 ?? {}, CHOP2_TOOL_FIELDS, `${at}.chop2`);
    inRange(c2, 'bite', 0, 1, `${at}.chop2`, true);
    return { ...t, held: t.held ?? null, heldVertical: t.heldVertical ?? t.held ?? null, swing: sw, clears, chop2: c2 };
  });
  if (!Array.isArray(data.woods)) fail('woods must be a list');
  const woodNames = new Set();
  const woods = data.woods.map((w, i) => {
    const at = typeof w?.block === 'string' ? `woods.${w.block}` : `woods[${i}]`;
    known(w, WOOD_FIELDS, at);
    const def = blocks.get(w.block);
    if (!def) fail(`${at}: no block of that name`);
    if (!def.properties?.axis) fail(`${at}: the block has no axis property (its grain)`);
    if (woodNames.has(w.block)) fail(`${at}: listed twice`);
    woodNames.add(w.block);
    inRange(w, 'fellFraction', 0, 1, at, true);
    inRange(w, 'buckFraction', 0, 1, at, true);
    // The fell wedge (Phase 55 T2; owner, 2026-11-09): a stored-ramp block (`facing`, `half`,
    // `shape`) whose ramp the stump keeps and whose upside-down ramp is the felled trunk's bottom.
    const fellWedge = w.fellWedge ?? null;
    if (fellWedge !== null) {
      const wd = blocks.get(fellWedge);
      if (!wd) fail(`${at}.fellWedge: no block named ${JSON.stringify(fellWedge)}`);
      // A `family: ramp` entry (shared/blocks: `<m>_ramp[facing, flooded, half, shape]`) or a block
      // declaring those properties itself.
      const p = wd.properties ?? {};
      const ramp = wd.family === 'ramp' || (p.facing && p.half?.includes('top') && p.half?.includes('bottom') && p.shape?.includes('ramp'));
      if (!ramp) {
        fail(`${at}.fellWedge: ${fellWedge} is not a ramp block (facing, half bottom/top, shape ramp)`);
      }
      if ((wd.support ?? 'ground') !== 'carrier') fail(`${at}.fellWedge: ${fellWedge} must be a carrier (support)`);
    }
    // How the trunk's upside-down ramp lies: `open` (the notch's upper face, meeting the stump's
    // ramp on the hinge's edge) or `matching` (parallel to it, the default: no lost half).
    const fellWedgeTrunk = w.fellWedgeTrunk ?? 'matching';
    if (!['open', 'matching'].includes(fellWedgeTrunk)) fail(`${at}.fellWedgeTrunk must be one of open, matching`);
    // The trunk's tip toward the notch as a share of the topple spin (0: none, the default).
    const fellTip = w.fellTip ?? 0;
    if (typeof fellTip !== 'number' || !(fellTip >= 0 && fellTip <= 2)) fail(`${at}.fellTip must be a number in [0, 2]`);
    if (!Array.isArray(w.buckDrops)) fail(`${at}.buckDrops must be a list`);
    const buckDrops = w.buckDrops.map((d, j) => {
      const dat = `${at}.buckDrops[${j}]`;
      known(d, DROP_FIELDS, dat);
      if (!items.has(d.item)) fail(`${dat}: no item named ${d.item}`);
      const c = d.count ?? 1;
      const [min, max] = Array.isArray(c) ? c : [c, c];
      if (!Number.isInteger(min) || !Number.isInteger(max) || min < 1 || max < min || max > 64) fail(`${dat}.count must be n or [min, max] in 1..64`);
      const chance = d.chance ?? 1;
      if (!num(chance) || chance <= 0 || chance > 1) fail(`${dat}.chance must be in (0, 1]`);
      return { item: d.item, min, max, chance };
    });
    // The chips a swing knocks out of it (the client's particles).
    const chips = validateChips(w.chips ?? {}, `${at}.chips`);
    // How a cut is carved into the cell's mesh (the client's): the cut faces' atlas tile (a tile of
    // shared/textures/materials.json) and a tint multiplying it, the notch's opening along the grain per metre of depth and
    // the kerf slits' width.
    const k = w.cut ?? {};
    known(k, CUT_FIELDS, `${at}.cut`);
    const cut = { tile: k.tile ?? null, tint: k.tint ?? '#ffffff', open: k.open ?? 2.5, kerfWidthM: k.kerfWidthM ?? 0.03 };
    if (typeof cut.tint !== 'string' || !COLOR.test(cut.tint)) fail(`${at}.cut.tint must be #rrggbb`);
    if (cut.tile !== null && !tiles.has(cut.tile)) fail(`${at}.cut.tile: no atlas tile named ${cut.tile}`);
    inRange(cut, 'open', 0.2, 8, `${at}.cut`, true);
    inRange(cut, 'kerfWidthM', 0.005, 0.2, `${at}.cut`, true);
    // Leaves shaken down from the tree's leaf blocks on each hit (the client's particles).
    const lv = { block: null, count: 0, color: '#5f9e3e', radiusM: 3, heightM: 8, ...(w.leaves ?? {}) };
    known(w.leaves ?? {}, LEAF_FIELDS, `${at}.leaves`);
    if (lv.block !== null && !blocks.has(lv.block)) fail(`${at}.leaves.block: no block named ${lv.block}`);
    if (!Number.isInteger(lv.count) || lv.count < 0 || lv.count > 32) fail(`${at}.leaves.count must be a whole number in [0, 32]`);
    if (typeof lv.color !== 'string' || !COLOR.test(lv.color)) fail(`${at}.leaves.color must be #rrggbb`);
    inRange(lv, 'radiusM', 0, 16, `${at}.leaves`, true);
    inRange(lv, 'heightM', 0, 64, `${at}.leaves`, true);
    // The standing tree sways once cut past `fromFraction`, up to `maxDeg` at the fell fraction.
    const sway = { fromFraction: 0.4, maxDeg: 0, ...(w.sway ?? {}) };
    known(w.sway ?? {}, SWAY_FIELDS, `${at}.sway`);
    inRange(sway, 'fromFraction', 0, 1, `${at}.sway`);
    inRange(sway, 'maxDeg', 0, 30, `${at}.sway`);
    if (sway.fromFraction >= w.fellFraction) fail(`${at}.sway.fromFraction must be below fellFraction`);
    // A hit's sound by how far through the wood is cut: [{ from, event }], from rising from 0.
    if (w.sounds !== undefined && !Array.isArray(w.sounds)) fail(`${at}.sounds must be a list`);
    const sounds = (w.sounds ?? []).map((x, j) => {
      const sat = `${at}.sounds[${j}]`;
      known(x, ['from', 'event'], sat);
      inRange(x, 'from', 0, 1, sat);
      return { from: x.from, event: event(x.event, `${sat}.event`) ?? fail(`${sat}.event is required`) };
    });
    sounds.forEach((x, j) => {
      if (j === 0 ? x.from !== 0 : x.from <= sounds[j - 1].from) fail(`${at}.sounds: from must start at 0 and rise`);
    });
    // The chopping prototype's rules (WORK_QUEUE item 7): it falls past `fellFraction` of the
    // section cut, a chop along the grain cuts `along` of one across it, the trunk's wedge.
    const c2 = { fellFraction: 0.5, along: 0.5, fellWedgeTrunk: 'open', ...(w.chop2 ?? {}) };
    known(w.chop2 ?? {}, CHOP2_WOOD_FIELDS, `${at}.chop2`);
    inRange(c2, 'fellFraction', 0, 1, `${at}.chop2`, true);
    inRange(c2, 'along', 0, 1, `${at}.chop2`, true);
    if (!['open', 'matching'].includes(c2.fellWedgeTrunk)) fail(`${at}.chop2.fellWedgeTrunk must be one of open, matching`);
    return { ...w, buckDrops, chips, leaves: lv, sway, sounds, cut, fellWedge, fellWedgeTrunk, fellTip, chop2: c2 };
  });
  // Blocks a break needs a tool kind for where blocks are not unlimited (`breakWith` on the block;
  // owner, 2026-11-08: logs need an axe in adventure).
  const breakWith = [];
  for (const [name, def] of blocks) {
    if (def.breakWith === undefined) continue;
    if (!KINDS.includes(def.breakWith)) fail(`${name}.breakWith must be one of ${KINDS.join(', ')}`);
    breakWith.push({ block: name, kind: def.breakWith });
  }
  const breaking = validateBreaking(data.breaking, items, blocks);
  const chop2 = { enabled: false, ...(data.chop2 ?? {}) };
  known(data.chop2 ?? {}, [...CHOP2_FIELDS, '$comment'], 'chop2');
  if (typeof chop2.enabled !== 'boolean') fail('chop2.enabled must be true or false');
  return { chop2, tools, woods, breakWith, breaking, damage: validateDamage(blocks, items, data.breaking), durability: validateDurability(data.durability, items, soundEvents) };
}

/** Validates `durability` (tools wear; owner, 2026-11-11): each listed item a tool item that stacks
 * to one, its hits a whole number in [1, 65535]; `breakSound` a sound event; `creativeWear` a bool. */
export function validateDurability(d, items, soundEvents) {
  if (d === undefined) return { creativeWear: false, breakSound: null, items: [] };
  known(d, ['$comment', 'creativeWear', 'breakSound', 'items'], 'durability');
  if (typeof d.creativeWear !== 'boolean') fail('durability.creativeWear must be true or false');
  if (d.breakSound !== undefined && !soundEvents.has(d.breakSound)) fail(`durability.breakSound: no sound event ${JSON.stringify(d.breakSound)}`);
  if (typeof d.items !== 'object' || d.items === null || Array.isArray(d.items)) fail('durability.items must map a tool item to its hits');
  const list = Object.entries(d.items).map(([item, hits]) => {
    if (!items.has(item)) fail(`durability.items: no item ${JSON.stringify(item)}`);
    if (!Number.isInteger(hits) || hits < 1 || hits > 65535) fail(`durability.items.${item}: hits must be a whole number in [1, 65535]`);
    return { item, hits };
  });
  return { creativeWear: d.creativeWear, breakSound: d.breakSound ?? null, items: list };
}

/** Validates each block's `damage` (docs/BLOCK_DAMAGE.md; owner, 2026-11-10: "Blocks will need per
 * tool and default values"): `default` the hits to destroy it with bare hands or a tool not listed
 * (null: it can't be broken so), and per tool class (`breaking.classes`' keys) or item its hits, an
 * item's over its class's. A block without `damage` breaks in one hit, as before. */
const LOOKS = ['shards', 'scoops', 'chips'];
/** A carved mark's height field (BLOCK_DAMAGE.md §6.2): a smooth bowl, or angular facets. */
const PROFILES = ['bowl', 'facets'];

/** A damage look's `cracks` against the crack tile sets (shared/textures/cracks.json): resolved to its tiles. */
export function validateCracksLook(c, at, crackSets) {
  if (c === null || typeof c !== 'object' || Array.isArray(c)) fail(`${at} must be an object`);
  known(c, ['set', 'stages', 'strength'], at);
  const tiles = crackSets.sets[c.set];
  if (typeof c.set !== 'string' || !tiles) fail(`${at}.set must be a crack set of shared/textures/cracks.json (${Object.keys(crackSets.sets).join(', ')}), not ${JSON.stringify(c.set)}`);
  if (!Array.isArray(c.stages) || c.stages.length !== tiles.length) fail(`${at}.stages must list ${tiles.length} damage fractions, one for each of set ${c.set}'s tiles`);
  c.stages.forEach((v, i) => {
    if (!(num(v) && v > 0 && v <= 1)) fail(`${at}.stages[${i}] must be a damage fraction in (0, 1]`);
    if (i > 0 && !(v > c.stages[i - 1])) fail(`${at}.stages must ascend (stage ${i} at ${v} is not past ${c.stages[i - 1]})`);
  });
  if (!(num(c.strength) && c.strength >= 0 && c.strength <= 1)) fail(`${at}.strength must be a number in [0, 1]`);
  return { set: c.set, tiles, stages: c.stages, strength: c.strength, span: crackSets.span };
}

export function validateDamage(blocks, items, breaking, crackSets = loadCracks()) {
  const classes = new Set(Object.keys(breaking?.classes ?? {}).filter((k) => k[0] !== '$'));
  const hits = (v, at) => {
    if (!(Number.isInteger(v) && v >= 1 && v <= 255)) fail(`${at} is a hit count from 1 to 255, not ${JSON.stringify(v)}`);
    return v;
  };
  const out = [];
  for (const [name, def] of blocks) {
    const d = def.damage;
    if (d === undefined) continue;
    const at = `${name}.damage`;
    if (d === null || typeof d !== 'object' || Array.isArray(d)) fail(`${at} must be an object`);
    if (!Object.hasOwn(d, 'default')) fail(`${at} needs a default (hits with bare hands; null: can't)`);
    const dflt = d.default === null ? null : hits(d.default, `${at}.default`);
    const tools = [];
    // The look of its damage (D2): shards (stone), scoops (soils) or chips (wood) at each hit mark,
    // `size` the mark's width (cells) at full damage, `color` the fresh face inside, `crack` the
    // cracks that grow with the damage, `depth` (optional, cells; default 0.1) how deep the mark is
    // shaded as cut into the face (a scoop's bowl, a shard's facets; look only). A scoop's relief,
    // computed per pixel (BLOCK_DAMAGE.md §6.1): `rim` (optional, m; default 0.012) the loose soil
    // raised round it, `parallax` (optional, steps 0–8; default 6) the texture's march into the dent
    // (0: lit only; the Low tier marches none), `darken` (optional, 0–1; default 0.35) the damp floor.
    // The carved mesh (BLOCK_DAMAGE.md §6.2, WORK_QUEUE item 18: the struck face meshed with the mark
    // cut in): `profile` (optional; `bowl` | `facets`, default bowl for scoops, facets otherwise) the
    // height field, `facets` (optional, 3–8; default 5) a shard's facets round its apex, `grid`
    // (optional, 2–16; default 8) the dent's grid per side, `triangles` (optional, 128–2048; default
    // 256) the cell's triangle budget (its struck faces share it; the grid is coarsened to fit; 128
    // fits four struck faces at the coarsest grid).
    let look = null;
    if (d.look !== undefined) {
      const lat = `${at}.look`;
      if (d.look === null || typeof d.look !== 'object' || Array.isArray(d.look)) fail(`${lat} must be an object`);
      known(d.look, ['kind', 'size', 'color', 'crack', 'depth', 'rim', 'parallax', 'darken', 'profile', 'facets', 'grid', 'triangles', 'cracks'], lat);
      if (!LOOKS.includes(d.look.kind)) fail(`${lat}.kind must be one of ${LOOKS.join(', ')}`);
      if (!(num(d.look.size) && d.look.size >= 0.05 && d.look.size <= 0.9)) fail(`${lat}.size must be a number in [0.05, 0.9]`);
      for (const c of ['color', 'crack']) if (!/^#[0-9a-f]{6}$/i.test(d.look[c] ?? '')) fail(`${lat}.${c} must be a #rrggbb colour`);
      if (d.look.depth !== undefined && !(num(d.look.depth) && d.look.depth >= 0 && d.look.depth <= 0.5)) fail(`${lat}.depth must be a number in [0, 0.5]`);
      if (d.look.rim !== undefined && !(num(d.look.rim) && d.look.rim >= 0 && d.look.rim <= 0.03)) fail(`${lat}.rim must be a number in [0, 0.03] (m)`);
      if (d.look.parallax !== undefined && !(Number.isInteger(d.look.parallax) && d.look.parallax >= 0 && d.look.parallax <= 8)) fail(`${lat}.parallax must be a whole number of steps from 0 to 8`);
      if (d.look.darken !== undefined && !(num(d.look.darken) && d.look.darken >= 0 && d.look.darken <= 1)) fail(`${lat}.darken must be a number in [0, 1]`);
      if (d.look.profile !== undefined && !PROFILES.includes(d.look.profile)) fail(`${lat}.profile must be one of ${PROFILES.join(', ')}`);
      const whole = (k, lo, hi) => {
        if (d.look[k] !== undefined && !(Number.isInteger(d.look[k]) && d.look[k] >= lo && d.look[k] <= hi)) fail(`${lat}.${k} must be a whole number from ${lo} to ${hi}`);
      };
      whole('facets', 3, 8);
      whole('grid', 2, 16);
      whole('triangles', 128, 2048);
      // The crack overlay (BLOCK_DAMAGE.md §6.3, WORK_QUEUE item 18): `cracks` (optional) `set` a
      // crack tile set of shared/textures/cracks.json, `stages` the damage fraction each of its tiles
      // starts at (ascending in (0, 1], one a tile), `strength` (0–1) how far a crack darkens the face.
      const cracks = d.look.cracks === undefined ? null : validateCracksLook(d.look.cracks, `${lat}.cracks`, crackSets);
      look = {
        ...d.look,
        cracks,
        depth: d.look.depth ?? 0.1,
        rim: d.look.rim ?? 0.012,
        parallax: d.look.parallax ?? 6,
        darken: d.look.darken ?? 0.35,
        profile: d.look.profile ?? (d.look.kind === 'scoops' ? 'bowl' : 'facets'),
        facets: d.look.facets ?? 5,
        grid: d.look.grid ?? 8,
        triangles: d.look.triangles ?? 256,
      };
    }
    // The chips a hit knocks out of it (the client's particles, sounds round 2b): stone grey
    // chips, soil clods; none: no particles.
    const chips = d.chips === undefined ? null : validateChips(d.chips, `${at}.chips`);
    for (const [k, v] of Object.entries(d)) {
      if (k === 'default' || k === 'look' || k === 'chips' || k[0] === '$') continue;
      if (!classes.has(k) && !items.has(k)) fail(`${at}.${k}: no tool class or item ${JSON.stringify(k)} (classes: ${[...classes].join(', ')})`);
      tools.push({ tool: k, hits: hits(v, `${at}.${k}`) });
    }
    out.push({ block: name, default: dflt, tools, look, chips });
  }
  return out;
}

/** Validates `breaking` (the right tool's break speed): each block in one class, every tool item
 * known with a known class and tier, every tier's speed above 0. None: no tool speeds a break. */
export function validateBreaking(b, items, blocks) {
  if (b === undefined) return { classes: [], tools: [] };
  known(b, ['tiers', 'classes', 'tools'], 'breaking');
  known(b.tiers, [...Object.keys(b.tiers ?? {})], 'breaking.tiers');
  for (const [t, v] of Object.entries(b.tiers)) {
    if (t[0] === '$') continue;
    if (!/^[a-z][a-z0-9_]*$/.test(t)) fail(`breaking.tiers.${t}: tiers are lower_snake_case`);
    if (!(num(v) && v > 0)) fail(`breaking.tiers.${t} is a speed above 0, not ${JSON.stringify(v)}`);
  }
  known(b.classes, [...Object.keys(b.classes ?? {})], 'breaking.classes');
  const classOf = new Map();
  const classes = [];
  for (const [c, list] of Object.entries(b.classes)) {
    if (c[0] === '$') continue;
    if (!/^[a-z][a-z0-9_]*$/.test(c)) fail(`breaking.classes.${c}: classes are lower_snake_case`);
    if (!Array.isArray(list)) fail(`breaking.classes.${c} is a list of block names`);
    for (const block of list) {
      if (!blocks.has(block)) fail(`breaking.classes.${c}: no block ${JSON.stringify(block)}`);
      if (classOf.has(block)) fail(`breaking.classes: ${block} is in both ${classOf.get(block)} and ${c}`);
      classOf.set(block, c);
      classes.push({ block, class: c });
    }
  }
  if (!Array.isArray(b.tools)) fail('breaking.tools must be a list');
  const seen = new Set();
  const tools = b.tools.map((t, i) => {
    const at = `breaking.tools[${i}]`;
    known(t, ['item', 'class', 'tier'], at);
    if (!items.has(t.item)) fail(`${at}: no item ${JSON.stringify(t.item)} (shared/inventory or a block)`);
    if (seen.has(t.item)) fail(`${at}: ${t.item} is listed twice`);
    seen.add(t.item);
    if (!Object.hasOwn(b.classes, t.class) || t.class[0] === '$') fail(`${at}: unknown class ${JSON.stringify(t.class)} (${Object.keys(b.classes).filter((k) => k[0] !== '$').join(', ')})`);
    if (!Object.hasOwn(b.tiers, t.tier) || t.tier[0] === '$') fail(`${at}: unknown tier ${JSON.stringify(t.tier)} (${Object.keys(b.tiers).filter((k) => k[0] !== '$').join(', ')})`);
    return { item: t.item, class: t.class, tier: t.tier, speed: b.tiers[t.tier] };
  });
  return { classes, tools };
}

