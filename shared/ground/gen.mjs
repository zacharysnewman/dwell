#!/usr/bin/env node
// Generates the ground items (docs/adr/0071-ground-items.md) for Rust from shared/ground/ground.json:
// `crates/dwell-world/src/ground.gen.rs`, read by `dwell_world::ground` (the server's scatter and
// pickup, the client's targeting and the mesher's look alike). It checks every name against the
// block registry (shared/blocks/*.json) and the inventory's items (shared/inventory/inventory.json).
// The output is checked in; CI regenerates it and fails on any diff. A bad entry fails with a
// message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { LOOK_SHAPES, loadBlocks, loadInventory, lookVariant } from '../inventory/gen.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/ground/gen.mjs from shared/ground/ground.json. Do not edit.';

const TOP_FIELDS = ['formatVersion', 'kinds', 'rules'];
const KIND_FIELDS = ['name', 'item', 'scale', 'step', 'hit'];
const RULE_FIELDS = ['kind', 'on', 'under', 'nearWall', 'density'];
const NAMESPACED = /^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$/;
const COLOR = /^#[0-9a-f]{6}$/;
/** How far a rule may look (the client's mesh jobs see this far around a chunk: `dwell_world::SKY_APRON`). */
export const MAX_ROWS = 16;
export const MAX_REACH = 6;

const fail = (m) => {
  throw new Error(`shared/ground: ${m}`);
};
const num = (v) => typeof v === 'number' && Number.isFinite(v);
const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);
const unknown = (o, fields, at) => {
  for (const k of Object.keys(o)) if (!fields.includes(k) && k[0] !== '$') fail(`${at}: unknown field ${k} (${fields.join(', ')})`);
};

/** The sound events (shared/sounds/dwell.json `events`): a kind's `step` and `hit` name one. */
export function loadSoundEvents() {
  const s = JSON.parse(readFileSync(join(root, 'shared/sounds/dwell.json'), 'utf8'));
  return new Set(Object.keys(s.events ?? {}));
}

/** Checks the ground data against the block files (`{ namespace, blocks }`) and the inventory. */
export function validateGround(data, namespaces, inventory, soundEvents = loadSoundEvents()) {
  if (!isObject(data)) fail('the file must hold an object');
  unknown(data, TOP_FIELDS, 'the file');
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  const blocks = new Set(namespaces.flatMap((ns) => ns.blocks.map((b) => `${ns.namespace}:${b.name}`)));
  const items = new Map(inventory.items.map((i) => [i.name, i]));
  const block = (name, at) => {
    if (!blocks.has(name)) fail(`${at}: ${JSON.stringify(name)} is not a block`);
  };
  if (!Array.isArray(data.kinds) || data.kinds.length === 0) fail('kinds must be a non-empty list');
  if (data.kinds.length > 255) fail('at most 255 kinds');
  const kinds = new Map();
  data.kinds.forEach((k, i) => {
    const at = `kinds.${k?.name ?? i}`;
    if (!isObject(k)) fail(`${at} must be an object`);
    unknown(k, KIND_FIELDS, at);
    if (typeof k.name !== 'string' || !NAMESPACED.test(k.name)) fail(`${at}: name must be namespace:name`);
    if (kinds.has(k.name)) fail(`${at}: listed twice`);
    // Its look is its item's (shared/inventory `look`): one look for the item wherever it is drawn.
    const item = items.get(k.item);
    if (!item) fail(`${at}: item ${JSON.stringify(k.item)} is not an inventory item`);
    const look = item.look;
    if (!look) fail(`${at}: item ${k.item} has no look (shared/inventory/inventory.json \`look\`)`);
    if (!LOOK_SHAPES.includes(look.shape)) fail(`${at}: ${k.item}'s look.shape must be one of ${LOOK_SHAPES.join(', ')}`);
    block(look.texture, `${at}: ${k.item}'s look.texture`);
    if (typeof look.color !== 'string' || !COLOR.test(look.color)) fail(`${at}: ${k.item}'s look.color must be #rrggbb`);
    const s = k.scale ?? [1, 1];
    if (!Array.isArray(s) || s.length !== 2 || !s.every((v) => num(v) && v > 0 && v <= 3) || s[0] > s[1]) fail(`${at}: scale must be [min, max] in (0, 3], min <= max`);
    // Its sounds (AUDIO.md §5): `step` as a player steps onto it, `hit` as one knocks it loose.
    for (const e of ['step', 'hit'])
      if (k[e] !== undefined && !soundEvents.has(k[e])) fail(`${at}: ${e}: no sound event ${JSON.stringify(k[e])} in shared/sounds/dwell.json's events`);
    kinds.set(k.name, { ...k, shape: look.shape, size: look.size, texture: look.texture, color: look.color, scale: s, index: i, step: k.step ?? null, hit: k.hit ?? null });
  });
  if (!Array.isArray(data.rules) || data.rules.length === 0) fail('rules must be a non-empty list');
  const rules = data.rules.map((r, i) => {
    const at = `rules[${i}]`;
    if (!isObject(r)) fail(`${at} must be an object`);
    unknown(r, RULE_FIELDS, at);
    if (!kinds.has(r.kind)) fail(`${at}: kind ${JSON.stringify(r.kind)} is not in kinds`);
    if (!Array.isArray(r.on) || r.on.length === 0) fail(`${at}: on must list the blocks it lies on`);
    r.on.forEach((b, j) => block(b, `${at}.on[${j}]`));
    let under = null;
    if (r.under !== undefined) {
      if (!isObject(r.under)) fail(`${at}.under must be an object`);
      unknown(r.under, ['blocks', 'withinRows'], `${at}.under`);
      if (!Array.isArray(r.under.blocks) || r.under.blocks.length === 0) fail(`${at}.under.blocks must list blocks`);
      r.under.blocks.forEach((b, j) => block(b, `${at}.under.blocks[${j}]`));
      const w = r.under.withinRows;
      if (!Number.isInteger(w) || w < 1 || w > MAX_ROWS) fail(`${at}.under.withinRows must be a whole number in [1, ${MAX_ROWS}]`);
      under = { blocks: r.under.blocks, withinRows: w };
    }
    let nearWall = null;
    if (r.nearWall !== undefined) {
      if (!isObject(r.nearWall)) fail(`${at}.nearWall must be an object`);
      unknown(r.nearWall, ['rows', 'reach'], `${at}.nearWall`);
      const { rows, reach } = r.nearWall;
      if (!Number.isInteger(rows) || rows < 1 || rows > MAX_ROWS) fail(`${at}.nearWall.rows must be a whole number in [1, ${MAX_ROWS}]`);
      if (!Number.isInteger(reach) || reach < 1 || reach > MAX_REACH) fail(`${at}.nearWall.reach must be a whole number in [1, ${MAX_REACH}]`);
      nearWall = { rows, reach };
    }
    if (!num(r.density) || r.density <= 0 || r.density > 1) fail(`${at}: density must be in (0, 1]`);
    return { kind: kinds.get(r.kind).index, on: r.on, under, nearWall, density: r.density };
  });
  return { kinds: [...kinds.values()], rules };
}

export function loadGround() {
  return JSON.parse(readFileSync(join(here, 'ground.json'), 'utf8'));
}

const f = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const strs = (a) => `&[${a.map((s) => JSON.stringify(s)).join(', ')}]`;
const rgb = (c) => `[${[1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16)).join(', ')}]`;

export function groundRust(d) {
  const rs = [`// ${header}`, '', 'use crate::ground::{GroundKind, GroundRule, GroundShape, NearWall, Under};', ''];
  rs.push('/// The ground items\' kinds, in data order (a kind\'s index is its id in the mesh and on the wire).');
  rs.push(`pub const KINDS: [GroundKind; ${d.kinds.length}] = [`);
  for (const k of d.kinds) {
    const shape = lookVariant(k.shape);
    rs.push(
      `    GroundKind { name: ${JSON.stringify(k.name)}, item: ${JSON.stringify(k.item)}, shape: GroundShape::${shape}, size: [${k.size.map(f).join(', ')}], texture: ${JSON.stringify(k.texture)}, color: ${rgb(k.color)}, scale: [${k.scale.map(f).join(', ')}], step: ${k.step === null ? 'None' : `Some(${JSON.stringify(k.step)})`}, hit: ${k.hit === null ? 'None' : `Some(${JSON.stringify(k.hit)})`} },`,
    );
  }
  rs.push('];', '');
  rs.push('/// The scatter\'s rules, in order: the first whose conditions hold and whose roll hits places its kind.');
  rs.push(`pub const RULES: [GroundRule; ${d.rules.length}] = [`);
  for (const r of d.rules) {
    const under = r.under ? `Some(Under { blocks: ${strs(r.under.blocks)}, within_rows: ${r.under.withinRows} })` : 'None';
    const wall = r.nearWall ? `Some(NearWall { rows: ${r.nearWall.rows}, reach: ${r.nearWall.reach} })` : 'None';
    rs.push(`    GroundRule { kind: ${r.kind}, on: ${strs(r.on)}, under: ${under}, near_wall: ${wall}, density: ${f(r.density)} },`);
  }
  rs.push('];', '');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const d = validateGround(loadGround(), loadBlocks(), loadInventory());
  writeFileSync(join(root, 'crates/dwell-world/src/ground.gen.rs'), groundRust(d));
}
