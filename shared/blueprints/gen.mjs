#!/usr/bin/env node
// Validates the blueprints' data (shared/blueprints/blueprints.json, docs/BLUEPRINTS.md) against the
// structures (shared/structures) and the creatures (shared/creatures), and emits its Rust table for
// dwell-world (`blueprint.rs`). The output is checked in; CI regenerates it and fails on a diff.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const OUT = join(root, "crates/dwell-world/src/blueprints.gen.rs");
const header =
  "Generated by shared/blueprints/gen.mjs from shared/blueprints/blueprints.json. Do not edit.";

const TOP = [
  "$comment",
  "formatVersion",
  "limits",
  "player",
  "ghost",
  "builder",
  "jobs",
  "storehouse",
  "carryLook",
  "catalog",
  "towns",
];
/** The job kinds built (B5, docs/BLUEPRINTS.md §9); `haul` (carters) and `fell` (foresters) are later phases. */
const JOB_KINDS = ["build"];
const LATER_KINDS = ["haul", "fell", "plant"];
/** A town plan blueprint's roles: an ordinary building, or the town's storehouse (built first). */
const ROLES = ["building", "storehouse"];
/** The storehouse's stock modes: `unlimited` for now; a counted stock comes with harvesting. */
const STOCKS = ["unlimited"];
const TOWN_FIELDS = {
  spacingM: [64, 100000, true],
  jitter: [0, 1, false],
  attempts: [1, 64, true],
  maxSlopeDeg: [0, 60, false],
  footprintM: [1, 256, true],
  foundM: [16, 2048, false],
  clearM: [0, 64, true],
};
const SECTIONS = {
  limits: { perWorld: [1, 1024, true] },
  player: { paceMs: [16, 5000, false], panelRows: [1, 32, true] },
  ghost: { faceCap: [64, 1_000_000, true] },
  builder: {
    paceS: [0.05, 600, false],
    reachM: [1, 16, false],
    nearM: [8, 1024, false],
    perBlueprint: [0, 8, true],
    clearMarginM: [0, 8, true],
    clearPaceS: [0.05, 600, false],
  },
  storehouse: { rangeM: [4, 1024, false], reachM: [0.5, 16, false] },
};
const JOB_FIELDS = { carryMax: [1, 255, true], waitS: [0, 600, false] };
const CARRY_FIELDS = { pieceM: [0.02, 1, false], perLayer: [1, 8, true] };

/** The block names in shared/blocks/dwell.json. */
export function loadBlockNames() {
  const j = JSON.parse(
    readFileSync(join(root, "shared/blocks/dwell.json"), "utf8"),
  );
  return new Set(j.blocks.map((b) => `${j.namespace}:${b.name}`));
}

/** The item names of shared/characters/characters.json. */
export function loadCharacterItems() {
  const j = JSON.parse(
    readFileSync(join(root, "shared/characters/characters.json"), "utf8"),
  );
  return new Set(Object.keys(j.items));
}

/** The structure names in shared/structures (and its test/ fixtures). */
export function loadStructureNames() {
  const names = new Set();
  for (const dir of ["shared/structures", "shared/structures/test"]) {
    for (const f of readdirSync(join(root, dir)).filter((n) =>
      n.endsWith(".json"),
    )) {
      const j = JSON.parse(readFileSync(join(root, dir, f), "utf8"));
      if (typeof j.name === "string" && j.kind === "voxels") names.add(j.name);
    }
  }
  return names;
}

/** The creature names in shared/creatures/creatures.json. */
export function loadCreatureNames() {
  const j = JSON.parse(
    readFileSync(join(root, "shared/creatures/creatures.json"), "utf8"),
  );
  return new Set(j.creatures.map((c) => c.name));
}

/** Validates the data, failing with a message naming the entry; returns it with its defaults. */
export function validateBlueprints(
  d,
  structures,
  creatures,
  file = "shared/blueprints/blueprints.json",
) {
  const fail = (m) => {
    throw new Error(`${file}: ${m}`);
  };
  if (typeof d !== "object" || d === null || Array.isArray(d))
    fail("must be an object");
  for (const k of Object.keys(d))
    if (!TOP.includes(k)) fail(`unknown field "${k}"`);
  if (d.formatVersion !== 1) fail("formatVersion must be 1");
  for (const [section, fields] of Object.entries(SECTIONS)) {
    const s = d[section];
    if (typeof s !== "object" || s === null || Array.isArray(s))
      fail(`${section} must be an object`);
    const allowed = [
      ...Object.keys(fields),
      ...(section === "builder" ? ["creature", "job"] : []),
      ...(section === "storehouse" ? ["stock"] : []),
    ];
    for (const k of Object.keys(s))
      if (!allowed.includes(k)) fail(`${section}: unknown field "${k}"`);
    for (const [k, [lo, hi, int]] of Object.entries(fields)) {
      const v = s[k];
      if (
        typeof v !== "number" ||
        !Number.isFinite(v) ||
        v < lo ||
        v > hi ||
        (int && !Number.isInteger(v))
      ) {
        fail(
          `${section}.${k} must be ${int ? "an integer" : "a number"} in ${lo}..${hi} (got ${JSON.stringify(v)})`,
        );
      }
    }
  }
  if (!creatures.has(d.builder.creature))
    fail(
      `builder.creature: unknown creature ${JSON.stringify(d.builder.creature)} (shared/creatures)`,
    );
  validateJobs(d, fail);
  if (!STOCKS.includes(d.storehouse.stock))
    fail(
      `storehouse.stock must be one of ${STOCKS.join(", ")} (a counted stock comes with harvesting; got ${JSON.stringify(d.storehouse.stock)})`,
    );
  validateCarryLook(d.carryLook, fail);
  if (!Array.isArray(d.catalog))
    fail("catalog must be a list of structure names");
  const seen = new Set();
  d.catalog.forEach((n, i) => {
    if (!structures.has(n))
      fail(
        `catalog[${i}]: unknown structure ${JSON.stringify(n)} (shared/structures)`,
      );
    if (seen.has(n)) fail(`catalog[${i}]: ${n} twice`);
    seen.add(n);
  });
  const t = d.towns;
  if (typeof t !== "object" || t === null || Array.isArray(t))
    fail("towns must be an object");
  for (const k of Object.keys(t))
    if (![...Object.keys(TOWN_FIELDS), "heightM", "plans", "map"].includes(k))
      fail(`towns: unknown field "${k}"`);
  validateTownMap(t.map, fail);
  for (const [k, [lo, hi, int]] of Object.entries(TOWN_FIELDS)) {
    const v = t[k];
    if (
      typeof v !== "number" ||
      !Number.isFinite(v) ||
      v < lo ||
      v > hi ||
      (int && !Number.isInteger(v))
    ) {
      fail(
        `towns.${k} must be ${int ? "an integer" : "a number"} in ${lo}..${hi} (got ${JSON.stringify(v)})`,
      );
    }
  }
  if (
    !Array.isArray(t.heightM) ||
    t.heightM.length !== 2 ||
    !t.heightM.every(Number.isFinite) ||
    t.heightM[0] > t.heightM[1]
  ) {
    fail("towns.heightM must be [min, max] m");
  }
  if (!Array.isArray(t.plans) || t.plans.length === 0)
    fail("towns.plans must be a non-empty list");
  const names = new Set();
  t.plans.forEach((p, i) => {
    const at = `towns.plans[${i}]`;
    if (typeof p.name !== "string" || !/^[a-z0-9_]+:[a-z0-9_]+$/.test(p.name))
      fail(`${at}.name must be namespace:name`);
    if (names.has(p.name)) fail(`${at}: ${p.name} twice`);
    names.add(p.name);
    for (const k of Object.keys(p))
      if (!["name", "weight", "blueprints"].includes(k))
        fail(`${at}: unknown field "${k}"`);
    if (!Number.isInteger(p.weight) || p.weight < 1)
      fail(`${at}.weight must be a positive integer`);
    if (!Array.isArray(p.blueprints) || p.blueprints.length === 0)
      fail(`${at}.blueprints must be a non-empty list`);
    p.blueprints.forEach((b, j) => {
      const bat = `${at}.blueprints[${j}]`;
      for (const k of Object.keys(b))
        if (!["structure", "at", "turn", "role"].includes(k))
          fail(`${bat}: unknown field "${k}"`);
      if (b.role !== undefined && !ROLES.includes(b.role))
        fail(`${bat}.role must be one of ${ROLES.join(", ")}`);
      if (b.role === "storehouse" && j !== 0)
        fail(
          `${bat}: the storehouse must be the plan's first blueprint (it is built first)`,
        );
      if (!structures.has(b.structure))
        fail(
          `${bat}: unknown structure ${JSON.stringify(b.structure)} (shared/structures)`,
        );
      if (
        !Array.isArray(b.at) ||
        b.at.length !== 2 ||
        !b.at.every(Number.isInteger) ||
        b.at.some((v) => Math.abs(v) > t.footprintM)
      ) {
        fail(`${bat}.at must be [x, z] whole metres within footprintM`);
      }
      if (![0, 1, 2, 3].includes(b.turn)) fail(`${bat}.turn must be 0..3`);
    });
  });
  return d;
}

/** The jobs (B5): each a name, a kind of the built ones, its carry; `builder.job` names one. */
function validateJobs(d, fail) {
  if (!Array.isArray(d.jobs) || d.jobs.length === 0)
    fail("jobs must be a non-empty list");
  const names = new Set();
  d.jobs.forEach((j, i) => {
    const at = `jobs[${i}]`;
    if (typeof j !== "object" || j === null) fail(`${at} must be an object`);
    for (const k of Object.keys(j))
      if (
        !["name", "kind", "mixedLoads", ...Object.keys(JOB_FIELDS)].includes(k)
      )
        fail(`${at}: unknown field "${k}"`);
    if (typeof j.name !== "string" || !/^[a-z0-9_]+:[a-z0-9_]+$/.test(j.name))
      fail(`${at}.name must be namespace:name`);
    if (names.has(j.name)) fail(`${at}: ${j.name} twice`);
    names.add(j.name);
    if (LATER_KINDS.includes(j.kind))
      fail(
        `${at}.kind ${JSON.stringify(j.kind)} is a later phase (docs/BLUEPRINTS.md §9); built: ${JOB_KINDS.join(", ")}`,
      );
    if (!JOB_KINDS.includes(j.kind))
      fail(
        `${at}.kind must be one of ${JOB_KINDS.join(", ")} (got ${JSON.stringify(j.kind)})`,
      );
    if (typeof j.mixedLoads !== "boolean")
      fail(`${at}.mixedLoads must be true or false`);
    for (const [k, [lo, hi, int]] of Object.entries(JOB_FIELDS)) {
      const v = j[k];
      if (
        typeof v !== "number" ||
        !Number.isFinite(v) ||
        v < lo ||
        v > hi ||
        (int && !Number.isInteger(v))
      ) {
        fail(
          `${at}.${k} must be ${int ? "an integer" : "a number"} in ${lo}..${hi} (got ${JSON.stringify(v)})`,
        );
      }
    }
  });
  if (!names.has(d.builder.job))
    fail(`builder.job: unknown job ${JSON.stringify(d.builder.job)} (jobs)`);
}

/** How a carried load shows (`carryLook`): a characters item, a model joint, its layers. */
function validateCarryLook(c, fail) {
  if (typeof c !== "object" || c === null || Array.isArray(c))
    fail("carryLook must be an object");
  for (const k of Object.keys(c))
    if (
      !["item", "joint", "at", "kinds", ...Object.keys(CARRY_FIELDS)].includes(
        k,
      )
    )
      fail(`carryLook: unknown field "${k}"`);
  if (!loadCharacterItems().has(c.item))
    fail(
      `carryLook.item: unknown item ${JSON.stringify(c.item)} (shared/characters items)`,
    );
  if (typeof c.joint !== "string" || c.joint === "")
    fail("carryLook.joint must be a joint name of the NPCs' model");
  if (
    !Array.isArray(c.at) ||
    c.at.length !== 3 ||
    !c.at.every((v) => Number.isFinite(v) && Math.abs(v) <= 2)
  )
    fail("carryLook.at must be [x, y, z] m within 2 m");
  const fields = (o, at) => {
    for (const [k, [lo, hi, int]] of Object.entries(CARRY_FIELDS)) {
      const v = o[k];
      if (
        typeof v !== "number" ||
        !Number.isFinite(v) ||
        v < lo ||
        v > hi ||
        (int && !Number.isInteger(v))
      ) {
        fail(
          `${at}.${k} must be ${int ? "an integer" : "a number"} in ${lo}..${hi} (got ${JSON.stringify(v)})`,
        );
      }
    }
  };
  fields(c, "carryLook");
  if (!Array.isArray(c.kinds)) fail("carryLook.kinds must be a list");
  const blocks = loadBlockNames();
  const seen = new Set();
  c.kinds.forEach((k, i) => {
    const at = `carryLook.kinds[${i}]`;
    for (const f of Object.keys(k))
      if (!["block", ...Object.keys(CARRY_FIELDS)].includes(f))
        fail(`${at}: unknown field "${f}"`);
    if (!blocks.has(k.block))
      fail(
        `${at}.block: unknown block ${JSON.stringify(k.block)} (shared/blocks)`,
      );
    if (seen.has(k.block)) fail(`${at}: ${k.block} twice`);
    seen.add(k.block);
    fields(k, at);
  });
}

/** The towns' map rules (`towns.map`; the shell's `mapTowns.ts`): the shrines' map rules' shape. */
function validateTownMap(m, fail) {
  if (typeof m !== "object" || m === null || Array.isArray(m))
    fail("towns.map must be an object");
  const known = [
    "reveal",
    "icon",
    "color",
    "buildingColor",
    "iconPx",
    "clusterPx",
    "siteMsPerDraw",
  ];
  for (const k of Object.keys(m))
    if (!known.includes(k)) fail(`towns.map: unknown field "${k}"`);
  if (!["explored", "all"].includes(m.reveal))
    fail("towns.map.reveal must be explored or all");
  const icons = JSON.parse(
    readFileSync(join(root, "shared/ui/markers.json"), "utf8"),
  ).icons;
  if (!icons.some((i) => i.id === m.icon))
    fail(
      `towns.map.icon ${JSON.stringify(m.icon)} is not an icon of shared/ui/markers.json`,
    );
  for (const k of ["color", "buildingColor"])
    if (!/^#[0-9a-fA-F]{6}$/.test(m[k] ?? ""))
      fail(`towns.map.${k} must be #rrggbb`);
  if (!(Number.isInteger(m.iconPx) && m.iconPx >= 3 && m.iconPx <= 32))
    fail("towns.map.iconPx must be a whole number in [3, 32]");
  if (
    !(
      Number.isInteger(m.clusterPx) &&
      m.clusterPx >= m.iconPx &&
      m.clusterPx <= 256
    )
  )
    fail("towns.map.clusterPx must be a whole number from iconPx to 256");
  if (
    !(
      typeof m.siteMsPerDraw === "number" &&
      m.siteMsPerDraw >= 1 &&
      m.siteMsPerDraw <= 100
    )
  )
    fail("towns.map.siteMsPerDraw must be a number in [1, 100]");
}

const num = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust table (types in dwell-world `blueprint.rs`). */
export function rust(d) {
  return [
    `// ${header}`,
    "",
    "pub const SHIPPED: Rules = Rules {",
    `    per_world: ${d.limits.perWorld},`,
    `    player_pace_ms: ${num(d.player.paceMs)},`,
    `    panel_rows: ${d.player.panelRows},`,
    `    ghost_face_cap: ${d.ghost.faceCap},`,
    `    builder: BuilderRules { creature: ${JSON.stringify(d.builder.creature)}, pace_s: ${num(d.builder.paceS)}, reach_m: ${num(d.builder.reachM)}, near_m: ${num(d.builder.nearM)}, per_blueprint: ${d.builder.perBlueprint}, job: ${JSON.stringify(d.builder.job)}, clear_margin_m: ${d.builder.clearMarginM}, clear_pace_s: ${num(d.builder.clearPaceS)} },`,
    `    jobs: &[${d.jobs.map((j) => `JobRules { name: ${JSON.stringify(j.name)}, kind: JobKind::${j.kind[0].toUpperCase()}${j.kind.slice(1)}, carry_max: ${j.carryMax}, mixed_loads: ${j.mixedLoads}, wait_s: ${num(j.waitS)} }`).join(", ")}],`,
    `    storehouse: StorehouseRules { stock: StockMode::${d.storehouse.stock[0].toUpperCase()}${d.storehouse.stock.slice(1)}, range_m: ${num(d.storehouse.rangeM)}, reach_m: ${num(d.storehouse.reachM)} },`,
    `    carry_look: CarryLook { item: ${JSON.stringify(d.carryLook.item)}, joint: ${JSON.stringify(d.carryLook.joint)}, at: [${d.carryLook.at.map(num).join(", ")}], piece_m: ${num(d.carryLook.pieceM)}, per_layer: ${d.carryLook.perLayer}, kinds: &[${d.carryLook.kinds.map((k) => `CarryKind { block: ${JSON.stringify(k.block)}, piece_m: ${num(k.pieceM)}, per_layer: ${k.perLayer} }`).join(", ")}] },`,
    `    catalog: &[${d.catalog.map((n) => JSON.stringify(n)).join(", ")}],`,
    `    towns: TownRules { spacing_m: ${d.towns.spacingM}, jitter: ${num(d.towns.jitter)}, attempts: ${d.towns.attempts}, height_m: [${num(d.towns.heightM[0])}, ${num(d.towns.heightM[1])}], max_slope_deg: ${num(d.towns.maxSlopeDeg)}, footprint_m: ${d.towns.footprintM}, found_m: ${num(d.towns.foundM)}, clear_m: ${d.towns.clearM}, plans: &[${d.towns.plans
      .map(
        (p) =>
          `TownPlan { name: ${JSON.stringify(p.name)}, weight: ${p.weight}, blueprints: &[${p.blueprints
            .map(
              (b) =>
                `PlanBlueprint { structure: ${JSON.stringify(b.structure)}, at: [${b.at[0]}, ${b.at[1]}], turn: ${b.turn}, role: Role::${b.role === "storehouse" ? "Storehouse" : "Building"} }`,
            )
            .join(", ")}] }`,
      )
      .join(", ")}] },`,
    "};",
    "",
  ].join("\n");
}

export function generate() {
  const d = JSON.parse(readFileSync(join(here, "blueprints.json"), "utf8"));
  return [
    [
      OUT,
      rust(validateBlueprints(d, loadStructureNames(), loadCreatureNames())),
    ],
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [path, text] of generate()) writeFileSync(path, text);
  console.log(
    "shared/blueprints: wrote crates/dwell-world/src/blueprints.gen.rs",
  );
}
