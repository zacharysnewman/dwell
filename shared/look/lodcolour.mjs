#!/usr/bin/env node
// Generates the LOD colour's riser makeup (ARCHITECTURE.md §6.6 'Colour') for Rust
// (crates/dwell-look/src/lodcolour.gen.rs) from shared/look/lodcolour.json, after validating it: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/lodcolour.mjs from shared/look/lodcolour.json. Do not edit.';

const fail = (m) => {
  throw new Error(`lodcolour.json: ${m}`);
};

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

function checkKeys(where, o, keys) {
  if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`${where} must be an object`);
  for (const k of Object.keys(o)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in o)) fail(`missing entry ${where}.${k}`);
}

/** Checks the makeup; returns it. Throws naming the entry. */
export function validateLodColour(data) {
  checkKeys('(root)', data, ['gradientStep', 'rise']);
  checkNumber('gradientStep', data.gradientStep, 0.001, 1);
  if (!Array.isArray(data.rise) || data.rise.length === 0) fail('rise must be a non-empty array');
  let last = -Infinity;
  data.rise.forEach((p, i) => {
    const at = `rise[${i}]`;
    checkKeys(at, p, ['gradient', 'top', 'fringe']);
    checkNumber(`${at}.gradient`, p.gradient, 0, 100);
    if (p.gradient <= last) fail(`${at}.gradient must be greater than the point before's (${last})`);
    last = p.gradient;
    checkNumber(`${at}.top`, p.top, 0, 1);
    checkNumber(`${at}.fringe`, p.fringe, 0, 1);
    if (p.top + p.fringe > 1 + 1e-9) fail(`${at}: top + fringe must be at most 1, got ${p.top + p.fringe}`);
  });
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for a validated makeup. */
export function lodColourRust(data) {
  const rs = [`// ${header}`, '', 'use crate::lod_colour::*;', ''];
  rs.push("/// The LOD risers' makeup by gradient (shared/look/lodcolour.json).");
  rs.push('pub const LOD_COLOUR: LodColourTunables = LodColourTunables {');
  rs.push(`    gradient_step: ${rf(data.gradientStep)},`);
  rs.push('    rise: &[');
  for (const p of data.rise) {
    rs.push(`        RisePoint { gradient: ${rf(p.gradient)}, top: ${rf(p.top)}, fringe: ${rf(p.fringe)} },`);
  }
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateLodColour(JSON.parse(readFileSync(join(here, 'lodcolour.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/lodcolour.gen.rs'), lodColourRust(data));
  console.log('look: LOD colour makeup generated');
}
