#!/usr/bin/env node
// Generates the waterfalls' looks (docs/WATER_SURFACE_GRID.md §2e, G6) for Rust
// (crates/dwell-look/src/waterfalls.gen.rs) from shared/look/waterfalls.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff. A liquid is named by its registry fluid (`dwell:water`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/waterfalls.mjs from shared/look/waterfalls.json. Do not edit.';

const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
const COLOR = /^#[0-9a-fA-F]{6}$/;

const fail = (m) => {
  throw new Error(`waterfalls.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, { open = false, whole = false } = {}) {
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (whole && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkColor(where, v) {
  if (typeof v !== 'string' || !COLOR.test(v)) fail(`${where} must be #rrggbb, got ${JSON.stringify(v)}`);
}

const PARTS = {
  sheet: {
    opacityThin: [0, 1],
    opacityFull: [0, 1, { open: true }],
    streaksPerM: [0, 64],
    scroll: [0, 8],
    segments: [1, 32, { whole: true }],
  },
  foam: { opacity: [0, 1], radiusM: [0, 8] },
  spray: {
    count: [0, 64, { whole: true }],
    cpuCount: [0, 64, { whole: true }],
    sizeM: [0.01, 2],
    heightM: [0, 16],
    lifeS: [0.1, 10],
    opacity: [0, 1],
  },
};
const COLORS = { sheet: ['color'], foam: ['color'], spray: ['color'] };

/** One liquid's falls look, checked: throws naming the bad entry. */
export function checkLiquid(name, l) {
  const at = `liquids.${name}`;
  if (!NAME.test(name)) fail(`${at}: the name must be \`namespace:name\` (lowercase, digits, _)`);
  checkKeys(at, l, Object.keys(PARTS));
  for (const [part, numbers] of Object.entries(PARTS)) {
    const p = l[part];
    checkKeys(`${at}.${part}`, p, [...Object.keys(numbers), ...(COLORS[part] ?? [])]);
    for (const [k, [lo, hi, o]] of Object.entries(numbers)) checkNumber(`${at}.${part}.${k}`, p[k], lo, hi, o);
    for (const k of COLORS[part] ?? []) checkColor(`${at}.${part}.${k}`, p[k]);
  }
  if (l.sheet.opacityFull < l.sheet.opacityThin) fail(`${at}.sheet.opacityFull must be at least sheet.opacityThin`);
  if (l.spray.cpuCount > l.spray.count) fail(`${at}.spray.cpuCount must be at most spray.count`);
  return l;
}

export function liquidNames(data) {
  return Object.keys(data.liquids).filter((k) => k !== '$comment');
}

/** Checks the data; returns it. */
export function validateWaterfalls(data) {
  checkKeys('the file', data, ['drawM', 'maxFalls', 'refreshS', 'liquids']);
  checkNumber('drawM', data.drawM, 4, 512);
  checkNumber('maxFalls', data.maxFalls, 1, 256, { whole: true });
  checkNumber('refreshS', data.refreshS, 0.02, 5);
  if (typeof data.liquids !== 'object' || data.liquids === null || Array.isArray(data.liquids)) {
    fail('liquids must be an object');
  }
  for (const n of liquidNames(data)) checkLiquid(n, data.liquids[n]);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const hex = (c) => `0x${c.replace('#', '').toLowerCase()}`;

/** The Rust source for validated data. */
export function waterfallsRust(data) {
  const rows = liquidNames(data).map((n) => {
    const { sheet: s, foam: f, spray: p } = data.liquids[n];
    return [
      '    FallLook {',
      `        fluid: ${JSON.stringify(n)},`,
      `        sheet_color: ${hex(s.color)},`,
      `        sheet_opacity_thin: ${rf(s.opacityThin)},`,
      `        sheet_opacity_full: ${rf(s.opacityFull)},`,
      `        sheet_streaks_per_m: ${rf(s.streaksPerM)},`,
      `        sheet_scroll: ${rf(s.scroll)},`,
      `        sheet_segments: ${s.segments},`,
      `        foam_color: ${hex(f.color)},`,
      `        foam_opacity: ${rf(f.opacity)},`,
      `        foam_radius_m: ${rf(f.radiusM)},`,
      `        spray_count: ${p.count},`,
      `        spray_cpu_count: ${p.cpuCount},`,
      `        spray_size_m: ${rf(p.sizeM)},`,
      `        spray_height_m: ${rf(p.heightM)},`,
      `        spray_life_s: ${rf(p.lifeS)},`,
      `        spray_color: ${hex(p.color)},`,
      `        spray_opacity: ${rf(p.opacity)},`,
      '    },',
    ].join('\n');
  });
  return [
    `// ${header}`,
    '',
    'use crate::waterfalls::{FallLook, WaterfallTunables};',
    '',
    "/// The waterfalls' tunables (shared/look/waterfalls.json).",
    'pub const WATERFALLS: WaterfallTunables = WaterfallTunables {',
    `    draw_m: ${rf(data.drawM)},`,
    `    max_falls: ${data.maxFalls},`,
    `    refresh_s: ${rf(data.refreshS)},`,
    '};',
    '',
    "/// The liquids' falls looks, by fluid name.",
    `pub static FALL_LOOKS: [FallLook; ${rows.length}] = [`,
    ...rows,
    '];',
    '',
  ].join('\n');
}

export function loadWaterfalls() {
  return validateWaterfalls(JSON.parse(readFileSync(join(here, 'waterfalls.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/waterfalls.gen.rs'), waterfallsRust(loadWaterfalls()));
  console.log('look: waterfalls generated');
}
