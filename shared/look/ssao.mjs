#!/usr/bin/env node
// Generates the screen-space ambient occlusion's looks (docs/SSAO.md) for Rust
// (crates/dwell-look/src/ssao.gen.rs) from shared/look/ssao.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/ssao.mjs from shared/look/ssao.json. Do not edit.';

/** The most samples a texel may take (the pass's loop bound). */
export const MAX_SAMPLES = 32;
/** The most blur taps each way. */
export const MAX_BLUR = 6;
export const TIERS = ['high', 'low'];

const fail = (m) => {
  throw new Error(`ssao.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, [lo, hi, kind]) {
  const open = kind === 'open';
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (kind === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

const TOP = {
  radius: [0, 8, 'open'],
  intensity: [0, 8],
  bias: [0, 1],
  strength: [0, 1],
  baked: [0, 1],
  maxPixels: [4, 512, 'count'],
  nearFrom: [0, 100],
  nearTo: [0, 100],
  farFrom: [1, 2000],
  farTo: [1, 2000],
  blurRadius: [0, MAX_BLUR, 'count'],
  blurSharpness: [0, 1, 'open'],
};
const TIER = { scale: [0, 1, 'open'], samples: [4, MAX_SAMPLES, 'count'] };

/** Checks the data; returns it. */
export function validateSsao(data) {
  checkKeys('the file', data, [...Object.keys(TOP), 'tiers']);
  for (const [k, spec] of Object.entries(TOP)) checkValue(k, data[k], spec);
  if (data.nearTo < data.nearFrom) fail('nearTo must be at least nearFrom');
  if (data.farTo <= data.farFrom) fail('farTo must be past farFrom');
  if (data.farFrom <= data.nearTo) fail('farFrom must be past nearTo');
  checkKeys('tiers', data.tiers, TIERS);
  for (const t of TIERS) {
    checkKeys(`tiers.${t}`, data.tiers[t], Object.keys(TIER));
    for (const [k, spec] of Object.entries(TIER)) checkValue(`tiers.${t}.${k}`, data.tiers[t][k], spec);
  }
  const [lo, hi] = [data.tiers.low, data.tiers.high];
  if (lo.scale > hi.scale || lo.samples > hi.samples) fail('tiers.low must cost no more than tiers.high (scale and samples)');
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const tierRust = (t) => `SsaoTier {\n    scale: ${rf(t.scale)},\n    samples: ${t.samples},\n}`;

/** The Rust source for validated data. */
export function ssaoRust(data) {
  const look = [
    ['radius', rf(data.radius)],
    ['intensity', rf(data.intensity)],
    ['bias', rf(data.bias)],
    ['strength', rf(data.strength)],
    ['baked', rf(data.baked)],
    ['max_pixels', rf(data.maxPixels)],
    ['near_from', rf(data.nearFrom)],
    ['near_to', rf(data.nearTo)],
    ['far_from', rf(data.farFrom)],
    ['far_to', rf(data.farTo)],
    ['blur_radius', `${data.blurRadius}`],
    ['blur_sharpness', rf(data.blurSharpness)],
  ];
  return [
    `// ${header}`,
    '',
    'use crate::ssao::*;',
    '',
    '/// The most samples a texel may take.',
    `pub const MAX_SAMPLES: u32 = ${MAX_SAMPLES};`,
    '/// The most blur taps each way.',
    `pub const MAX_BLUR: u32 = ${MAX_BLUR};`,
    '',
    '/// The look (every entry but `tiers`).',
    `pub const SSAO: SsaoLook = SsaoLook {\n${look.map(([k, v]) => `    ${k}: ${v},`).join('\n')}\n};`,
    '',
    '/// The High and Low tiers (`tiers`).',
    `pub const HIGH: SsaoTier = ${tierRust(data.tiers.high)};`,
    `pub const LOW: SsaoTier = ${tierRust(data.tiers.low)};`,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateSsao(JSON.parse(readFileSync(join(here, 'ssao.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/ssao.gen.rs'), ssaoRust(data));
  console.log('look: ssao generated');
}
