#!/usr/bin/env node
// Generates the water flow looks (docs/WATER_SURFACE_GRID.md §2c, G3d) for Rust
// (crates/dwell-look/src/waterflow.gen.rs) from shared/look/waterflow.json, after validating them:
// an unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff. A liquid is named by its registry fluid (`dwell:water`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/waterflow.mjs from shared/look/waterflow.json. Do not edit.';

const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
const COLOR = /^#[0-9a-fA-F]{6}$/;

const fail = (m) => {
  throw new Error(`waterflow.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, { open = false, whole = false } = {}) {
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (whole && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkColor(where, v) {
  if (typeof v !== 'string' || !COLOR.test(v)) fail(`${where} must be #rrggbb, got ${JSON.stringify(v)}`);
}

const PARTS = {
  ripples: { advect: [0, 4], cycleS: [0.1, 30, { open: true }] },
  foam: {
    fromMs: [0, 20],
    toMs: [0, 20, { open: true }],
    strength: [0, 1],
    lengthM: [0.1, 64],
    widthM: [0.01, 16],
  },
  particles: {
    count: [0, 1024, { whole: true }],
    cpuCount: [0, 1024, { whole: true }],
    fromMs: [0, 20],
    sizeM: [0.005, 1],
    lifeS: [0.1, 120],
    radiusM: [1, 128],
  },
};
const COLORS = { foam: ['color'], particles: ['color'] };

/** One liquid's flow look, checked: throws naming the bad entry. */
export function checkLiquid(name, l) {
  const at = `liquids.${name}`;
  if (!NAME.test(name)) fail(`${at}: the name must be \`namespace:name\` (lowercase, digits, _)`);
  checkKeys(at, l, Object.keys(PARTS));
  for (const [part, numbers] of Object.entries(PARTS)) {
    const p = l[part];
    checkKeys(`${at}.${part}`, p, [...Object.keys(numbers), ...(COLORS[part] ?? [])]);
    for (const [k, [lo, hi, o]] of Object.entries(numbers)) checkNumber(`${at}.${part}.${k}`, p[k], lo, hi, o);
    for (const k of COLORS[part] ?? []) checkColor(`${at}.${part}.${k}`, p[k]);
  }
  if (l.foam.toMs <= l.foam.fromMs) fail(`${at}.foam.toMs must be above foam.fromMs`);
  if (l.particles.cpuCount > l.particles.count) fail(`${at}.particles.cpuCount must be at most count`);
  return l;
}

/** Checks the data; returns it. */
export function validateWaterFlow(data) {
  checkKeys('the file', data, ['windowColumns', 'rangeMs', 'fadeFromM', 'fadeToM', 'liquids']);
  checkNumber('windowColumns', data.windowColumns, 16, 1024, { whole: true });
  if ((data.windowColumns & (data.windowColumns - 1)) !== 0) fail('windowColumns must be a power of two');
  checkNumber('rangeMs', data.rangeMs, 0.5, 50);
  checkNumber('fadeFromM', data.fadeFromM, 0, 512);
  checkNumber('fadeToM', data.fadeToM, 1, 512);
  if (data.fadeToM <= data.fadeFromM) fail('fadeToM must be above fadeFromM');
  if (data.fadeToM > data.windowColumns / 2) fail('fadeToM must be within half the window (windowColumns / 2)');
  if (typeof data.liquids !== 'object' || data.liquids === null || Array.isArray(data.liquids)) {
    fail('liquids must be an object');
  }
  for (const n of liquidNames(data)) checkLiquid(n, data.liquids[n]);
  return data;
}

export function liquidNames(data) {
  return Object.keys(data.liquids).filter((k) => k !== '$comment');
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const hex = (c) => `0x${c.replace('#', '').toLowerCase()}`;

/** The Rust source for validated data. */
export function waterFlowRust(data) {
  const rows = liquidNames(data).map((n) => {
    const { ripples: r, foam: f, particles: p } = data.liquids[n];
    return [
      '    LiquidFlowLook {',
      `        fluid: ${JSON.stringify(n)},`,
      `        advect: ${rf(r.advect)},`,
      `        cycle_s: ${rf(r.cycleS)},`,
      `        foam_from_ms: ${rf(f.fromMs)},`,
      `        foam_to_ms: ${rf(f.toMs)},`,
      `        foam_color: ${hex(f.color)},`,
      `        foam_strength: ${rf(f.strength)},`,
      `        foam_length_m: ${rf(f.lengthM)},`,
      `        foam_width_m: ${rf(f.widthM)},`,
      `        particle_count: ${p.count},`,
      `        particle_cpu_count: ${p.cpuCount},`,
      `        particle_from_ms: ${rf(p.fromMs)},`,
      `        particle_size_m: ${rf(p.sizeM)},`,
      `        particle_color: ${hex(p.color)},`,
      `        particle_life_s: ${rf(p.lifeS)},`,
      `        particle_radius_m: ${rf(p.radiusM)},`,
      '    },',
    ].join('\n');
  });
  return [
    `// ${header}`,
    '',
    'use crate::waterflow::{LiquidFlowLook, WaterFlowTunables};',
    '',
    "/// The flow looks' tunables (shared/look/waterflow.json).",
    'pub const WATER_FLOW: WaterFlowTunables = WaterFlowTunables {',
    `    window_columns: ${data.windowColumns},`,
    `    range_ms: ${rf(data.rangeMs)},`,
    `    fade_from_m: ${rf(data.fadeFromM)},`,
    `    fade_to_m: ${rf(data.fadeToM)},`,
    '};',
    '',
    "/// The liquids' flow looks, by fluid name.",
    `pub static LIQUID_FLOWS: [LiquidFlowLook; ${rows.length}] = [`,
    ...rows,
    '];',
    '',
  ].join('\n');
}

export function loadWaterFlow() {
  return validateWaterFlow(JSON.parse(readFileSync(join(here, 'waterflow.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/waterflow.gen.rs'), waterFlowRust(loadWaterFlow()));
  console.log('look: water flow generated');
}
