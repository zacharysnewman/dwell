#!/usr/bin/env node
// Generates the loading screen's tunables (ARCHITECTURE.md §6.3) for Rust
// (crates/dwell-game/src/loading.gen.rs: the near ring, the timeout and the respawn preload),
// for the server (crates/dwell-sim/src/respawn_preload.gen.rs: the respawn preload) and for the
// shell (client/src/ui/loading.gen.ts: the fade in from white and the start's stages) from
// shared/look/loading.json,
// after validating them: an
// unknown, missing or out-of-range entry fails with its path named, and the near ring may not reach
// past the server's streamed view (shared/protocol/constants.json's viewRadiusChunks). The output is
// checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/loading.mjs from shared/look/loading.json. Do not edit.';

/** The server's streamed view radius (chunks): the near ring's largest radius. */
export const VIEW_RADIUS_CHUNKS = JSON.parse(
  readFileSync(join(root, 'shared/protocol/constants.json'), 'utf8'),
).world.viewRadiusChunks;

const fail = (m) => {
  throw new Error(`loading.json: ${m}`);
};

/** Checks the tunables; returns them. Throws naming the entry. */
export function validateLoading(data, viewRadius = VIEW_RADIUS_CHUNKS) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  const keys = ['radiusChunks', 'timeoutS', 'respawnPreload', 'fade', 'estimate', 'stages'];
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry ${k}`);
  const r = data.radiusChunks;
  if (!Number.isInteger(r) || r < 0 || r > viewRadius) {
    fail(
      `radiusChunks must be a whole number in [0, ${viewRadius}] (the server streams chunks unasked within viewRadiusChunks), got ${JSON.stringify(r)}`,
    );
  }
  const t = data.timeoutS;
  if (typeof t !== 'number' || !Number.isFinite(t) || t < 1 || t > 600) {
    fail(`timeoutS must be a number in [1, 600], got ${JSON.stringify(t)}`);
  }
  validateRespawnPreload(data.respawnPreload, viewRadius);
  validateFade(data.fade);
  validateStages(data.stages);
  validateEstimate(data.estimate, data.stages);
  return data;
}

/** Checks the respawn preload's entry (`respawnPreload`). Throws naming the entry. */
function validateRespawnPreload(p, viewRadius) {
  if (typeof p !== 'object' || p === null || Array.isArray(p)) fail('respawnPreload must be an object');
  const keys = ['enabled', 'radiusChunks'];
  for (const k of Object.keys(p)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry respawnPreload.${k}`);
  for (const k of keys) if (!(k in p)) fail(`missing entry respawnPreload.${k}`);
  if (typeof p.enabled !== 'boolean') fail(`respawnPreload.enabled must be true or false, got ${JSON.stringify(p.enabled)}`);
  const r = p.radiusChunks;
  if (!Number.isInteger(r) || r < 0 || r > viewRadius) {
    fail(
      `respawnPreload.radiusChunks must be a whole number in [0, ${viewRadius}] (a second view no larger than the first), got ${JSON.stringify(r)}`,
    );
  }
}

/** fade's entries: [min, max] seconds or a number range, or 'color' (#rrggbb). */
const FADE = {
  color: 'color',
  holdS: [0, 2],
  durationS: [0, 5],
  easePower: [1, 8],
  cpuDurationS: [0, 5],
  reducedMotionDurationS: [0, 5],
};

function validateFade(f) {
  if (typeof f !== 'object' || f === null || Array.isArray(f)) fail('fade must be an object');
  for (const k of Object.keys(f)) if (k !== '$comment' && !(k in FADE)) fail(`unknown entry fade.${k}`);
  for (const [k, spec] of Object.entries(FADE)) {
    if (!(k in f)) fail(`missing entry fade.${k}`);
    const v = f[k];
    if (spec === 'color') {
      if (typeof v !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v)) {
        fail(`fade.${k} must be a #rrggbb colour, got ${JSON.stringify(v)}`);
      }
    } else if (typeof v !== 'number' || !Number.isFinite(v) || v < spec[0] || v > spec[1]) {
      fail(`fade.${k} must be a number in [${spec[0]}, ${spec[1]}], got ${JSON.stringify(v)}`);
    }
  }
  if (f.cpuDurationS > f.durationS || f.reducedMotionDurationS > f.durationS) {
    fail('fade.cpuDurationS and fade.reducedMotionDurationS must be at most fade.durationS (they are the quick fades)');
  }
}

/** A stage's progress kinds: none (absent), bytes downloaded, or a count of things done. */
export const STAGE_PROGRESS = ['bytes', 'count'];
/** The longest label (characters): one line on a phone's loading sheet. */
export const STAGE_LABEL_MAX = 32;

/** Checks the start's stages (`stages`). Throws naming the entry. */
function validateStages(st) {
  if (typeof st !== 'object' || st === null || Array.isArray(st)) fail('stages must be an object');
  const keys = ['slowS', 'list'];
  for (const k of Object.keys(st)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry stages.${k}`);
  for (const k of keys) if (!(k in st)) fail(`missing entry stages.${k}`);
  if (typeof st.slowS !== 'number' || !Number.isFinite(st.slowS) || st.slowS < 0.5 || st.slowS > 60) {
    fail(`stages.slowS must be a number in [0.5, 60], got ${JSON.stringify(st.slowS)}`);
  }
  if (!Array.isArray(st.list) || st.list.length === 0) fail('stages.list must be a non-empty array');
  const seen = new Set();
  st.list.forEach((e, i) => {
    const at = `stages.list[${i}]`;
    if (typeof e !== 'object' || e === null || Array.isArray(e)) fail(`${at} must be an object`);
    for (const k of Object.keys(e)) {
      if (!['id', 'label', 'progress'].includes(k)) fail(`unknown entry ${at}.${k}`);
    }
    if (typeof e.id !== 'string' || !/^[a-z][A-Za-z0-9]*$/.test(e.id)) {
      fail(`${at}.id must be a lowerCamel name, got ${JSON.stringify(e.id)}`);
    }
    if (seen.has(e.id)) fail(`${at}.id ${e.id} is listed twice`);
    seen.add(e.id);
    const named = `stages.list ${e.id}`;
    if (typeof e.label !== 'string' || e.label.trim() === '' || e.label.length > STAGE_LABEL_MAX) {
      fail(`${named}: label must be 1–${STAGE_LABEL_MAX} characters, got ${JSON.stringify(e.label)}`);
    }
    if (/(…|\.\.\.)$/.test(e.label)) fail(`${named}: label must not end in an ellipsis (the screen adds one)`);
    if ('progress' in e && !STAGE_PROGRESS.includes(e.progress)) {
      fail(`${named}: progress must be one of ${STAGE_PROGRESS.join(', ')} (or absent), got ${JSON.stringify(e.progress)}`);
    }
  });
}

/** The near ring's chunk count: chunks c with |c|² ≤ r² + r (the server's view sphere). */
export function ringChunks(r) {
  let n = 0;
  for (let x = -r; x <= r; x++) {
    for (let y = -r; y <= r; y++) {
      for (let z = -r; z <= r; z++) if (x * x + y * y + z * z <= r * r + r) n++;
    }
  }
  return n;
}

/** estimate's numbers: [min, max]. */
const ESTIMATE = {
  holdFraction: [0.5, 0.995],
  easeS: [0, 5],
  labelEveryS: [0, 5],
  labelHysteresisS: [0, 10],
  hideBelowS: [0, 10],
  roundAboveS: [1, 600],
  minSamples: [1, 1000],
  overrunFraction: [0, 2],
};
const DEVICE = {
  referenceCores: [1, 128],
  minFactor: [0.1, 1],
  maxFactor: [1, 20],
  phoneFactor: [0.1, 20],
  lowMemoryGB: [0, 64],
  lowMemoryFactor: [0.1, 20],
  cpuFactor: [0.1, 50],
};
/** A stage's estimate numbers: [min, max]. */
const STAGE_COST = { baseS: [0, 120], perItemS: [0, 60], totalGuess: [0, 1e10], bytesPerS: [1, 1e10] };
/** What scales a stage's opening guess: the device read, or nothing (the network). */
export const STAGE_SCALES = ['device', 'network'];

function numbers(obj, spec, at) {
  for (const [k, [lo, hi]] of Object.entries(spec)) {
    if (!(k in obj)) fail(`missing entry ${at}.${k}`);
    const v = obj[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
      fail(`${at}.${k} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  }
}

const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Checks the bar's time estimate (`estimate`) against the stages. Throws naming the entry. */
function validateEstimate(e, stages) {
  if (!isObject(e)) fail('estimate must be an object');
  const keys = [...Object.keys(ESTIMATE), 'device', 'stages'];
  for (const k of Object.keys(e)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry estimate.${k}`);
  numbers(e, ESTIMATE, 'estimate');
  if (!Number.isInteger(e.minSamples)) fail(`estimate.minSamples must be a whole number, got ${e.minSamples}`);
  const d = e.device;
  if (!isObject(d)) fail('estimate.device must be an object');
  for (const k of Object.keys(d)) if (k !== '$comment' && !(k in DEVICE)) fail(`unknown entry estimate.device.${k}`);
  numbers(d, DEVICE, 'estimate.device');
  const st = e.stages;
  if (!isObject(st)) fail('estimate.stages must be an object');
  const defs = new Map(stages.list.map((s) => [s.id, s]));
  for (const [id, c] of Object.entries(st)) {
    if (id === '$comment') continue;
    const at = `estimate.stages.${id}`;
    const def = defs.get(id);
    if (!def) fail(`${at}: no stage ${id} in stages.list`);
    if (!isObject(c)) fail(`${at} must be an object`);
    for (const k of Object.keys(c)) {
      if (!(k in STAGE_COST) && !['scales', 'local', 'remote', 'perWorker'].includes(k)) fail(`unknown entry ${at}.${k}`);
    }
    if (!STAGE_SCALES.includes(c.scales)) {
      fail(`${at}.scales must be one of ${STAGE_SCALES.join(', ')}, got ${JSON.stringify(c.scales)}`);
    }
    numbers(c, { baseS: STAGE_COST.baseS }, at);
    for (const k of ['perItemS', 'totalGuess', 'bytesPerS']) if (k in c) numbers(c, { [k]: STAGE_COST[k] }, at);
    for (const k of ['local', 'remote', 'perWorker']) {
      if (k in c && typeof c[k] !== 'boolean') fail(`${at}.${k} must be true or false, got ${JSON.stringify(c[k])}`);
    }
    if (c.local && c.remote) fail(`${at}: local and remote cannot both be set`);
    if (!def.progress && ('perItemS' in c || 'totalGuess' in c || 'bytesPerS' in c)) {
      fail(`${at}: perItemS, totalGuess and bytesPerS need a stage with progress`);
    }
    if (def.progress === 'bytes' && !('bytesPerS' in c && 'totalGuess' in c)) {
      fail(`${at}: a bytes stage needs bytesPerS and totalGuess`);
    }
    if (def.progress === 'bytes' && 'perItemS' in c) fail(`${at}: a bytes stage takes bytesPerS, not perItemS`);
    if (def.progress === 'count' && !('perItemS' in c)) fail(`${at}: a count stage needs perItemS`);
  }
}

/** The bar's time estimate's tunables (TypeScript lines). */
function estimateTs(data) {
  const e = data.estimate;
  const out = [
    "/** A stage's opening cost on the reference desktop (shared/look/loading.json `estimate.stages`). */",
    'export interface LoadingStageCost {',
    "  scales: 'device' | 'network';",
    '  baseS: number;',
    '  perItemS?: number;',
    '  totalGuess?: number;',
    '  bytesPerS?: number;',
    '  local?: boolean;',
    '  remote?: boolean;',
    '  perWorker?: boolean;',
    '}',
    '',
    "/** The loading bar's per-device time estimate (ARCHITECTURE.md §6.3). */",
    'export const LOADING_ESTIMATE = {',
    ...Object.keys(ESTIMATE).map((k) => `  ${k}: ${e[k]},`),
    `  device: { ${Object.keys(DEVICE).map((k) => `${k}: ${e.device[k]}`).join(', ')} },`,
    `  /** The near ring's chunks (radiusChunks ${data.radiusChunks}): the terrain's count. */`,
    `  ringChunks: ${ringChunks(data.radiusChunks)},`,
    '  stages: {',
  ];
  for (const [id, c] of Object.entries(e.stages)) {
    if (id === '$comment') continue;
    const fields = ['scales', 'baseS', 'perItemS', 'totalGuess', 'bytesPerS', 'local', 'remote', 'perWorker']
      .filter((k) => k in c)
      .map((k) => `${k}: ${typeof c[k] === 'string' ? `'${c[k]}'` : c[k]}`);
    out.push(`    ${id}: { ${fields.join(', ')} },`);
  }
  out.push('  } as Partial<Record<LoadingStageId, LoadingStageCost>>,', '};', '');
  return out;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated tunables. */
export function loadingRust(data) {
  return [
    `// ${header}`,
    '',
    "/// The loading screen's tunables (shared/look/loading.json).",
    'pub const LOADING: LoadingTunables = LoadingTunables {',
    `    radius_chunks: ${data.radiusChunks},`,
    `    timeout_s: ${rf(data.timeoutS)},`,
    '};',
    '',
    "/// The respawn preload (shared/look/loading.json `respawnPreload`): the near ring's radius around",
    '/// the respawn point streamed and meshed from a death until the respawn; None: off.',
    `pub const RESPAWN_PRELOAD_RADIUS_CHUNKS: Option<i32> = ${preload(data)};`,
    '',
  ].join('\n');
}

const preload = (data) => (data.respawnPreload.enabled ? `Some(${data.respawnPreload.radiusChunks})` : 'None');

/** The server's Rust source (dwell-sim) for validated tunables: the respawn preload's radius. */
export function preloadServerRust(data) {
  return [
    `// ${header}`,
    '',
    "/// The respawn preload (shared/look/loading.json `respawnPreload`): from a death until the",
    "/// respawn, the view sphere of this radius around the respawn point is streamed as a second",
    '/// centre (`ServerConfig::respawn_preload_radius_chunks`\'s default); None: off.',
    `pub const RESPAWN_PRELOAD_RADIUS_CHUNKS: Option<i32> = ${preload(data)};`,
    '',
  ].join('\n');
}

/** The TypeScript the shell's fade reads (client/src/ui/loadingScreen.ts). */
export function loadingTs(data) {
  const f = data.fade;
  return [
    `// ${header}`,
    '',
    "/** The loading screen's fade in from white when it opens (ARCHITECTURE.md §6.3). */",
    'export const LOADING_FADE = {',
    `  color: '${f.color.toLowerCase()}',`,
    `  holdS: ${f.holdS},`,
    `  durationS: ${f.durationS},`,
    `  easePower: ${f.easePower},`,
    `  cpuDurationS: ${f.cpuDurationS},`,
    `  reducedMotionDurationS: ${f.reducedMotionDurationS},`,
    '} as const;',
    '',
    "/** A start stage's id (shared/look/loading.json `stages.list`): what code reports it by. */",
    `export type LoadingStageId = ${data.stages.list.map((e) => `'${e.id}'`).join(' | ')};`,
    '',
    "/** One stage's definition. */",
    'export interface LoadingStageDef {',
    '  id: LoadingStageId;',
    '  label: string;',
    "  progress?: 'bytes' | 'count';",
    '}',
    '',
    "/** The loading screen's stages while the game starts, in their usual order (ARCHITECTURE.md §6.3). */",
    'export const LOADING_STAGES: readonly LoadingStageDef[] = [',
    ...data.stages.list.map(
      (e) =>
        `  { id: '${e.id}', label: ${JSON.stringify(e.label)}${e.progress ? `, progress: '${e.progress}'` : ''} },`,
    ),
    '];',
    '',
    '/** A stage running longer than this (s) is marked slow. */',
    `export const LOADING_STAGE_SLOW_S = ${data.stages.slowS};`,
    '',
    ...estimateTs(data),
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateLoading(JSON.parse(readFileSync(join(here, 'loading.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-game/src/loading.gen.rs'), loadingRust(data));
  writeFileSync(join(root, 'crates/dwell-sim/src/respawn_preload.gen.rs'), preloadServerRust(data));
  writeFileSync(join(root, 'client/src/ui/loading.gen.ts'), loadingTs(data));
  console.log('look: loading screen tunables generated');
}
