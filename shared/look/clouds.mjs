#!/usr/bin/env node
// Generates the sky clouds' tunables for Rust (crates/dwell-look/src/clouds.gen.rs) from
// shared/look/clouds.json (docs/CLOUDS.md), after validating them: an unknown, missing or
// out-of-range entry fails with its path named. The output is checked in; CI regenerates it and
// fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadAtmosphere } from './atmosphere.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/clouds.mjs from shared/look/clouds.json. Do not edit.';

/** The most octaves the shader loops over (a WGSL constant). */
export const MAX_OCTAVES = 8;

/** Section → field → [min, max] (numbers), 'color' (#rrggbb) or ['count', min, max] (whole). */
const SCHEMA = {
  deck: {
    altitudeM: [10, 1e6],
    curvatureM: [1000, 1e8],
    crossFadeM: [1, 1e5],
    insideFog: [0, 1],
    horizonFade: [0.001, 1],
    fadeStartM: [0, 1e7],
    fadeEndM: [1, 1e7],
  },
  shape: {
    scaleM: [16, 1e6],
    wrapM: [64, 1e6],
    octaves: ['count', 1, MAX_OCTAVES],
    lowOctaves: ['count', 1, MAX_OCTAVES],
    gain: [0.05, 0.95],
    warp: [0, 4],
    coverage: [0, 1],
    edgeSoftness: [0.01, 1],
    opacity: [0, 1],
  },
  wind: {
    speedMps: [0, 1000],
    directionDeg: [-360, 360],
    evolveMps: [0, 1000],
    evolveDirectionDeg: [-360, 360],
  },
  light: {
    sunlit: 'color',
    shade: 'color',
    sunset: 'color',
    nightLit: 'color',
    nightShade: 'color',
    absorption: [0, 20],
    shadowStepM: [0, 1e5],
    silverLining: [0, 4],
    silverPower: [1, 512],
    sunWarmth: [0, 1],
    topLight: [0, 1],
  },
  volume: {
    baseM: [10, 1e5],
    topM: [20, 1e5],
    topFloor: [0.05, 1],
    detailCellM: [8, 1e5],
    detailErosion: [0, 1],
    extinction: [0, 1],
    lightStepM: [1, 1e4],
    powder: [0, 1],
    ambient: [0, 1],
    maxDistanceM: [100, 1e6],
    plumeBillow: [0, 1],
  },
};

/** The most march steps and light samples a tier may take (the shader's loop bounds). */
export const MAX_STEPS = 64;
export const MAX_LIGHT_STEPS = 4;
/** The most samples a tier may take through one plume (the shader's loop bound). */
export const MAX_PLUME_STEPS = 16;
/** The Clouds setting's values that draw clouds, each with a tier. */
const TIERS = ['high', 'medium', 'low'];
const TIER = {
  steps: ['count', 0, MAX_STEPS],
  lightSteps: ['count', 0, MAX_LIGHT_STEPS],
  divisor: ['count', 1, 4],
  historyBlend: [0.02, 1],
  plumeSteps: ['count', 0, MAX_PLUME_STEPS],
};
/** A plume's look: a column of cloud (steam, smoke, volcano ash) rising at riseMps. */
const PLUME_LOOK = {
  radiusM: [1, 1e5],
  spread: [0, 10],
  density: [0, 4],
  color: 'color',
  riseMps: [0, 100],
};
/** A plume the world starts with (the run-time list's defaults), in world x, z and heights above
 * sea level on face A (docs/CLOUDS.md §8.7). */
const PLUME = {
  name: 'name',
  xM: [-1e7, 1e7],
  zM: [-1e7, 1e7],
  baseM: [-1e5, 1e5],
  topM: [-1e5, 1e5],
  ...PLUME_LOOK,
};
/** A run-time source's look (`sources`): a plume's, with its height over the source. */
const SOURCE = { ...PLUME_LOOK, heightM: [1, 1e5] };
/** The sources the game knows (the code's fixed vocabulary). */
const SOURCES = ['lavaVent'];
/** The most plume slots the run-time list may have (the uniform's size). */
export const MAX_PLUME_SLOTS = 32;

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const fail = (m) => {
  throw new Error(`clouds.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj))
    fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  if (spec === 'name') {
    if (typeof v !== 'string' || !/^[a-z0-9_:-]+$/.test(v))
      fail(`${where} must be a name [a-z0-9_:-], got ${JSON.stringify(v)}`);
    return;
  }
  if (spec === 'color') {
    if (typeof v !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v)) {
      fail(`${where} must be a colour "#rrggbb", got ${JSON.stringify(v)}`);
    }
    return;
  }
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v))
    fail(`${where} must be a whole number, got ${v}`);
}

/** Checks the tunables against the schema and each other, and their tops against the atmosphere's
 * (`atmosphere`: shared/look/atmosphere.json's; owner, 2026-11-12: "Clouds shouldn't extend past the
 * earth atmosphere either."); returns them. Throws naming the entry. */
export function validateClouds(data, atmosphere = loadAtmosphere()) {
  checkKeys('(root)', data, [...Object.keys(SCHEMA), 'tiers', 'plumeSlots', 'sources', 'plumes']);
  checkValue('plumeSlots', data.plumeSlots, ['count', 1, MAX_PLUME_SLOTS]);
  checkKeys('sources', data.sources, SOURCES);
  for (const src of SOURCES) {
    checkKeys(`sources.${src}`, data.sources[src], Object.keys(SOURCE));
    for (const [k, spec] of Object.entries(SOURCE))
      checkValue(`sources.${src}.${k}`, data.sources[src][k], spec);
  }
  checkKeys('tiers', data.tiers, TIERS);
  for (const tier of TIERS) {
    checkKeys(`tiers.${tier}`, data.tiers[tier], Object.keys(TIER));
    for (const [k, spec] of Object.entries(TIER))
      checkValue(`tiers.${tier}.${k}`, data.tiers[tier][k], spec);
  }
  if (!Array.isArray(data.plumes)) fail('plumes must be a list');
  if (data.plumes.length > data.plumeSlots) fail(`plumes: at most plumeSlots (${data.plumeSlots})`);
  const names = new Set();
  data.plumes.forEach((p, i) => {
    checkKeys(`plumes[${i}]`, p, Object.keys(PLUME));
    for (const [k, spec] of Object.entries(PLUME)) checkValue(`plumes[${i}].${k}`, p[k], spec);
    if (p.topM <= p.baseM) fail(`plumes[${i}].topM must be greater than its baseM`);
    if (names.has(p.name)) fail(`plumes[${i}].name ${p.name} is used twice`);
    names.add(p.name);
  });
  for (const [section, fields] of Object.entries(SCHEMA)) {
    checkKeys(section, data[section], Object.keys(fields));
    for (const [k, spec] of Object.entries(fields))
      checkValue(`${section}.${k}`, data[section][k], spec);
  }
  const { deck, shape, volume } = data;
  if (volume.topM <= volume.baseM) fail('volume.topM must be greater than volume.baseM');
  const top = atmosphere.topM;
  const under = (where, v) => {
    if (v > top) fail(`${where} (${v} m) must not be above the atmosphere's top (atmosphere.json topM ${top} m)`);
  };
  under('deck.altitudeM', deck.altitudeM);
  under('volume.topM', volume.topM);
  data.plumes.forEach((p, i) => under(`plumes[${i}].topM`, p.topM));
  for (const src of SOURCES) under(`sources.${src}.heightM`, data.sources[src].heightM);
  if (!Number.isInteger(shape.scaleM / volume.detailCellM)) {
    fail(
      'shape.scaleM must be a whole multiple of volume.detailCellM (the detail noise tiles with the deck)',
    );
  }
  if (deck.fadeEndM <= deck.fadeStartM) fail('deck.fadeEndM must be greater than deck.fadeStartM');
  if (shape.lowOctaves > shape.octaves) fail('shape.lowOctaves must not exceed shape.octaves');
  // The noise repeats every wrapM: a whole number of its largest cells, so it tiles without a seam.
  const cells = shape.wrapM / shape.scaleM;
  if (!Number.isInteger(cells)) fail('shape.wrapM must be a whole multiple of shape.scaleM');
  if (cells < 4)
    fail('shape.wrapM must be at least 4 × shape.scaleM (the noise would repeat in view)');
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
export { SCHEMA };
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
const rgbRust = (hex) =>
  `[${rgb(hex)
    .map((c) => rf(+c.toFixed(6)))
    .join(', ')}]`;

/** The Rust source for validated tunables. */
export function cloudsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::clouds::*;', ''];
  rs.push("/// The sky clouds' tunables (shared/look/clouds.json).");
  rs.push('pub const CLOUDS: CloudTunables = CloudTunables {');
  for (const [section, fields] of Object.entries(SCHEMA)) {
    const type = {
      deck: 'DeckTunables',
      shape: 'ShapeTunables',
      wind: 'WindTunables',
      light: 'CloudLight',
      volume: 'VolumeTunables',
    }[section];
    rs.push(`    ${section}: ${type} {`);
    for (const [k, spec] of Object.entries(fields)) {
      const v = data[section][k];
      if (spec === 'color')
        rs.push(
          `        ${snake(k)}: [${rgb(v)
            .map((c) => rf(+c.toFixed(6)))
            .join(', ')}],`,
        );
      else if (spec[0] === 'count') rs.push(`        ${snake(k)}: ${v},`);
      else rs.push(`        ${snake(k)}: ${rf(v)},`);
    }
    rs.push('    },');
  }
  rs.push('    tiers: VolumeTiers {');
  for (const tier of TIERS) {
    const t = data.tiers[tier];
    rs.push(
      `        ${tier}: VolumeTier {`,
      `            steps: ${t.steps},`,
      `            light_steps: ${t.lightSteps},`,
      `            divisor: ${t.divisor},`,
      `            history_blend: ${rf(t.historyBlend)},`,
      `            plume_steps: ${t.plumeSteps},`,
      '        },',
    );
  }
  rs.push('    },');
  rs.push(`    plume_slots: ${data.plumeSlots},`);
  rs.push('    sources: PlumeSources {');
  for (const src of SOURCES) {
    const v = data.sources[src];
    rs.push(`        ${snake(src)}: PlumeSource {`);
    for (const k of Object.keys(SOURCE)) {
      if (k === 'color') rs.push(`            color: ${rgbRust(v.color)},`);
      else rs.push(`            ${snake(k)}: ${rf(v[k])},`);
    }
    rs.push('        },');
  }
  rs.push('    },');
  rs.push(data.plumes.length ? '    plumes: &[' : '    plumes: &[],');
  for (const p of data.plumes) {
    rs.push('        Plume {');
    rs.push(`            name: ${JSON.stringify(p.name)},`);
    for (const k of Object.keys(PLUME)) {
      if (k === 'name') continue;
      if (k === 'color') rs.push(`            color: ${rgbRust(p.color)},`);
      else rs.push(`            ${snake(k)}: ${rf(p[k])},`);
    }
    rs.push('        },');
  }
  if (data.plumes.length) rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateClouds(JSON.parse(readFileSync(join(here, 'clouds.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/clouds.gen.rs'), cloudsRust(data));
  console.log('look: cloud tunables generated');
}
