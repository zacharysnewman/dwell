#!/usr/bin/env node
// Generates the sky clouds' tunables for Rust (crates/dwell-look/src/clouds.gen.rs) from
// shared/look/clouds.json (docs/CLOUDS.md), after validating them: an unknown, missing or
// out-of-range entry fails with its path named. The output is checked in; CI regenerates it and
// fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/clouds.mjs from shared/look/clouds.json. Do not edit.';

/** The most octaves the shader loops over (a WGSL constant). */
export const MAX_OCTAVES = 8;

/** Section → field → [min, max] (numbers), 'color' (#rrggbb) or ['count', min, max] (whole). */
const SCHEMA = {
  deck: {
    altitudeM: [10, 1e6],
    curvatureM: [1000, 1e8],
    crossFadeM: [1, 1e5],
    insideFog: [0, 1],
    horizonFade: [0.001, 1],
    fadeStartM: [0, 1e7],
    fadeEndM: [1, 1e7],
  },
  shape: {
    scaleM: [16, 1e6],
    wrapM: [64, 1e6],
    octaves: ['count', 1, MAX_OCTAVES],
    lowOctaves: ['count', 1, MAX_OCTAVES],
    gain: [0.05, 0.95],
    warp: [0, 4],
    coverage: [0, 1],
    edgeSoftness: [0.01, 1],
    opacity: [0, 1],
  },
  wind: {
    speedMps: [0, 1000],
    directionDeg: [-360, 360],
    evolveMps: [0, 1000],
    evolveDirectionDeg: [-360, 360],
  },
  light: {
    sunlit: 'color',
    shade: 'color',
    sunset: 'color',
    nightLit: 'color',
    nightShade: 'color',
    absorption: [0, 20],
    shadowStepM: [0, 1e5],
    silverLining: [0, 4],
    silverPower: [1, 512],
    sunWarmth: [0, 1],
    topLight: [0, 1],
  },
};

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const fail = (m) => {
  throw new Error(`clouds.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  if (spec === 'color') {
    if (typeof v !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v)) {
      fail(`${where} must be a colour "#rrggbb", got ${JSON.stringify(v)}`);
    }
    return;
  }
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

/** Checks the tunables against the schema and each other; returns them. Throws naming the entry. */
export function validateClouds(data) {
  checkKeys('(root)', data, Object.keys(SCHEMA));
  for (const [section, fields] of Object.entries(SCHEMA)) {
    checkKeys(section, data[section], Object.keys(fields));
    for (const [k, spec] of Object.entries(fields)) checkValue(`${section}.${k}`, data[section][k], spec);
  }
  const { deck, shape } = data;
  if (deck.fadeEndM <= deck.fadeStartM) fail('deck.fadeEndM must be greater than deck.fadeStartM');
  if (shape.lowOctaves > shape.octaves) fail('shape.lowOctaves must not exceed shape.octaves');
  // The noise repeats every wrapM: a whole number of its largest cells, so it tiles without a seam.
  const cells = shape.wrapM / shape.scaleM;
  if (!Number.isInteger(cells)) fail('shape.wrapM must be a whole multiple of shape.scaleM');
  if (cells < 4) fail('shape.wrapM must be at least 4 × shape.scaleM (the noise would repeat in view)');
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);

/** The Rust source for validated tunables. */
export function cloudsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::clouds::*;', ''];
  rs.push("/// The sky clouds' tunables (shared/look/clouds.json).");
  rs.push('pub const CLOUDS: CloudTunables = CloudTunables {');
  for (const [section, fields] of Object.entries(SCHEMA)) {
    const type = { deck: 'DeckTunables', shape: 'ShapeTunables', wind: 'WindTunables', light: 'CloudLight' }[section];
    rs.push(`    ${section}: ${type} {`);
    for (const [k, spec] of Object.entries(fields)) {
      const v = data[section][k];
      if (spec === 'color') rs.push(`        ${snake(k)}: [${rgb(v).map((c) => rf(+c.toFixed(6))).join(', ')}],`);
      else if (spec[0] === 'count') rs.push(`        ${snake(k)}: ${v},`);
      else rs.push(`        ${snake(k)}: ${rf(v)},`);
    }
    rs.push('    },');
  }
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateClouds(JSON.parse(readFileSync(join(here, 'clouds.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/clouds.gen.rs'), cloudsRust(data));
  console.log('look: cloud tunables generated');
}
