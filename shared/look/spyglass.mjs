#!/usr/bin/env node
// Generates the spyglass's tunables (docs/SPYGLASS.md) for Rust (crates/dwell-look/src/spyglass.gen.rs)
// and its key and steps for the shell's controls table (client/src/ui/spyglass.gen.ts) from
// shared/look/spyglass.json, after validating them: an unknown, missing or out-of-range entry fails
// with its path named. The outputs are checked in; CI regenerates them and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/spyglass.mjs from shared/look/spyglass.json. Do not edit.';

/** The most steps, and the largest magnification a step may have. */
export const MAX_STEPS = 8;
export const MAX_MAGNIFICATION = 64;

/**
 * Keys other controls already use (client/src/ui/controls.ts; dwell-game input.rs, region_tools.rs,
 * brush_tool.rs; the shell's Esc and F-keys): the spyglass's key may not be one of them. Letters
 * and digits are all taken (movement, tools, the brush presets, the hotbar).
 */
export const TAKEN_KEYS = [
  'Escape',
  'Space',
  'ShiftLeft',
  'ShiftRight',
  'ControlLeft',
  'ControlRight',
  'Minus',
  'Equal',
  'BracketLeft',
  'BracketRight',
  'Delete',
  'Backspace',
  'F3',
  'F4',
  'F6',
  'F7',
  'F8',
];

const fail = (m) => {
  throw new Error(`spyglass.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/** Checks the tunables; returns them. Throws naming the entry. */
export function validateSpyglass(data) {
  checkKeys('(root)', data, ['key', 'steps', 'detailBoost', 'transitionS', 'vignette']);
  const key = data.key;
  if (typeof key !== 'string' || !/^[A-Za-z0-9]+$/.test(key)) {
    fail(`key must be a KeyboardEvent.code, got ${JSON.stringify(key)}`);
  }
  if (/^(Key[A-Z]|Digit[0-9]|Arrow.*)$/.test(key) || TAKEN_KEYS.includes(key)) {
    fail(`key ${key} is already another control's (client/src/ui/controls.ts)`);
  }
  if (!Array.isArray(data.steps) || data.steps.length === 0 || data.steps.length > MAX_STEPS) {
    fail(`steps must be a list of 1 to ${MAX_STEPS} steps`);
  }
  let last = 1;
  data.steps.forEach((s, i) => {
    checkKeys(`steps[${i}]`, s, ['magnification']);
    checkNumber(`steps[${i}].magnification`, s.magnification, 1, MAX_MAGNIFICATION);
    if (s.magnification <= last) {
      fail(`steps[${i}].magnification must be greater than ${last} (steps go from the least zoom to the most)`);
    }
    last = s.magnification;
  });
  checkNumber('detailBoost', data.detailBoost, 1, MAX_MAGNIFICATION);
  checkNumber('transitionS', data.transitionS, 0, 5);
  const v = data.vignette;
  checkKeys('vignette', v, ['innerRadius', 'outerRadius', 'opacity', 'color']);
  checkNumber('vignette.innerRadius', v.innerRadius, 0, 4);
  checkNumber('vignette.outerRadius', v.outerRadius, 0, 8);
  checkNumber('vignette.opacity', v.opacity, 0, 1);
  if (typeof v.color !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v.color)) {
    fail(`vignette.color must be a colour "#rrggbb", got ${JSON.stringify(v.color)}`);
  }
  if (v.outerRadius <= v.innerRadius) fail('vignette.outerRadius must be greater than vignette.innerRadius');
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rgb = (hex) => [1, 3, 5].map((i) => +(parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(6));

/** The Rust source for validated tunables. */
export function spyglassRust(data) {
  const v = data.vignette;
  const rs = [`// ${header}`, '', 'use crate::spyglass::*;', ''];
  rs.push("/// The spyglass's tunables (shared/look/spyglass.json).");
  rs.push('pub const SPYGLASS: SpyglassTunables = SpyglassTunables {');
  rs.push(`    key: ${JSON.stringify(data.key)},`);
  rs.push('    steps: &[');
  for (const s of data.steps) rs.push(`        SpyglassStep { magnification: ${rf(s.magnification)} },`);
  rs.push('    ],');
  rs.push(`    detail_boost: ${rf(data.detailBoost)},`);
  rs.push(`    transition_s: ${rf(data.transitionS)},`);
  rs.push('    vignette: VignetteTunables {');
  rs.push(`        inner_radius: ${rf(v.innerRadius)},`);
  rs.push(`        outer_radius: ${rf(v.outerRadius)},`);
  rs.push(`        opacity: ${rf(v.opacity)},`);
  rs.push(`        color: [${rgb(v.color).map(rf).join(', ')}],`);
  rs.push('    },');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

/** The TypeScript the controls table reads: the key and the steps' magnifications. */
export function spyglassTs(data) {
  const ts = [`// ${header}`, ''];
  ts.push("/** The spyglass's key (`KeyboardEvent.code`) and its steps' magnifications, least first. */");
  ts.push('export const SPYGLASS = {');
  ts.push(`  key: '${data.key}',`);
  ts.push(`  magnifications: [${data.steps.map((s) => s.magnification).join(', ')}],`);
  ts.push('} as const;');
  ts.push('');
  return ts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateSpyglass(JSON.parse(readFileSync(join(here, 'spyglass.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/spyglass.gen.rs'), spyglassRust(data));
  writeFileSync(join(root, 'client/src/ui/spyglass.gen.ts'), spyglassTs(data));
  console.log('look: spyglass tunables generated');
}
