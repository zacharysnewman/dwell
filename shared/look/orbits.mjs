#!/usr/bin/env node
// Generates the orbits' ranges and presets (docs/proposals/REALISTIC_WORLD.md §8) for Rust
// (crates/dwell-look/src/orbits.gen.rs) and the New world form's Sky choices (client/src/ui/skyPresets.gen.ts)
// from shared/look/orbits.json, after validating them: an unknown, missing or out-of-range entry, or a
// preset that breaks a limit, fails with its path named. The outputs are checked in; CI regenerates them
// and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/orbits.mjs from shared/look/orbits.json. Do not edit.';

/** Each rolled entry → its absolute bounds [lo, hi]. */
export const ROLL = {
  poleDeg: [0, 90],
  poleYawDeg: [0, 360],
  distance: [0.5, 2],
  tiltDeg: [0, 45],
  yearDays: [1, 1000],
  yearPhase: [0, 1],
  dayLengthS: [60, 86400],
  dayShare: [0.05, 0.95],
};
export const MOON = { cycleDays: [1, 100], inclinationDeg: [0, 30], nodeDeg: [0, 360], phase: [0, 1] };
export const MAX_PRESETS = 16;

const fail = (m) => {
  throw new Error(`orbits.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

function checkRange(where, v, [lo, hi]) {
  if (!Array.isArray(v) || v.length !== 2) fail(`${where} must be a range [min, max]`);
  checkNumber(`${where}[0]`, v[0], lo, hi);
  checkNumber(`${where}[1]`, v[1], lo, hi);
  if (v[1] < v[0]) fail(`${where}: max ${v[1]} is under min ${v[0]}`);
}

function checkText(where, v) {
  if (typeof v !== 'string' || v.trim() === '' || v.length > 200) fail(`${where} must be text (1–200 characters)`);
}

/** Checks the orbits' data; returns it. Throws naming the entry. */
export function validateOrbits(data) {
  checkKeys('(root)', data, ['presets', 'limits']);
  const l = data.limits;
  checkKeys('limits', l, ['maxPoleDeg', 'dayShare', 'offsetC']);
  checkNumber('limits.maxPoleDeg', l.maxPoleDeg, 0, 89);
  checkRange('limits.dayShare', l.dayShare, [0.05, 0.95]);
  checkRange('limits.offsetC', l.offsetC, [-50, 50]);
  const p = data.presets;
  if (typeof p !== 'object' || p === null || Array.isArray(p)) fail('presets must be an object');
  const names = Object.keys(p).filter((k) => k !== '$comment');
  if (names[0] !== 'default') fail('presets: the first preset must be `default` (the Sky choice a world gets by default)');
  if (names.length > MAX_PRESETS) fail(`presets: at most ${MAX_PRESETS}`);
  for (const name of names) {
    const w = `presets.${name}`;
    if (!/^[a-z][a-z0-9_]{0,31}$/.test(name)) fail(`${w}: a preset's name is lower_snake_case`);
    checkKeys(w, p[name], ['label', 'description', 'roll']);
    checkText(`${w}.label`, p[name].label);
    checkText(`${w}.description`, p[name].description);
    const r = p[name].roll;
    checkKeys(`${w}.roll`, r, [...Object.keys(ROLL), 'moon']);
    for (const [k, b] of Object.entries(ROLL)) checkRange(`${w}.roll.${k}`, r[k], b);
    checkKeys(`${w}.roll.moon`, r.moon, Object.keys(MOON));
    for (const [k, b] of Object.entries(MOON)) checkRange(`${w}.roll.moon.${k}`, r.moon[k], b);
    if (r.poleDeg[1] > l.maxPoleDeg) {
      fail(`${w}.roll.poleDeg: max ${r.poleDeg[1]} is over limits.maxPoleDeg ${l.maxPoleDeg} (the noon sun too low)`);
    }
    // Both faces' daylight within the limit: face A's share, face B's the rest.
    const [slo, shi] = r.dayShare;
    if (slo < l.dayShare[0] || shi > l.dayShare[1] || 1 - shi < l.dayShare[0] || 1 - slo > l.dayShare[1]) {
      fail(`${w}.roll.dayShare: [${slo}, ${shi}] leaves a face's daylight outside limits.dayShare [${l.dayShare}]`);
    }
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const range = (v) => `[${rf(v[0])}, ${rf(v[1])}]`;

/** The Rust source for validated data. */
export function orbitsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::orbits::*;', ''];
  rs.push("/// The orbits' presets and limits (shared/look/orbits.json).");
  rs.push('pub const ORBITS: OrbitRules = OrbitRules {');
  rs.push('    presets: &[');
  for (const [name, p] of Object.entries(data.presets)) {
    if (name === '$comment') continue;
    const r = p.roll;
    rs.push('        OrbitPreset {');
    rs.push(`            name: ${JSON.stringify(name)},`);
    rs.push(`            label: ${JSON.stringify(p.label)},`);
    rs.push('            roll: OrbitRanges {');
    for (const k of Object.keys(ROLL)) rs.push(`                ${snake(k)}: ${range(r[k])},`);
    rs.push('                moon: MoonRanges {');
    for (const k of Object.keys(MOON)) rs.push(`                    ${snake(k)}: ${range(r.moon[k])},`);
    rs.push('                },');
    rs.push('            },');
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('    limits: OrbitLimits {');
  rs.push(`        max_pole_deg: ${rf(data.limits.maxPoleDeg)},`);
  rs.push(`        day_share: ${range(data.limits.dayShare)},`);
  rs.push(`        offset_c: ${range(data.limits.offsetC)},`);
  rs.push('    },');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

/** The TypeScript the New world form reads: the Sky choices, the default first. */
export function orbitsTs(data) {
  const ts = [`// ${header}`, ''];
  ts.push("/** The New world form's Sky choices (a world that rolls an orbit), the default first. */");
  ts.push('export const SKY_PRESETS = [');
  for (const [name, p] of Object.entries(data.presets)) {
    if (name === '$comment') continue;
    ts.push(`  { name: '${name}', label: ${JSON.stringify(p.label)}, description: ${JSON.stringify(p.description)} },`);
  }
  ts.push('] as const;');
  ts.push('');
  return ts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateOrbits(JSON.parse(readFileSync(join(here, 'orbits.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/orbits.gen.rs'), orbitsRust(data));
  writeFileSync(join(root, 'client/src/ui/skyPresets.gen.ts'), orbitsTs(data));
  console.log('look: orbits generated');
}
