#!/usr/bin/env node
// Generates the distant terrain's shadows' tunables for Rust (crates/dwell-look/src/lodshadows.gen.rs)
// from shared/look/lodshadows.json (docs/DAY_NIGHT.md §12), after validating them: an unknown,
// missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/lodshadows.mjs from shared/look/lodshadows.json. Do not edit.';

/** The most heightmaps a tier may have (the shader's array, the uniform block). */
export const MAX_LEVELS = 2;
/** The most march steps (each is a texture gather per far pixel). */
export const MAX_STEPS = 64;
/** The Shadows setting's tiers that draw shadows, in the renderer's order (Off draws none). */
export const TIERS = ['low', 'high'];

/** Field → [min, max] (numbers) or ['count', min, max] (whole). */
const HEIGHTS = {
  bottomM: [-1000, 1000],
  topM: [1, 100000],
};
const MARCH = {
  startTexels: [0.5, 16],
  biasM: [0, 64],
  penumbraDeg: [0.05, 20],
  edgeFade: [0.01, 1],
};
const REFRESH = {
  moveShare: [0.001, 1],
  everyS: [0.1, 3600],
  turnDeg: [0.01, 45],
};
const TIER = {
  resolution: ['count', 64, 4096],
  texelM: [0.25, 256],
  levels: ['count', 1, MAX_LEVELS],
  levelScale: ['count', 2, 16],
  steps: ['count', 2, MAX_STEPS],
  reachM: [1, 100000],
  fillKtris: [1, 100000],
  fillDraws: ['count', 1, 100000],
  sweepRows: ['count', 1, 4096],
};

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const fail = (m) => {
  throw new Error(`lodshadows.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkSection(where, obj, schema) {
  checkKeys(where, obj, Object.keys(schema));
  for (const [k, spec] of Object.entries(schema)) checkValue(`${where}.${k}`, obj[k], spec);
}

/** Checks the tunables against the schema and each other; returns them. Throws naming the entry. */
export function validateLodShadows(data) {
  checkKeys('(root)', data, ['heights', 'march', 'refresh', 'tiers']);
  checkSection('heights', data.heights, HEIGHTS);
  if (data.heights.topM <= data.heights.bottomM) fail('heights.topM must be over heights.bottomM');
  checkSection('march', data.march, MARCH);
  checkSection('refresh', data.refresh, REFRESH);
  checkKeys('tiers', data.tiers, TIERS);
  for (const tier of TIERS) {
    const t = data.tiers[tier];
    checkSection(`tiers.${tier}`, t, TIER);
    if ((t.resolution & (t.resolution - 1)) !== 0) fail(`tiers.${tier}.resolution must be a power of two`);
    if (t.sweepRows > t.resolution) fail(`tiers.${tier}.sweepRows must be at most its resolution`);
    const half = (t.resolution * t.texelM * t.levelScale ** (t.levels - 1)) / 2;
    if (t.reachM > half) fail(`tiers.${tier}.reachM must be at most the outermost map's half-width (${half} m)`);
    if (t.reachM <= t.texelM * data.march.startTexels) {
      fail(`tiers.${tier}.reachM must be over the first step (texelM × march.startTexels)`);
    }
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const value = (v, spec) => (spec[0] === 'count' ? `${v}` : rf(v));

function section(rs, indent, name, type, obj, schema) {
  rs.push(`${indent}${name}: ${type} {`);
  for (const [k, spec] of Object.entries(schema)) rs.push(`${indent}    ${snake(k)}: ${value(obj[k], spec)},`);
  rs.push(`${indent}},`);
}

/** The Rust source for validated tunables. */
export function lodShadowsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::lod_shadows::*;', ''];
  rs.push("/// The distant terrain's shadows' tunables (shared/look/lodshadows.json).");
  rs.push('pub const LOD_SHADOWS: LodShadowTunables = LodShadowTunables {');
  section(rs, '    ', 'heights', 'HeightRange', data.heights, HEIGHTS);
  section(rs, '    ', 'march', 'MarchTunables', data.march, MARCH);
  section(rs, '    ', 'refresh', 'RefreshTunables', data.refresh, REFRESH);
  rs.push('    tiers: [');
  for (const tier of TIERS) {
    rs.push(`        // ${tier}`);
    rs.push('        LodShadowTier {');
    for (const [k, spec] of Object.entries(TIER)) rs.push(`            ${snake(k)}: ${value(data.tiers[tier][k], spec)},`);
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateLodShadows(JSON.parse(readFileSync(join(here, 'lodshadows.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/lodshadows.gen.rs'), lodShadowsRust(data));
  console.log('look: LOD shadow tunables generated');
}
