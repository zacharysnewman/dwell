#!/usr/bin/env node
// Generates the dynamic lights' tunables (docs/LIGHTS.md §3) for Rust
// (crates/dwell-look/src/lights.gen.rs) from shared/look/lights.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff. The light sources themselves are block data
// (shared/blocks `lights`, lights.mjs there).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/lights.mjs from shared/look/lights.json. Do not edit.';

/** The most lights the shader's array holds (dwell-look `lights::MAX_SHADER_LIGHTS`). */
export const MAX_SHADER_LIGHTS = 16;
/** The most lights with shadow maps (dwell-look `lights::MAX_SHADOWED`). */
export const MAX_SHADOWED = 4;

const fail = (m) => {
  throw new Error(`lights.json: ${m}`);
};

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/** Checks the data; returns it. */
export function validateLights(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('must be an object');
  const keys = ['maxLights', 'cullM', 'curve', 'wrap', 'glowPeak', 'shadows'];
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry ${k}`);
  checkNumber('maxLights', data.maxLights, 0, MAX_SHADER_LIGHTS);
  if (!Number.isInteger(data.maxLights)) fail(`maxLights must be a whole number, got ${data.maxLights}`);
  checkNumber('cullM', data.cullM, 1, 512);
  checkNumber('curve', data.curve, 1, 16);
  checkNumber('wrap', data.wrap, 0, 1);
  checkNumber('glowPeak', data.glowPeak, 0.1, 1e9);
  const sh = data.shadows;
  if (typeof sh !== 'object' || sh === null || Array.isArray(sh)) fail('shadows must be an object');
  const shKeys = ['tiers', 'redrawsPerFrame', 'placedM', 'placedStrength', 'nearM', 'biasM', 'normalOffsetM', 'faceMargin'];
  for (const k of Object.keys(sh)) if (k !== '$comment' && !shKeys.includes(k)) fail(`unknown entry shadows.${k}`);
  for (const k of shKeys) if (!(k in sh)) fail(`missing entry shadows.${k}`);
  if (!Array.isArray(sh.tiers) || sh.tiers.length !== 2) fail('shadows.tiers must be [Low, High]');
  sh.tiers.forEach((t, i) => {
    const w = `shadows.tiers[${i}]`;
    if (typeof t !== 'object' || t === null) fail(`${w} must be an object`);
    for (const k of Object.keys(t)) if (!['lights', 'resolution'].includes(k)) fail(`unknown entry ${w}.${k}`);
    checkNumber(`${w}.lights`, t.lights, 1, MAX_SHADOWED);
    if (!Number.isInteger(t.lights)) fail(`${w}.lights must be a whole number`);
    if (![64, 128, 256, 384, 512, 768, 1024].includes(t.resolution)) fail(`${w}.resolution must be one of 64, 128, 256, 384, 512, 768, 1024`);
  });
  checkNumber('shadows.redrawsPerFrame', sh.redrawsPerFrame, 1, MAX_SHADOWED);
  if (!Number.isInteger(sh.redrawsPerFrame)) fail('shadows.redrawsPerFrame must be a whole number');
  checkNumber('shadows.placedM', sh.placedM, 0, 64);
  checkNumber('shadows.placedStrength', sh.placedStrength, 0, 1);
  checkNumber('shadows.nearM', sh.nearM, 0.01, 1);
  checkNumber('shadows.biasM', sh.biasM, 0, 1);
  checkNumber('shadows.normalOffsetM', sh.normalOffsetM, 0, 1);
  checkNumber('shadows.faceMargin', sh.faceMargin, 1, 1.5);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated data. */
export function lightsRust(data) {
  return [
    `// ${header}`,
    '',
    'use crate::lights::{LightTunables, TorchShadowTier, TorchShadowTunables};',
    '',
    '/// The dynamic lights (shared/look/lights.json).',
    'pub const LIGHTS: LightTunables = LightTunables {',
    `    max_lights: ${data.maxLights},`,
    `    cull_m: ${rf(data.cullM)},`,
    `    curve: ${rf(data.curve)},`,
    `    wrap: ${rf(data.wrap)},`,
    `    glow_peak: ${rf(data.glowPeak)},`,
    '    shadows: TorchShadowTunables {',
    `        tiers: [${data.shadows.tiers.map((t) => `TorchShadowTier { lights: ${t.lights}, resolution: ${t.resolution} }`).join(', ')}],`,
    `        redraws_per_frame: ${data.shadows.redrawsPerFrame},`,
    `        placed_m: ${rf(data.shadows.placedM)},`,
    `        placed_strength: ${rf(data.shadows.placedStrength)},`,
    `        near_m: ${rf(data.shadows.nearM)},`,
    `        bias_m: ${rf(data.shadows.biasM)},`,
    `        normal_offset_m: ${rf(data.shadows.normalOffsetM)},`,
    `        face_margin: ${rf(data.shadows.faceMargin)},`,
    '    },',
    '};',
    '',
  ].join('\n');
}

export function loadLights() {
  return validateLights(JSON.parse(readFileSync(join(here, 'lights.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/lights.gen.rs'), lightsRust(loadLights()));
  console.log('look: lights generated');
}
