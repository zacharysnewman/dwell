#!/usr/bin/env node
// Generates the dynamic lights' tunables (docs/LIGHTS.md §3) for Rust
// (crates/dwell-look/src/lights.gen.rs) from shared/look/lights.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff. The light sources themselves are block data
// (shared/blocks `lights`, lights.mjs there).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/lights.mjs from shared/look/lights.json. Do not edit.';

/** The most lights the shader's array holds (dwell-look `lights::MAX_SHADER_LIGHTS`). */
export const MAX_SHADER_LIGHTS = 16;

const fail = (m) => {
  throw new Error(`lights.json: ${m}`);
};

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/** Checks the data; returns it. */
export function validateLights(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('must be an object');
  const keys = ['maxLights', 'cullM', 'curve', 'wrap'];
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry ${k}`);
  checkNumber('maxLights', data.maxLights, 0, MAX_SHADER_LIGHTS);
  if (!Number.isInteger(data.maxLights)) fail(`maxLights must be a whole number, got ${data.maxLights}`);
  checkNumber('cullM', data.cullM, 1, 512);
  checkNumber('curve', data.curve, 1, 16);
  checkNumber('wrap', data.wrap, 0, 1);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated data. */
export function lightsRust(data) {
  return [
    `// ${header}`,
    '',
    'use crate::lights::LightTunables;',
    '',
    '/// The dynamic lights (shared/look/lights.json).',
    'pub const LIGHTS: LightTunables = LightTunables {',
    `    max_lights: ${data.maxLights},`,
    `    cull_m: ${rf(data.cullM)},`,
    `    curve: ${rf(data.curve)},`,
    `    wrap: ${rf(data.wrap)},`,
    '};',
    '',
  ].join('\n');
}

export function loadLights() {
  return validateLights(JSON.parse(readFileSync(join(here, 'lights.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/lights.gen.rs'), lightsRust(loadLights()));
  console.log('look: lights generated');
}
