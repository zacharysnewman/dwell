#!/usr/bin/env node
// Generates the sun and moon shadows' tunables for Rust (crates/dwell-look/src/shadows.gen.rs)
// from shared/look/shadows.json (docs/DAY_NIGHT.md §10), after validating them: an unknown,
// missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/shadows.mjs from shared/look/shadows.json. Do not edit.';

/** The most cascades a tier may have (the shader's array, the uniform block). */
export const MAX_CASCADES = 4;
/** The most PCF taps a side (each is a 2×2 hardware compare per shaded pixel). */
export const MAX_TAPS = 4;

/** The Shadows setting's tiers that draw shadows, in the renderer's order (Off draws none). */
export const TIERS = ['low', 'high'];
/** The lights that cast. */
export const LIGHTS = ['sun', 'moon'];

/** Field → [min, max] (numbers) or ['count', min, max] (whole). */
const CASCADES = {
  nearM: [0.01, 100],
  radiusStepM: [0.01, 100],
  casterReachM: [0, 10000],
  edgeFade: [0.01, 1],
  spyglassMaxM: [1, 10000],
};
const BIAS = {
  normalOffsetTexels: [0, 16],
  depthBiasM: [0, 4],
  slopeScale: [0, 16],
};
const LIGHT = {
  fadeStartDeg: [-10, 90],
  fadeEndDeg: [-10, 90],
  strength: [0, 1],
};
const TIER = {
  cascades: ['count', 1, MAX_CASCADES],
  resolution: ['count', 64, 8192],
  distanceM: [1, 10000],
  splitLambda: [0, 1],
  filterTexels: [0, 8],
  filterTaps: ['count', 1, MAX_TAPS],
  refreshFrames: ['count', 1, 16],
};

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const fail = (m) => {
  throw new Error(`shadows.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkSection(where, obj, schema) {
  checkKeys(where, obj, Object.keys(schema));
  for (const [k, spec] of Object.entries(schema)) checkValue(`${where}.${k}`, obj[k], spec);
}

/** Checks the tunables against the schema and each other; returns them. Throws naming the entry. */
export function validateShadows(data) {
  checkKeys('(root)', data, ['cascades', 'bias', 'lights', 'tiers']);
  checkSection('cascades', data.cascades, CASCADES);
  checkSection('bias', data.bias, BIAS);
  checkKeys('lights', data.lights, LIGHTS);
  for (const light of LIGHTS) {
    const l = data.lights[light];
    checkSection(`lights.${light}`, l, LIGHT);
    if (l.fadeEndDeg <= l.fadeStartDeg) fail(`lights.${light}.fadeEndDeg must be over fadeStartDeg`);
  }
  checkKeys('tiers', data.tiers, TIERS);
  for (const tier of TIERS) {
    const t = data.tiers[tier];
    checkSection(`tiers.${tier}`, t, TIER);
    if ((t.resolution & (t.resolution - 1)) !== 0) fail(`tiers.${tier}.resolution must be a power of two`);
    if (t.distanceM <= data.cascades.nearM) fail(`tiers.${tier}.distanceM must be over cascades.nearM`);
    if (t.refreshFrames < t.cascades - 1) fail(`tiers.${tier}.refreshFrames must be at least cascades − 1`);
  }
  if (data.cascades.spyglassMaxM < Math.max(...TIERS.map((t) => data.tiers[t].distanceM))) {
    fail('cascades.spyglassMaxM must be at least every tier\'s distanceM');
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const value = (v, spec) => (spec[0] === 'count' ? `${v}` : rf(v));

function section(rs, indent, name, type, obj, schema) {
  rs.push(`${indent}${name}: ${type} {`);
  for (const [k, spec] of Object.entries(schema)) rs.push(`${indent}    ${snake(k)}: ${value(obj[k], spec)},`);
  rs.push(`${indent}},`);
}

/** The Rust source for validated tunables. */
export function shadowsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::shadows::*;', ''];
  rs.push("/// The sun and moon shadows' tunables (shared/look/shadows.json).");
  rs.push('pub const SHADOWS: ShadowTunables = ShadowTunables {');
  section(rs, '    ', 'cascades', 'CascadeTunables', data.cascades, CASCADES);
  section(rs, '    ', 'bias', 'BiasTunables', data.bias, BIAS);
  section(rs, '    ', 'sun', 'LightTunables', data.lights.sun, LIGHT);
  section(rs, '    ', 'moon', 'LightTunables', data.lights.moon, LIGHT);
  rs.push('    tiers: [');
  for (const tier of TIERS) {
    rs.push(`        // ${tier}`);
    rs.push('        ShadowTier {');
    for (const [k, spec] of Object.entries(TIER)) rs.push(`            ${snake(k)}: ${value(data.tiers[tier][k], spec)},`);
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateShadows(JSON.parse(readFileSync(join(here, 'shadows.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/shadows.gen.rs'), shadowsRust(data));
  console.log('look: shadow tunables generated');
}
