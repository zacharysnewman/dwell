#!/usr/bin/env node
// Generates the flame looks (docs/LIGHTS.md §6) for Rust (crates/dwell-look/src/flames.gen.rs) from
// shared/look/flames.json, after validating them: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff. Light
// sources reference a flame by name (shared/blocks `lights`, `flame`); shared/blocks/gen.mjs checks
// the names against `flameNames`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/flames.mjs from shared/look/flames.json. Do not edit.';

const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
const COLOR = /^#[0-9a-fA-F]{6}$/;
/** The most colours a ramp holds (the shader's array). */
export const MAX_RAMP = 6;

const fail = (m) => {
  throw new Error(`flames.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, { open = false, whole = false } = {}) {
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (whole && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkColor(where, v) {
  if (typeof v !== 'string' || !COLOR.test(v)) fail(`${where} must be #rrggbb, got ${JSON.stringify(v)}`);
}

// Every number of a flame look: [min, max, options].
const NUMBERS = {
  bands: [0, 8, { whole: true }],
  heightM: [0, 2, { open: true }],
  widthM: [0, 1, { open: true }],
  baseM: [0, 1],
  speed: [0, 10, { open: true }],
  noiseScale: [0.25, 8],
  distort: [0, 2],
  tongues: [0, 3],
  sway: [0, 1],
  sizeFlicker: [0, 4],
};
const GLOW = { radiusM: [0, 4, { open: true }], strength: [0, 2] };
const EMBERS = {
  count: [0, 8, { whole: true }],
  sizeM: [0, 0.1, { open: true }],
  riseM: [0, 4],
  speed: [0, 10, { open: true }],
};

/** One flame look, checked: throws naming the bad entry. */
export function checkFlame(name, f) {
  const at = `flames.${name}`;
  if (!NAME.test(name)) fail(`${at}: the name must be \`namespace:name\` (lowercase, digits, _)`);
  checkKeys(at, f, ['ramp', ...Object.keys(NUMBERS), 'glow', 'embers']);
  if (!Array.isArray(f.ramp) || f.ramp.length < 2 || f.ramp.length > MAX_RAMP) {
    fail(`${at}.ramp must list 2 to ${MAX_RAMP} colours (tips to core)`);
  }
  f.ramp.forEach((c, i) => checkColor(`${at}.ramp[${i}]`, c));
  for (const [k, [lo, hi, o]] of Object.entries(NUMBERS)) checkNumber(`${at}.${k}`, f[k], lo, hi, o);
  checkKeys(`${at}.glow`, f.glow, ['color', ...Object.keys(GLOW)]);
  checkColor(`${at}.glow.color`, f.glow.color);
  for (const [k, [lo, hi, o]] of Object.entries(GLOW)) checkNumber(`${at}.glow.${k}`, f.glow[k], lo, hi, o);
  checkKeys(`${at}.embers`, f.embers, ['color', ...Object.keys(EMBERS)]);
  checkColor(`${at}.embers.color`, f.embers.color);
  for (const [k, [lo, hi, o]] of Object.entries(EMBERS)) checkNumber(`${at}.embers.${k}`, f.embers[k], lo, hi, o);
  return f;
}

/** Checks the data; returns it. */
export function validateFlames(data) {
  checkKeys('the file', data, ['drawM', 'maxFlames', 'flames']);
  checkNumber('drawM', data.drawM, 1, 256);
  checkNumber('maxFlames', data.maxFlames, 1, 256, { whole: true });
  if (typeof data.flames !== 'object' || data.flames === null || Array.isArray(data.flames)) fail('flames must be an object');
  const names = Object.keys(data.flames).filter((k) => k !== '$comment');
  if (names.length === 0) fail('flames must have at least one look');
  if (names.length > 255) fail('too many flames');
  for (const n of names) checkFlame(n, data.flames[n]);
  return data;
}

/** The flame looks' names, in table order (what light sources may reference). */
export function flameNames(data) {
  return Object.keys(data.flames).filter((k) => k !== '$comment');
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const hex = (c) => `0x${c.replace('#', '').toLowerCase()}`;

/** The Rust source for validated data. */
export function flamesRust(data) {
  const names = flameNames(data);
  const rows = names.map((n) => {
    const f = data.flames[n];
    return [
      '    FlameLook {',
      `        name: ${JSON.stringify(n)},`,
      `        ramp: &[${f.ramp.map(hex).join(', ')}],`,
      `        bands: ${f.bands},`,
      `        height_m: ${rf(f.heightM)},`,
      `        width_m: ${rf(f.widthM)},`,
      `        base_m: ${rf(f.baseM)},`,
      `        speed: ${rf(f.speed)},`,
      `        noise_scale: ${rf(f.noiseScale)},`,
      `        distort: ${rf(f.distort)},`,
      `        tongues: ${rf(f.tongues)},`,
      `        sway: ${rf(f.sway)},`,
      `        size_flicker: ${rf(f.sizeFlicker)},`,
      `        glow: FlameGlow { color: ${hex(f.glow.color)}, radius_m: ${rf(f.glow.radiusM)}, strength: ${rf(f.glow.strength)} },`,
      `        embers: FlameEmbers { count: ${f.embers.count}, color: ${hex(f.embers.color)}, size_m: ${rf(f.embers.sizeM)}, rise_m: ${rf(f.embers.riseM)}, speed: ${rf(f.embers.speed)} },`,
      '    },',
    ].join('\n');
  });
  return [
    `// ${header}`,
    '',
    'use crate::flames::{FlameEmbers, FlameGlow, FlameLook, FlameTunables};',
    '',
    '/// The flames\' tunables (shared/look/flames.json).',
    'pub const FLAME_TUNABLES: FlameTunables = FlameTunables {',
    `    draw_m: ${rf(data.drawM)},`,
    `    max_flames: ${data.maxFlames},`,
    '};',
    '',
    '/// The flame looks, in the file\'s order (a look\'s index is its id in the shader).',
    `pub static FLAMES: [FlameLook; ${names.length}] = [`,
    ...rows,
    '];',
    '',
  ].join('\n');
}

export function loadFlames() {
  return validateFlames(JSON.parse(readFileSync(join(here, 'flames.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/flames.gen.rs'), flamesRust(loadFlames()));
  console.log('look: flames generated');
}
