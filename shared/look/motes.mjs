#!/usr/bin/env node
// Generates the mote looks (docs/BIFACIAL_WORLD.md §12.1) for Rust (crates/dwell-look/src/motes.gen.rs)
// from shared/look/motes.json, after validating them: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff. Portals
// reference a look by name (shared/worldgen/midplane.json `portals.motes`); shared/worldgen/gen.mjs
// checks the name against `moteNames`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/motes.mjs from shared/look/motes.json. Do not edit.';

const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
const COLOR = /^#[0-9a-fA-F]{6}$/;

const fail = (m) => {
  throw new Error(`motes.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, { open = false, whole = false } = {}) {
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (whole && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkColor(where, v) {
  if (typeof v !== 'string' || !COLOR.test(v)) fail(`${where} must be #rrggbb, got ${JSON.stringify(v)}`);
}

// Every number of a mote look: [min, max, options].
const NUMBERS = {
  count: [0, 256, { whole: true }],
  cpuCount: [0, 256, { whole: true }],
  sizeM: [0, 0.5, { open: true }],
  radiusM: [0, 16, { open: true }],
  heightM: [0, 64, { open: true }],
  swirl: [0, 4],
  drift: [0, 8],
  wobbleM: [0, 4],
  glow: [0, 8],
  pulseHz: [0, 8],
  pulseDepth: [0, 1],
};

/** One mote look, checked: throws naming the bad entry. */
export function checkMotes(name, m) {
  const at = `motes.${name}`;
  if (!NAME.test(name)) fail(`${at}: the name must be \`namespace:name\` (lowercase, digits, _)`);
  checkKeys(at, m, ['color', 'core', ...Object.keys(NUMBERS)]);
  checkColor(`${at}.color`, m.color);
  checkColor(`${at}.core`, m.core);
  for (const [k, [lo, hi, o]] of Object.entries(NUMBERS)) checkNumber(`${at}.${k}`, m[k], lo, hi, o);
  if (m.cpuCount > m.count) fail(`${at}.cpuCount must be at most count`);
  return m;
}

/** Checks the data; returns it. */
export function validateMotes(data) {
  checkKeys('the file', data, ['drawM', 'maxMotes', 'motes']);
  checkNumber('drawM', data.drawM, 1, 512);
  checkNumber('maxMotes', data.maxMotes, 1, 4096, { whole: true });
  if (typeof data.motes !== 'object' || data.motes === null || Array.isArray(data.motes)) fail('motes must be an object');
  const names = Object.keys(data.motes).filter((k) => k !== '$comment');
  if (names.length === 0) fail('motes must have at least one look');
  if (names.length > 255) fail('too many mote looks');
  for (const n of names) checkMotes(n, data.motes[n]);
  return data;
}

/** The mote looks' names, in table order (what portals may reference). */
export function moteNames(data) {
  return Object.keys(data.motes).filter((k) => k !== '$comment');
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const hex = (c) => `0x${c.replace('#', '').toLowerCase()}`;

/** The Rust source for validated data. */
export function motesRust(data) {
  const names = moteNames(data);
  const rows = names.map((n) => {
    const m = data.motes[n];
    return [
      '    MoteLook {',
      `        name: ${JSON.stringify(n)},`,
      `        color: ${hex(m.color)},`,
      `        core: ${hex(m.core)},`,
      `        count: ${m.count},`,
      `        cpu_count: ${m.cpuCount},`,
      `        size_m: ${rf(m.sizeM)},`,
      `        radius_m: ${rf(m.radiusM)},`,
      `        height_m: ${rf(m.heightM)},`,
      `        swirl: ${rf(m.swirl)},`,
      `        drift: ${rf(m.drift)},`,
      `        wobble_m: ${rf(m.wobbleM)},`,
      `        glow: ${rf(m.glow)},`,
      `        pulse_hz: ${rf(m.pulseHz)},`,
      `        pulse_depth: ${rf(m.pulseDepth)},`,
      '    },',
    ].join('\n');
  });
  return [
    `// ${header}`,
    '',
    'use crate::motes::{MoteLook, MoteTunables};',
    '',
    "/// The motes' tunables (shared/look/motes.json).",
    'pub const MOTE_TUNABLES: MoteTunables = MoteTunables {',
    `    draw_m: ${rf(data.drawM)},`,
    `    max_motes: ${data.maxMotes},`,
    '};',
    '',
    "/// The mote looks, in the file's order (a look's index is its id in the shader).",
    `pub static MOTES: [MoteLook; ${names.length}] = [`,
    ...rows,
    '];',
    '',
  ].join('\n');
}

export function loadMotes() {
  return validateMotes(JSON.parse(readFileSync(join(here, 'motes.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/motes.gen.rs'), motesRust(loadMotes()));
  console.log('look: motes generated');
}
