#!/usr/bin/env node
// Generates the atmosphere (docs/DAY_NIGHT.md §15) for Rust (crates/dwell-look/src/atmosphere.gen.rs)
// from shared/look/atmosphere.json, after validating it: an unknown, missing or out-of-range entry
// fails with its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/atmosphere.mjs from shared/look/atmosphere.json. Do not edit.';

/** Field → [min, max] (numbers) or 'color' (#rrggbb). */
export const ATMOSPHERE_SCHEMA = {
  baseM: [0, 1e6],
  topM: [100, 1e7],
  scaleHeightM: [100, 1e6],
  spaceColor: 'color',
  starsInSpace: [0, 1],
  limbBrightness: [0, 4],
  limbWidthDeg: [0.05, 30],
  limbDistanceM: [1000, 1e8],
  limbFadeM: [1, 1e8],
  sunWhiteness: [0, 1],
  sunBloom: [0, 1],
};

const fail = (m) => {
  throw new Error(`atmosphere.json: ${m}`);
};

/** Checks the atmosphere; returns it. Throws naming the entry. */
export function validateAtmosphere(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  const keys = Object.keys(ATMOSPHERE_SCHEMA);
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry (root).${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry (root).${k}`);
  for (const [k, spec] of Object.entries(ATMOSPHERE_SCHEMA)) {
    const v = data[k];
    if (spec === 'color') {
      if (typeof v !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v))
        fail(`${k} must be a colour "#rrggbb", got ${JSON.stringify(v)}`);
      continue;
    }
    const [lo, hi] = spec;
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
      fail(`${k} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  }
  if (data.topM <= data.baseM) fail('topM must be greater than baseM');
  return data;
}

/** The checked-in atmosphere, validated (clouds.mjs reads its top). */
export function loadAtmosphere() {
  return validateAtmosphere(JSON.parse(readFileSync(join(here, 'atmosphere.json'), 'utf8')));
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rgb = (hex) => [1, 3, 5].map((i) => rf(+(parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(6)));

/** The Rust source for a validated atmosphere. */
export function atmosphereRust(data) {
  const rs = [`// ${header}`, '', 'use crate::atmosphere::Atmosphere;', ''];
  rs.push('/// The atmosphere every client draws (shared/look/atmosphere.json).');
  rs.push('pub const ATMOSPHERE: Atmosphere = Atmosphere {');
  for (const [k, spec] of Object.entries(ATMOSPHERE_SCHEMA)) {
    const v = data[k];
    rs.push(`    ${snake(k)}: ${spec === 'color' ? `[${rgb(v).join(', ')}]` : rf(v)},`);
  }
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = loadAtmosphere();
  writeFileSync(join(root, 'crates/dwell-look/src/atmosphere.gen.rs'), atmosphereRust(data));
  console.log('look: atmosphere generated');
}
