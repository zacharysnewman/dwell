#!/usr/bin/env node
// Generates the 3D pixel-art preview's palettes and presets (docs/proposals/PIXEL_ART_LOOK.md) for
// Rust (crates/dwell-look/src/pixelart.gen.rs) from shared/look/pixelart.json, with palette
// references resolved from shared/textures/palette.json, after validating them: an unknown,
// missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolveColor, validatePalette } from '../textures/paint.mjs';
import { STYLES } from '../textures/cel.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/pixelart.mjs from shared/look/pixelart.json. Do not edit.';

/** The edge kinds (the ink outline's bits, dwell-look outline.rs `EDGE_*`). */
export const EDGE_KINDS = ['depth', 'normal'];
export const FITS = ['crop', 'letterbox'];
export const ATLAS = ['point', 'point-mips'];
/** The most colours a palette holds (the post pass's uniform array). */
export const MAX_COLORS = 64;
export const MIN_COLORS = 4;
export const MAX_PRESETS = 16;

const fail = (m) => {
  throw new Error(`pixelart.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, whole = false) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (whole && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkOneOf(where, v, options) {
  if (!options.includes(v)) fail(`${where} must be one of ${options.join(', ')}, got ${JSON.stringify(v)}`);
}

const PRESET_KEYS = [
  'name',
  'height',
  'fit',
  'palette',
  'dither',
  'bands',
  'ambientBands',
  'shadowHue',
  'shadowTint',
  'edges',
  'edgeDarken',
  'edgeFadeM',
  'atlas',
  'textures',
  'snapCamera',
  'snapDepthM',
];

const HEX = /^#[0-9a-fA-F]{6}$/;

function colour(palette, ref, where) {
  if (typeof ref === 'string' && ref.startsWith('#')) {
    if (!HEX.test(ref)) fail(`${where} must be a colour "#rrggbb" or a palette reference, got ${JSON.stringify(ref)}`);
    const n = parseInt(ref.slice(1), 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  try {
    return resolveColor(palette, ref, null, where);
  } catch (e) {
    fail(e.message);
  }
}

function checkBands(where, v) {
  checkNumber(where, v, 0, 16, true);
  if (v === 1) fail(`${where} must be 0 (smooth) or at least 2 levels, got 1`);
}

/** Checks the preview's data against `palette`; returns it with every colour resolved (sRGB bytes). */
export function validatePixelArt(data, palette) {
  checkKeys('(root)', data, ['palettes', 'presets']);
  validatePalette(palette);
  if (typeof data.palettes !== 'object' || data.palettes === null || Array.isArray(data.palettes)) {
    fail('palettes must be an object of named palettes');
  }
  const palettes = {};
  for (const [name, ramps] of Object.entries(data.palettes)) {
    if (name === '$comment') continue;
    const at = `palettes.${name}`;
    if (!/^[a-z][a-z0-9-]*$/.test(name)) fail(`${at}: a palette's name must be lower-case letters, digits and '-'`);
    if (!Array.isArray(ramps) || ramps.length === 0) fail(`${at} must be a list of ramps`);
    const seen = new Map();
    const resolved = ramps.map((ramp, i) => {
      if (!Array.isArray(ramp) || ramp.length < 2 || ramp.length > 8) {
        fail(`${at}[${i}] must be a ramp of 2 to 8 colours, dark to light`);
      }
      return ramp.map((ref, j) => {
        const where = `${at}[${i}][${j}]`;
        const c = colour(palette, ref, where);
        const key = c.join(',');
        if (seen.has(key)) fail(`${where} is the same colour as ${seen.get(key)}`);
        seen.set(key, where);
        return c;
      });
    });
    const count = resolved.reduce((n, r) => n + r.length, 0);
    if (count < MIN_COLORS || count > MAX_COLORS) {
      fail(`${at} must hold ${MIN_COLORS} to ${MAX_COLORS} colours, has ${count}`);
    }
    palettes[name] = resolved;
  }
  if (Object.keys(palettes).length === 0) fail('palettes must name at least one palette');
  if (!Array.isArray(data.presets) || data.presets.length === 0 || data.presets.length > MAX_PRESETS) {
    fail(`presets must be a list of 1 to ${MAX_PRESETS} presets`);
  }
  const names = new Set();
  const presets = data.presets.map((p, i) => {
    const at = `presets[${i}]`;
    checkKeys(at, p, PRESET_KEYS);
    if (typeof p.name !== 'string' || !/^[a-z0-9][a-z0-9-]*$/.test(p.name)) {
      fail(`${at}.name must be lower-case letters, digits and '-', got ${JSON.stringify(p.name)}`);
    }
    if (p.name === 'off') fail(`${at}.name "off" is reserved (it turns the preview off)`);
    if (names.has(p.name)) fail(`${at}.name "${p.name}" is another preset's`);
    names.add(p.name);
    checkNumber(`${at}.height`, p.height, 60, 1080, true);
    checkOneOf(`${at}.fit`, p.fit, FITS);
    if (!(p.palette in palettes)) fail(`${at}.palette "${p.palette}" is not a palette (${Object.keys(palettes).join(', ')})`);
    checkNumber(`${at}.dither`, p.dither, 0, 1);
    checkBands(`${at}.bands`, p.bands);
    checkBands(`${at}.ambientBands`, p.ambientBands);
    checkNumber(`${at}.shadowHue`, p.shadowHue, 0, 1);
    const tint = colour(palette, p.shadowTint, `${at}.shadowTint`);
    if (!Array.isArray(p.edges)) fail(`${at}.edges must be a list of ${EDGE_KINDS.join(', ')} (or [])`);
    p.edges.forEach((e, j) => {
      if (!EDGE_KINDS.includes(e)) fail(`${at}.edges[${j}] "${e}" is not an edge kind (${EDGE_KINDS.join(', ')})`);
      if (p.edges.indexOf(e) !== j) fail(`${at}.edges[${j}] "${e}" is listed twice`);
    });
    checkNumber(`${at}.edgeDarken`, p.edgeDarken, 0, 1);
    checkNumber(`${at}.edgeFadeM`, p.edgeFadeM, 1, 4096);
    checkOneOf(`${at}.atlas`, p.atlas, ATLAS);
    checkOneOf(`${at}.textures`, p.textures, STYLES);
    if (typeof p.snapCamera !== 'boolean') fail(`${at}.snapCamera must be true or false`);
    checkNumber(`${at}.snapDepthM`, p.snapDepthM, 0.5, 1024);
    return { ...p, tintRgb: tint };
  });
  return { palettes, presets };
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const unit = (c) => `[${c.map((v) => rf(+(v / 255).toFixed(6))).join(', ')}]`;
const pascal = (s) => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');

/** The Rust source for validated data. */
export function pixelArtRust(data) {
  const rs = [`// ${header}`, '', 'use crate::pixel_art::*;', ''];
  const names = Object.keys(data.palettes);
  rs.push("/// The pixel-art preview's palettes and presets (shared/look/pixelart.json).");
  rs.push('pub const PIXEL_ART: PixelArtTunables = PixelArtTunables {');
  rs.push('    palettes: &[');
  for (const name of names) {
    rs.push('        Palette {');
    rs.push(`            name: ${JSON.stringify(name)},`);
    rs.push('            ramps: &[');
    for (const ramp of data.palettes[name]) {
      rs.push('                &[');
      for (const c of ramp) rs.push(`                    ${unit(c)},`);
      rs.push('                ],');
    }
    rs.push('            ],');
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('    presets: &[');
  for (const p of data.presets) {
    const edges = p.edges.reduce((bits, e) => bits | (1 << EDGE_KINDS.indexOf(e)), 0);
    rs.push('        PixelArtPreset {');
    rs.push(`            name: ${JSON.stringify(p.name)},`);
    rs.push(`            height: ${p.height},`);
    rs.push(`            fit: Fit::${pascal(p.fit)},`);
    rs.push(`            palette: ${names.indexOf(p.palette)},`);
    rs.push(`            dither: ${rf(p.dither)},`);
    rs.push(`            bands: ${p.bands},`);
    rs.push(`            ambient_bands: ${p.ambientBands},`);
    rs.push(`            shadow_hue: ${rf(p.shadowHue)},`);
    rs.push(`            shadow_tint: ${unit(p.tintRgb)},`);
    rs.push(`            edges: ${edges},`);
    rs.push(`            edge_darken: ${rf(p.edgeDarken)},`);
    rs.push(`            edge_fade_m: ${rf(p.edgeFadeM)},`);
    rs.push(`            atlas: AtlasFilter::${pascal(p.atlas)},`);
    rs.push(`            textures: Textures::${pascal(p.textures)},`);
    rs.push(`            snap_camera: ${p.snapCamera},`);
    rs.push(`            snap_depth_m: ${rf(p.snapDepthM)},`);
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

export function loadPixelArt() {
  const data = JSON.parse(readFileSync(join(here, 'pixelart.json'), 'utf8'));
  const palette = JSON.parse(readFileSync(join(root, 'shared/textures/palette.json'), 'utf8'));
  return validatePixelArt(data, palette);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/pixelart.gen.rs'), pixelArtRust(loadPixelArt()));
  console.log('look: pixel-art presets generated');
}
