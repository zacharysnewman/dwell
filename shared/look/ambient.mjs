#!/usr/bin/env node
// Generates the ambient lighting's tunables (corner AO, the baked sky visibility, the floor;
// docs/DAY_NIGHT.md §10) for Rust (crates/dwell-look/src/ambient.gen.rs) from
// shared/look/ambient.json, after validating them: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff. Whether
// the rays' reach fits the meshers' apron (dwell_world::SKY_APRON) is checked by the Rust build
// (crates/dwell-look/src/ambient.rs).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/ambient.mjs from shared/look/ambient.json. Do not edit.';

/** The most rays per vertex (the mesher's merge key holds a count of up to 63). */
export const MAX_RAYS = 63;

const fail = (m) => {
  throw new Error(`ambient.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/** Checks the ambient data; returns it. */
export function validateAmbient(data) {
  checkKeys('(root)', data, ['ao', 'sky', 'floor']);
  checkKeys('ao', data.ao, ['strength']);
  checkNumber('ao.strength', data.ao.strength, 0, 1);
  checkKeys('sky', data.sky, ['rays', 'lengthM', 'probeM']);
  checkNumber('sky.rays', data.sky.rays, 0, MAX_RAYS);
  if (!Number.isInteger(data.sky.rays)) fail(`sky.rays must be a whole number, got ${data.sky.rays}`);
  checkNumber('sky.lengthM', data.sky.lengthM, 0.25, 16);
  checkNumber('sky.probeM', data.sky.probeM, 0, 16);
  checkNumber('floor', data.floor, 0, 1);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated data. */
export function ambientRust(data) {
  return [
    `// ${header}`,
    '',
    'use crate::ambient::AmbientTunables;',
    '',
    '/// The ambient lighting (shared/look/ambient.json).',
    'pub const AMBIENT: AmbientTunables = AmbientTunables {',
    `    ao_strength: ${rf(data.ao.strength)},`,
    `    rays: ${data.sky.rays},`,
    `    length_m: ${rf(data.sky.lengthM)},`,
    `    probe_m: ${rf(data.sky.probeM)},`,
    `    floor: ${rf(data.floor)},`,
    '};',
    '',
  ].join('\n');
}

export function loadAmbient() {
  return validateAmbient(JSON.parse(readFileSync(join(here, 'ambient.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/ambient.gen.rs'), ambientRust(loadAmbient()));
  console.log('look: ambient generated');
}
