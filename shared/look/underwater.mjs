#!/usr/bin/env node
// Generates the underwater view's looks (docs/WATER_RENDERING.md §10, the waterline) for Rust
// (crates/dwell-look/src/underwater.gen.rs) from shared/look/underwater.json, after validating
// them: an unknown, missing or out-of-range entry fails with its path named. The output is checked
// in; CI regenerates it and fails on any diff. A fluid is named by its registry fluid (`dwell:water`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/underwater.mjs from shared/look/underwater.json. Do not edit.';

const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
const COLOR = /^#[0-9a-fA-F]{6}$/;

const fail = (m) => {
  throw new Error(`underwater.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, open = false) {
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
}

/** Part → field → [min, max, open below] or 'color'. */
const PARTS = {
  line: { amplitudeM: [0, 0.25], wavelengthM: [0.05, 64, true], speed: [0, 10] },
  band: {
    depthM: [0, 0.25],
    tint: 'color',
    streaks: [0, 1],
    glints: [0, 1],
    rimPx: [0, 32],
    rimShade: [0, 1],
    linePx: [0, 32],
    lineGlow: [1, 4],
    breakup: [0, 1],
    mirror: [0, 1],
    mirrorWarpPx: [0, 32],
  },
  underside: { texture: [0, 1], breakup: [0, 1], sunPatch: [0, 8], sunPower: [1, 256] },
  fog: { clearM: [0, 256], density: [0, 16, true] },
};

/** One fluid's underwater look, checked: throws naming the bad entry. */
export function checkLook(at, l) {
  checkKeys(at, l, ['lensM', ...Object.keys(PARTS)]);
  checkNumber(`${at}.lensM`, l.lensM, 0.01, 2);
  for (const [part, fields] of Object.entries(PARTS)) {
    checkKeys(`${at}.${part}`, l[part], Object.keys(fields));
    for (const [k, spec] of Object.entries(fields)) {
      const v = l[part][k];
      if (spec === 'color') {
        if (typeof v !== 'string' || !COLOR.test(v)) fail(`${at}.${part}.${k} must be #rrggbb, got ${JSON.stringify(v)}`);
      } else {
        checkNumber(`${at}.${part}.${k}`, v, spec[0], spec[1], spec[2]);
      }
    }
  }
  // The line's waves can't reach past the lens: the eye's band (±lensM) must hold them.
  if (l.line.amplitudeM >= l.lensM) fail(`${at}.line.amplitudeM must be under lensM`);
  return l;
}

export function fluidNames(data) {
  return Object.keys(data.fluids).filter((k) => k !== '$comment');
}

/** Checks the data; returns it. */
export function validateUnderwater(data) {
  checkKeys('the file', data, ['default', 'fluids']);
  checkLook('default', data.default);
  if (typeof data.fluids !== 'object' || data.fluids === null || Array.isArray(data.fluids)) {
    fail('fluids must be an object');
  }
  for (const n of fluidNames(data)) {
    if (!NAME.test(n)) fail(`fluids.${n}: the name must be \`namespace:name\` (lowercase, digits, _)`);
    checkLook(`fluids.${n}`, data.fluids[n]);
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const hex = (c) => `0x${c.replace('#', '').toLowerCase()}`;

function lookRust(name, l, indent) {
  const i = ' '.repeat(indent);
  return [
    'UnderwaterLook {',
    `${i}    fluid: ${JSON.stringify(name)},`,
    `${i}    lens_m: ${rf(l.lensM)},`,
    `${i}    line_amplitude_m: ${rf(l.line.amplitudeM)},`,
    `${i}    line_wavelength_m: ${rf(l.line.wavelengthM)},`,
    `${i}    line_speed: ${rf(l.line.speed)},`,
    `${i}    band_depth_m: ${rf(l.band.depthM)},`,
    `${i}    band_tint: ${hex(l.band.tint)},`,
    `${i}    band_streaks: ${rf(l.band.streaks)},`,
    `${i}    band_glints: ${rf(l.band.glints)},`,
    `${i}    band_rim_px: ${rf(l.band.rimPx)},`,
    `${i}    band_rim_shade: ${rf(l.band.rimShade)},`,
    `${i}    band_line_px: ${rf(l.band.linePx)},`,
    `${i}    band_line_glow: ${rf(l.band.lineGlow)},`,
    `${i}    band_breakup: ${rf(l.band.breakup)},`,
    `${i}    band_mirror: ${rf(l.band.mirror)},`,
    `${i}    band_mirror_warp_px: ${rf(l.band.mirrorWarpPx)},`,
    `${i}    underside_texture: ${rf(l.underside.texture)},`,
    `${i}    underside_breakup: ${rf(l.underside.breakup)},`,
    `${i}    underside_sun_patch: ${rf(l.underside.sunPatch)},`,
    `${i}    underside_sun_power: ${rf(l.underside.sunPower)},`,
    `${i}    fog_clear_m: ${rf(l.fog.clearM)},`,
    `${i}    fog_density: ${rf(l.fog.density)},`,
    `${i}}`,
  ].join('\n');
}

/** The Rust source for validated data. */
export function underwaterRust(data) {
  const rs = [`// ${header}`, '', 'use crate::underwater::UnderwaterLook;', ''];
  rs.push('/// The look of a fluid not listed (`default`).');
  rs.push(`pub const DEFAULT_UNDERWATER: UnderwaterLook = ${lookRust('', data.default, 0)};`);
  rs.push('');
  rs.push('/// Each listed fluid\'s look (`fluids`).');
  rs.push('pub const UNDERWATER_LOOKS: &[UnderwaterLook] = &[');
  for (const n of fluidNames(data)) rs.push(`    ${lookRust(n, data.fluids[n], 4)},`);
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateUnderwater(JSON.parse(readFileSync(join(here, 'underwater.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/underwater.gen.rs'), underwaterRust(data));
  console.log('look: underwater looks generated');
}
