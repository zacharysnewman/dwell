#!/usr/bin/env node
// Generates the water reflections' tunables for Rust (crates/dwell-look/src/reflections.gen.rs)
// from shared/look/reflections.json (docs/WATER_RENDERING.md §8), after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { MAX_OCTAVES } from './clouds.mjs';
import { validateWaterTiers } from './watertiers.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/reflections.mjs from shared/look/reflections.json. Do not edit.';

/** The most march and refine steps a tier may take (each is a depth read per water pixel). */
export const MAX_STEPS = 64;
export const MAX_REFINE = 12;

/** The water quality tiers (shared/look/watertiers.json), in the renderer's order (WaterQuality). */
export const WATER_TIERS = validateWaterTiers(JSON.parse(readFileSync(join(here, 'watertiers.json'), 'utf8')));
const TIERS = WATER_TIERS.tiers.map((t) => t.id);
const SCENELESS = WATER_TIERS.tiers.filter((t) => !t.readsScene).map((t) => t.id);

/** Field → [min, max] (numbers), ['count', min, max] (whole) or 'bool'. */
const SSR = {
  thicknessM: [0, 100],
  thicknessRel: [0, 1],
  edgeFade: [0.001, 0.5],
  distanceFade: [0.001, 1],
  rippleScale: [0, 1],
  minReflectance: [0, 0.5],
};
const TIER = {
  ssrSteps: ['count', 0, MAX_STEPS],
  refineSteps: ['count', 0, MAX_REFINE],
  maxDistanceM: [0, 1e5],
  cloudOctaves: ['count', 0, MAX_OCTAVES],
  cloudShadow: 'bool',
};

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const fail = (m) => {
  throw new Error(`reflections.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  if (spec === 'bool') {
    if (typeof v !== 'boolean') fail(`${where} must be true or false, got ${JSON.stringify(v)}`);
    return;
  }
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

/** Checks the tunables against the schema and each other; returns them. Throws naming the entry. */
export function validateReflections(data) {
  checkKeys('(root)', data, ['ssr', 'tiers', 'phone']);
  checkKeys('ssr', data.ssr, Object.keys(SSR));
  for (const [k, spec] of Object.entries(SSR)) checkValue(`ssr.${k}`, data.ssr[k], spec);
  checkKeys('tiers', data.tiers, TIERS);
  for (const tier of TIERS) {
    const t = data.tiers[tier];
    checkKeys(`tiers.${tier}`, t, Object.keys(TIER));
    for (const [k, spec] of Object.entries(TIER)) checkValue(`tiers.${tier}.${k}`, t[k], spec);
    if (SCENELESS.includes(tier) && t.ssrSteps !== 0) fail(`tiers.${tier}.ssrSteps must be 0 (it reads no copy of the scene)`);
    if (t.ssrSteps > 0 && t.maxDistanceM <= 0) fail(`tiers.${tier}.maxDistanceM must be over 0 when it marches`);
  }
  const phone = data.phone;
  if (typeof phone !== 'object' || phone === null || Array.isArray(phone)) fail('phone must be an object');
  for (const [tier, o] of Object.entries(phone)) {
    if (tier === '$comment') continue;
    if (SCENELESS.includes(tier)) fail(`phone.${tier}: it marches nothing, so it has nothing to override`);
    if (!TIERS.includes(tier)) fail(`unknown entry phone.${tier}`);
    if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`phone.${tier} must be an object`);
    for (const [k, v] of Object.entries(o)) {
      if (k === '$comment') continue;
      if (!(k in TIER)) fail(`unknown entry phone.${tier}.${k}`);
      checkValue(`phone.${tier}.${k}`, v, TIER[k]);
    }
    const t = phoneTier(data, tier);
    if (t.ssrSteps > 0 && t.maxDistanceM <= 0) fail(`phone.${tier}.maxDistanceM must be over 0 when it marches`);
  }
  return data;
}

/** A tier as a phone draws it: the tier's entries under the phone's overrides. */
export function phoneTier(data, tier) {
  const t = { ...data.tiers[tier] };
  for (const [k, v] of Object.entries(data.phone?.[tier] ?? {})) if (k !== '$comment') t[k] = v;
  delete t.$comment;
  return t;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const value = (v, spec) => (spec === 'bool' || spec[0] === 'count' ? `${v}` : rf(v));

/** The Rust source for validated tunables. */
export function reflectionsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::reflections::*;', ''];
  rs.push("/// The water reflections' tunables (shared/look/reflections.json).");
  rs.push('pub const REFLECTIONS: ReflectionTunables = ReflectionTunables {');
  rs.push('    ssr: SsrTunables {');
  for (const [k, spec] of Object.entries(SSR)) rs.push(`        ${snake(k)}: ${value(data.ssr[k], spec)},`);
  rs.push('    },');
  rs.push('    tiers: &[');
  const tiers = (pick) => {
    for (const tier of TIERS) {
      rs.push(`        // ${tier}`);
      rs.push('        ReflectionTier {');
      for (const [k, spec] of Object.entries(TIER)) rs.push(`            ${snake(k)}: ${value(pick(tier)[k], spec)},`);
      rs.push('        },');
    }
  };
  tiers((tier) => data.tiers[tier]);
  rs.push('    ],');
  rs.push('    phone_tiers: &[');
  tiers((tier) => phoneTier(data, tier));
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateReflections(JSON.parse(readFileSync(join(here, 'reflections.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/reflections.gen.rs'), reflectionsRust(data));
  console.log('look: reflection tunables generated');
}
