#!/usr/bin/env node
// Generates the water quality tiers for Rust (crates/dwell-look/src/watertiers.gen.rs) from
// shared/look/watertiers.json (docs/WATER_RENDERING.md §4), after validating them: an unknown,
// missing or out-of-range entry fails with its path named. The shell reads the JSON itself
// (client/src/ui/waterSettings.ts, with the same checks). The output is checked in; CI regenerates
// it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/watertiers.mjs from shared/look/watertiers.json. Do not edit.';

/** The most ripple layers (render/water.rs `LAYERS`). */
export const MAX_LAYERS = 3;
/** The most tiers (the frame uniform carries a tier's switches, not its index). */
export const MAX_TIERS = 8;

/** Field → [min, max] (numbers), ['count', min, max] (whole), 'bool' or 'id' / 'text'. */
const TIER = {
  id: 'id',
  label: 'text',
  setting: 'bool',
  cpu: 'bool',
  readsScene: 'bool',
  rippleLayers: ['count', 1, MAX_LAYERS],
  flowStreaks: 'bool',
  bankBand: 'bool',
};
const BAND = {
  reachM: [0.1, 100],
  depthSlack: [0, 4],
  spreadPx: [0, 32],
  blurPx: [0, 32],
  darken: [0, 1],
  strength: [0, 1],
};

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const fail = (m) => {
  throw new Error(`watertiers.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  if (spec === 'bool') {
    if (typeof v !== 'boolean') fail(`${where} must be true or false, got ${JSON.stringify(v)}`);
    return;
  }
  if (spec === 'id') {
    if (typeof v !== 'string' || !/^[a-z][a-z0-9-]*$/.test(v)) fail(`${where} must be a lower-case name, got ${JSON.stringify(v)}`);
    return;
  }
  if (spec === 'text') {
    if (typeof v !== 'string' || v.trim() === '') fail(`${where} must be a non-empty string`);
    return;
  }
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

/** Checks the tiers against the schema and each other; returns them. Throws naming the entry. */
export function validateWaterTiers(data) {
  checkKeys('(root)', data, ['tiers', 'aliases', 'band', 'causticEveryFrames']);
  if (!Array.isArray(data.tiers) || data.tiers.length === 0) fail('tiers must be a non-empty list');
  if (data.tiers.length > MAX_TIERS) fail(`tiers: at most ${MAX_TIERS}`);
  const ids = new Set();
  data.tiers.forEach((t, i) => {
    const where = `tiers[${i}]`;
    checkKeys(where, t, Object.keys(TIER));
    for (const [k, spec] of Object.entries(TIER)) checkValue(`${where}.${k}`, t[k], spec);
    if (ids.has(t.id)) fail(`${where}.id: "${t.id}" is listed twice`);
    ids.add(t.id);
    if (t.cpu && t.readsScene) fail(`${where} (${t.id}): the CPU adapter's tier may not read the scene`);
    if (t.bankBand && !t.readsScene) fail(`${where} (${t.id}).bankBand needs readsScene (it samples the scene copy)`);
  });
  const cpu = data.tiers.filter((t) => t.cpu);
  if (cpu.length !== 1) fail(`exactly one tier must be the CPU adapter's (cpu: true), found ${cpu.length}`);
  if (!data.tiers.some((t) => t.setting)) fail('at least one tier must be offered in Settings (setting: true)');
  checkKeys('aliases', data.aliases, Object.keys(data.aliases).filter((k) => k !== '$comment'));
  for (const [from, to] of Object.entries(data.aliases)) {
    if (from === '$comment') continue;
    if (ids.has(from)) fail(`aliases.${from}: a listed tier can't be an alias`);
    const target = data.tiers.find((t) => t.id === to);
    if (!target) fail(`aliases.${from}: unknown tier ${JSON.stringify(to)}`);
    if (!target.setting) fail(`aliases.${from}: ${to} is not offered in Settings`);
  }
  checkKeys('band', data.band, Object.keys(BAND));
  for (const [k, spec] of Object.entries(BAND)) checkValue(`band.${k}`, data.band[k], spec);
  checkValue('causticEveryFrames', data.causticEveryFrames, ['count', 1, 8]);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const value = (v, spec) =>
  spec === 'id' || spec === 'text' ? JSON.stringify(v) : spec === 'bool' || spec[0] === 'count' ? `${v}` : rf(v);

/** The Rust source for validated tiers. */
export function waterTiersRust(data) {
  const rs = [`// ${header}`, '', 'use crate::water_tiers::*;', ''];
  rs.push('/// The water quality tiers, cheapest first (shared/look/watertiers.json).');
  rs.push('pub const WATER_TIERS: &[WaterTier] = &[');
  for (const t of data.tiers) {
    rs.push('    WaterTier {');
    for (const [k, spec] of Object.entries(TIER)) rs.push(`        ${snake(k)}: ${value(t[k], spec)},`);
    rs.push('    },');
  }
  rs.push('];');
  rs.push('');
  rs.push('/// Removed tiers read as another (name, the tier it reads as).');
  rs.push('pub const WATER_TIER_ALIASES: &[(&str, &str)] = &[');
  for (const [from, to] of Object.entries(data.aliases)) {
    if (from !== '$comment') rs.push(`    (${JSON.stringify(from)}, ${JSON.stringify(to)}),`);
  }
  rs.push('];');
  rs.push('');
  rs.push('/// The bank band (a stylized reflection of the bank, no march).');
  rs.push('pub const BANK_BAND: BankBand = BankBand {');
  for (const [k, spec] of Object.entries(BAND)) rs.push(`    ${snake(k)}: ${value(data.band[k], spec)},`);
  rs.push('};');
  rs.push('');
  rs.push('/// The caustic tile is redrawn every this many frames.');
  rs.push(`pub const CAUSTIC_EVERY_FRAMES: u32 = ${data.causticEveryFrames};`);
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateWaterTiers(JSON.parse(readFileSync(join(here, 'watertiers.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/watertiers.gen.rs'), waterTiersRust(data));
  console.log('look: water tiers generated');
}
