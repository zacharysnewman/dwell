#!/usr/bin/env node
// Generates the LOD transitions' tunables (ARCHITECTURE.md §6.6 'Swaps') for Rust
// (crates/dwell-look/src/lodblend.gen.rs) from shared/look/lodblend.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/lodblend.mjs from shared/look/lodblend.json. Do not edit.';

/** The dither patterns the renderer knows (dwell-look `lod_blend.rs` `FadePattern`), JSON name → Rust. */
export const PATTERNS = { bayer4: 'Bayer4', bayer8: 'Bayer8', noise: 'Noise' };

const fail = (m) => {
  throw new Error(`lodblend.json: ${m}`);
};

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/** Checks the tunables; returns them. Throws naming the entry. */
export function validateLodBlend(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  const keys = ['fadeS', 'pattern', 'coarsenRatio'];
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry (root).${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry (root).${k}`);
  checkNumber('fadeS', data.fadeS, 0, 5);
  if (!Object.hasOwn(PATTERNS, data.pattern)) {
    fail(`pattern must be one of ${Object.keys(PATTERNS).join(', ')}, got ${JSON.stringify(data.pattern)}`);
  }
  checkNumber('coarsenRatio', data.coarsenRatio, 1, 4);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated tunables. */
export function lodBlendRust(data) {
  const rs = [`// ${header}`, '', 'use crate::lod_blend::*;', ''];
  rs.push("/// The LOD transitions' tunables (shared/look/lodblend.json).");
  rs.push('pub const LOD_BLEND: LodBlendTunables = LodBlendTunables {');
  rs.push(`    fade_s: ${rf(data.fadeS)},`);
  rs.push(`    pattern: FadePattern::${PATTERNS[data.pattern]},`);
  rs.push(`    coarsen_ratio: ${rf(data.coarsenRatio)},`);
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateLodBlend(JSON.parse(readFileSync(join(here, 'lodblend.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/lodblend.gen.rs'), lodBlendRust(data));
  console.log('look: LOD transition tunables generated');
}
