#!/usr/bin/env node
// Generates the flood light's tunables (falloff, brightness curves, the direct-light ramp, block
// light; docs/DAY_NIGHT.md §10) for Rust (crates/dwell-world/src/light.gen.rs) from
// shared/look/light.json, after validating them: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/light.mjs from shared/look/light.json. Do not edit.';

/** The brightest level (dwell_blocks::LIGHT_MAX). */
export const LEVELS = 15;

const fail = (m) => {
  throw new Error(`light.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

function checkLevel(where, v, lo) {
  checkNumber(where, v, lo, LEVELS);
  if (!Number.isInteger(v)) fail(`${where} must be a whole number of levels, got ${v}`);
}

/** Checks the light data; returns it. */
export function validateLight(data) {
  checkKeys('(root)', data, ['falloff', 'sky', 'block']);
  checkKeys('falloff', data.falloff, ['across', 'vertical']);
  checkLevel('falloff.across', data.falloff.across, 1);
  checkLevel('falloff.vertical', data.falloff.vertical, 1);
  checkKeys('sky', data.sky, ['curve', 'direct']);
  checkNumber('sky.curve', data.sky.curve, 1, 16);
  checkKeys('sky.direct', data.sky.direct, ['fromLevel', 'fullLevel']);
  checkLevel('sky.direct.fromLevel', data.sky.direct.fromLevel, 0);
  checkLevel('sky.direct.fullLevel', data.sky.direct.fullLevel, 1);
  if (data.sky.direct.fromLevel >= data.sky.direct.fullLevel) {
    fail(`sky.direct.fromLevel (${data.sky.direct.fromLevel}) must be below fullLevel (${data.sky.direct.fullLevel})`);
  }
  checkKeys('block', data.block, ['curve', 'color', 'strength']);
  checkNumber('block.curve', data.block.curve, 1, 16);
  if (typeof data.block.color !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(data.block.color)) {
    fail(`block.color must be "#rrggbb", got ${JSON.stringify(data.block.color)}`);
  }
  checkNumber('block.strength', data.block.strength, 0, 8);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);

/** The Rust source for validated data. */
export function lightRust(data) {
  const c = rgb(data.block.color).map((v) => rf(Math.round(v * 1e6) / 1e6));
  return [
    `// ${header}`,
    '',
    'use crate::light::LightTunables;',
    '',
    '/// The flood light (shared/look/light.json).',
    'pub const LIGHT: LightTunables = LightTunables {',
    `    falloff_across: ${data.falloff.across},`,
    `    falloff_vertical: ${data.falloff.vertical},`,
    `    sky_curve: ${rf(data.sky.curve)},`,
    `    direct_from: ${data.sky.direct.fromLevel},`,
    `    direct_full: ${data.sky.direct.fullLevel},`,
    `    block_curve: ${rf(data.block.curve)},`,
    `    block_color: [${c.join(', ')}],`,
    `    block_strength: ${rf(data.block.strength)},`,
    '};',
    '',
  ].join('\n');
}

export function loadLight() {
  return validateLight(JSON.parse(readFileSync(join(here, 'light.json'), 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-world/src/light.gen.rs'), lightRust(loadLight()));
  console.log('look: light generated');
}
