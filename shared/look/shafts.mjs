#!/usr/bin/env node
// Generates the light shafts' looks (ADR 0064, the volumetric glow rays) for Rust
// (crates/dwell-look/src/shafts.gen.rs) from shared/look/shafts.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff. A fluid is named by its registry fluid (`dwell:water`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/shafts.mjs from shared/look/shafts.json. Do not edit.';

/** The most lights a frame's shafts may come from (the frame block's `torch_shafts`). */
export const MAX_SHAFT_LIGHTS = 4;
const NAME = /^[a-z0-9_]+:[a-z0-9_]+$/;
const COLOR = /^#[0-9a-fA-F]{6}$/;

const fail = (m) => {
  throw new Error(`shafts.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  if (spec === 'color') {
    if (typeof v !== 'string' || !COLOR.test(v)) fail(`${where} must be #rrggbb, got ${JSON.stringify(v)}`);
    return;
  }
  const [lo, hi, kind] = spec;
  const open = kind === 'open';
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (kind === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

function checkFields(where, obj, fields) {
  checkKeys(where, obj, Object.keys(fields));
  for (const [k, spec] of Object.entries(fields)) {
    if (typeof spec === 'object' && !Array.isArray(spec)) checkFields(`${where}.${k}`, obj[k], spec);
    else checkValue(`${where}.${k}`, obj[k], spec);
  }
}

const TIER = {
  scale: [0, 1, 'open'],
  steps: [1, 64, 'count'],
  lights: [0, MAX_SHAFT_LIGHTS, 'count'],
  lightSteps: [1, 32, 'count'],
};
const LIGHTS = {
  nearM: [0, 16],
  rangeM: [0, 64, 'open'],
  reach: [0, 1, 'open'],
  decay: [0.5, 1],
  offscreen: [0, 4],
  dayShare: [0, 1],
};
const KIND = { strength: [0, 4], discM: [0, 16, 'open'] };
const LIGHT = {
  strength: [0, 4],
  reach: [0, 1, 'open'],
  decay: [0.5, 1],
  discRadius: [0, 4, 'open'],
  elevationDeg: [0, 90, 'open'],
  offscreen: [0, 4],
};
const FLUID = {
  strength: [0, 4],
  reachM: [0, 256, 'open'],
  fadeM: [0, 256, 'open'],
  cellM: [0.05, 64],
  speed: [0, 10],
  window: { color: 'color', glow: [0, 1], edge: [0, 1] },
};

export const TIERS = ['high', 'low'];

export function lightNames(data) {
  return Object.keys(data.lights.kinds).filter((k) => k !== '$comment');
}

export function fluidNames(data) {
  return Object.keys(data.fluids).filter((k) => k !== '$comment');
}

/** Checks the data; returns it. */
export function validateShafts(data) {
  checkKeys('the file', data, ['tiers', 'air', 'lights', 'default', 'fluids']);
  checkKeys('tiers', data.tiers, TIERS);
  for (const t of TIERS) checkFields(`tiers.${t}`, data.tiers[t], TIER);
  // Low is the cheaper choice: no more pixels or samples than High.
  const [lo, hi] = [data.tiers.low, data.tiers.high];
  if (lo.scale > hi.scale || lo.steps > hi.steps || lo.lights > hi.lights || lo.lightSteps > hi.lightSteps) {
    fail('tiers.low must cost no more than tiers.high (scale, steps, lights and lightSteps)');
  }
  checkKeys('lights', data.lights, [...Object.keys(LIGHTS), 'default', 'kinds']);
  for (const [k, spec] of Object.entries(LIGHTS)) checkValue(`lights.${k}`, data.lights[k], spec);
  checkFields('lights.default', data.lights.default, KIND);
  const kinds = data.lights.kinds;
  if (typeof kinds !== 'object' || kinds === null || Array.isArray(kinds)) fail('lights.kinds must be an object');
  for (const n of lightNames(data)) {
    if (!NAME.test(n)) fail(`lights.kinds.${n}: the name must be \`namespace:name\` (lowercase, digits, _)`);
    checkFields(`lights.kinds.${n}`, kinds[n], KIND);
  }
  checkKeys('air', data.air, ['sun', 'moon']);
  for (const l of ['sun', 'moon']) checkFields(`air.${l}`, data.air[l], LIGHT);
  checkFields('default', data.default, FLUID);
  if (typeof data.fluids !== 'object' || data.fluids === null || Array.isArray(data.fluids)) fail('fluids must be an object');
  for (const n of fluidNames(data)) {
    if (!NAME.test(n)) fail(`fluids.${n}: the name must be \`namespace:name\` (lowercase, digits, _)`);
    checkFields(`fluids.${n}`, data.fluids[n], FLUID);
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const hex = (c) => `0x${c.replace('#', '').toLowerCase()}`;

const tierRust = (t) =>
  `ShaftTier {\n    scale: ${rf(t.scale)},\n    steps: ${t.steps},\n    lights: ${t.lights},\n    light_steps: ${t.lightSteps},\n}`;
const kindRust = (name, k) => `LightShafts {\n        light: ${JSON.stringify(name)},\n        strength: ${rf(k.strength)},\n        disc_m: ${rf(k.discM)},\n    }`;
const lightRust = (l, indent) => {
  const i = ' '.repeat(indent);
  return [
    'AirShafts {',
    `${i}    strength: ${rf(l.strength)},`,
    `${i}    reach: ${rf(l.reach)},`,
    `${i}    decay: ${rf(l.decay)},`,
    `${i}    disc_radius: ${rf(l.discRadius)},`,
    `${i}    elevation_deg: ${rf(l.elevationDeg)},`,
    `${i}    offscreen: ${rf(l.offscreen)},`,
    `${i}}`,
  ].join('\n');
};

function fluidRust(name, l, indent) {
  const i = ' '.repeat(indent);
  return [
    'FluidShafts {',
    `${i}    fluid: ${JSON.stringify(name)},`,
    `${i}    strength: ${rf(l.strength)},`,
    `${i}    reach_m: ${rf(l.reachM)},`,
    `${i}    fade_m: ${rf(l.fadeM)},`,
    `${i}    cell_m: ${rf(l.cellM)},`,
    `${i}    speed: ${rf(l.speed)},`,
    `${i}    window_color: ${hex(l.window.color)},`,
    `${i}    window_glow: ${rf(l.window.glow)},`,
    `${i}    window_edge: ${rf(l.window.edge)},`,
    `${i}}`,
  ].join('\n');
}

/** The Rust source for validated data. */
export function shaftsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::shafts::*;', ''];
  rs.push('/// The High and Low tiers (`tiers`).');
  rs.push(`pub const HIGH: ShaftTier = ${tierRust(data.tiers.high)};`);
  rs.push(`pub const LOW: ShaftTier = ${tierRust(data.tiers.low)};`);
  rs.push('');
  rs.push("/// The sun's and the moon's shafts in the air (`air`).");
  rs.push(`pub const SUN_SHAFTS: AirShafts = ${lightRust(data.air.sun, 0)};`);
  rs.push(`pub const MOON_SHAFTS: AirShafts = ${lightRust(data.air.moon, 0)};`);
  rs.push('');
  const L = data.lights;
  rs.push('/// The most lights a frame draws shafts from.');
  rs.push(`pub const MAX_SHAFT_LIGHTS: usize = ${MAX_SHAFT_LIGHTS};`);
  rs.push('');
  rs.push("/// The placed and held lights' shafts (`lights`).");
  rs.push('pub const LIGHT_SHAFTS: LightShaftTuning = LightShaftTuning {');
  rs.push(`    near_m: ${rf(L.nearM)},`);
  rs.push(`    range_m: ${rf(L.rangeM)},`);
  rs.push(`    reach: ${rf(L.reach)},`);
  rs.push(`    decay: ${rf(L.decay)},`);
  rs.push(`    offscreen: ${rf(L.offscreen)},`);
  rs.push(`    day_share: ${rf(L.dayShare)},`);
  rs.push('};');
  rs.push('');
  rs.push('/// A light source not listed (`lights.default`), and each listed one (`lights.kinds`).');
  rs.push(`pub const DEFAULT_LIGHT_SHAFTS: LightShafts = ${kindRust('', L.default)};`);
  rs.push('pub const LIGHT_KINDS: &[LightShafts] = &[');
  for (const n of lightNames(data)) rs.push(`    ${kindRust(n, L.kinds[n])},`);
  rs.push('];');
  rs.push('');
  rs.push('/// The shafts under a fluid not listed (`default`).');
  rs.push(`pub const DEFAULT_FLUID_SHAFTS: FluidShafts = ${fluidRust('', data.default, 0)};`);
  rs.push('');
  rs.push("/// Each listed fluid's shafts (`fluids`).");
  rs.push('pub const FLUID_SHAFTS: &[FluidShafts] = &[');
  for (const n of fluidNames(data)) rs.push(`    ${fluidRust(n, data.fluids[n], 4)},`);
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateShafts(JSON.parse(readFileSync(join(here, 'shafts.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/shafts.gen.rs'), shaftsRust(data));
  console.log('look: light shafts generated');
}
