#!/usr/bin/env node
// Generates the LOD colour map's tunables (ARCHITECTURE.md §6.6 'Colour map') for Rust
// (crates/dwell-look/src/lodmap.gen.rs) from shared/look/lodmap.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/lodmap.mjs from shared/look/lodmap.json. Do not edit.';

/** The most rings (the shader's uniform block holds this many). */
export const MAX_RINGS = 4;

const fail = (m) => {
  throw new Error(`lodmap.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi, whole = false) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (whole && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

/** Checks the tunables against the schema and each other; returns them. Throws naming the entry. */
export function validateLodMap(data) {
  checkKeys('(root)', data, [
    'rings',
    'snapTexels',
    'tileTexels',
    'jobsInFlight',
    'riverMinTexels',
    'blend',
    'ringFadeTexels',
    'water',
    'valleyMarginM',
  ]);
  if (!Array.isArray(data.rings) || data.rings.length < 1 || data.rings.length > MAX_RINGS) {
    fail(`rings must list 1 to ${MAX_RINGS} rings`);
  }
  data.rings.forEach((r, i) => {
    checkKeys(`rings[${i}]`, r, ['texelM', 'size']);
    checkNumber(`rings[${i}].texelM`, r.texelM, 1, 4096, true);
    checkNumber(`rings[${i}].size`, r.size, 64, 2048, true);
    if ((r.size & (r.size - 1)) !== 0) fail(`rings[${i}].size must be a power of two, got ${r.size}`);
    if (r.size !== data.rings[0].size) fail(`rings[${i}].size must equal rings[0].size (one texture array)`);
    if (i > 0 && r.texelM <= data.rings[i - 1].texelM) fail(`rings[${i}].texelM must be coarser than rings[${i - 1}]'s`);
  });
  checkNumber('snapTexels', data.snapTexels, 1, data.rings[0].size / 4, true);
  checkNumber('tileTexels', data.tileTexels, data.rings[0].size, 1 << 22, true);
  checkNumber('jobsInFlight', data.jobsInFlight, 1, 16, true);
  checkNumber('riverMinTexels', data.riverMinTexels, 0, 8);
  checkKeys('blend', data.blend, ['fromM', 'toM']);
  checkNumber('blend.fromM', data.blend.fromM, 0, 1e5);
  checkNumber('blend.toM', data.blend.toM, data.blend.fromM, 1e5);
  checkNumber('ringFadeTexels', data.ringFadeTexels, 1, data.rings[0].size / 4);
  checkKeys('water', data.water, ['block', 'depthM', 'deepShade']);
  if (typeof data.water.block !== 'string' || !/^[a-z0-9_]+:[a-z0-9_]+$/.test(data.water.block)) {
    fail(`water.block must be a block name (namespace:name), got ${JSON.stringify(data.water.block)}`);
  }
  checkNumber('water.depthM', data.water.depthM, 0.01, 1000);
  checkNumber('water.deepShade', data.water.deepShade, 0, 1);
  checkNumber('valleyMarginM', data.valleyMarginM, 0.01, 16);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated tunables. */
export function lodMapRust(data) {
  const rs = [`// ${header}`, '', 'use crate::lod_map::*;', ''];
  rs.push("/// The LOD colour map's tunables (shared/look/lodmap.json).");
  rs.push('pub const LOD_MAP: LodMapTunables = LodMapTunables {');
  rs.push('    rings: &[');
  for (const r of data.rings) {
    rs.push('        LodMapRing {', `            texel_m: ${r.texelM},`, `            size: ${r.size},`, '        },');
  }
  rs.push('    ],');
  rs.push(`    snap_texels: ${data.snapTexels},`);
  rs.push(`    tile_texels: ${data.tileTexels},`);
  rs.push(`    jobs_in_flight: ${data.jobsInFlight},`);
  rs.push(`    river_min_texels: ${rf(data.riverMinTexels)},`);
  rs.push(`    blend_from_m: ${rf(data.blend.fromM)},`);
  rs.push(`    blend_to_m: ${rf(data.blend.toM)},`);
  rs.push(`    ring_fade_texels: ${rf(data.ringFadeTexels)},`);
  rs.push(`    water_block: ${JSON.stringify(data.water.block)},`);
  rs.push(`    water_depth_m: ${rf(data.water.depthM)},`);
  rs.push(`    water_deep_shade: ${rf(data.water.deepShade)},`);
  rs.push(`    valley_margin_m: ${rf(data.valleyMarginM)},`);
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateLodMap(JSON.parse(readFileSync(join(here, 'lodmap.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/lodmap.gen.rs'), lodMapRust(data));
  console.log('look: LOD colour map tunables generated');
}
