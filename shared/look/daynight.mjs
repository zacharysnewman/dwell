#!/usr/bin/env node
// Generates the day/night cycle's data for Rust (crates/dwell-look/src/daynight.gen.rs) from
// shared/look/daynight.json, after validating it: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff.
// docs/DAY_NIGHT.md describes the fields.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/daynight.mjs from shared/look/daynight.json. Do not edit.';

/** Field → [min, max] (numbers) or 'color' (#rrggbb). */
const SCHEMA = {
  clock: { dayS: [1, 1e7], nightS: [1, 1e7], startHour: [0, 24] },
  sunPath: { riseYawDeg: [-360, 360], noonElevationDeg: [5, 89] },
  sun: {
    radiusDeg: [0.05, 10],
    horizonScale: [1, 3],
    limbDarkening: [0, 1],
    bloomDeg: [0.1, 45],
    bloom: [0, 1],
    glowDeg: [1, 90],
    glow: [0, 1],
  },
  moon: {
    radiusDeg: [0.05, 10],
    cycleDays: [1, 1000],
    startPhase: [0, 1],
    color: 'color',
    maria: [0, 1],
    earthshine: [0, 1],
    bloomDeg: [0.1, 45],
    bloom: [0, 1],
    glowDeg: [1, 90],
    glow: [0, 1],
    glowColor: 'color',
    newMoonLight: [0, 1],
  },
  stars: {
    cells: [10, 2000],
    density: [0, 1],
    sizePx: [0.25, 8],
    brightness: [0, 2],
    twinkle: [0, 1],
    twinkleHz: [0, 20],
    horizonFade: [0, 1],
  },
  sky: {
    gradientPower: [0.05, 4],
    bandHeight: [0.01, 1],
    bandSpread: [0, 32],
    behindFrom: [0, 1],
    behindTo: [0.01, 1],
  },
};

const KEYFRAME = {
  sun: [0, 360],
  skyZenith: 'color',
  skyHorizon: 'color',
  sunDisc: 'color',
  glow: 'color',
  glowStrength: [0, 2],
  band: 'color',
  bandStrength: [0, 2],
  sunLight: 'color',
  sunIntensity: [0, 10],
  moonLight: 'color',
  moonIntensity: [0, 10],
  hemiSky: 'color',
  hemiGround: 'color',
  hemiIntensity: [0, 10],
  fogDensity: [0, 4],
  exposure: [0.25, 4],
  stars: [0, 1],
  moonGlow: [0, 2],
  saturation: [0, 1.5],
};

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

function fail(message) {
  throw new Error(`daynight.json: ${message}`);
}

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, spec) {
  if (spec === 'color') {
    if (typeof v !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v)) {
      fail(`${where} must be a colour "#rrggbb", got ${JSON.stringify(v)}`);
    }
    return;
  }
  const [lo, hi] = spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/**
 * The sun's speed along its path is uneven so that daylight lasts `dayS` of the day: the hour angle
 * is 2πu + k·sin 2πu (u the time from noon as a share of the day), with k chosen to put sunset at
 * dayS / 2 after noon. It stays monotonic only while |k| < 1.
 */
export function pathSkew(dayS, nightS) {
  const f = dayS / (dayS + nightS);
  return (Math.PI / 2 - Math.PI * f) / Math.sin(Math.PI * f);
}

/** Checks the data against the schema and the rules between entries. Throws naming the entry. */
export function validateDayNight(data) {
  checkKeys('(root)', data, [...Object.keys(SCHEMA), 'keyframes']);
  for (const [section, fields] of Object.entries(SCHEMA)) {
    checkKeys(section, data[section], Object.keys(fields));
    for (const [k, spec] of Object.entries(fields)) checkValue(`${section}.${k}`, data[section][k], spec);
  }
  const k = pathSkew(data.clock.dayS, data.clock.nightS);
  if (!(Math.abs(k) < 0.95)) {
    fail(`clock.dayS / (dayS + nightS) must be between about 0.3 and 0.7 (the sun's path would turn back), got ${(data.clock.dayS / (data.clock.dayS + data.clock.nightS)).toFixed(3)}`);
  }
  const frames = data.keyframes;
  if (!Array.isArray(frames) || frames.length < 2) fail('keyframes must be a list of at least 2');
  const names = new Set();
  frames.forEach((f, i) => {
    const where = `keyframes[${i}]`;
    checkKeys(where, f, ['name', ...Object.keys(KEYFRAME)]);
    if (typeof f.name !== 'string' || f.name.length === 0) fail(`${where}.name must be a non-empty string`);
    if (names.has(f.name)) fail(`${where}.name "${f.name}" is used twice`);
    names.add(f.name);
    const at = `keyframes[${i}] ("${f.name}")`;
    for (const [key, spec] of Object.entries(KEYFRAME)) checkValue(`${at}.${key}`, f[key], spec);
    if (f.sun >= 360) fail(`${at}.sun must be below 360`);
    if (i > 0 && f.sun <= frames[i - 1].sun) {
      fail(`${at}.sun must be greater than the keyframe before it (${frames[i - 1].sun}): keyframes are in order of the sun's angle`);
    }
    // The sun lights nothing once it has set, nor the moon while it is below the horizon (it is
    // opposite the sun): the lights are the face's own.
    if (f.sun > 180 && f.sunIntensity !== 0) fail(`${at}.sunIntensity must be 0: the sun is below the horizon at ${f.sun}°`);
    if (f.sun > 0 && f.sun < 180 && f.moonIntensity !== 0) {
      fail(`${at}.moonIntensity must be 0: the moon is below the horizon at ${f.sun}°`);
    }
  });
  return data;
}

const rf = (v) => {
  const s = `${+v.toFixed(6)}`;
  return /[.e]/.test(s) ? s : `${s}.0`;
};
const rgb = (hex) => `[${[1, 3, 5].map((i) => rf(parseInt(hex.slice(i, i + 2), 16) / 255)).join(', ')}]`;
const field = (v, spec) => (spec === 'color' ? rgb(v) : rf(v));

/** The Rust source for validated data. */
export function dayNightRust(data) {
  const rs = [`// ${header}`, '', 'use crate::daynight::*;', ''];
  rs.push("/// The day/night cycle's data (shared/look/daynight.json).");
  rs.push('pub const DAY_NIGHT: DayNight = DayNight {');
  const struct = {
    clock: 'Clock',
    sunPath: 'SunPath',
    sun: 'SunLook',
    moon: 'MoonLook',
    stars: 'StarLook',
    sky: 'SkyShape',
  };
  for (const [section, fields] of Object.entries(SCHEMA)) {
    rs.push(`    ${snake(section)}: ${struct[section]} {`);
    for (const [k, spec] of Object.entries(fields)) rs.push(`        ${snake(k)}: ${field(data[section][k], spec)},`);
    rs.push('    },');
  }
  rs.push('    keyframes: &[');
  for (const f of data.keyframes) {
    rs.push('        Keyframe {');
    rs.push(`            name: ${JSON.stringify(f.name)},`);
    for (const [k, spec] of Object.entries(KEYFRAME)) rs.push(`            ${snake(k)}: ${field(f[k], spec)},`);
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

export function loadDayNight(path = join(here, 'daynight.json')) {
  return validateDayNight(JSON.parse(readFileSync(path, 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/daynight.gen.rs'), dayNightRust(loadDayNight()));
  console.log('look: day/night data generated');
}
