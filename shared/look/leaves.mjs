#!/usr/bin/env node
// Generates the leaves' look (docs/TREE_GROWTH.md §8) for Rust (crates/dwell-look/src/leaves.gen.rs)
// from shared/look/leaves.json, after validating it: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/leaves.mjs from shared/look/leaves.json. Do not edit.';

const fail = (m) => {
  throw new Error(`leaves.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

/** Checks the look; returns it. Throws naming the entry. */
export function validateLeaves(data) {
  checkKeys('(root)', data, ['blocks', 'canopyBlend', 'chamfer']);
  if (!Array.isArray(data.blocks) || data.blocks.length === 0) fail('blocks must list at least one block');
  data.blocks.forEach((b, i) => {
    if (typeof b !== 'string' || !/^[a-z0-9_]+:[a-z0-9_]+$/.test(b)) {
      fail(`blocks[${i}] must be a block name (namespace:name), got ${JSON.stringify(b)}`);
    }
    if (data.blocks.indexOf(b) !== i) fail(`blocks[${i}] repeats ${b}`);
  });
  checkNumber('canopyBlend', data.canopyBlend, 0, 1);
  // Past 0.45 an edge's cut meets the opposite edge's in a one-cell-thick layer of leaves.
  checkNumber('chamfer', data.chamfer, 0, 0.45);
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for a validated look. */
export function leavesRust(data) {
  return [
    `// ${header}`,
    '',
    'use crate::leaves::LeavesLook;',
    '',
    "/// The leaves' look (shared/look/leaves.json).",
    'pub const LEAVES: LeavesLook = LeavesLook {',
    `    blocks: &[${data.blocks.map((b) => JSON.stringify(b)).join(', ')}],`,
    `    canopy_blend: ${rf(data.canopyBlend)},`,
    `    chamfer: ${rf(data.chamfer)},`,
    '};',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateLeaves(JSON.parse(readFileSync(join(here, 'leaves.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/leaves.gen.rs'), leavesRust(data));
  console.log("look: the leaves' look generated");
}
