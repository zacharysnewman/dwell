#!/usr/bin/env node
// Generates the motion effects' tunables for Rust (crates/dwell-look/src/motion.gen.rs) from
// shared/look/motion.json, after validating them: an unknown, missing or out-of-range entry fails
// with its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/gen.mjs from shared/look/motion.json. Do not edit.';

/** Field → [min, max] (numbers), 'color' (#rrggbb) or 'count' (a whole number in range). */
const SCHEMA = {
  fov: {
    sprintBoostPct: [0, 50],
    flightBoostPct: [0, 60],
    fullMps: [1, 1e9],
    widenRate: [0.1, 100],
    settleRate: [0.1, 100],
  },
  wind: {
    start: [0, 1],
    sprintIntensity: [0, 1],
    fullMps: [1, 1e9],
    riseRate: [0.1, 100],
    fallRate: [0.1, 100],
    streaks: ['count', 1, 512],
    flightStreaks: ['count', 0, 512],
    length: [0.01, 1],
    widthPx: [0.1, 32],
    opacity: [0, 1],
    color: 'color',
    innerRadius: [0, 4],
    outerRadius: [0, 8],
    vignette: [0, 1],
    flowSpeed: [0, 50],
    blur: [0, 0.25],
  },
  teleportM: [0.1, 1e6],
  crossingRollS: [0.05, 5],
};

const camel = (s) => s[0].toLowerCase() + s.slice(1);
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) {
    throw new Error(`motion.json: ${where} must be an object`);
  }
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) throw new Error(`motion.json: unknown entry ${where}.${k}`);
  }
  for (const k of keys) {
    if (!(k in obj)) throw new Error(`motion.json: missing entry ${where}.${k}`);
  }
}

function checkValue(where, v, spec) {
  if (spec === 'color') {
    if (typeof v !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(v)) {
      throw new Error(`motion.json: ${where} must be a colour "#rrggbb", got ${JSON.stringify(v)}`);
    }
    return;
  }
  const [lo, hi] = spec[0] === 'count' ? spec.slice(1) : spec;
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    throw new Error(`motion.json: ${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
  if (spec[0] === 'count' && !Number.isInteger(v)) {
    throw new Error(`motion.json: ${where} must be a whole number, got ${v}`);
  }
}

/**
 * Checks the tunables against the schema and `states` (the controller's state names, in id order,
 * from shared/protocol/constants.json): every state has a gain in [0, 1]. Throws naming the entry.
 */
export function validateMotion(data, states) {
  checkKeys('(root)', data, [...Object.keys(SCHEMA), 'stateGain']);
  for (const [section, fields] of Object.entries(SCHEMA)) {
    if (Array.isArray(fields)) {
      checkValue(section, data[section], fields);
      continue;
    }
    checkKeys(section, data[section], Object.keys(fields));
    for (const [k, spec] of Object.entries(fields)) checkValue(`${section}.${k}`, data[section][k], spec);
  }
  const names = states.map(camel);
  checkKeys('stateGain', data.stateGain, names);
  for (const n of names) checkValue(`stateGain.${n}`, data.stateGain[n], [0, 1]);
  if (data.wind.outerRadius <= data.wind.innerRadius) {
    throw new Error('motion.json: wind.outerRadius must be greater than wind.innerRadius');
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);

/** The Rust source for validated tunables. */
export function motionRust(data, states) {
  const rs = [`// ${header}`, '', 'use crate::motion::*;', ''];
  rs.push('/// The motion effects\' tunables (shared/look/motion.json).');
  rs.push('pub const MOTION: MotionTunables = MotionTunables {');
  rs.push('    fov: FovTunables {');
  for (const k of Object.keys(SCHEMA.fov)) rs.push(`        ${snake(k)}: ${rf(data.fov[k])},`);
  rs.push('    },');
  rs.push('    wind: WindTunables {');
  for (const [k, spec] of Object.entries(SCHEMA.wind)) {
    const v = data.wind[k];
    if (spec === 'color') rs.push(`        ${snake(k)}: [${rgb(v).map((c) => rf(+c.toFixed(6))).join(', ')}],`);
    else if (spec[0] === 'count') rs.push(`        ${snake(k)}: ${v},`);
    else rs.push(`        ${snake(k)}: ${rf(v)},`);
  }
  rs.push('    },');
  rs.push(`    // By controller state id: ${states.join(', ')}.`);
  rs.push(`    state_gain: [${states.map((s) => rf(data.stateGain[camel(s)])).join(', ')}],`);
  rs.push(`    teleport_m: ${rf(data.teleportM)},`);
  rs.push(`    crossing_roll_s: ${rf(data.crossingRollS)},`);
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

/** The controller's state names in id order (shared/protocol/constants.json's playerStates). */
export function playerStates() {
  const c = JSON.parse(readFileSync(join(root, 'shared/protocol/constants.json'), 'utf8'));
  return Object.entries(c.playerStates)
    .sort((a, b) => a[1] - b[1])
    .map(([name]) => name);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const states = playerStates();
  const data = validateMotion(JSON.parse(readFileSync(join(here, 'motion.json'), 'utf8')), states);
  writeFileSync(join(root, 'crates/dwell-look/src/motion.gen.rs'), motionRust(data, states));
  console.log('look: motion tunables generated');
}
