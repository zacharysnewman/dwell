#!/usr/bin/env node
// Generates the ink outline's modes (docs/ART_DIRECTION.md §7) for Rust
// (crates/dwell-look/src/outline.gen.rs) from shared/look/outline.json, with the ink resolved from
// the palette (shared/textures/palette.json), after validating them: an unknown, missing or
// out-of-range entry fails with its path named. The output is checked in; CI regenerates it and
// fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolveColor, validatePalette } from '../textures/paint.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/outline.mjs from shared/look/outline.json. Do not edit.';

/** The edge kinds the composite understands (render/shaders.rs `ink_outline`), in bit order. */
export const EDGE_KINDS = ['depth', 'normal', 'block'];
/** The most modes. */
export const MAX_MODES = 16;

const fail = (m) => {
  throw new Error(`outline.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) {
    if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  }
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkNumber(where, v, lo, hi) {
  if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
    fail(`${where} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
  }
}

const MODE_KEYS = [
  'name',
  'edges',
  'widthPx',
  'fadeStartM',
  'fadeEndM',
  'strength',
  'depthThreshold',
  'creaseThreshold',
];

/** Checks the outline's data against `palette`; returns it with the ink resolved (sRGB bytes). */
export function validateOutline(data, palette) {
  checkKeys('(root)', data, ['ink', 'modes']);
  validatePalette(palette);
  let ink;
  try {
    ink = resolveColor(palette, data.ink, null, 'ink');
  } catch (e) {
    fail(e.message);
  }
  if (!Array.isArray(data.modes) || data.modes.length === 0 || data.modes.length > MAX_MODES) {
    fail(`modes must be a list of 1 to ${MAX_MODES} modes`);
  }
  const names = new Set();
  data.modes.forEach((m, i) => {
    const at = `modes[${i}]`;
    checkKeys(at, m, MODE_KEYS);
    if (typeof m.name !== 'string' || !/^[a-z][a-z0-9-]*$/.test(m.name)) {
      fail(`${at}.name must be lower-case letters, digits and '-', got ${JSON.stringify(m.name)}`);
    }
    if (m.name === 'off') fail(`${at}.name "off" is reserved (it turns the outline off)`);
    if (names.has(m.name)) fail(`${at}.name "${m.name}" is another mode's`);
    names.add(m.name);
    if (!Array.isArray(m.edges) || m.edges.length === 0) fail(`${at}.edges must list one or more of ${EDGE_KINDS.join(', ')}`);
    m.edges.forEach((e, j) => {
      if (!EDGE_KINDS.includes(e)) fail(`${at}.edges[${j}] "${e}" is not an edge kind (${EDGE_KINDS.join(', ')})`);
      if (m.edges.indexOf(e) !== j) fail(`${at}.edges[${j}] "${e}" is listed twice`);
    });
    checkNumber(`${at}.widthPx`, m.widthPx, 0.5, 8);
    checkNumber(`${at}.fadeStartM`, m.fadeStartM, 0, 4096);
    checkNumber(`${at}.fadeEndM`, m.fadeEndM, 0, 4096);
    if (m.fadeEndM <= m.fadeStartM) fail(`${at}.fadeEndM must be greater than ${at}.fadeStartM`);
    checkNumber(`${at}.strength`, m.strength, 0, 1);
    checkNumber(`${at}.depthThreshold`, m.depthThreshold, 0.001, 1);
    checkNumber(`${at}.creaseThreshold`, m.creaseThreshold, 0.01, 0.5);
  });
  return { ...data, inkRgb: ink };
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust source for validated data. */
export function outlineRust(data) {
  const rs = [`// ${header}`, '', 'use crate::outline::*;', ''];
  rs.push("/// The ink outline's modes (shared/look/outline.json).");
  rs.push('pub const OUTLINE: OutlineTunables = OutlineTunables {');
  const ink = data.inkRgb.map((c) => rf(+(c / 255).toFixed(6)));
  rs.push(`    ink: [${ink.join(', ')}],`);
  rs.push('    modes: &[');
  for (const m of data.modes) {
    const edges = m.edges.reduce((bits, e) => bits | (1 << EDGE_KINDS.indexOf(e)), 0);
    rs.push('        OutlineMode {');
    rs.push(`            name: ${JSON.stringify(m.name)},`);
    rs.push(`            edges: ${edges},`);
    rs.push(`            width_px: ${rf(m.widthPx)},`);
    rs.push(`            fade_start_m: ${rf(m.fadeStartM)},`);
    rs.push(`            fade_end_m: ${rf(m.fadeEndM)},`);
    rs.push(`            strength: ${rf(m.strength)},`);
    rs.push(`            depth_threshold: ${rf(m.depthThreshold)},`);
    rs.push(`            crease_threshold: ${rf(m.creaseThreshold)},`);
    rs.push('        },');
  }
  rs.push('    ],');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

export function loadOutline() {
  const data = JSON.parse(readFileSync(join(here, 'outline.json'), 'utf8'));
  const palette = JSON.parse(readFileSync(join(root, 'shared/textures/palette.json'), 'utf8'));
  return validateOutline(data, palette);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  writeFileSync(join(root, 'crates/dwell-look/src/outline.gen.rs'), outlineRust(loadOutline()));
  console.log('look: outline modes generated');
}
