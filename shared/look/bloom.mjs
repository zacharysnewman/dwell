#!/usr/bin/env node
// Generates bloom's looks (the glow round self-lit surfaces, WORK_QUEUE item 19) for Rust
// (crates/dwell-look/src/bloom.gen.rs) from shared/look/bloom.json, after validating them: an
// unknown, missing or out-of-range entry fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/look/bloom.mjs from shared/look/bloom.json. Do not edit.';

/** The most levels a chain may have (the first is the bright pass's, the rest the blur's). */
export const MAX_LEVELS = 8;
export const TIERS = ['high', 'low'];

const fail = (m) => {
  throw new Error(`bloom.json: ${m}`);
};

function checkKeys(where, obj, keys) {
  if (typeof obj !== 'object' || obj === null || Array.isArray(obj)) fail(`${where} must be an object`);
  for (const k of Object.keys(obj)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry ${where}.${k}`);
  for (const k of keys) if (!(k in obj)) fail(`missing entry ${where}.${k}`);
}

function checkValue(where, v, [lo, hi, kind]) {
  const open = kind === 'open';
  const ok = typeof v === 'number' && Number.isFinite(v) && (open ? v > lo : v >= lo) && v <= hi;
  if (!ok) fail(`${where} must be a number in ${open ? '(' : '['}${lo}, ${hi}], got ${JSON.stringify(v)}`);
  if (kind === 'count' && !Number.isInteger(v)) fail(`${where} must be a whole number, got ${v}`);
}

const TOP = { threshold: [0, 16], intensity: [0, 8], radius: [0.25, 4] };
const TIER = { scale: [0, 1, 'open'], levels: [2, MAX_LEVELS, 'count'] };

/** Checks the data; returns it. */
export function validateBloom(data) {
  checkKeys('the file', data, [...Object.keys(TOP), 'tiers']);
  for (const [k, spec] of Object.entries(TOP)) checkValue(k, data[k], spec);
  checkKeys('tiers', data.tiers, TIERS);
  for (const t of TIERS) {
    checkKeys(`tiers.${t}`, data.tiers[t], Object.keys(TIER));
    for (const [k, spec] of Object.entries(TIER)) checkValue(`tiers.${t}.${k}`, data.tiers[t][k], spec);
  }
  const [lo, hi] = [data.tiers.low, data.tiers.high];
  if (lo.scale > hi.scale || lo.levels > hi.levels) fail('tiers.low must cost no more than tiers.high (scale and levels)');
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const tierRust = (t) => `BloomTier {\n    scale: ${rf(t.scale)},\n    levels: ${t.levels},\n}`;

/** The Rust source for validated data. */
export function bloomRust(data) {
  return [
    `// ${header}`,
    '',
    'use crate::bloom::*;',
    '',
    '/// The most levels a chain may have.',
    `pub const MAX_LEVELS: u32 = ${MAX_LEVELS};`,
    '',
    '/// The look (`threshold`, `intensity`, `radius`).',
    `pub const BLOOM: BloomLook = BloomLook {\n    threshold: ${rf(data.threshold)},\n    intensity: ${rf(data.intensity)},\n    radius: ${rf(data.radius)},\n};`,
    '',
    '/// The High and Low tiers (`tiers`).',
    `pub const HIGH: BloomTier = ${tierRust(data.tiers.high)};`,
    `pub const LOW: BloomTier = ${tierRust(data.tiers.low)};`,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateBloom(JSON.parse(readFileSync(join(here, 'bloom.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-look/src/bloom.gen.rs'), bloomRust(data));
  console.log('look: bloom generated');
}
