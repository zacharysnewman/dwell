#!/usr/bin/env node
// Generates protocol constants for C++, TypeScript and Rust from constants.json.
// Outputs are checked in; CI regenerates and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const c = JSON.parse(readFileSync(join(here, 'constants.json'), 'utf8'));
const header = 'Generated by shared/protocol/gen.mjs from shared/protocol/constants.json. Do not edit.';

const enumEntries = (obj) => Object.entries(obj);

// ---- C++ -----------------------------------------------------------------------------------------
const cpp = [];
cpp.push(`// ${header}`);
cpp.push('#pragma once');
cpp.push('');
cpp.push('#include <cstddef>');
cpp.push('#include <cstdint>');
cpp.push('#include <string_view>');
cpp.push('');
cpp.push('namespace dwell::protocol {');
cpp.push('');
cpp.push(`inline constexpr std::uint16_t kProtocolVersion = ${c.protocolVersion};`);
cpp.push(`inline constexpr int kSimHz = ${c.simHz};`);
cpp.push(`inline constexpr int kSnapshotHz = ${c.snapshotHz};`);
cpp.push(`inline constexpr std::size_t kMaxDatagramBytes = ${c.maxDatagramBytes};`);
cpp.push(`inline constexpr std::size_t kMaxReliableMessageBytes = ${c.maxReliableMessageBytes};`);
cpp.push(`inline constexpr int kChunkSize = ${c.chunkSize};`);
cpp.push(`inline constexpr std::string_view kAuthDomainTag = "${c.authDomainTag}";`);
cpp.push(`inline constexpr std::size_t kMaxInputsPerDatagram = ${c.maxInputsPerDatagram};`);
cpp.push('');
// Player constants: distances and radii (metres) are floats, the rest integers.
for (const [k, v] of enumEntries(c.players)) {
  const isFloat = /Distance|Radius/.test(k);
  const value = isFloat ? `${Number.isInteger(v) ? `${v}.0` : v}f` : `${v}`;
  cpp.push(`inline constexpr ${isFloat ? 'float' : 'int'} k${k[0].toUpperCase()}${k.slice(1)} = ${value};`);
}
cpp.push('');
// Chunk streaming (ARCHITECTURE.md §6.3, §7.4).
for (const [k, v] of enumEntries(c.world)) {
  cpp.push(`inline constexpr int k${k[0].toUpperCase()}${k.slice(1)} = ${v};`);
}
cpp.push('');
// Level of detail (ARCHITECTURE.md §6.6, §7.4).
for (const [k, v] of enumEntries(c.lod)) {
  cpp.push(`inline constexpr int kLod${k[0].toUpperCase()}${k.slice(1)} = ${v};`);
}
cpp.push('');
for (const [k, v] of enumEntries(c.limits)) {
  cpp.push(`inline constexpr std::size_t k${k[0].toUpperCase()}${k.slice(1)} = ${v};`);
}
const cppEnum = (name, type, obj) => {
  cpp.push('');
  cpp.push(`enum class ${name} : ${type} {`);
  for (const [k, v] of enumEntries(obj)) cpp.push(`  k${k[0].toUpperCase()}${k.slice(1)} = ${v},`);
  cpp.push('};');
};
cppEnum('Channel', 'std::uint8_t', c.channels);
cppEnum('MessageType', 'std::uint8_t', c.messageTypes);
cppEnum('RejectReason', 'std::uint8_t', c.rejectReasons);
cpp.push(`inline constexpr std::uint8_t kMaxRejectReason = ${Math.max(...Object.values(c.rejectReasons))};`);
cppEnum('TransportKind', 'std::uint8_t', c.transportKinds);
cppEnum('PlayerState', 'std::uint8_t', c.playerStates);
cppEnum('GroundKind', 'std::uint8_t', c.groundKinds);
cppEnum('PlayerEventKind', 'std::uint8_t', c.playerEventKinds);
cppEnum('DamageCause', 'std::uint8_t', c.damageCauses);
cppEnum('ChunkForm', 'std::uint8_t', c.chunkForms);
cppEnum('LodForm', 'std::uint8_t', c.lodForms);
cppEnum('BlockEditAction', 'std::uint8_t', c.blockEditActions);
cppEnum('VoxelModificationReason', 'std::uint8_t', c.voxelModificationReasons);
cppEnum('HostState', 'std::uint8_t', c.hostStates);
const maxOf = (obj) => Math.max(...Object.values(obj));
cpp.push('');
cpp.push(`inline constexpr std::uint8_t kMaxPlayerState = ${maxOf(c.playerStates)};`);
cpp.push(`inline constexpr std::uint8_t kMaxGroundKind = ${maxOf(c.groundKinds)};`);
cpp.push(`inline constexpr std::uint8_t kMaxPlayerEventKind = ${maxOf(c.playerEventKinds)};`);
cpp.push(`inline constexpr std::uint8_t kMaxDamageCause = ${maxOf(c.damageCauses)};`);
cpp.push(`inline constexpr std::uint8_t kMaxChunkForm = ${maxOf(c.chunkForms)};`);
cpp.push(`inline constexpr std::uint8_t kMaxLodForm = ${maxOf(c.lodForms)};`);
cpp.push(`inline constexpr std::uint8_t kMaxBlockEditAction = ${maxOf(c.blockEditActions)};`);
cpp.push(
  `inline constexpr std::uint8_t kMaxVoxelModificationReason = ${maxOf(c.voxelModificationReasons)};`,
);
cpp.push(`inline constexpr std::uint8_t kMaxHostState = ${maxOf(c.hostStates)};`);
const cppFlags = (name, type, obj) => {
  cpp.push('');
  cpp.push(`namespace ${name} {`);
  let mask = 0;
  for (const [k, v] of enumEntries(obj)) {
    cpp.push(`inline constexpr ${type} k${k[0].toUpperCase()}${k.slice(1)} = ${v};`);
    mask |= v;
  }
  cpp.push(`inline constexpr ${type} kAll = ${mask};`);
  cpp.push(`}  // namespace ${name}`);
};
cppFlags('InputButtons', 'std::uint16_t', c.inputButtons);
cppFlags('PlayerFlags', 'std::uint8_t', c.playerFlags);
cppFlags('ControllerFlags', 'std::uint8_t', c.controllerFlags);
cppFlags('WelcomeFlags', 'std::uint8_t', c.welcomeFlags);
cpp.push('');
cpp.push('}  // namespace dwell::protocol');
cpp.push('');
writeFileSync(join(root, 'server/core/include/dwell/protocol/constants.gen.h'), cpp.join('\n'));

// ---- TypeScript ----------------------------------------------------------------------------------
const ts = [];
ts.push(`// ${header}`);
ts.push('');
ts.push(`export const PROTOCOL_VERSION = ${c.protocolVersion};`);
ts.push(`export const SIM_HZ = ${c.simHz};`);
ts.push(`export const SNAPSHOT_HZ = ${c.snapshotHz};`);
ts.push(`export const MAX_DATAGRAM_BYTES = ${c.maxDatagramBytes};`);
ts.push(`export const MAX_RELIABLE_MESSAGE_BYTES = ${c.maxReliableMessageBytes};`);
ts.push(`export const CHUNK_SIZE = ${c.chunkSize};`);
ts.push(`export const AUTH_DOMAIN_TAG = '${c.authDomainTag}';`);
ts.push(`export const MAX_INPUTS_PER_DATAGRAM = ${c.maxInputsPerDatagram};`);
ts.push('');
ts.push('export const Players = {');
for (const [k, v] of enumEntries(c.players)) ts.push(`  ${k}: ${v},`);
ts.push('} as const;');
ts.push('');
ts.push('export const World = {');
for (const [k, v] of enumEntries(c.world)) ts.push(`  ${k}: ${v},`);
ts.push('} as const;');
ts.push('');
ts.push('export const Lod = {');
for (const [k, v] of enumEntries(c.lod)) ts.push(`  ${k}: ${v},`);
ts.push('} as const;');
ts.push('');
ts.push('export const Limits = {');
for (const [k, v] of enumEntries(c.limits)) ts.push(`  ${k}: ${v},`);
ts.push('} as const;');
const tsEnum = (name, obj) => {
  ts.push('');
  ts.push(`export const ${name} = {`);
  for (const [k, v] of enumEntries(obj)) ts.push(`  ${k}: ${v},`);
  ts.push('} as const;');
  const alias = `export type ${name} = (typeof ${name})[keyof typeof ${name}];`;
  // Prettier's layout for aliases longer than the 100-column print width.
  ts.push(alias.length <= 100 ? alias : `export type ${name} =\n  (typeof ${name})[keyof typeof ${name}];`);
};
tsEnum('Channel', c.channels);
tsEnum('MessageType', c.messageTypes);
tsEnum('RejectReason', c.rejectReasons);
tsEnum('TransportKind', c.transportKinds);
tsEnum('PlayerState', c.playerStates);
tsEnum('GroundKind', c.groundKinds);
tsEnum('PlayerEventKind', c.playerEventKinds);
tsEnum('DamageCause', c.damageCauses);
tsEnum('ChunkForm', c.chunkForms);
tsEnum('LodForm', c.lodForms);
tsEnum('BlockEditAction', c.blockEditActions);
tsEnum('VoxelModificationReason', c.voxelModificationReasons);
tsEnum('HostState', c.hostStates);
const tsFlags = (name, obj) => {
  ts.push('');
  ts.push(`export const ${name} = {`);
  for (const [k, v] of enumEntries(obj)) ts.push(`  ${k}: ${v},`);
  ts.push('} as const;');
};
tsFlags('InputButtons', c.inputButtons);
tsFlags('PlayerFlags', c.playerFlags);
tsFlags('ControllerFlags', c.controllerFlags);
tsFlags('WelcomeFlags', c.welcomeFlags);
ts.push('');
writeFileSync(join(root, 'client/src/protocol/constants.gen.ts'), ts.join('\n'));


// ---- Rust (crates/dwell-protocol, ADR 0028) ------------------------------------------------------
const snake = (k) => k.replace(/([A-Z])/g, '_$1').toUpperCase();
const pascalKey = (k) => k[0].toUpperCase() + k.slice(1);
const rs = [];
rs.push(`// ${header}`);
rs.push('');
rs.push(`pub const PROTOCOL_VERSION: u16 = ${c.protocolVersion};`);
rs.push(`pub const SIM_HZ: u32 = ${c.simHz};`);
rs.push(`pub const SNAPSHOT_HZ: u32 = ${c.snapshotHz};`);
rs.push(`pub const MAX_DATAGRAM_BYTES: usize = ${c.maxDatagramBytes};`);
rs.push(`pub const MAX_RELIABLE_MESSAGE_BYTES: usize = ${c.maxReliableMessageBytes};`);
rs.push(`pub const CHUNK_SIZE: i32 = ${c.chunkSize};`);
rs.push(`pub const AUTH_DOMAIN_TAG: &str = "${c.authDomainTag}";`);
rs.push(`pub const MAX_INPUTS_PER_DATAGRAM: usize = ${c.maxInputsPerDatagram};`);
const rsGroup = (mod, obj, typeOf) => {
  rs.push('');
  rs.push(`pub mod ${mod} {`);
  for (const [k, v] of enumEntries(obj)) {
    const t = typeOf(k, v);
    const value = t === 'f32' && Number.isInteger(v) ? `${v}.0` : `${v}`;
    rs.push(`    pub const ${snake(k)}: ${t} = ${value};`);
  }
  rs.push('}');
};
// Player distances and radii (metres) are floats, the rest integers (as in C++).
rsGroup('players', c.players, (k) => (/Distance|Radius/.test(k) ? 'f32' : 'i64'));
rsGroup('world', c.world, () => 'i64');
rsGroup('lod', c.lod, () => 'i64');
rsGroup('limits', c.limits, () => 'usize');
const rsEnum = (name, obj) => {
  rs.push('');
  rs.push('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]');
  rs.push('#[repr(u8)]');
  rs.push(`pub enum ${name} {`);
  for (const [k, v] of enumEntries(obj)) rs.push(`    ${pascalKey(k)} = ${v},`);
  rs.push('}');
  rs.push('');
  rs.push(`impl ${name} {`);
  rs.push(`    pub const MAX: u8 = ${maxOf(obj)};`);
  rs.push('');
  rs.push('    pub const fn from_u8(v: u8) -> Option<Self> {');
  rs.push('        match v {');
  for (const [k, v] of enumEntries(obj)) rs.push(`            ${v} => Some(Self::${pascalKey(k)}),`);
  rs.push('            _ => None,');
  rs.push('        }');
  rs.push('    }');
  rs.push('}');
};
rsEnum('Channel', c.channels);
rsEnum('MessageType', c.messageTypes);
rsEnum('RejectReason', c.rejectReasons);
rsEnum('TransportKind', c.transportKinds);
rsEnum('PlayerState', c.playerStates);
rsEnum('GroundKind', c.groundKinds);
rsEnum('PlayerEventKind', c.playerEventKinds);
rsEnum('DamageCause', c.damageCauses);
rsEnum('ChunkForm', c.chunkForms);
rsEnum('LodForm', c.lodForms);
rsEnum('BlockEditAction', c.blockEditActions);
rsEnum('VoxelModificationReason', c.voxelModificationReasons);
rsEnum('HostState', c.hostStates);
const rsFlags = (mod, type, obj) => {
  rs.push('');
  rs.push(`pub mod ${mod} {`);
  let mask = 0;
  for (const [k, v] of enumEntries(obj)) {
    rs.push(`    pub const ${snake(k)}: ${type} = ${v};`);
    mask |= v;
  }
  rs.push(`    pub const ALL: ${type} = ${mask};`);
  rs.push('}');
};
rsFlags('input_buttons', 'u16', c.inputButtons);
rsFlags('player_flags', 'u8', c.playerFlags);
rsFlags('controller_flags', 'u8', c.controllerFlags);
rsFlags('welcome_flags', 'u8', c.welcomeFlags);
rs.push('');
writeFileSync(join(root, 'crates/dwell-protocol/src/constants.gen.rs'), rs.join('\n'));
