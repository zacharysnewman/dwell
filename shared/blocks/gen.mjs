#!/usr/bin/env node
// Generates the block registries for TypeScript and Rust from shared/blocks/*.json
// (docs/BLOCK_REGISTRY.md). Outputs are checked in; CI regenerates and fails on any diff.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { blockFluid, fluidsRust, readFluids } from './fluids.mjs';
import { blockHeld, blockLight, lightsRust, readLights } from './lights.mjs';
import { flameNames, loadFlames } from '../look/flames.mjs';
import { checkParts } from './parts.mjs';
import {
  FACINGS as SHAPE_FACINGS,
  RAMP_SHAPES,
  SLOPE_SHAPES,
  cubeShape,
  rampShape,
  slabShape,
  slopeShape,
} from './shapes.mjs';
import { blockTiles, sideUnderRules } from './faces.mjs';
import { loadSounds } from '../sounds/load.mjs';
import { checkBlockSounds } from '../sounds/validate.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = process.argv.includes('--fixture')
  ? 'Generated by shared/blocks/gen.mjs from shared/blocks/*.json and shared/blocks/fixtures/*.json (tests only). Do not edit.'
  : 'Generated by shared/blocks/gen.mjs from shared/blocks/*.json. Do not edit.';

// ---- Load and expand ---------------------------------------------------------------------------
// `--fixture`: the build's namespaces plus shared/blocks/fixtures/*.json (test content, e.g. a
// second fluid), written only as crates/dwell-blocks/src/fixture.gen.rs for tests.
const fixture = process.argv.includes('--fixture');
// Every JSON file here is a namespace of blocks but the owner's playground heights (a test terrain,
// `dwell-physics/tests/ramps.rs`).
const NOT_NAMESPACES = ['playground-export.json'];
const jsonIn = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith('.json') && !NOT_NAMESPACES.includes(f))
    .sort()
    .map((f) => join(dir, f));
const files = [...jsonIn(here), ...(fixture ? jsonIn(join(here, 'fixtures')) : [])];
const namespaces = files
  .map((f) => JSON.parse(readFileSync(f, 'utf8')))
  .sort((a, b) => (a.namespace < b.namespace ? -1 : a.namespace > b.namespace ? 1 : 0));

const NAME = /^[a-z0-9_]+$/;
const SHAPES = { empty: 'kEmpty', full: 'kFull', shaped: 'kShaped' };
const FACINGS = ['north', 'east', 'south', 'west'];
// The face (mesher axis·2 + sign) a ladder's plate sits against, per facing (0 +X, 1 −X, 4 +Z, 5 −Z).
const LADDER_FACE = { east: 0, west: 1, south: 4, north: 5 };
// A `selectionBox` on a block with a `facingProperty` is written for facing north (facing out of
// −Z, its back against +Z) and turned about the cell's vertical for the others: (x, z) in the
// cell → the facing's (x, z).
const TURN = {
  north: (x, z) => [x, z],
  east: (x, z) => [1 - z, x],
  south: (x, z) => [1 - x, 1 - z],
  west: (x, z) => [z, 1 - x],
};
// The state's selection box: the block's, turned to the state's facing.
function selectionOf(d, values) {
  const b = d.selectionBox;
  if (!b || !d.facingProperty) return b;
  const turn = TURN[values[d.facingProperty]];
  const [ax, az] = turn(b[0], b[2]);
  const [bx, bz] = turn(b[3], b[5]);
  return [Math.min(ax, bx), b[1], Math.min(az, bz), Math.max(ax, bx), b[4], Math.max(az, bz)];
}
const LOOKS = ['cube', 'shaped', 'ladder', 'fluid', 'cross'];
// Render modes (docs/TRANSPARENT_BLOCKS.md): how a look's pixels are drawn. `opaque` covers every
// pixel it draws; `cutout` is alpha-tested (alpha-to-coverage under MSAA), writes depth and needs
// no sorting; `translucent` is alpha-blended without depth writes, sorted far to near.
const RENDER_MODES = ['opaque', 'cutout', 'translucent'];
// Which neighbour a `needsSupport` block stands on ("below": toward its face's ground; "behind":
// the cell opposite its facing, a ladder's wall, docs/ITEMS.md).
const SUPPORTS = ['below', 'behind'];
// The natural, moldable material groups (`moldable`; docs/ITEMS.md): building with one of a group
// onto a slope of the same group replaces the slope.
const MOLD_GROUP = /^[a-z][a-z0-9_]*$/;
// What a block may stand in (`medium`): only air (put into water, refused), or only water (drawn
// inside it, its `flooded` property true). Absent: anything.
const MEDIUMS = ['air', 'water'];
// The cross geometry's fade must end inside the nearest full-detail distance (the streamed view,
// VIEW_RADIUS_CHUNKS × 32 m, the settings' minimum), so plants are gone before chunks meet the LOD.
const MIN_DETAIL_M = 96;
const isNum = (v) => typeof v === 'number' && Number.isFinite(v);
const inRange = (v, lo, hi) => isNum(v) && v >= lo && v <= hi;
const onlyKeys = (id, what, o, keys) => {
  if (o === null || typeof o !== 'object' || Array.isArray(o)) fail(`${id}: ${what} must be an object`);
  const extra = Object.keys(o).filter((k) => !keys.includes(k));
  if (extra.length) fail(`${id}: ${what}: unknown ${extra.join(', ')}`);
};

const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const fail = (m) => {
  throw new Error(`shared/blocks: ${m}`);
};

// Shape families (docs/SLOPE_BLOCKS.md §2): every material listed in `shapeFamilies` gets
// `<m>_slope[facing, flooded, half, shape]` and `<m>_slab[flooded, half]`, linked to the base block
// for look and behaviour. A block entry `{ "name", "family": "slab" | "slope", "of": "<m>" }` places
// that family member at its own slot in the list (with its own `placeable` / `palette`); the rest
// are appended after the explicit blocks, so adding a family keeps earlier ids.
const familyBlock = (base, kind, extra = {}) => {
  if (!base || base.shape !== 'full') fail(`shape family of ${base?.name}: not a full block`);
  const common = {
    density: base.density,
    color: base.color,
    textures: base.textures,
    look: 'shaped',
    shape: 'shaped',
    slopeFamily: kind,
    palette: 'all',
    // A slope is of its block's moldable material (dirt's ramp is dirt).
    ...(base.moldable === undefined ? {} : { moldable: base.moldable }),
  };
  if (kind === 'ramp') {
    // Stored cardinal ramps (docs/HALF_HEIGHT_GRID.md §3): placed by generation only, so not in
    // the palette; they sound like their base block.
    return {
      ...common,
      name: `${base.name}_ramp`,
      sound: base.sound,
      palette: [],
      properties: {
        facing: SHAPE_FACINGS,
        flooded: ['false', 'true'],
        half: ['bottom', 'top'],
        shape: RAMP_SHAPES,
      },
      ...extra,
    };
  }
  return kind === 'slope'
    ? {
        ...common,
        name: `${base.name}_slope`,
        properties: {
          facing: SHAPE_FACINGS,
          flooded: ['false', 'true'],
          half: ['bottom', 'top'],
          shape: Object.keys(SLOPE_SHAPES),
        },
        ...extra,
      }
    : {
        ...common,
        name: `${base.name}_slab`,
        properties: { flooded: ['false', 'true'], half: ['bottom', 'top'] },
        ...extra,
      };
};
for (const ns of namespaces) {
  const base = (name) => ns.blocks.find((b) => b.name === name);
  const declared = new Set();
  ns.blocks = ns.blocks.map((def) => {
    if (!def.family) return def;
    declared.add(`${def.of}:${def.family}`);
    const { family, of, name, ...rest } = def;
    return familyBlock(base(of), family, { ...rest, name });
  });
  const generated = [];
  for (const m of ns.shapeFamilies ?? []) {
    for (const kind of ['slope', 'slab']) {
      if (!declared.has(`${m}:${kind}`)) generated.push(familyBlock(base(m), kind));
    }
  }
  // `rampFamilies`: `<m>_ramp[facing, flooded, half, shape]` for natural ground on the half-height
  // grid (Phase 41).
  for (const m of ns.rampFamilies ?? []) {
    if (!declared.has(`${m}:ramp`)) generated.push(familyBlock(base(m), 'ramp'));
  }
  ns.blocks = [...ns.blocks, ...generated];
}

// Render mode, cross geometry, wind and the placement rules (docs/TRANSPARENT_BLOCKS.md).
// A block's render mode: its data's, else translucent for fluids and opaque for the rest.
const renderOf = (def) => def.render ?? ((def.look ?? 'cube') === 'fluid' ? 'translucent' : 'opaque');
// Whether the ink outline (docs/ART_DIRECTION.md §7) draws on it: its data's `outline`, else off
// for the cross plants (a field of blades turns to scribble) and on for the rest. Only the cross
// geometry carries the flag to the frame, so `outline` is a cross option.
const outlineOf = (def) => def.outline ?? (def.look ?? 'cube') !== 'cross';
// Flood light (docs/DAY_NIGHT.md §11): how many levels (0–15) a cell of the block takes off the sky
// and block light passing into it (15: none gets in), its data's `lightFilter`, else 15 for full
// cubes that are not see-through and 0 for the rest (crates/dwell-blocks `light_filter_default`);
// and the block light it gives off (`emits`, 0–15, default 0).
const lightFilterOf = (def) =>
  def.lightFilter ?? ((def.look ?? 'cube') === 'cube' && def.shape === 'full' && renderOf(def) !== 'translucent' ? 15 : 0);
const LIGHT_MAX = 15;
function validateLight(id, def) {
  for (const k of ['lightFilter', 'emits']) {
    const v = def[k];
    if (v !== undefined && !(Number.isInteger(v) && v >= 0 && v <= LIGHT_MAX)) {
      fail(`${id}: ${k} must be a whole number in [0, ${LIGHT_MAX}] (got ${JSON.stringify(v)})`);
    }
  }
}
function validateRender(id, def, look, isAir) {
  const render = renderOf(def);
  if (!RENDER_MODES.includes(render)) fail(`${id}: render must be one of ${RENDER_MODES.join(', ')} (got ${render})`);
  const opacity = def.opacity ?? fluids.find((f) => f.name === def.fluid)?.opacity ?? 1;
  if (!inRange(opacity, 0, 1)) fail(`${id}: opacity must be in [0, 1]`);
  if (!isAir && opacity < 1 && render !== 'translucent') fail(`${id}: opacity ${opacity} needs "render": "translucent"`);
  if (render === 'cutout' && !def.textures) fail(`${id}: render cutout needs textures (a tile with transparent texels)`);
  if (look === 'fluid' && render !== 'translucent') fail(`${id}: look fluid is drawn translucent (got render ${render})`);
  if (look === 'cross') {
    if (render === 'opaque') fail(`${id}: look cross has gaps: render must be cutout or translucent`);
    if (def.shape !== 'empty') fail(`${id}: look cross needs shape empty (crosses have no collision geometry)`);
  }
  if (def.outline !== undefined) {
    if (typeof def.outline !== 'boolean') fail(`${id}: outline must be true or false`);
    if (look !== 'cross') fail(`${id}: outline needs look cross (only the cross geometry carries the ink flag)`);
  }
  if (def.cross !== undefined) {
    if (look !== 'cross') fail(`${id}: cross options need look cross`);
    onlyKeys(id, 'cross', def.cross, ['height', 'quads', 'jitter', 'sitOnSupport']);
    const { height = 1, quads = 2, jitter, sitOnSupport = true } = def.cross;
    if (typeof sitOnSupport !== 'boolean') fail(`${id}: cross.sitOnSupport must be true or false`);
    if (!(isNum(height) && height > 0 && height <= 1)) fail(`${id}: cross.height must be in (0, 1]`);
    if (![2, 3, 4].includes(quads)) fail(`${id}: cross.quads must be 2, 3 or 4`);
    if (jitter !== undefined) {
      onlyKeys(id, 'cross.jitter', jitter, ['offset', 'rotation', 'height']);
      const { offset = 0, rotation = 0, height: h = [1, 1] } = jitter;
      if (!(isNum(offset) && offset >= 0 && offset < 0.5)) fail(`${id}: cross.jitter.offset must be in [0, 0.5)`);
      if (!inRange(rotation, 0, 90)) fail(`${id}: cross.jitter.rotation must be in [0, 90] degrees`);
      if (!(Array.isArray(h) && h.length === 2 && isNum(h[0]) && isNum(h[1]) && h[0] > 0 && h[0] <= h[1] && h[1] <= 1)) {
        fail(`${id}: cross.jitter.height must be [min, max] with 0 < min <= max <= 1`);
      }
    }
  }
  if (def.wind !== undefined) {
    if (look !== 'cross') fail(`${id}: wind needs look cross (it sways a cross's top)`);
    onlyKeys(id, 'wind', def.wind, ['strength', 'speed']);
    if (!inRange(def.wind.strength, 0, 0.5)) fail(`${id}: wind.strength must be in [0, 0.5] (metres at the top)`);
    if (!(isNum(def.wind.speed) && def.wind.speed > 0 && def.wind.speed <= 10)) fail(`${id}: wind.speed must be in (0, 10]`);
  }
  if (def.fade !== undefined) {
    if (look !== 'cross') fail(`${id}: fade needs look cross`);
    onlyKeys(id, 'fade', def.fade, ['start', 'end']);
    const { start, end } = def.fade;
    if (!(isNum(start) && isNum(end) && start > 0 && start < end && end <= MIN_DETAIL_M)) {
      fail(`${id}: fade must have 0 < start < end <= ${MIN_DETAIL_M} (metres; inside the full-detail distance)`);
    }
  }
  if (def.selectionBox !== undefined) {
    const b = def.selectionBox;
    if (!(Array.isArray(b) && b.length === 6 && b.every((v) => inRange(v, 0, 1)) && b[0] < b[3] && b[1] < b[4] && b[2] < b[5])) {
      fail(`${id}: selectionBox must be [x0, y0, z0, x1, y1, z1] in the cell (0..1, min < max)`);
    }
  }
  if (def.placeOn !== undefined) {
    if (!(Array.isArray(def.placeOn) && def.placeOn.length && def.placeOn.every((n) => typeof n === 'string'))) {
      fail(`${id}: placeOn must be a non-empty list of block ids`);
    }
  }
  if (def.needsSupport !== undefined && !SUPPORTS.includes(def.needsSupport)) {
    fail(`${id}: needsSupport must be one of ${SUPPORTS.join(', ')}`);
  }
  if (def.replaceable !== undefined && typeof def.replaceable !== 'boolean') fail(`${id}: replaceable must be true or false`);
  if (def.needsSupport === 'behind' && !def.facingProperty) fail(`${id}: needsSupport behind needs a facingProperty (what is behind it)`);
  if (def.onSlopes !== undefined && typeof def.onSlopes !== 'boolean') fail(`${id}: onSlopes must be true or false`);
  if (def.moldable !== undefined && !(typeof def.moldable === 'string' && MOLD_GROUP.test(def.moldable))) {
    fail(`${id}: moldable must name a material group (lowercase letters, digits, _)`);
  }
  if (def.medium !== undefined) {
    if (!MEDIUMS.includes(def.medium)) fail(`${id}: medium must be one of ${MEDIUMS.join(', ')}`);
    const f = def.properties?.flooded;
    if (def.medium === 'water' && !(Array.isArray(f) && f.includes('true'))) {
      fail(`${id}: medium water needs a flooded property (it holds the water it stands in)`);
    }
  }
}

const fluids = readFluids(namespaces); // fluids.mjs
// Light sources (lights.mjs, docs/LIGHTS.md): blocks reference them by name; a block's held item
// names an item of the characters' data.
const lights = readLights(namespaces, flameNames(loadFlames()));
const heldItems = Object.keys(JSON.parse(readFileSync(join(root, 'shared/characters/characters.json'), 'utf8')).items);
const opacityOf = (block) => block.def.opacity ?? fluids[block.fluid]?.opacity ?? 1;
const blocks = []; // { id, def, props: [{name, values}], first, count, look, fluid }
const states = []; // { id, block, string, values: {prop: value}, ... }
for (const ns of namespaces) {
  if (!NAME.test(ns.namespace)) fail(`bad namespace ${ns.namespace}`);
  for (const def of ns.blocks) {
    if (!NAME.test(def.name)) fail(`bad block name ${def.name}`);
    const id = `${ns.namespace}:${def.name}`;
    if (blocks.some((b) => b.id === id)) fail(`duplicate block ${id}`);
    const props = Object.keys(def.properties ?? {})
      .sort()
      .map((name) => {
        if (!NAME.test(name)) fail(`${id}: bad property name ${name}`);
        const values = def.properties[name];
        if (!values.length || new Set(values).size !== values.length) fail(`${id}.${name}: values`);
        for (const v of values) if (!NAME.test(v)) fail(`${id}.${name}: bad value ${v}`);
        return { name, values };
      });
    if (!(def.shape in SHAPES)) fail(`${id}: shape ${def.shape}`);
    if (def.tint !== undefined) fail(`${id}: tint is no longer supported (biome tints were removed)`);
    if (def.launchSpeed !== undefined) fail(`${id}: launchSpeed is no longer supported`);
    // `grid` (a look option): lines the terrain shader draws every `every` blocks in world space,
    // darkening by `strength`. `every` divides the chunk size (32), so chunk-local uvs line up.
    if (def.grid !== undefined) {
      const { every, strength, ...rest } = def.grid ?? {};
      if (Object.keys(rest).length) fail(`${id}: grid: unknown ${Object.keys(rest).join(', ')}`);
      if (![1, 2, 4, 8, 16, 32].includes(every)) fail(`${id}: grid.every must divide 32 (1, 2, 4, 8, 16 or 32)`);
      if (!(typeof strength === 'number' && strength > 0 && strength <= 1)) fail(`${id}: grid.strength must be in (0, 1]`);
    }
    const look = def.look ?? 'cube';
    if (!LOOKS.includes(look)) fail(`${id}: look ${look}`);
    validateRender(id, def, look, states.length === 0);
    validateLight(id, def);
    if (def.facingProperty) {
      const p = props.find((q) => q.name === def.facingProperty);
      if (!p || p.values.some((v) => !FACINGS.includes(v))) fail(`${id}: facingProperty`);
    }
    if (def.shape === 'shaped' && !def.slopeFamily) fail(`${id}: shaped blocks come from shapeFamilies`);
    // Adaptive blocks (shaped from their neighbours) were removed with ½ m cells (ADR 0042): natural
    // ground is shaped once, by the generator's stored ramps.
    if (def.adaptive !== undefined) fail(`${id}: adaptive blocks were removed (ADR 0042); natural ground uses rampFamilies`);
    const count = props.reduce((n, p) => n * p.values.length, 1);
    const fluid = blockFluid(id, def, fluids);
    const light = blockLight(id, def, lights);
    const held = blockHeld(id, def, heldItems);
    const block = { id, def, props, first: states.length, count, look, fluid, light, held };
    blocks.push(block);
    // Mixed radix: the last (alphabetically) property varies fastest.
    for (let i = 0; i < count; ++i) {
      const values = {};
      let rest = i;
      for (let k = props.length - 1; k >= 0; --k) {
        const p = props[k];
        values[p.name] = p.values[rest % p.values.length];
        rest = Math.floor(rest / p.values.length);
      }
      const string = props.length
        ? `${id}[${props.map((p) => `${p.name}=${values[p.name]}`).join(',')}]`
        : id;
      states.push({ id: states.length, block, string, values });
    }
  }
}
if (states[0]?.string !== 'dwell:air') fail('dwell:air must be state 0');
for (const b of blocks) {
  for (const name of b.def.placeOn ?? []) {
    if (!blocks.some((o) => o.id === name)) fail(`${b.id}: placeOn names unknown block ${name}`);
  }
  // Side tiles chosen by the block above (faces.mjs).
  try {
    // A rule naming a block also holds under its shape families (the half-height grid's stored
    // ramps, `<m>_ramp`): sloped grass over dirt is still grass.
    b.sideUnder = sideUnderRules(b.id, b.def, blocks.map((o) => o.id)).flatMap((r) => [
      r,
      ...blocks
        .filter((o) => o.def.slopeFamily && o.id === `${r.above}_${o.def.slopeFamily}`)
        .map((o) => ({ ...r, above: o.id })),
    ]);
  } catch (e) {
    fail(e.message);
  }
}
// The terrain shader finds a face's grid from its texture tile (dwell-mesh tile_grids), so every
// block drawn with a tile (an untextured one with `plain`) must want the same grid, or none.
{
  const gridOfTile = new Map();
  for (const b of blocks) {
    const tiles = b.def.textures ? blockTiles(b.def) : ['plain'];
    const want = b.def.grid ? `every ${b.def.grid.every}, strength ${b.def.grid.strength}` : 'no grid';
    for (const tile of tiles) {
      const seen = gridOfTile.get(tile);
      if (seen && seen.want !== want) {
        fail(`${b.id}: texture tile ${tile} is drawn with ${seen.want} by ${seen.id} but ${want} here (a tile has one grid: give the block its own tile)`);
      }
      gridOfTile.set(tile, seen ?? { id: b.id, want });
    }
  }
}
// Multi-cell blocks (parts.mjs): `extends` and `partOf` name each other.
let parts;
try {
  parts = checkParts(blocks);
} catch (e) {
  fail(e.message.replace(/^shared\/blocks: /, ''));
}
// Sound sets (docs/AUDIO.md): a block's optional `sound` names a set in shared/sounds/*.json.
checkBlockSounds(blocks.map((b) => ({ id: b.id, sound: b.def.sound })), loadSounds());
if (states.length > 0xffff) fail('too many states');

// Shapes (shapes.mjs): one baked geometry per distinct (corners, inversion, diagonal); index 0 is
// the empty shape. States of full blocks use the cube, shaped families derive theirs from their
// properties.
const shapeTable = [{ key: 'empty', shape: null }];
const shapeIndexOf = (shape) => {
  const key = JSON.stringify(shape.fan ? [shape.points, shape.inverted, 'fan'] : [shape.corners, shape.inverted, shape.diagonal]);
  let i = shapeTable.findIndex((t) => t.key === key);
  if (i < 0) {
    i = shapeTable.length;
    shapeTable.push({ key, shape });
  }
  return i;
};
for (const st of states) {
  const d = st.block.def;
  st.flooded = st.values.flooded === 'true';
  if (d.shape === 'empty') st.shapeIndex = 0;
  else if (d.shape === 'full') st.shapeIndex = shapeIndexOf(cubeShape());
  else {
    const of = { slope: slopeShape, slab: slabShape, ramp: rampShape }[d.slopeFamily];
    st.shapeIndex = shapeIndexOf(of(st.values));
  }
}
if (shapeTable.length > 0xffff) fail('too many shapes');

// Palette (creative inventory) membership: a block's `palette` lists partial property assignments;
// `placeable` alone means the default state.
const defaultOf = (block) => Object.fromEntries(block.props.map((p) => [p.name, p.values[0]]));
for (const block of blocks) {
  const { def } = block;
  if (def.palette === 'all') {
    // Every state is placeable (the shaped families: the client picks the piece, the facing and the
    // half; the server normalises `flooded` from the cell).
    for (const st of states) if (st.block === block) st.placeable = true;
    continue;
  }
  const entries = def.palette ?? (def.placeable ? [{}] : []);
  for (const entry of entries) {
    const want = { ...defaultOf(block), ...entry };
    const s = states.find(
      (st) => st.block === block && block.props.every((p) => st.values[p.name] === want[p.name]),
    );
    if (!s) fail(`${block.id}: palette entry ${JSON.stringify(entry)} matches no state`);
    s.placeable = true;
  }
}

// ---- Registry hash: FNV-1a 64 over each canonical string followed by "\n", in id order ------------
function registryHash() {
  let h = 0xcbf29ce484222325n;
  for (const s of states) {
    for (const byte of Buffer.from(`${s.string}\n`, 'utf8')) {
      h ^= BigInt(byte);
      h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
    }
  }
  return h;
}
const hash = registryHash();
const hashHex = hash.toString(16).padStart(16, '0');

// Constant names: PascalCase block name, plus Property+Value for every non-default value.
const constName = (s) => {
  let n = `k${pascal(s.block.def.name)}`;
  for (const p of s.block.props) {
    if (s.values[p.name] !== p.values[0]) n += pascal(p.name) + pascal(s.values[p.name]);
  }
  return n;
};
const seen = new Set();
for (const s of states) {
  s.constName = constName(s);
  if (seen.has(s.constName)) fail(`constant name clash ${s.constName}`);
  seen.add(s.constName);
}

