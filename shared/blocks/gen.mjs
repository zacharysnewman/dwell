#!/usr/bin/env node
// Generates the block registries for C++, TypeScript and Rust from shared/blocks/*.json
// (docs/BLOCK_REGISTRY.md). Outputs are checked in; CI regenerates and fails on any diff.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { blockFluid, fluidsRust, readFluids } from './fluids.mjs';
import { FACINGS as SHAPE_FACINGS, SLOPE_SHAPES, cubeShape, slabShape, slopeShape } from './shapes.mjs';
import { loadSounds } from '../sounds/load.mjs';
import { checkBlockSounds } from '../sounds/validate.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = process.argv.includes('--fixture')
  ? 'Generated by shared/blocks/gen.mjs from shared/blocks/*.json and shared/blocks/fixtures/*.json (tests only). Do not edit.'
  : 'Generated by shared/blocks/gen.mjs from shared/blocks/*.json. Do not edit.';

// ---- Load and expand ---------------------------------------------------------------------------
// `--fixture`: the build's namespaces plus shared/blocks/fixtures/*.json (test content, e.g. a
// second fluid), written only as crates/dwell-blocks/src/fixture.gen.rs for tests.
const fixture = process.argv.includes('--fixture');
const jsonIn = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => join(dir, f));
const files = [...jsonIn(here), ...(fixture ? jsonIn(join(here, 'fixtures')) : [])];
const namespaces = files
  .map((f) => JSON.parse(readFileSync(f, 'utf8')))
  .sort((a, b) => (a.namespace < b.namespace ? -1 : a.namespace > b.namespace ? 1 : 0));

const NAME = /^[a-z0-9_]+$/;
const SHAPES = { empty: 'kEmpty', full: 'kFull', shaped: 'kShaped' };
const FACINGS = ['north', 'east', 'south', 'west'];
// The face (mesher axis·2 + sign) a ladder's plate sits against, per facing (0 +X, 1 −X, 4 +Z, 5 −Z).
const LADDER_FACE = { east: 0, west: 1, south: 4, north: 5 };
const LOOKS = ['cube', 'shaped', 'ladder', 'fluid'];

const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const fail = (m) => {
  throw new Error(`shared/blocks: ${m}`);
};

// Shape families (docs/SLOPE_BLOCKS.md §2): every material listed in `shapeFamilies` gets
// `<m>_slope[facing, flooded, half, shape]` and `<m>_slab[flooded, half]`, linked to the base block
// for look and behaviour. A block entry `{ "name", "family": "slab" | "slope", "of": "<m>" }` places
// that family member at its own slot in the list (with its own `placeable` / `palette`); the rest
// are appended after the explicit blocks, so adding a family keeps earlier ids.
const familyBlock = (base, kind, extra = {}) => {
  if (!base || base.shape !== 'full') fail(`shape family of ${base?.name}: not a full block`);
  const common = {
    density: base.density,
    color: base.color,
    textures: base.textures,
    look: 'shaped',
    shape: 'shaped',
    slopeFamily: kind,
    palette: 'all',
  };
  return kind === 'slope'
    ? {
        ...common,
        name: `${base.name}_slope`,
        properties: {
          facing: SHAPE_FACINGS,
          flooded: ['false', 'true'],
          half: ['bottom', 'top'],
          shape: Object.keys(SLOPE_SHAPES),
        },
        ...extra,
      }
    : {
        ...common,
        name: `${base.name}_slab`,
        properties: { flooded: ['false', 'true'], half: ['bottom', 'top'] },
        ...extra,
      };
};
for (const ns of namespaces) {
  const base = (name) => ns.blocks.find((b) => b.name === name);
  const declared = new Set();
  ns.blocks = ns.blocks.map((def) => {
    if (!def.family) return def;
    declared.add(`${def.of}:${def.family}`);
    const { family, of, name, ...rest } = def;
    return familyBlock(base(of), family, { ...rest, name });
  });
  const generated = [];
  for (const m of ns.shapeFamilies ?? []) {
    for (const kind of ['slope', 'slab']) {
      if (!declared.has(`${m}:${kind}`)) generated.push(familyBlock(base(m), kind));
    }
  }
  ns.blocks = [...ns.blocks, ...generated];
}

const fluids = readFluids(namespaces); // fluids.mjs
const opacityOf = (block) => block.def.opacity ?? fluids[block.fluid]?.opacity ?? 1;
const blocks = []; // { id, def, props: [{name, values}], first, count, look, fluid }
const states = []; // { id, block, string, values: {prop: value}, ... }
for (const ns of namespaces) {
  if (!NAME.test(ns.namespace)) fail(`bad namespace ${ns.namespace}`);
  for (const def of ns.blocks) {
    if (!NAME.test(def.name)) fail(`bad block name ${def.name}`);
    const id = `${ns.namespace}:${def.name}`;
    if (blocks.some((b) => b.id === id)) fail(`duplicate block ${id}`);
    const props = Object.keys(def.properties ?? {})
      .sort()
      .map((name) => {
        if (!NAME.test(name)) fail(`${id}: bad property name ${name}`);
        const values = def.properties[name];
        if (!values.length || new Set(values).size !== values.length) fail(`${id}.${name}: values`);
        for (const v of values) if (!NAME.test(v)) fail(`${id}.${name}: bad value ${v}`);
        return { name, values };
      });
    if (!(def.shape in SHAPES)) fail(`${id}: shape ${def.shape}`);
    if (def.tint !== undefined) fail(`${id}: tint is no longer supported (biome tints were removed)`);
    if (def.launchSpeed !== undefined) fail(`${id}: launchSpeed is no longer supported`);
    // `grid` (a look option): lines the terrain shader draws every `every` blocks in world space,
    // darkening by `strength`. `every` divides the chunk size (32), so chunk-local uvs line up.
    if (def.grid !== undefined) {
      const { every, strength, ...rest } = def.grid ?? {};
      if (Object.keys(rest).length) fail(`${id}: grid: unknown ${Object.keys(rest).join(', ')}`);
      if (![1, 2, 4, 8, 16, 32].includes(every)) fail(`${id}: grid.every must divide 32 (1, 2, 4, 8, 16 or 32)`);
      if (!(typeof strength === 'number' && strength > 0 && strength <= 1)) fail(`${id}: grid.strength must be in (0, 1]`);
    }
    const look = def.look ?? 'cube';
    if (!LOOKS.includes(look)) fail(`${id}: look ${look}`);
    if (def.facingProperty) {
      const p = props.find((q) => q.name === def.facingProperty);
      if (!p || p.values.some((v) => !FACINGS.includes(v))) fail(`${id}: facingProperty`);
    }
    if (def.shape === 'shaped' && !def.slopeFamily) fail(`${id}: shaped blocks come from shapeFamilies`);
    const count = props.reduce((n, p) => n * p.values.length, 1);
    const fluid = blockFluid(id, def, fluids);
    const block = { id, def, props, first: states.length, count, look, fluid };
    blocks.push(block);
    // Mixed radix: the last (alphabetically) property varies fastest.
    for (let i = 0; i < count; ++i) {
      const values = {};
      let rest = i;
      for (let k = props.length - 1; k >= 0; --k) {
        const p = props[k];
        values[p.name] = p.values[rest % p.values.length];
        rest = Math.floor(rest / p.values.length);
      }
      const string = props.length
        ? `${id}[${props.map((p) => `${p.name}=${values[p.name]}`).join(',')}]`
        : id;
      states.push({ id: states.length, block, string, values });
    }
  }
}
if (states[0]?.string !== 'dwell:air') fail('dwell:air must be state 0');
// The terrain shader finds a face's grid from its texture tile (dwell-mesh tile_grids), so every
// block drawn with a tile (an untextured one with `plain`) must want the same grid, or none.
{
  const gridOfTile = new Map();
  for (const b of blocks) {
    const t = b.def.textures;
    const tiles = t ? (typeof t === 'string' ? [t] : [t.top, t.side, t.bottom]) : ['plain'];
    const want = b.def.grid ? `every ${b.def.grid.every}, strength ${b.def.grid.strength}` : 'no grid';
    for (const tile of tiles) {
      const seen = gridOfTile.get(tile);
      if (seen && seen.want !== want) {
        fail(`${b.id}: texture tile ${tile} is drawn with ${seen.want} by ${seen.id} but ${want} here (a tile has one grid: give the block its own tile)`);
      }
      gridOfTile.set(tile, seen ?? { id: b.id, want });
    }
  }
}
// Sound sets (docs/AUDIO.md): a block's optional `sound` names a set in shared/sounds/*.json.
checkBlockSounds(blocks.map((b) => ({ id: b.id, sound: b.def.sound })), loadSounds());
if (states.length > 0xffff) fail('too many states');

// Shapes (shapes.mjs): one baked geometry per distinct (corners, inversion, diagonal); index 0 is
// the empty shape. States of full blocks use the cube, shaped families derive theirs from their
// properties.
const shapeTable = [{ key: 'empty', shape: null }];
const shapeIndexOf = (shape) => {
  const key = JSON.stringify([shape.corners, shape.inverted, shape.diagonal]);
  let i = shapeTable.findIndex((t) => t.key === key);
  if (i < 0) {
    i = shapeTable.length;
    shapeTable.push({ key, shape });
  }
  return i;
};
for (const st of states) {
  const d = st.block.def;
  st.flooded = st.values.flooded === 'true';
  if (d.shape === 'empty') st.shapeIndex = 0;
  else if (d.shape === 'full') st.shapeIndex = shapeIndexOf(cubeShape());
  else st.shapeIndex = shapeIndexOf((d.slopeFamily === 'slope' ? slopeShape : slabShape)(st.values));
}
if (shapeTable.length > 0xffff) fail('too many shapes');

// Palette (creative inventory) membership: a block's `palette` lists partial property assignments;
// `placeable` alone means the default state.
const defaultOf = (block) => Object.fromEntries(block.props.map((p) => [p.name, p.values[0]]));
for (const block of blocks) {
  const { def } = block;
  if (def.palette === 'all') {
    // Every state is placeable (the shaped families: the client picks the piece, the facing and the
    // half; the server normalises `flooded` from the cell).
    for (const st of states) if (st.block === block) st.placeable = true;
    continue;
  }
  const entries = def.palette ?? (def.placeable ? [{}] : []);
  for (const entry of entries) {
    const want = { ...defaultOf(block), ...entry };
    const s = states.find(
      (st) => st.block === block && block.props.every((p) => st.values[p.name] === want[p.name]),
    );
    if (!s) fail(`${block.id}: palette entry ${JSON.stringify(entry)} matches no state`);
    s.placeable = true;
  }
}

// ---- Registry hash: FNV-1a 64 over each canonical string followed by "\n", in id order ------------
function registryHash() {
  let h = 0xcbf29ce484222325n;
  for (const s of states) {
    for (const byte of Buffer.from(`${s.string}\n`, 'utf8')) {
      h ^= BigInt(byte);
      h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
    }
  }
  return h;
}
const hash = registryHash();
const hashHex = hash.toString(16).padStart(16, '0');

// Constant names: PascalCase block name, plus Property+Value for every non-default value.
const constName = (s) => {
  let n = `k${pascal(s.block.def.name)}`;
  for (const p of s.block.props) {
    if (s.values[p.name] !== p.values[0]) n += pascal(p.name) + pascal(s.values[p.name]);
  }
  return n;
};
const seen = new Set();
for (const s of states) {
  s.constName = constName(s);
  if (seen.has(s.constName)) fail(`constant name clash ${s.constName}`);
  seen.add(s.constName);
}

const colorNum = (c) => `0x${c.replace('#', '').toLowerCase()}`;
const num = (v) => (Number.isInteger(v) ? `${v}.0f` : `${v}f`);

// ---- TypeScript --------------------------------------------------------------------------------
const ts = [];
ts.push(`// ${header}`);
ts.push("export type MaterialLook = 'cube' | 'shaped' | 'ladder' | 'fluid';");
ts.push('');
ts.push('/** Texture tiles (dwell-mesh textures.rs) per face group; untextured materials use `color`. */');
ts.push('export interface MaterialTextures {');
ts.push('  top: string;');
ts.push('  side: string;');
ts.push('  bottom: string;');
ts.push('}');
ts.push('');
ts.push('export interface BlockProperty {');
ts.push('  name: string;');
ts.push('  values: readonly string[];');
ts.push('}');
ts.push('');
ts.push('/** A block: a namespaced id, its typed properties and the run of runtime state ids it owns. */');
ts.push('export interface BlockDef {');
ts.push('  id: string;');
ts.push('  first: number;');
ts.push('  count: number;');
ts.push('  properties: readonly BlockProperty[];');
ts.push('  /** Its sound set (shared/sounds, docs/AUDIO.md); none: the sounds\' fallback set. */');
ts.push('  sound?: string;');
ts.push('}');
ts.push('');
ts.push('/** One block state with how it is drawn (the physics side lives in the C++ core). */');
ts.push('export interface StateDef {');
ts.push('  /** Runtime state id. */');
ts.push('  id: number;');
ts.push('  /** Canonical string: `ns:name[k=v,…]`, every property, keys alphabetical. */');
ts.push('  state: string;');
ts.push('  block: number;');
ts.push('  values: Readonly<Record<string, string>>;');
ts.push('  look: MaterialLook;');
ts.push('  color: number;');
ts.push('  opacity: number;');
ts.push('  textures?: MaterialTextures;');
ts.push('  /** Ladders: the face whose side the plate faces (0 +X, 1 −X, 4 +Z, 5 −Z). */');
ts.push('  ladderFace?: number;');
ts.push('  /** Index into SHAPES: the solid\'s geometry in its cell (0 = none). */');
ts.push('  shape: number;');
ts.push('  /** Shaped blocks only: water fills the open part of the cell (SLOPE_BLOCKS.md §3.1). */');
ts.push('  flooded: boolean;');
ts.push('  /** In the infinite creative palette (§6.5; C++ `Placeable`). */');
ts.push('  placeable: boolean;');
ts.push('}');
ts.push('');
ts.push('/** One polygon of a shape: convex, outward-wound, on cell face `tag` (0 +X, 1 −X, 2 +Y, 3 −Y, 4 +Z, 5 −Z) or the sloped surface (6). */');
ts.push('export interface ShapeFace {');
ts.push('  tag: number;');
ts.push('  pts: readonly (readonly [number, number, number])[];');
ts.push('}');
ts.push('');
ts.push('/** Baked solid geometry of a voxel state inside its 1 m cell (shared/blocks/shapes.mjs). */');
ts.push('export interface ShapeDef {');
ts.push('  /** Top-surface corner heights in halves of a cell, NW NE SE SW. */');
ts.push('  corners: readonly [number, number, number, number];');
ts.push('  inverted: boolean;');
ts.push('  /** Top-surface diagonal: 0 NW–SE, 1 NE–SW. */');
ts.push('  diagonal: number;');
ts.push('  convex: boolean;');
ts.push('  volume: number;');
ts.push('  /** Side profile heights (halves) at the face\'s low and high running coordinate, faces +X −X +Z −Z. */');
ts.push('  sides: readonly (readonly [number, number])[];');
ts.push('  fullTop: boolean;');
ts.push('  fullBottom: boolean;');
ts.push('  minY: number;');
ts.push('  maxY: number;');
ts.push('  faces: readonly ShapeFace[];');
ts.push('}');
ts.push('');
ts.push('/** FNV-1a 64 over the canonical state strings (each followed by "\\n") in id order. */');
ts.push(`export const REGISTRY_HASH = 0x${hashHex}n;`);
ts.push('');
ts.push('export const BLOCK_DEFS: readonly BlockDef[] = [');
for (const b of blocks) {
  const props = b.props.map((p) => `{ name: '${p.name}', values: [${p.values.map((v) => `'${v}'`).join(', ')}] }`);
  const sound = b.def.sound ? `, sound: '${b.def.sound}'` : '';
  ts.push(`  { id: '${b.id}', first: ${b.first}, count: ${b.count}, properties: [${props.join(', ')}]${sound} },`);
}
ts.push('];');
ts.push('');
ts.push('export const SHAPES: readonly ShapeDef[] = [');
for (const t of shapeTable) {
  const sh = t.shape;
  if (!sh) {
    ts.push("  { corners: [0, 0, 0, 0], inverted: false, diagonal: 0, convex: true, volume: 0, sides: [[0, 0], [0, 0], [0, 0], [0, 0]], fullTop: false, fullBottom: false, minY: 0, maxY: 0, faces: [] },");
    continue;
  }
  const faces = sh.faces.map((fc) => `{ tag: ${fc.tag}, pts: [${fc.pts.map((p) => `[${p.join(', ')}]`).join(', ')}] }`);
  ts.push(`  { corners: [${sh.corners.join(', ')}], inverted: ${sh.inverted}, diagonal: ${sh.diagonal}, convex: ${sh.convex}, volume: ${sh.volume}, sides: [${sh.sides.map((p) => `[${p.join(', ')}]`).join(', ')}], fullTop: ${sh.fullTop}, fullBottom: ${sh.fullBottom}, minY: ${sh.minY}, maxY: ${sh.maxY}, faces: [${faces.join(', ')}] },`);
}
ts.push('];');
ts.push('');
const tex = (t) => {
  if (!t) return null;
  const o = typeof t === 'string' ? { top: t, side: t, bottom: t } : t;
  return `{ top: '${o.top}', side: '${o.side}', bottom: '${o.bottom}' }`;
};
// Chunked: one literal of a thousand distinct object types is too complex for the type checker.
const CHUNK = 128;
for (let first = 0; first < states.length; first += CHUNK) {
  ts.push(`const STATES_${first / CHUNK}: readonly StateDef[] = [`);
  for (const s of states.slice(first, first + CHUNK)) {
  const d = s.block.def;
  const parts = [
    `id: ${s.id}`,
    `state: '${s.string}'`,
    `block: ${blocks.indexOf(s.block)}`,
    `values: { ${s.block.props.map((p) => `${p.name}: '${s.values[p.name]}'`).join(', ')} }`,
    `look: '${s.block.look}'`,
    `color: ${colorNum(d.color)}`,
    `opacity: ${opacityOf(s.block)}`,
  ];
  if (d.textures) parts.push(`textures: ${tex(d.textures)}`);
  if (d.look === 'ladder' && d.facingProperty) {
    parts.push(`ladderFace: ${LADDER_FACE[s.values[d.facingProperty]]}`);
  }
  parts.push(`shape: ${s.shapeIndex}`);
  parts.push(`flooded: ${s.flooded}`);
  parts.push(`placeable: ${!!s.placeable}`);
  ts.push(`  { ${parts.join(', ')} },`);
  }
  ts.push('];');
  ts.push('');
}
ts.push('export const STATE_DEFS: readonly StateDef[] = [');
for (let first = 0; first < states.length; first += CHUNK) ts.push(`  ...STATES_${first / CHUNK},`);
ts.push('];');
ts.push('');
if (!fixture) writeFileSync(join(root, 'client/src/world/blocks.gen.ts'), ts.join('\n'));

// ---- Rust (crates/dwell-blocks, ADR 0028): tables only; code looks states up by name --------------
{
  const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
  const rstr = (v) => JSON.stringify(v);
  const rs = [];
  rs.push(`// ${header}`);
  rs.push('');
  rs.push('use crate::types::*;');
  rs.push('');
  rs.push('/// FNV-1a 64 over the canonical state strings (each followed by a newline) in runtime id order.');
  rs.push(`pub const REGISTRY_HASH: u64 = 0x${hashHex};`);
  rs.push('');
  const values = [];
  const props = [];
  const blockRows = [];
  for (const b of blocks) {
    const begin = props.length;
    for (const p of b.props) {
      props.push(`    PropertyDef { name: ${rstr(p.name)}, first_value: ${values.length}, value_count: ${p.values.length} },`);
      for (const v of p.values) values.push(`    ${rstr(v)},`);
    }
    blockRows.push(
      `    BlockDef { name: ${rstr(b.id)}, first_state: ${b.first}, state_count: ${b.count}, first_property: ${begin}, property_count: ${b.props.length} },`,
    );
  }
  rs.push(`pub static PROPERTY_VALUES: [&str; ${values.length}] = [`);
  rs.push(...values);
  rs.push('];');
  rs.push('');
  rs.push(`pub static PROPERTIES: [PropertyDef; ${props.length}] = [`);
  rs.push(...props);
  rs.push('];');
  rs.push('');
  rs.push(`pub static BLOCKS: [BlockDef; ${blocks.length}] = [`);
  rs.push(...blockRows);
  rs.push('];');
  rs.push('');
  const faces = [];
  const shapes = [];
  for (const t of shapeTable) {
    const sh = t.shape;
    const first = faces.length;
    for (const face of sh?.faces ?? []) {
      const pts = [...face.pts, ...Array(4 - face.pts.length).fill([0, 0, 0])];
      faces.push(`    ShapeFace { tag: ${face.tag}, count: ${face.pts.length}, v: [${pts.map((q) => `[${q.map(rf).join(', ')}]`).join(', ')}] },`);
    }
    shapes.push(
      sh
        ? `    ShapeInfo { first_face: ${first}, face_count: ${sh.faces.length}, corners: [${sh.corners.join(', ')}], inverted: ${sh.inverted}, diagonal: ${sh.diagonal}, convex: ${sh.convex}, volume: ${rf(sh.volume)}, sides: [${sh.sides.map((q) => `[${q.join(', ')}]`).join(', ')}], full_top: ${sh.fullTop}, full_bottom: ${sh.fullBottom}, min_y: ${rf(sh.minY)}, max_y: ${rf(sh.maxY)} },`
        : '    ShapeInfo::EMPTY,',
    );
  }
  rs.push(`pub static SHAPE_FACES: [ShapeFace; ${faces.length}] = [`);
  rs.push(...faces);
  rs.push('];');
  rs.push('');
  rs.push(`pub static SHAPES: [ShapeInfo; ${shapes.length}] = [`);
  rs.push(...shapes);
  rs.push('];');
  rs.push('');
  const RS_SHAPES = { empty: 'Empty', full: 'Full', shaped: 'Shaped' };
  rs.push(`pub static STATES: [StateInfo; ${states.length}] = [`);
  for (const st of states) {
    const d = st.block.def;
    const t = d.textures ? (typeof d.textures === 'string' ? { top: d.textures, side: d.textures, bottom: d.textures } : d.textures) : null;
    const facing = d.facingProperty ? `Facing::${pascal(st.values[d.facingProperty])}` : 'Facing::None';
    const fields = [
      `name: ${rstr(st.string)}`,
      `block: ${blocks.indexOf(st.block)}`,
      `density_kg_m3: ${rf(d.density)}`,
      `solid: ${d.shape !== 'empty'}`,
      `indestructible: ${!!d.indestructible}`,
      `shape: VoxelShape::${RS_SHAPES[d.shape]}`,
      `shape_index: ${st.shapeIndex}`,
      `flooded: ${st.flooded}`,
      `climbable: ${!!d.climbable}`,
      `facing: ${facing}`,
      `climb_speed_scale: ${rf(d.climbSpeedScale ?? 1)}`,
      `liquid: ${!!d.liquid}`,
      `fluid: ${st.block.fluid === null ? 'None' : `Some(${st.block.fluid})`}`,
      `placeable: ${!!st.placeable}`,
      `look: ${rstr(st.block.look)}`,
      `color: 0x${d.color.replace('#', '').toLowerCase()}`,
      `opacity: ${rf(opacityOf(st.block))}`,
      `textures: ${t ? `Some(Textures { top: ${rstr(t.top)}, side: ${rstr(t.side)}, bottom: ${rstr(t.bottom)} })` : 'None'}`,
      `grid: ${d.grid ? `Some(Grid { every: ${d.grid.every}, strength: ${rf(d.grid.strength)} })` : 'None'}`,
    ];
    rs.push(`    StateInfo { ${fields.join(', ')} },`);
  }
  rs.push('];');
  rs.push('');
  rs.push(...fluidsRust(fluids, rf));
  const out = fixture ? 'fixture.gen.rs' : 'blocks.gen.rs';
  writeFileSync(join(root, 'crates/dwell-blocks/src', out), rs.join('\n'));
}

// ---- Shared vector: the canonical strings in id order and the hash (both sides' tests read it) -----
