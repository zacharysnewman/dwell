#!/usr/bin/env node
// Generates inventories, items and block drops (docs/adr/0066-inventory-and-drops.md) for Rust and
// TypeScript from shared/inventory/inventory.json and every block's `drops` in shared/blocks/*.json:
// `crates/dwell-protocol/src/inventory.gen.rs` (the server keeps inventories and loose items, the
// client draws them, through `dwell_protocol::inventory`) and `client/src/ui/inventory.gen.ts` (the
// hotbar and the backpack screen). Outputs are checked in; CI regenerates them and fails on any
// diff. A bad entry fails with a message naming it.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header =
  'Generated by shared/inventory/gen.mjs from shared/inventory/inventory.json and shared/blocks/*.json. Do not edit.';

const TOP_FIELDS = [
  '$comment',
  'formatVersion',
  'hotbarSlots',
  'backpackSlots',
  'stackSize',
  'despawnSeconds',
  'pickupRadiusM',
  'pickupDelaySeconds',
  'maxDrops',
  'items',
  'wallets',
  'startingWallet',
  'startingItems',
];
const ITEM_FIELDS = ['name', 'label', 'color', 'size', 'stack', 'value'];
const DROP_FIELDS = ['item', 'count', 'chance', 'pick'];
const PICK_FIELDS = ['item', 'count', 'weight'];
const WALLET_FIELDS = ['name', 'label', 'capacity'];
/** A namespaced name, as blocks have (`dwell:rock`); sent on the wire and saved, so kept short. */
const NAMESPACED = /^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$/;
const MAX_NAME = 64;
const COLOR = /^#[0-9a-f]{6}$/;

const fail = (m) => {
  throw new Error(`shared/inventory: ${m}`);
};
const isInt = (v) => Number.isInteger(v);
const num = (v) => typeof v === 'number' && Number.isFinite(v);

/**
 * Checks the inventory data and the blocks' drops. `namespaces` are the block files' contents
 * (`{ namespace, blocks }`). Returns the data with every block's drops resolved (defaults filled).
 */
export function validateInventory(data, namespaces) {
  if (typeof data !== 'object' || data === null) fail('the file must hold an object');
  for (const k of Object.keys(data)) {
    if (!TOP_FIELDS.includes(k) && k[0] !== "$") fail(`unknown field ${k} (${TOP_FIELDS.filter((f) => f[0] !== '$').join(', ')})`);
  }
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  const whole = (k, lo, hi) => {
    if (!isInt(data[k]) || data[k] < lo || data[k] > hi) fail(`${k} must be a whole number in [${lo}, ${hi}]`);
  };
  whole('hotbarSlots', 1, 10);
  whole('backpackSlots', 0, 90);
  whole('stackSize', 1, 999);
  whole('maxDrops', 1, 65535);
  const pos = (k, hi) => {
    if (!num(data[k]) || data[k] < 0 || data[k] > hi) fail(`${k} must be in [0, ${hi}]`);
  };
  pos('despawnSeconds', 86400);
  pos('pickupRadiusM', 8);
  pos('pickupDelaySeconds', 10);
  if (data.despawnSeconds <= 0 || data.pickupRadiusM <= 0) fail('despawnSeconds and pickupRadiusM must be above 0');

  // Blocks: every block is an item of its own name.
  const blocks = [];
  for (const ns of namespaces) {
    for (const def of ns.blocks) blocks.push({ id: `${ns.namespace}:${def.name}`, ns: ns.namespace, def });
  }
  const blockIds = new Set(blocks.map((b) => b.id));
  if (!Array.isArray(data.items)) fail('items must be a list');
  const items = data.items.map((it, i) => {
    const at = typeof it?.name === 'string' ? `items.${it.name}` : `items[${i}]`;
    if (typeof it !== 'object' || it === null) fail(`${at} must be an object`);
    for (const k of Object.keys(it)) {
      if (!ITEM_FIELDS.includes(k)) fail(`${at}: unknown field ${k} (${ITEM_FIELDS.join(', ')})`);
    }
    if (typeof it.name !== 'string' || !NAMESPACED.test(it.name) || it.name.length > MAX_NAME) {
      fail(`${at}: name must be namespace:name in lower case letters, digits and _`);
    }
    if (blockIds.has(it.name)) fail(`${at}: a block of that name is already an item (blocks need no entry)`);
    if (typeof it.label !== 'string' || it.label.trim() === '' || it.label.length > 40) fail(`${at}: label must be 1–40 characters`);
    if (typeof it.color !== 'string' || !COLOR.test(it.color)) fail(`${at}: color must be #rrggbb`);
    if (!num(it.size) || it.size <= 0 || it.size > 1) fail(`${at}: size must be in (0, 1] metres`);
    if (it.stack !== undefined && (!isInt(it.stack) || it.stack < 1 || it.stack > data.stackSize)) {
      fail(`${at}: stack must be a whole number in [1, stackSize ${data.stackSize}]`);
    }
    // `value`: currency. Picked up into the wallet (its value), never into a slot.
    if (it.value !== undefined && (!isInt(it.value) || it.value < 1 || it.value > 9999)) {
      fail(`${at}: value must be a whole number in [1, 9999] (a currency item's worth in the wallet)`);
    }
    return { name: it.name, label: it.label, color: it.color, size: it.size, stack: it.stack ?? data.stackSize, value: it.value ?? 0 };
  });
  // Wallets (currency's holder, separate from the slots): a capacity each; players start with one.
  if (!Array.isArray(data.wallets) || data.wallets.length === 0) fail('wallets: at least one wallet');
  const wallets = data.wallets.map((w, i) => {
    const at = typeof w?.name === 'string' ? `wallets.${w.name}` : `wallets[${i}]`;
    if (typeof w !== 'object' || w === null) fail(`${at} must be an object`);
    for (const k of Object.keys(w)) if (!WALLET_FIELDS.includes(k)) fail(`${at}: unknown field ${k} (${WALLET_FIELDS.join(', ')})`);
    if (typeof w.name !== 'string' || !NAMESPACED.test(w.name)) fail(`${at}: name must be namespace:name`);
    if (typeof w.label !== 'string' || w.label.trim() === '') fail(`${at}: label must be text`);
    if (!isInt(w.capacity) || w.capacity < 1 || w.capacity > 65535) fail(`${at}: capacity must be a whole number in [1, 65535]`);
    return { name: w.name, label: w.label, capacity: w.capacity };
  });
  if (new Set(wallets.map((w) => w.name)).size !== wallets.length) fail('wallets: a name is listed twice');
  if (!wallets.some((w) => w.name === data.startingWallet)) fail(`startingWallet must name one of the wallets, not ${data.startingWallet}`);
  const itemNames = new Set(items.map((i) => i.name));
  if (itemNames.size !== items.length) fail('items: a name is listed twice');
  const known = (n) => blockIds.has(n) || itemNames.has(n);

  const byId = new Map(blocks.map((b) => [b.id, b]));
  const explicit = (b) => {
    const list = b.def.drops;
    if (!Array.isArray(list)) fail(`${b.id}: drops must be a list (of { item, count, chance })`);
    return list.map((d, i) => {
      const at = `${b.id}: drops[${i}]`;
      if (typeof d !== 'object' || d === null) fail(`${at} must be an object`);
      for (const k of Object.keys(d)) if (!DROP_FIELDS.includes(k)) fail(`${at}: unknown field ${k} (${DROP_FIELDS.join(', ')})`);
      const chance = d.chance ?? 1;
      if (!num(chance) || chance <= 0 || chance > 1) fail(`${at}: chance must be in (0, 1]`);
      // One item (`item`, `count`), or a weighted pick of several (`pick`: [{ item, count, weight }]).
      const choice = (c, where, weighted) => {
        if (typeof c.item !== 'string' || !known(c.item)) fail(`${where}: item ${c.item} is neither a block nor an item of shared/inventory`);
        const [min, max] = Array.isArray(c.count) ? c.count : [c.count ?? 1, c.count ?? 1];
        if (!isInt(min) || !isInt(max) || min < 0 || max < min || max > data.stackSize) {
          fail(`${where}: count must be a whole number or [min, max] in [0, stackSize ${data.stackSize}]`);
        }
        const weight = weighted ? c.weight : 1;
        if (!num(weight) || weight <= 0) fail(`${where}: weight must be above 0`);
        return { item: c.item, min, max, weight };
      };
      if ((d.item === undefined) === (d.pick === undefined)) fail(`${at}: give item or pick (not both)`);
      if (d.pick === undefined) {
        return { chance, choices: [choice(d, at, false)] };
      }
      if (d.count !== undefined) fail(`${at}: count goes in each pick`);
      if (!Array.isArray(d.pick) || d.pick.length === 0) fail(`${at}: pick must be a non-empty list of { item, count, weight }`);
      const choices = d.pick.map((c, j) => {
        const where = `${at}.pick[${j}]`;
        if (typeof c !== 'object' || c === null) fail(`${where} must be an object`);
        for (const k of Object.keys(c)) if (!PICK_FIELDS.includes(k)) fail(`${where}: unknown field ${k} (${PICK_FIELDS.join(', ')})`);
        return choice(c, where, true);
      });
      return { chance, choices };
    });
  };
  const resolve = (b, depth = 0) => {
    if (b.def.drops !== undefined) return explicit(b);
    if (b.def.indestructible || b.def.liquid || b.def.partOf || b.id.endsWith(':air')) return [];
    // A stored ramp (a shape family's block) drops what its base drops.
    if (b.def.of !== undefined) {
      const base = byId.get(`${b.ns}:${b.def.of}`);
      if (!base || depth > 2) fail(`${b.id}: of names no block`);
      return resolve(base, depth + 1);
    }
    return [{ chance: 1, choices: [{ item: b.id, min: 1, max: 1, weight: 1 }] }];
  };
  // What placing a block uses up: a ramp its base's item, everything else itself.
  const cost = (b) => (b.def.of !== undefined ? `${b.ns}:${b.def.of}` : b.id);
  const drops = blocks.map((b) => ({ block: b.id, drops: resolve(b), cost: cost(b) }));
  // What a new player starts with (owner, 2026-11-08: "Adventure starts with an axe"): a list of
  // { item, count }, each a known item; optional, none by default.
  const startingItems = (data.startingItems ?? []).map((st, i) => {
    const at = `startingItems[${i}]`;
    if (typeof st !== 'object' || st === null) fail(`${at} must be an object`);
    for (const k of Object.keys(st)) if (!['item', 'count'].includes(k)) fail(`${at}: unknown field ${k} (item, count)`);
    if (typeof st.item !== 'string' || !known(st.item)) fail(`${at}: item must name a block or an item, not ${st.item}`);
    if (!isInt(st.count) || st.count < 1 || st.count > 65535) fail(`${at}: count must be a whole number in [1, 65535]`);
    return { item: st.item, count: st.count };
  });
  return { ...data, items, wallets, drops, startingItems };
}

/** The block files, as shared/blocks/gen.mjs reads them (and the fixtures with `fixture`). */
export function loadBlocks(fixture = false) {
  const dir = join(root, 'shared/blocks');
  const list = (d) =>
    readdirSync(d)
      .filter((f) => f.endsWith('.json') && f !== 'playground-export.json')
      .sort()
      .map((f) => JSON.parse(readFileSync(join(d, f), 'utf8')));
  return [...list(dir), ...(fixture ? list(join(dir, 'fixtures')) : [])];
}

export function loadInventory() {
  return JSON.parse(readFileSync(join(here, 'inventory.json'), 'utf8'));
}

const f64 = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

export function inventoryRust(d) {
  const rs = [`// ${header}`, '', 'use crate::inventory::{BlockDrops, DropChoice, DropRule, ItemDef, WalletDef};', ''];
  rs.push('/// Hotbar slots: the inventory\'s first slots.');
  rs.push(`pub const HOTBAR_SLOTS: usize = ${d.hotbarSlots};`);
  rs.push('/// Backpack slots, after the hotbar\'s.');
  rs.push(`pub const BACKPACK_SLOTS: usize = ${d.backpackSlots};`);
  rs.push('/// The most of one item a slot holds (an item may hold fewer, `ItemDef::stack`).');
  rs.push(`pub const STACK_SIZE: u16 = ${d.stackSize};`);
  rs.push('/// A loose item older than this is gone.');
  rs.push(`pub const DESPAWN_SECONDS: f64 = ${f64(d.despawnSeconds)};`);
  rs.push('/// How near a player a loose item is picked up (metres from the body\'s centre line).');
  rs.push(`pub const PICKUP_RADIUS_M: f64 = ${f64(d.pickupRadiusM)};`);
  rs.push('/// A loose item younger than this is not picked up.');
  rs.push(`pub const PICKUP_DELAY_SECONDS: f64 = ${f64(d.pickupDelaySeconds)};`);
  rs.push('/// The most loose items a world holds (the oldest go first).');
  rs.push(`pub const MAX_DROPS: usize = ${d.maxDrops};`);
  rs.push('');
  rs.push('/// The wallets (currency\'s holder, apart from the slots), and the one players start with.');
  rs.push('pub static WALLETS: &[WalletDef] = &[');
  for (const w of d.wallets) rs.push(`    WalletDef { name: "${w.name}", label: ${JSON.stringify(w.label)}, capacity: ${w.capacity} },`);
  rs.push('];');
  rs.push(`pub const STARTING_WALLET: &str = "${d.startingWallet}";`);
  rs.push('/// What a new player starts with: (item, count).');
  rs.push(`pub static STARTING_ITEMS: &[(&str, u16)] = &[${d.startingItems.map((s) => `("${s.item}", ${s.count})`).join(', ')}];`);
  rs.push('');
  rs.push('/// The items that are not blocks.');
  rs.push('pub static ITEMS: &[ItemDef] = &[');
  for (const it of d.items) {
    const c = [1, 3, 5].map((i) => parseInt(it.color.slice(i, i + 2), 16));
    rs.push(
      `    ItemDef { name: "${it.name}", label: ${JSON.stringify(it.label)}, color: [${c.join(', ')}], size: ${f64(it.size)}, stack: ${it.stack}, value: ${it.value} },`,
    );
  }
  rs.push('];');
  rs.push('');
  rs.push('/// What every block drops when broken without unlimited blocks, and what placing it uses up.');
  rs.push('pub static DROPS: &[BlockDrops] = &[');
  for (const b of d.drops) {
    const rules = b.drops.map((r) => {
      const cs = r.choices.map((c) => `DropChoice { item: "${c.item}", min: ${c.min}, max: ${c.max}, weight: ${f64(c.weight)} }`);
      return `DropRule { chance: ${f64(r.chance)}, choices: &[${cs.join(', ')}] }`;
    });
    rs.push(`    BlockDrops { block: "${b.block}", cost: "${b.cost}", drops: &[${rules.join(', ')}] },`);
  }
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

export function inventoryTs(d) {
  const ts = [`// ${header}`, ''];
  ts.push(`export const HOTBAR_SLOTS = ${d.hotbarSlots};`);
  ts.push(`export const BACKPACK_SLOTS = ${d.backpackSlots};`);
  ts.push(`export const STACK_SIZE = ${d.stackSize};`);
  ts.push('');
  ts.push('/** An item that is not a block: its label and simple look. */');
  ts.push('export interface ItemDef {');
  ts.push('  name: string;');
  ts.push('  label: string;');
  ts.push('  color: string;');
  ts.push('  size: number;');
  ts.push('  stack: number;');
  ts.push('  /** A currency item\'s worth in the wallet (0: an ordinary item). */');
  ts.push('  value: number;');
  ts.push('}');
  ts.push('');
  ts.push('export const ITEMS: readonly ItemDef[] = [');
  for (const it of d.items) {
    ts.push(
      `  { name: ${JSON.stringify(it.name)}, label: ${JSON.stringify(it.label)}, color: ${JSON.stringify(it.color)}, size: ${it.size}, stack: ${it.stack}, value: ${it.value} },`,
    );
  }
  ts.push('];');
  ts.push('');
  ts.push('export const WALLETS: readonly { name: string; label: string; capacity: number }[] = [');
  for (const w of d.wallets) ts.push(`  { name: ${JSON.stringify(w.name)}, label: ${JSON.stringify(w.label)}, capacity: ${w.capacity} },`);
  ts.push('];');
  ts.push(`export const STARTING_WALLET = ${JSON.stringify(d.startingWallet)};`);
  ts.push('');
  return ts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const d = validateInventory(loadInventory(), loadBlocks());
  writeFileSync(join(root, 'crates/dwell-protocol/src/inventory.gen.rs'), inventoryRust(d));
  writeFileSync(join(root, 'client/src/ui/inventory.gen.ts'), inventoryTs(d));
}
