#!/usr/bin/env node
// Generates the sound data for the client (TypeScript) and the sound event kinds and gaits for the
// Rust game from shared/sounds/*.json (docs/AUDIO.md). Outputs are checked in; CI regenerates and
// fails on any diff. Validation lives in validate.mjs (shared with shared/blocks/gen.mjs).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadSounds, SOUNDS_DIR } from './load.mjs';
import { GAITS } from './validate.mjs';

const root = join(SOUNDS_DIR, '..', '..');
const header = 'Generated by shared/sounds/gen.mjs from shared/sounds/*.json. Do not edit.';
const data = loadSounds();

// ---- TypeScript: the whole resolved data, for the synth and the event mapping --------------------
const ts = [
  `// ${header}`,
  "import type { SoundData } from './types';",
  '',
  `export const SOUND_DATA: SoundData = ${JSON.stringify({ ...data, gaitOrder: GAITS }, null, 2)};`,
  '',
];
writeFileSync(join(root, 'client/src/audio/sounds.gen.ts'), ts.join('\n'));

// ---- Rust: event kinds (ids in order), their speed ranges, gaits and strides ---------------------
const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rs = [`// ${header}`, ''];
rs.push('/// A sound event the game emits (shared/sounds `events`), numbered in declaration order.');
rs.push('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]');
rs.push('#[repr(u8)]');
rs.push('pub enum SoundKind {');
data.events.forEach((e, i) => rs.push(`    ${pascal(e.name)} = ${i},`));
rs.push('}');
rs.push('');
rs.push('impl SoundKind {');
rs.push(`    pub const ALL: [SoundKind; ${data.events.length}] = [`);
for (const e of data.events) rs.push(`        SoundKind::${pascal(e.name)},`);
rs.push('    ];');
rs.push('');
rs.push("    /// The event's name in the data.");
rs.push("    pub const fn name(self) -> &'static str {");
rs.push('        match self {');
for (const e of data.events) rs.push(`            SoundKind::${pascal(e.name)} => ${JSON.stringify(e.name)},`);
rs.push('        }');
rs.push('    }');
rs.push('');
rs.push('    /// The speed (m/s) at which the event starts and at which its intensity reaches 1, if any.');
rs.push('    pub const fn speed(self) -> Option<(f64, f64)> {');
rs.push('        match self {');
for (const e of data.events) {
  rs.push(
    `            SoundKind::${pascal(e.name)} => ${e.speed ? `Some((${rf(e.speed[0])}, ${rf(e.speed[1])}))` : 'None'},`,
  );
}
rs.push('        }');
rs.push('    }');
rs.push('}');
rs.push('');
rs.push('/// A footstep gait (shared/sounds `gaits`).');
rs.push('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]');
rs.push('#[repr(u8)]');
rs.push('pub enum Gait {');
GAITS.forEach((g, i) => rs.push(`    ${pascal(g)} = ${i},`));
rs.push('}');
rs.push('');
rs.push('impl Gait {');
rs.push('    /// Metres travelled between footsteps.');
rs.push('    pub const fn stride(self) -> f64 {');
rs.push('        match self {');
for (const g of GAITS) rs.push(`            Gait::${pascal(g)} => ${rf(data.gaits[g].stride)},`);
rs.push('        }');
rs.push('    }');
rs.push('}');
rs.push('');
writeFileSync(join(root, 'crates/dwell-game/src/sound.gen.rs'), rs.join('\n'));
console.log(
  `sounds: ${Object.keys(data.sounds).length} sounds, ${Object.keys(data.sets).length} sets, ${data.events.length} events`,
);
