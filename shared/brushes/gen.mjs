#!/usr/bin/env node
// Generates the brush presets and the per-world-type brush policy for Rust and TypeScript from
// shared/brushes/brushes.json (docs/BRUSHES.md). Outputs are checked in; CI regenerates and fails on
// any diff. A bad entry fails with a message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/brushes/gen.mjs from shared/brushes/brushes.json. Do not edit.';
const data = JSON.parse(readFileSync(join(here, 'brushes.json'), 'utf8'));

const fail = (m) => {
  throw new Error(`shared/brushes: ${m}`);
};

// ---- The engine's vocabulary (dwell-world brush.rs): fixed in code ---------------------------------
const BRUSHES = ['ball', 'disc', 'cylinder', 'cube', 'ellipsoid', 'splatter', 'line'];
const PERFORMERS = ['set', 'replace', 'overlay', 'erase', 'smooth', 'erode', 'flatten', 'raise', 'lower'];
const MASKS = ['none', 'air', 'solid', 'target'];
/** World types a policy may name (client/src/local/worldIndex.ts WORLD_TYPES; dwell-world `world_type`). */
const WORLD_TYPES = ['terrain', 'flat', 'sandbox'];
/** Keys a preset may take while the brush tool is on: none of the game's other bindings
 * (client/src/ui/controls.ts) nor the brush tool's own (V, Q, E, P, Z, [, ]). */
const PRESET_KEYS = ['KeyU', 'KeyI', 'KeyO', 'KeyJ', 'KeyK', 'KeyL', 'KeyY', 'Semicolon', 'Quote', 'Comma', 'Period', 'Slash'];
const MAX_REACH = 256;
/** A brush's radius is at most this: 2 · 16 + 1 = 33 cells a side, split into ≤ 32³ region edits. */
const SIZE_CAP = 16;

const int = (lo, hi) => (v) => Number.isInteger(v) && v >= lo && v <= hi;
const num = (lo, hi) => (v) => typeof v === 'number' && Number.isFinite(v) && v >= lo && v <= hi;
/** Each parameter: its check, a description for messages, its default, and who takes it. */
const PARAMS = {
  height: { ok: int(1, 32), want: 'an integer 1–32', def: 1, for: ['cylinder', 'flatten', 'raise', 'lower'] },
  stretch: {
    ok: (v) => Array.isArray(v) && v.length === 3 && v.every(num(0.1, 4)),
    want: 'three numbers 0.1–4 (x, y, z)',
    def: [1, 1, 1],
    for: ['ellipsoid'],
  },
  density: { ok: num(0.01, 1), want: 'a number 0.01–1', def: 0.5, for: ['splatter'] },
  seed: { ok: int(0, 0xffffffff), want: 'an integer 0–4294967295', def: 0, for: ['splatter'] },
  depth: { ok: int(1, 8), want: 'an integer 1–8', def: 1, for: ['overlay'] },
  mask: { ok: (v) => MASKS.includes(v), want: MASKS.join(', '), def: 'none', for: ['set', 'erase', 'overlay'] },
  iterations: { ok: int(1, 8), want: 'an integer 1–8', def: 1, for: ['smooth'] },
  erodeFaces: { ok: int(1, 6), want: 'an integer 1–6', def: 2, for: ['erode'] },
  erodeIterations: { ok: int(0, 8), want: 'an integer 0–8', def: 1, for: ['erode'] },
  fillFaces: { ok: int(1, 6), want: 'an integer 1–6', def: 5, for: ['erode'] },
  fillIterations: { ok: int(0, 8), want: 'an integer 0–8', def: 1, for: ['erode'] },
  falloff: { ok: (v) => typeof v === 'boolean', want: 'true or false', def: false, for: ['raise', 'lower'] },
};

// ---- Validate ------------------------------------------------------------------------------------
if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
const sizes = data.sizes ?? {};
if (!int(1, SIZE_CAP)(sizes.min) || !int(1, SIZE_CAP)(sizes.max) || sizes.min > sizes.max) {
  fail(`sizes: min and max must be integers 1–${SIZE_CAP}, min ≤ max`);
}
const policies = Object.entries(data.worldTypes ?? {}).map(([type, p]) => {
  if (!WORLD_TYPES.includes(type)) fail(`worldTypes.${type}: not a world type (${WORLD_TYPES.join(', ')})`);
  if (typeof p.brushes !== 'boolean') fail(`worldTypes.${type}.brushes must be true or false`);
  if (!num(1, MAX_REACH)(p.reach)) fail(`worldTypes.${type}.reach must be a number 1–${MAX_REACH} (m)`);
  return { type, brushes: p.brushes, reach: p.reach };
});
if (!Array.isArray(data.presets) || data.presets.length === 0) fail('presets: at least one');
const names = new Set();
const keys = new Set();
const presets = data.presets.map((p, i) => {
  const at = `presets[${i}]${p?.name ? ` (${p.name})` : ''}`;
  for (const k of Object.keys(p)) {
    if (!['name', 'label', 'brush', 'performer', 'size', 'key', 'params'].includes(k)) fail(`${at}: unknown field ${k}`);
  }
  if (typeof p.name !== 'string' || !/^[a-z][a-z0-9_]*$/.test(p.name)) fail(`${at}: name must be snake_case`);
  if (names.has(p.name)) fail(`${at}: duplicate name`);
  names.add(p.name);
  if (typeof p.label !== 'string' || p.label.trim() === '' || p.label.length > 24 || /['"\\]/.test(p.label)) {
    fail(`${at}: label must be 1–24 characters without quotes or backslashes`);
  }
  if (!BRUSHES.includes(p.brush)) fail(`${at}: brush ${p.brush} is not one of ${BRUSHES.join(', ')}`);
  if (!PERFORMERS.includes(p.performer)) fail(`${at}: performer ${p.performer} is not one of ${PERFORMERS.join(', ')}`);
  if (!int(sizes.min, sizes.max)(p.size)) fail(`${at}: size must be an integer ${sizes.min}–${sizes.max}`);
  if (p.key !== undefined) {
    if (!PRESET_KEYS.includes(p.key)) fail(`${at}: key ${p.key} is not a free key (${PRESET_KEYS.join(', ')})`);
    if (keys.has(p.key)) fail(`${at}: key ${p.key} is taken by another preset`);
    keys.add(p.key);
  }
  const params = {};
  for (const [k, def] of Object.entries(PARAMS)) params[k] = def.def;
  for (const [k, v] of Object.entries(p.params ?? {})) {
    const def = PARAMS[k];
    if (!def) fail(`${at}: unknown parameter ${k}`);
    if (!def.for.includes(p.brush) && !def.for.includes(p.performer)) {
      fail(`${at}: ${k} is for ${def.for.join(', ')}, not ${p.brush} ${p.performer}`);
    }
    if (!def.ok(v)) fail(`${at}: ${k} must be ${def.want}`);
    params[k] = v;
  }
  return { ...p, params };
});

// ---- Rust ----------------------------------------------------------------------------------------
const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const f32 = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const rs = [];
rs.push(`// ${header}`);
rs.push('');
rs.push('use crate::brush::{BrushKind, Mask, Params, PerformerKind, Preset, WorldPolicy};');
rs.push('');
rs.push(`pub const FORMAT_VERSION: u32 = ${data.formatVersion};`);
rs.push(`pub const MIN_SIZE: u8 = ${sizes.min};`);
rs.push(`pub const MAX_SIZE: u8 = ${sizes.max};`);
rs.push('');
rs.push('pub static WORLD_POLICIES: &[WorldPolicy] = &[');
for (const w of policies) {
  rs.push('    WorldPolicy {');
  rs.push(`        world_type: "${w.type}",`);
  rs.push(`        brushes: ${w.brushes},`);
  rs.push(`        reach: ${f32(w.reach)},`);
  rs.push('    },');
}
rs.push('];');
rs.push('');
rs.push('pub static PRESETS: &[Preset] = &[');
for (const p of presets) {
  const q = p.params;
  rs.push('    Preset {');
  rs.push(`        name: "${p.name}",`);
  rs.push(`        label: ${JSON.stringify(p.label)},`);
  rs.push(`        brush: BrushKind::${pascal(p.brush)},`);
  rs.push(`        performer: PerformerKind::${pascal(p.performer)},`);
  rs.push(`        size: ${p.size},`);
  rs.push(`        key: ${p.key ? `Some("${p.key}")` : 'None'},`);
  rs.push('        params: Params {');
  rs.push(`            height: ${q.height},`);
  rs.push(`            stretch: [${q.stretch.map(f32).join(', ')}],`);
  rs.push(`            density: ${f32(q.density)},`);
  rs.push(`            seed: ${q.seed},`);
  rs.push(`            depth: ${q.depth},`);
  rs.push(`            mask: Mask::${pascal(q.mask)},`);
  rs.push(`            iterations: ${q.iterations},`);
  rs.push(`            erode_faces: ${q.erodeFaces},`);
  rs.push(`            erode_iterations: ${q.erodeIterations},`);
  rs.push(`            fill_faces: ${q.fillFaces},`);
  rs.push(`            fill_iterations: ${q.fillIterations},`);
  rs.push(`            falloff: ${q.falloff},`);
  rs.push('        },');
  rs.push('    },');
}
rs.push('];');
rs.push('');
writeFileSync(join(root, 'crates/dwell-world/src/brushes.gen.rs'), rs.join('\n'));

// ---- TypeScript (the controls table and the HUD) ---------------------------------------------------
const ts = [];
ts.push(`// ${header}`);
ts.push('');
ts.push('export interface BrushPreset {');
ts.push('  name: string;');
ts.push('  label: string;');
ts.push('  brush: string;');
ts.push('  performer: string;');
ts.push('  size: number;');
ts.push('  /** `KeyboardEvent.code` that picks it while the brush tool is on. */');
ts.push('  key?: string;');
ts.push('}');
ts.push('');
ts.push(`export const BRUSH_SIZES = { min: ${sizes.min}, max: ${sizes.max} } as const;`);
ts.push('');
ts.push('export const BRUSH_PRESETS: readonly BrushPreset[] = [');
for (const p of presets) {
  const parts = [
    `name: '${p.name}'`,
    `label: '${p.label}'`,
    `brush: '${p.brush}'`,
    `performer: '${p.performer}'`,
    `size: ${p.size}`,
  ];
  if (p.key) parts.push(`key: '${p.key}'`);
  ts.push('  {');
  for (const part of parts) ts.push(`    ${part},`);
  ts.push('  },');
}
ts.push('];');
ts.push('');
writeFileSync(join(root, 'client/src/ui/brushes.gen.ts'), ts.join('\n'));
