// ---- Between the faces: the bedrock and the portals (midplane.json) ------------------------------

const midplaneHeader = 'Generated by shared/worldgen/gen.mjs from shared/worldgen/midplane.json. Do not edit.';
/** The walls a portal's ladder may be fixed to, and the ladder's facing on each (away from it). */
export const LADDER_WALLS = { north: 'south', east: 'west', south: 'north', west: 'east' };
const MIDPLANE = {
  bedrock: { thickness: [0, 10] },
  portals: {
    spacing: [0, 100_000],
    within: [{ above: 0 }, 100_000],
    attempts: [1, 100_000, true],
    inland: [0, 10_000],
    maxHeight: [0, 10_000],
    radius: [1, 16],
    clear: [0, 64],
  },
  rim: { width: [0, 8], height: [0, 8] },
};

/** Checks the bedrock and portals against `blocks` (id → block data); throws naming the key. */
export function validateMidplane(data, blocks, structures = registryStructures()) {
  const fail = (m) => {
    throw new Error(`midplane.json: ${m}`);
  };
  const constants = JSON.parse(readFileSync(join(here, '../protocol/constants.json'), 'utf8'));
  const cell = constants.cellHeight;
  const checkGroup = (at, g, keys, extraKeys) => {
    if (typeof g !== 'object' || g === null || Array.isArray(g)) fail(`${at} must be an object`);
    const ge = Object.keys(g).filter((k) => k !== '$comment' && !(k in keys) && !extraKeys.includes(k));
    if (ge.length) fail(`${at}: unknown ${ge.join(', ')}`);
    for (const [key, [min, max, whole]] of Object.entries(keys)) {
      const v = g[key];
      const low = typeof min === 'object' ? v > min.above : v >= min;
      const lo = typeof min === 'object' ? `(${min.above}` : `[${min}`;
      if (!(isNum(v) && low && v <= max && (!whole || Number.isInteger(v)))) {
        fail(`${at}.${key} must be ${whole ? 'a whole number ' : ''}in ${lo}, ${max}]`);
      }
    }
  };
  const block = (at, id) => {
    const b = blocks.get(id);
    if (!b) fail(`${at} ${id} is not in the registry`);
    return b;
  };
  if (typeof data !== 'object' || data === null) fail('must be an object');
  const top = Object.keys(data).filter((k) => !['$comment', 'bedrock', 'portals'].includes(k));
  if (top.length) fail(`unknown ${top.join(', ')}`);
  checkGroup('bedrock', data.bedrock, MIDPLANE.bedrock, ['block']);
  const bedrock = block('bedrock.block', data.bedrock.block);
  if (bedrock.shape !== 'full') fail(`bedrock.block ${data.bedrock.block} must be a full block`);
  if (bedrock.indestructible !== true) fail(`bedrock.block ${data.bedrock.block} must be indestructible`);
  if (!Number.isInteger(data.bedrock.thickness / cell)) fail(`bedrock.thickness must be a whole number of cells (${cell} m)`);
  if (data.bedrock.thickness / cell > constants.world.coreLayers) {
    fail(`bedrock.thickness must lie inside the core (${constants.world.coreLayers * cell} m)`);
  }
  const p = data.portals;
  checkGroup('portals', p, MIDPLANE.portals, ['count', 'rim', 'ladder', 'motes', 'monument']);
  if (!moteNames(loadMotes()).includes(p.motes)) fail(`portals.motes ${JSON.stringify(p.motes)} is not a look in shared/look/motes.json`);
  const c = p.count;
  if (!(Array.isArray(c) && c.length === 2 && c.every((n) => Number.isInteger(n) && n >= 0 && n <= 64) && c[0] <= c[1])) {
    fail('portals.count must be [min, max], whole numbers 0–64 with min ≤ max');
  }
  checkGroup('portals.rim', p.rim, MIDPLANE.rim, ['block']);
  if (block('portals.rim.block', p.rim.block).shape !== 'full') fail(`portals.rim.block ${p.rim.block} must be a full block`);
  if (!Number.isInteger(p.rim.height / cell)) fail(`portals.rim.height must be a whole number of cells (${cell} m)`);
  if (typeof p.ladder !== 'object' || p.ladder === null) fail('portals.ladder must be an object');
  const le = Object.keys(p.ladder).filter((k) => !['$comment', 'block', 'wall'].includes(k));
  if (le.length) fail(`portals.ladder: unknown ${le.join(', ')}`);
  const ladder = block('portals.ladder.block', p.ladder.block);
  if (ladder.climbable !== true) fail(`portals.ladder.block ${p.ladder.block} must be climbable`);
  if (!(p.ladder.wall in LADDER_WALLS)) fail(`portals.ladder.wall must be one of ${Object.keys(LADDER_WALLS).join(', ')}`);
  const facing = ladder.facingProperty;
  if (!(facing && ladder.properties?.[facing]?.includes(LADDER_WALLS[p.ladder.wall]))) {
    fail(`portals.ladder.block ${p.ladder.block} has no ${facing ?? 'facing'}=${LADDER_WALLS[p.ladder.wall]} state`);
  }
  const mo = p.monument;
  if (typeof mo !== 'object' || mo === null || Array.isArray(mo)) fail('portals.monument must be an object');
  const me = Object.keys(mo).filter((k) => !['$comment', 'structure', 'lodCellM'].includes(k));
  if (me.length) fail(`portals.monument: unknown ${me.join(', ')}`);
  const cellOk = Number.isInteger(mo.lodCellM) && mo.lodCellM >= 1 && mo.lodCellM <= 64 && (mo.lodCellM & (mo.lodCellM - 1)) === 0;
  if (!cellOk) fail('portals.monument.lodCellM must be a power of two in [1, 64]');
  if (mo.structure !== null) {
    const s = structures.get(mo.structure);
    if (!s) fail(`portals.monument.structure ${JSON.stringify(mo.structure)} is not in shared/structures`);
    // It stands on the clear ground: every cell it fills within the clear radius of the axis
    // (cells x fastest, then z, then y; a palette character mapped to null keeps what is there).
    const reach = p.radius + p.rim.width + p.clear;
    const [sx, , sz] = s.size;
    const [ax, , az] = s.anchor;
    let far = 0;
    for (let i = 0; i < s.cells.length; i++) {
      if (s.palette.get(s.cells[i]) == null) continue;
      const x = (i % sx) - ax;
      const z = (Math.floor(i / sx) % sz) - az;
      far = Math.max(far, Math.hypot(x, z));
    }
    if (far > reach) {
      fail(`portals.monument.structure ${mo.structure} reaches ${far.toFixed(1)} m from the axis, past the clear ground (${reach} m)`);
    }
  }
  return data;
}

