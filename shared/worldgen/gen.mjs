#!/usr/bin/env node
// Generates the terrain's data for Rust from shared/worldgen/: the decorations
// (decorations.json → crates/dwell-worldgen/src/decorations.gen.rs), validated against the block
// registry's data, the height field (terrain.json → crates/dwell-worldgen/src/terrain.gen.rs) and the
// hydrology prototype's profiles (hydrology.json → crates/dwell-worldgen/src/hydrology/profiles.gen.rs) and
// the bedrock and portals between the faces (midplane.json → crates/dwell-worldgen/src/midplane.gen.rs).
// An unknown block, a bad range or an unknown key fails with the entry named. The output is checked
// in; CI regenerates it and fails on any diff (docs/TRANSPARENT_BLOCKS.md §10, ARCHITECTURE.md §6.3).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadDir, registryFromVector } from '../structures/gen.mjs';
import { loadMotes, moteNames } from '../look/motes.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/worldgen/gen.mjs from shared/worldgen/decorations.json. Do not edit.';
const terrainHeader = 'Generated by shared/worldgen/gen.mjs from shared/worldgen/terrain.json. Do not edit.';
const placementsHeader = 'Generated by shared/worldgen/gen.mjs from shared/worldgen/placements.json. Do not edit.';

const NAME = /^[a-z0-9_]+$/;
const KEYS = ['name', 'block', 'on', 'density', 'patches', 'maxSlope', 'height', '$comment'];
const isNum = (v) => typeof v === 'number' && Number.isFinite(v);

/** The build's blocks by id (`ns:name`), from shared/blocks/*.json. */
export function registryBlocks() {
  const dir = join(root, 'shared/blocks');
  const out = new Map();
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const ns = JSON.parse(readFileSync(join(dir, f), 'utf8'));
    for (const b of ns.blocks ?? []) out.set(`${ns.namespace}:${b.name}`, b);
  }
  return out;
}

/** Checks the decorations against `blocks` (id → block data); throws naming the entry. */
export function validateDecorations(data, blocks) {
  const fail = (m) => {
    throw new Error(`decorations.json: ${m}`);
  };
  if (!Array.isArray(data?.decorations)) fail('decorations must be a list');
  const names = new Set();
  for (const d of data.decorations) {
    const at = d?.name ?? '(unnamed)';
    if (typeof d !== 'object' || d === null) fail('an entry must be an object');
    const extra = Object.keys(d).filter((k) => !KEYS.includes(k));
    if (extra.length) fail(`${at}: unknown ${extra.join(', ')}`);
    if (!(typeof d.name === 'string' && NAME.test(d.name))) fail(`${at}: name must be [a-z0-9_]+`);
    if (names.has(d.name)) fail(`${at}: duplicate name`);
    names.add(d.name);
    const block = blocks.get(d.block);
    if (!block) fail(`${at}: block ${d.block} is not in the registry`);
    if (!(Array.isArray(d.on) && d.on.length)) fail(`${at}: on must be a non-empty list of block ids`);
    for (const o of d.on) {
      const ground = blocks.get(o);
      if (!ground) fail(`${at}: on names unknown block ${o}`);
      if (ground.shape !== 'full') fail(`${at}: on block ${o} is not a full block`);
      if (block.placeOn && !block.placeOn.includes(o)) {
        fail(`${at}: ${d.block} may not stand on ${o} (its placeOn)`);
      }
    }
    if (block.shape !== 'empty') fail(`${at}: block ${d.block} must have shape empty (a decoration has no collision)`);
    if ((block.medium ?? 'air') !== 'air') fail(`${at}: block ${d.block} grows in ${block.medium}; decorations are put in air`);
    if (!(isNum(d.density) && d.density > 0 && d.density <= 1)) fail(`${at}: density must be in (0, 1]`);
    if (d.patches !== undefined) {
      const p = d.patches;
      const pk = Object.keys(p ?? {}).filter((k) => !['wavelength', 'coverage'].includes(k));
      if (pk.length) fail(`${at}: patches: unknown ${pk.join(', ')}`);
      if (!(Number.isInteger(p.wavelength) && p.wavelength >= 4 && p.wavelength <= 4096)) {
        fail(`${at}: patches.wavelength must be a whole number of metres in [4, 4096]`);
      }
      if (!(isNum(p.coverage) && p.coverage > 0 && p.coverage <= 1)) fail(`${at}: patches.coverage must be in (0, 1]`);
    }
    if (!(Number.isInteger(d.maxSlope) && d.maxSlope >= 0 && d.maxSlope <= 16)) {
      fail(`${at}: maxSlope must be a whole number of metres in [0, 16]`);
    }
    const h = d.height;
    if (!(Array.isArray(h) && h.length === 2 && h.every(Number.isInteger) && h[0] <= h[1])) {
      fail(`${at}: height must be [min, max] whole metres above sea level`);
    }
  }
  return data;
}

const rf = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);

/** The Rust table for validated decorations. */
export function decorationsRust(data) {
  const rs = [`// ${header}`, '', 'use crate::decorations::Decoration;', ''];
  rs.push('/// The terrain decorations (shared/worldgen/decorations.json), in their file order.');
  rs.push(`pub static DECORATIONS: [Decoration; ${data.decorations.length}] = [`);
  for (const d of data.decorations) {
    const p = d.patches ?? { wavelength: 0, coverage: 1 };
    rs.push(
      `    Decoration { name: ${JSON.stringify(d.name)}, block: ${JSON.stringify(d.block)}, on: &[${d.on.map((o) => JSON.stringify(o)).join(', ')}], density: ${rf(d.density)}, patch_wavelength: ${p.wavelength}, patch_coverage: ${rf(p.coverage)}, max_slope: ${d.maxSlope}, min_height: ${d.height[0]}, max_height: ${d.height[1]} },`,
    );
  }
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

// ---- Structure placements (placements.json) -----------------------------------------------------

const PLACEMENT_KEYS = [
  '$comment', 'name', 'structures', 'on', 'footprint', 'grid', 'density', 'groves', 'height', 'rise',
  'maxSlopeDeg', 'spacing', 'rotate', 'variants',
];
/** What `footprint` may say: "on" (every column under the structure is one of `on`) or "anchor". */
export const FOOTPRINTS = ['on', 'anchor'];
/** The widest reach of a placed structure from its anchor, in blocks (bounds a chunk's search). */
export const MAX_REACH = 16;

/** The build's structures by name (shared/structures/*.json, checked by its own validator). */
export function registryStructures() {
  const registry = registryFromVector(readFileSync(join(root, 'shared/blocks/vectors.txt'), 'utf8'));
  return new Map(loadDir(join(root, 'shared/structures'), registry, { test: false }).map((s) => [s.name, s]));
}

/** A structure's horizontal reach from its anchor in any quarter turn, in blocks. */
export function reach(s) {
  return Math.max(s.anchor[0], s.size[0] - 1 - s.anchor[0], s.anchor[2], s.size[2] - 1 - s.anchor[2]);
}

/** Checks the placements against `blocks` and `structures` (name → structure); throws naming the entry. */
export function validatePlacements(data, blocks, structures) {
  const fail = (m) => {
    throw new Error(`placements.json: ${m}`);
  };
  if (!Array.isArray(data?.placements)) fail('placements must be a list');
  const names = new Set();
  for (const p of data.placements) {
    if (typeof p !== 'object' || p === null) fail('an entry must be an object');
    const at = p.name ?? '(unnamed)';
    const extra = Object.keys(p).filter((k) => !PLACEMENT_KEYS.includes(k));
    if (extra.length) fail(`${at}: unknown ${extra.join(', ')}`);
    if (!(typeof p.name === 'string' && NAME.test(p.name))) fail(`${at}: name must be [a-z0-9_]+`);
    if (names.has(p.name)) fail(`${at}: duplicate name`);
    names.add(p.name);
    const ss = Object.entries(p.structures ?? {});
    if (typeof p.structures !== 'object' || Array.isArray(p.structures) || !ss.length) {
      fail(`${at}: structures must map structure names to weights`);
    }
    for (const [n, w] of ss) {
      const s = structures.get(n);
      if (!s) fail(`${at}: structure ${n} is not in shared/structures`);
      if (s.kind !== 'voxels') fail(`${at}: structure ${n} is not of kind voxels`);
      if (reach(s) > MAX_REACH) fail(`${at}: structure ${n} reaches more than ${MAX_REACH} blocks from its anchor`);
      if (!(Number.isInteger(w) && w >= 1 && w <= 1_000_000)) {
        fail(`${at}: structures.${n} weight must be a whole number in [1, 1000000]`);
      }
    }
    if (!(Array.isArray(p.on) && p.on.length)) fail(`${at}: on must be a non-empty list of block ids`);
    for (const o of p.on) {
      const ground = blocks.get(o);
      if (!ground) fail(`${at}: on names unknown block ${o}`);
      if (ground.shape !== 'full') fail(`${at}: on block ${o} is not a full block`);
    }
    if (!FOOTPRINTS.includes(p.footprint)) fail(`${at}: footprint must be one of ${FOOTPRINTS.join(', ')}`);
    if (!(Number.isInteger(p.grid) && p.grid >= 2 && p.grid <= 256)) fail(`${at}: grid must be a whole number of metres in [2, 256]`);
    if (!(isNum(p.density) && p.density > 0 && p.density <= 1)) fail(`${at}: density must be in (0, 1]`);
    if (p.groves !== undefined) {
      const g = p.groves;
      const gk = Object.keys(g ?? {}).filter((k) => !['wavelength', 'coverage', 'outside'].includes(k));
      if (gk.length) fail(`${at}: groves: unknown ${gk.join(', ')}`);
      if (!(Number.isInteger(g.wavelength) && g.wavelength >= 8 && g.wavelength <= 4096)) {
        fail(`${at}: groves.wavelength must be a whole number of metres in [8, 4096]`);
      }
      if (!(isNum(g.coverage) && g.coverage > 0 && g.coverage <= 1)) fail(`${at}: groves.coverage must be in (0, 1]`);
      if (!(isNum(g.outside) && g.outside >= 0 && g.outside <= 1)) fail(`${at}: groves.outside must be in [0, 1]`);
    }
    const h = p.height;
    if (!(Array.isArray(h) && h.length === 2 && h.every(Number.isInteger) && h[0] <= h[1])) {
      fail(`${at}: height must be [min, max] whole metres above sea level`);
    }
    if (p.rise !== undefined) {
      const r = p.rise;
      const rk = Object.keys(r ?? {}).filter((k) => !['full', 'low'].includes(k));
      if (rk.length) fail(`${at}: rise: unknown ${rk.join(', ')}`);
      if (!(Number.isInteger(r.full) && r.full > h[0] && r.full <= h[1])) {
        fail(`${at}: rise.full must be a whole number of metres in (height[0], height[1]]`);
      }
      if (!(isNum(r.low) && r.low >= 0 && r.low <= 1)) fail(`${at}: rise.low must be in [0, 1]`);
    }
    if (!(isNum(p.maxSlopeDeg) && p.maxSlopeDeg > 0 && p.maxSlopeDeg < 90)) fail(`${at}: maxSlopeDeg must be in (0, 90) degrees`);
    if (!(Number.isInteger(p.spacing) && p.spacing >= 0 && p.spacing <= 16)) {
      fail(`${at}: spacing must be a whole number of blocks in [0, 16]`);
    }
    const r = p.rotate;
    if (!(Array.isArray(r) && r.length && r.every((d) => [0, 90, 180, 270].includes(d)) && new Set(r).size === r.length)) {
      fail(`${at}: rotate must be distinct angles from 0, 90, 180, 270`);
    }
    for (const v of p.variants ?? []) {
      const vat = `${at}: variant ${v?.name ?? '(unnamed)'}`;
      const vk = Object.keys(v ?? {}).filter((k) => !['name', 'replace', 'height', '$comment'].includes(k));
      if (vk.length) fail(`${vat}: unknown ${vk.join(', ')}`);
      if (!(typeof v.name === 'string' && NAME.test(v.name))) fail(`${vat}: name must be [a-z0-9_]+`);
      const pairs = Object.entries(v.replace ?? {});
      if (!pairs.length) fail(`${vat}: replace must map blocks to blocks`);
      for (const [from, to] of pairs) {
        if (!blocks.get(from)) fail(`${vat}: replace names unknown block ${from}`);
        if (!blocks.get(to)) fail(`${vat}: replace names unknown block ${to}`);
      }
      const vh = v.height;
      if (!(Array.isArray(vh) && vh.length === 2 && vh.every(Number.isInteger) && vh[0] <= vh[1])) {
        fail(`${vat}: height must be [from, full] whole metres above sea level`);
      }
    }
  }
  return data;
}

/** The Rust table for validated placements. The slope limit is emitted as the squared gradient. */
export function placementsRust(data) {
  const rs = [`// ${placementsHeader}`, '', 'use crate::placements::{Placement, Variant};', ''];
  rs.push('/// The structure placements (shared/worldgen/placements.json), in their file order.');
  rs.push(`pub static PLACEMENTS: [Placement; ${data.placements.length}] = [`);
  for (const p of data.placements) {
    const g = p.groves ?? { wavelength: 0, coverage: 1, outside: 1 };
    const r = p.rise ?? { full: p.height[0], low: 1 };
    const tan = Math.tan((p.maxSlopeDeg * Math.PI) / 180);
    // The shortest decimal that reads back as the same f32.
    const f = Math.fround(tan * tan);
    let grad = f;
    for (let digits = 1; digits <= 9; digits++) {
      const v = Number(f.toPrecision(digits));
      if (Math.fround(v) === f) {
        grad = v;
        break;
      }
    }
    const ss = Object.entries(p.structures).map(([n, w]) => `(${JSON.stringify(n)}, ${w})`);
    rs.push('    Placement {');
    rs.push(`        name: ${JSON.stringify(p.name)},`);
    rs.push(`        structures: &[${ss.join(', ')}],`);
    rs.push(`        on: &[${p.on.map((o) => JSON.stringify(o)).join(', ')}],`);
    rs.push(`        footprint_on: ${p.footprint === 'on'},`);
    rs.push(`        grid: ${p.grid},`);
    rs.push(`        density: ${rf(p.density)},`);
    rs.push(`        grove_wavelength: ${g.wavelength},`);
    rs.push(`        grove_coverage: ${rf(g.coverage)},`);
    rs.push(`        grove_outside: ${rf(g.outside)},`);
    rs.push(`        min_height: ${p.height[0]},`);
    rs.push(`        max_height: ${p.height[1]},`);
    rs.push(`        rise_full: ${r.full},`);
    rs.push(`        rise_low: ${rf(r.low)},`);
    rs.push(`        max_gradient_sq: ${rf(grad)},`);
    rs.push(`        spacing: ${p.spacing},`);
    rs.push(`        rotations: &[${p.rotate.map((d) => d / 90).join(', ')}],`);
    const vs = (p.variants ?? []).map((v) => {
      const pairs = Object.entries(v.replace).map(([a, b]) => `(${JSON.stringify(a)}, ${JSON.stringify(b)})`);
      return `Variant { name: ${JSON.stringify(v.name)}, replace: &[${pairs.join(', ')}], from: ${v.height[0]}, full: ${v.height[1]} }`;
    });
    rs.push(`        variants: &[${vs.join(', ')}],`);
    rs.push('    },');
  }
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

