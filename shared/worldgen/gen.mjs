  const pairs = u.pairs.map(
    (e) =>
      `PairRule { boundary: ${bkind(e.boundary)}, plates: [${kind(e.plates[0])}, ${kind(e.plates[1])}], landforms: &[${e.landforms.map(form).join(", ")}], arc: ArcMode::${cap(e.arc)} }`,
  );
