/**
 * Checks the world's elevation and water (terrain.json, its `defaultBiome`) and the biomes;
 * returns `{ world, biomes }` with the default biome first. Throws naming the file, group and key.
 */
export function validateTerrainAndBiomes(
  world,
  biomes,
  blocks = registryBlocks(),
  refs = biomeRefs(),
) {
  const fail = (m) => {
    throw new Error(`terrain.json: ${m}`);
  };
  if (typeof world !== "object" || world === null) fail("must be an object");
  const extra = Object.keys(world).filter(
    (k) => !["$comment", "defaultBiome", ...WORLD_GROUPS].includes(k),
  );
  if (extra.length) fail(`unknown ${extra.join(", ")}`);
  checkGroups(world, WORLD_GROUPS, fail);
  if (!(world.hills.fadeTo > world.hills.fadeFrom))
    fail("hills.fadeTo must be greater than hills.fadeFrom");
  if (!(world.spawn.maxHeight > world.spawn.minHeight))
    fail("spawn.maxHeight must be greater than spawn.minHeight");
  for (const b of biomes) validateBiome(b, blocks, refs);
  const names = biomes.map((b) => b.name);
  const dup = names.find((n, i) => names.indexOf(n) !== i);
  if (dup) fail(`biome ${dup} is defined twice`);
  const def = biomes.find((b) => b.name === world.defaultBiome);
  if (!def)
    fail(
      `defaultBiome ${JSON.stringify(world.defaultBiome)} is not a biome of shared/worldgen/biomes`,
    );
  return { world, biomes: [def, ...biomes.filter((b) => b !== def)] };
}

