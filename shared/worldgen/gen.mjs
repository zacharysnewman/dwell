/** The volume node vocabulary's inputs, by name (volume.json `$comment`). */
const VOLUME_INPUTS = {
  depth: "Depth",
  height: "Height",
  surface: "Surface",
  water: "Water",
  strength: "Strength",
};
/** Nodes over a list of children. */
const VOLUME_LISTS = { add: "Add", mul: "Mul", min: "Min", max: "Max" };
/** The most nodes a volume's density may have. */
const VOLUME_MAX_NODES = 256;

/**
 * A density tree flattened children first (post-order): each node `{ kind, ...params, kids }`
 * with its children's indices. Throws naming the volume and the node's path.
 */
export function flattenDensity(node, fail, path = "density", out = []) {
  const at = (m) => fail(`${path}: ${m}`);
  const num = (v, name, [min, max], whole = false) => {
    if (!(
      isNum(v) &&
      v >= min &&
      v <= max &&
      (!whole || Number.isInteger(v))
    )) {
      at(
        `${name} must be ${whole ? "a whole number " : ""}in [${min}, ${max}]`,
      );
    }
    return v;
  };
  const keysOnly = (o, keys, what) => {
    if (typeof o !== "object" || o === null || Array.isArray(o))
      at(`${what} must be an object`);
    const extra = Object.keys(o).filter((k) => !keys.includes(k));
    if (extra.length) at(`${what}: unknown ${extra.join(", ")}`);
    const missing = keys.filter((k) => !(k in o));
    if (missing.length) at(`${what}: missing ${missing.join(", ")}`);
  };
  // Identical subtrees are one node (a value used twice is computed once per column).
  const push = (n) => {
    const key = JSON.stringify(n);
    const same = out.findIndex((o) => JSON.stringify(o) === key);
    if (same >= 0) return same;
    if (out.length >= VOLUME_MAX_NODES)
      at(`more than ${VOLUME_MAX_NODES} nodes`);
    out.push(n);
    return out.length - 1;
  };
  if (isNum(node)) return push({ kind: "Const", value: node });
  if (typeof node === "string") {
    if (!(node in VOLUME_INPUTS))
      at(
        `unknown input ${JSON.stringify(node)} (inputs: ${Object.keys(VOLUME_INPUTS).join(", ")})`,
      );
    return push({ kind: VOLUME_INPUTS[node] });
  }
  if (typeof node !== "object" || node === null || Array.isArray(node))
    at("a node must be a number, an input name or an object");
  const kinds = Object.keys(node);
  if (kinds.length !== 1)
    at(`a node object has exactly one kind, not ${kinds.join(", ") || "none"}`);
  const kind = kinds[0];
  const v = node[kind];
  const sub = (child, name) =>
    flattenDensity(child, fail, `${path}.${name}`, out);
  if (kind in VOLUME_LISTS) {
    if (!(Array.isArray(v) && v.length >= 2))
      at(`${kind} takes a list of at least two nodes`);
    const kids = v.map((c, i) => sub(c, `${kind}[${i}]`));
    return push({ kind: VOLUME_LISTS[kind], kids });
  }
  if (kind === "abs") return push({ kind: "Abs", kids: [sub(v, "abs")] });
  if (kind === "slope") {
    keysOnly(v, ["radius"], "slope");
    return push({
      kind: "Slope",
      radius: num(v.radius, "slope.radius", [1, 16], true),
    });
  }
  if (kind === "noise") {
    keysOnly(v, ["wavelength", "octaves", "stretchY", "stream"], "noise");
    return push({
      kind: "Noise",
      wavelength: num(v.wavelength, "noise.wavelength", [2, 4096], true),
      octaves: num(v.octaves, "noise.octaves", [1, 6], true),
      stretchY: num(v.stretchY, "noise.stretchY", [0, 8]),
      stream: num(v.stream, "noise.stream", [0, 65_535], true),
    });
  }
  if (kind === "clamp") {
    keysOnly(v, ["of", "min", "max"], "clamp");
    num(v.min, "clamp.min", [-1e6, 1e6]);
    num(v.max, "clamp.max", [-1e6, 1e6]);
    if (!(v.max > v.min)) at("clamp.max must be greater than clamp.min");
    return push({
      kind: "Clamp",
      min: v.min,
      max: v.max,
      kids: [sub(v.of, "clamp.of")],
    });
  }
  if (kind === "terrace") {
    keysOnly(v, ["of", "step", "jitter", "flat", "riser", "stream"], "terrace");
    return push({
      kind: "Terrace",
      step: num(v.step, "terrace.step", [0.5, 256]),
      jitter: num(v.jitter, "terrace.jitter", [0, 0.9]),
      flat: num(v.flat, "terrace.flat", [0, 1]),
      riser: num(v.riser, "terrace.riser", [0.01, 1]),
      stream: num(v.stream, "terrace.stream", [0, 65_535], true),
      kids: [sub(v.of, "terrace.of")],
    });
  }
  if (kind === "smoothstep") {
    keysOnly(v, ["of", "from", "to"], "smoothstep");
    num(v.from, "smoothstep.from", [-1e6, 1e6]);
    num(v.to, "smoothstep.to", [-1e6, 1e6]);
    if (v.from === v.to) at("smoothstep.from and .to must differ");
    return push({
      kind: "Smoothstep",
      from: v.from,
      to: v.to,
      kids: [sub(v.of, "smoothstep.of")],
    });
  }
  at(`unknown node kind ${JSON.stringify(kind)}`);
}

/** A density tree's nodes, children first: the root is the last. */
export function densityNodes(node, fail) {
  const out = [];
  flattenDensity(node, fail, "density", out);
  return out;
}

/** Checks the volumes against `blocks` (id → block data); throws naming the volume and node. */
export function validateVolume(data, blocks = registryBlocks()) {
  const fail = (m) => {
    throw new Error(`volume.json: ${m}`);
  };
  if (typeof data !== "object" || data === null) fail("must be an object");
  const extra = Object.keys(data).filter(
    (k) => !["$comment", "terrain", "volumes"].includes(k),
  );
  if (extra.length) fail(`unknown ${extra.join(", ")}`);
  if (!Array.isArray(data.volumes)) fail("volumes must be a list");
  if (
    data.terrain !== null &&
    !data.volumes.some((v) => v?.name === data.terrain)
  ) {
    fail(
      `terrain must name one of the volumes, or be null (got ${JSON.stringify(data.terrain)})`,
    );
  }
  const names = new Set();
  for (const vol of data.volumes) {
    const at = vol?.name ?? "(unnamed)";
    const vf = (m) => fail(`${at}: ${m}`);
    if (typeof vol !== "object" || vol === null)
      fail("a volume must be an object");
    const ve = Object.keys(vol).filter(
      (k) =>
        ![
          "$comment",
          "name",
          "reach",
          "material",
          "soilDepth",
          "floorGrass",
          "strength",
          "density",
        ].includes(k),
    );
    if (ve.length) vf(`unknown ${ve.join(", ")}`);
    if (!(typeof vol.name === "string" && NAME.test(vol.name)))
      vf("name must be [a-z0-9_]+");
    if (names.has(vol.name)) vf("duplicate name");
    names.add(vol.name);
    if (!(isNum(vol.reach) && vol.reach > 0 && vol.reach <= 64))
      vf("reach must be in (0, 64] m");
    if (!(isNum(vol.soilDepth) && vol.soilDepth >= 0 && vol.soilDepth <= 16))
      vf("soilDepth must be in [0, 16] m");
    if (!(isNum(vol.floorGrass) && vol.floorGrass >= 0 && vol.floorGrass <= 32))
      vf("floorGrass must be in [0, 32] m");
    if (!(isNum(vol.strength) && vol.strength >= 0 && vol.strength <= 1))
      vf("strength must be in [0, 1]");
    const b = blocks.get(vol.material);
    if (!b)
      vf(`material ${JSON.stringify(vol.material)} is not in the registry`);
    if (b.shape !== "full") vf(`material ${vol.material} must be a full block`);
    if (vol.density === undefined) vf("density is missing");
    densityNodes(vol.density, vf);
  }
  return data;
}

/** One flattened node as a Rust `Node`. */
function nodeRust(n) {
  const kids = (n.kids ?? []).join(", ");
  switch (n.kind) {
    case "Const":
      return `Node::Const(${rf(n.value)})`;
    case "Depth":
    case "Height":
    case "Surface":
    case "Water":
    case "Strength":
      return `Node::${n.kind}`;
    case "Slope":
      return `Node::Slope { radius: ${n.radius} }`;
    case "Noise":
      return `Node::Noise { wavelength: ${n.wavelength}, octaves: ${n.octaves}, stretch_y: ${rf(n.stretchY)}, stream: ${n.stream} }`;
    case "Abs":
      return `Node::Abs(${kids})`;
    case "Clamp":
      return `Node::Clamp { of: ${kids}, min: ${rf(n.min)}, max: ${rf(n.max)} }`;
    case "Smoothstep":
      return `Node::Smoothstep { of: ${kids}, from: ${rf(n.from)}, to: ${rf(n.to)} }`;
    case "Terrace":
      return `Node::Terrace { of: ${kids}, step: ${rf(n.step)}, jitter: ${rf(n.jitter)}, flat: ${rf(n.flat)}, riser: ${rf(n.riser)}, stream: ${n.stream} }`;
    default:
      return `Node::${n.kind}(&[${kids}])`;
  }
}

