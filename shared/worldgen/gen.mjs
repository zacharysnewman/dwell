/**
 * Checks fixture world settings (worlds/*.json, for tests and Chisel's examples: `name` and
 * `overrides`, terrain.json's world groups with some keys changed); returns each merged over
 * `world` (terrain.json), checked by the same ranges.
 */
export function validateFixtureWorlds(fixtures, world, pool = null) {
  return fixtures.map((f) => {
    const fail = (m) => {
      throw new Error(`world fixture ${f?.name ?? "?"}: ${m}`);
    };
    if (typeof f?.name !== "string" || !/^[a-z0-9_]+:[a-z0-9_]+$/.test(f.name))
      fail('name must be "namespace:name"');
    const extra = Object.keys(f).filter(
      (k) =>
        ![
          "$comment",
          "name",
          "overrides",
          "biomes",
          "biomeMap",
          "geology",
          "newWorld",
          "cliffs",
        ].includes(k),
    );
    if (extra.length) fail(`unknown ${extra.join(", ")}`);
    // Offered in the New world form (0.52.64): a label and a line for people.
    if (f.newWorld !== undefined) {
      const n = f.newWorld;
      if (
        typeof n?.label !== "string" ||
        n.label.length < 1 ||
        n.label.length > 40
      )
        fail("newWorld.label must be 1 to 40 characters");
      if (
        n.description !== undefined &&
        (typeof n.description !== "string" || n.description.length > 200)
      )
        fail("newWorld.description must be at most 200 characters");
      const more = Object.keys(n).filter(
        (k) => !["label", "description"].includes(k),
      );
      if (more.length) fail(`newWorld: unknown ${more.join(", ")}`);
    }
    const merged = structuredClone(world);
    for (const [g, keys] of Object.entries(f.overrides ?? {})) {
      if (!WORLD_GROUPS.includes(g))
        fail(`overrides: ${g} is not a world group`);
      Object.assign(merged[g], keys);
    }
    checkGroups(merged, WORLD_GROUPS, fail);
    // A lava vent's fluid is one of shared/fluids/lava.json's hot fluids (VOLCANOES.md §6.2).
    const hot = hotFluids();
    for (const [i, v] of (merged.tectonics.lavaVents ?? []).entries())
      if (!hot.includes(v.fluid))
        fail(`tectonics.lavaVents[${i}]: ${v.fluid} is not a hot fluid (shared/fluids/lava.json)`);
    const out = { name: f.name, world: merged };
    if (
      f.biomes !== undefined ||
      f.biomeMap !== undefined ||
      f.geology !== undefined
    )
      out.edit = fixtureWorldEdit(f, world, pool ?? biomePool(), fail);
    return out;
  });
}

/** The hot fluids' names (shared/fluids/lava.json `fluids`). */
function hotFluids() {
  const lava = JSON.parse(readFileSync(join(here, "../fluids/lava.json"), "utf8"));
  return lava.fluids.map((f) => f.name);
}

