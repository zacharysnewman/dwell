/**
 * The generator tunables a slider may drive: a fixed vocabulary (crates/dwell-worldgen/src/settings.rs
 * `Target` applies each). `stage` is what it changes: `map` the world map (its cache key carries the
 * settings' hash), `columns` the chunks' columns from it, `midplane` the bedrock and the portals.
 * `read` gives the tunable's value in its data file (for `set` and `choose`, which must reproduce it
 * at the default); `whole` tunables take only whole numbers; `check` rejects a value the generator
 * cannot use; `ops` limits the ops a target takes.
 */
export const TARGETS = {
  'island.radius': { stage: 'map', rust: 'IslandRadius' },
  'island.coastAmplitude': { stage: 'map', rust: 'CoastAmplitude' },
  'uplift.baseHeight': { stage: 'map', rust: 'UpliftBaseHeight' },
  'uplift.rate': { stage: 'map', rust: 'UpliftRate' },
  'uplift.ranges.count': { stage: 'map', rust: 'RangeCount', whole: true, read: (d) => upliftOf(d).ranges?.count ?? 0, check: (v) => v >= 0 && v <= 16 },
  'uplift.plates.count': {
    stage: 'map',
    rust: 'PlateCount',
    whole: true,
    read: (d) => upliftOf(d).plates?.count ?? 0,
    check: (v) => v === 0 || (v >= 2 && v <= 64),
    needs: (d) => (upliftOf(d).plates ? null : 'the default hydrology profile has no uplift.plates group to turn on'),
  },
  'rain.amount': { stage: 'map', rust: 'RainAmount' },
  'erosion.erodibility': { stage: 'map', rust: 'Erodibility' },
  'bands.snowLine': { stage: 'columns', rust: 'SnowLine', read: (d) => d.terrain.bands.snowLine, check: (v) => v >= 0 },
  'placements.maxHeight': { stage: 'columns', rust: 'PlacementMaxHeight', whole: true },
  'placements.variantHeight': { stage: 'columns', rust: 'PlacementVariantHeight', whole: true, ops: ['shift'] },
  'placements.density': { stage: 'columns', rust: 'PlacementDensity' },
  'placements.groveOutside': { stage: 'columns', rust: 'PlacementGroveOutside' },
  'portals.countMin': { stage: 'midplane', rust: 'PortalCountMin', whole: true, read: (d) => d.midplane.portals.count[0], check: (v) => v >= 0 && v <= 64 },
  'portals.countMax': { stage: 'midplane', rust: 'PortalCountMax', whole: true, read: (d) => d.midplane.portals.count[1], check: (v) => v >= 0 && v <= 64 },
  'bedrock.thickness': {
    stage: 'midplane',
    rust: 'BedrockThickness',
    read: (d) => d.midplane.bedrock.thickness,
    check: (v, d) => Number.isInteger(v / d.constants.cellHeight) && v / d.constants.cellHeight <= d.constants.world.coreLayers && v > 0,
  },
};

function upliftOf(d) {
  const p = d.hydrology.profiles.find((q) => q.name === d.hydrology.default);
  return p?.uplift ?? {};
}

/** The number of decimals a step has (its shortest decimal form). */
export function decimalsOf(step) {
  const t = String(step);
  const dot = t.indexOf('.');
  return dot < 0 ? 0 : t.length - dot - 1;
}

/** A slider's range as numbers: toggles are 0–1 in steps of 1. */
export function rangeOf(s) {
  return s.toggle ? { min: 0, max: 1, step: 1 } : { min: s.min, max: s.max, step: s.step };
}

/** The canonical text of a slider value (the encoding's): snapped to the step, trailing zeros off. */
export function formatValue(s, v) {
  const { min, max, step } = rangeOf(s);
  const k = Math.round((Math.min(max, Math.max(min, v)) - min) / step);
  const t = (min + k * step).toFixed(decimalsOf(step));
  return t.includes('.') ? t.replace(/0+$/, '').replace(/\.$/, '') : t;
}

/** Every value a slider can take, canonical. */
export function stepsOf(s) {
  const { min, max, step } = rangeOf(s);
  const n = Math.round((max - min) / step);
  return Array.from({ length: n + 1 }, (_, k) => Number(formatValue(s, min + k * step)));
}

/**
 * Checks the settings against the data files they drive (`files`: terrain, hydrology, midplane,
 * placements, constants); throws naming the slider or preset.
 */
export function validateSettings(data, files) {
  const fail = (m) => {
    throw new Error(`settings.json: ${m}`);
  };
  if (typeof data !== 'object' || data === null) fail('must be an object');
  const top = Object.keys(data).filter((k) => !['$comment', 'categories', 'sliders', 'presets'].includes(k));
  if (top.length) fail(`unknown ${top.join(', ')}`);
  if (!(Array.isArray(data.categories) && data.categories.length)) fail('categories must be a non-empty list');
  const cats = new Set();
  for (const c of data.categories) {
    if (!(typeof c?.id === 'string' && SLIDER_ID.test(c.id))) fail(`category ${JSON.stringify(c?.id)}: id must be [a-z][a-zA-Z0-9]*`);
    if (cats.has(c.id)) fail(`category ${c.id}: duplicate id`);
    if (!(typeof c.label === 'string' && c.label.length)) fail(`category ${c.id}: label must be text`);
    cats.add(c.id);
  }
  if (!(Array.isArray(data.sliders) && data.sliders.length)) fail('sliders must be a non-empty list');
  const ids = new Map();
  for (const s of data.sliders) {
    const at = `slider ${s?.id ?? '(unnamed)'}`;
    if (typeof s !== 'object' || s === null) fail('a slider must be an object');
    const extra = Object.keys(s).filter((k) => !SLIDER_KEYS.includes(k));
    if (extra.length) fail(`${at}: unknown ${extra.join(', ')}`);
    if (!(typeof s.id === 'string' && SLIDER_ID.test(s.id))) fail(`${at}: id must be [a-z][a-zA-Z0-9]*, at most 24 characters`);
    if (ids.has(s.id)) fail(`${at}: duplicate id`);
    ids.set(s.id, s);
    if (!(typeof s.label === 'string' && s.label.length)) fail(`${at}: label must be text`);
    if (!cats.has(s.category)) fail(`${at}: category ${JSON.stringify(s.category)} is not one of the categories`);
    if (!(typeof s.format === 'string' && s.format.includes('{v}'))) fail(`${at}: format must contain {v}`);
    if (s.hint !== undefined && typeof s.hint !== 'string') fail(`${at}: hint must be text`);
    if (s.toggle !== undefined && s.toggle !== true) fail(`${at}: toggle must be true or absent`);
    if (s.toggle) {
      for (const k of ['min', 'max', 'step']) if (s[k] !== undefined) fail(`${at}: a toggle has no ${k}`);
      if (!(s.default === 0 || s.default === 1)) fail(`${at}: a toggle's default must be 0 (off) or 1 (on)`);
      if (!(Array.isArray(s.labels) && s.labels.length === 2 && s.labels.every((l) => typeof l === 'string' && l))) {
        fail(`${at}: a toggle needs labels [off, on]`);
      }
    } else {
      if (s.labels !== undefined) fail(`${at}: only a toggle has labels`);
      if (!(isNum(s.min) && isNum(s.max) && s.min < s.max)) fail(`${at}: min and max must be numbers with min < max`);
      if (!(isNum(s.step) && s.step > 0)) fail(`${at}: step must be a positive number`);
      const n = (s.max - s.min) / s.step;
      if (Math.abs(n - Math.round(n)) > 1e-9) fail(`${at}: (max − min) must be a whole number of steps`);
      if (!(isNum(s.default) && s.default >= s.min && s.default <= s.max)) fail(`${at}: default must be in [min, max]`);
      if (Number(formatValue(s, s.default)) !== s.default) fail(`${at}: default must lie on a step`);
    }
    if (!(Array.isArray(s.drives) && s.drives.length)) fail(`${at}: drives must be a non-empty list`);
    const seen = new Set();
    for (const d of s.drives) {
      const dat = `${at}: drive ${d?.target}`;
      const dk = Object.keys(d ?? {}).filter((k) => !['target', 'op', 'factor', 'values'].includes(k));
      if (dk.length) fail(`${dat}: unknown ${dk.join(', ')}`);
      const t = TARGETS[d.target];
      if (!t) fail(`${dat}: unknown target (one of ${Object.keys(TARGETS).join(', ')})`);
      if (seen.has(d.target)) fail(`${dat}: the slider drives it twice`);
      seen.add(d.target);
      const need = t.needs?.(files);
      if (need) fail(`${dat}: ${need}`);
      if (!OPS.includes(d.op)) fail(`${dat}: op must be one of ${OPS.join(', ')}`);
      if (t.ops && !t.ops.includes(d.op)) fail(`${dat}: this target takes only ${t.ops.join(', ')}`);
      if (d.factor !== undefined && d.op !== 'set') fail(`${dat}: only set takes a factor`);
      if (d.values !== undefined && d.op !== 'choose') fail(`${dat}: only choose takes values`);
      if ((d.op === 'choose') !== Boolean(s.toggle)) fail(`${dat}: choose is a toggle's op, and a toggle's only op`);
      if (d.op === 'scale') {
        if (t.whole) fail(`${dat}: a whole-number tunable cannot be scaled (set it)`);
        if (s.default !== 1) fail(`${dat}: a scaling slider's default must be 1 (the data file's value)`);
        if (!(s.min >= 0)) fail(`${dat}: a scaling slider's min must be at least 0`);
      }
      const results = [];
      if (d.op === 'set' || d.op === 'choose') {
        if (!t.read) fail(`${dat}: ${d.op} needs a tunable with a data value; scale or shift it`);
        const data0 = t.read(files);
        if (d.op === 'set') {
          const f = d.factor ?? 1;
          if (!(isNum(f) && f > 0)) fail(`${dat}: factor must be a positive number`);
          if (s.default * f !== data0) fail(`${dat}: the default × factor (${s.default * f}) must equal the data file's ${data0}`);
          for (const v of stepsOf(s)) results.push(v * f);
        } else {
          if (!(Array.isArray(d.values) && d.values.length === 2 && d.values.every(isNum))) fail(`${dat}: values must be [off, on] numbers`);
          if (d.values[s.default] !== data0) fail(`${dat}: values[default] (${d.values[s.default]}) must equal the data file's ${data0}`);
          results.push(...d.values);
        }
      }
      for (const v of results) {
        if (t.whole && !Number.isInteger(v)) fail(`${dat}: every step must give a whole number (${v} does not)`);
        if (t.check && !t.check(v, files)) fail(`${dat}: the generator cannot use ${v}`);
      }
    }
  }
  if (!(Array.isArray(data.presets) && data.presets.length)) fail('presets must be a non-empty list');
  const pids = new Set();
  const seenValues = new Map();
  data.presets.forEach((p, i) => {
    const at = `preset ${p?.id ?? '(unnamed)'}`;
    const pk = Object.keys(p ?? {}).filter((k) => !['$comment', 'id', 'label', 'description', 'values'].includes(k));
    if (pk.length) fail(`${at}: unknown ${pk.join(', ')}`);
    if (!(typeof p.id === 'string' && SLIDER_ID.test(p.id))) fail(`${at}: id must be [a-z][a-zA-Z0-9]*`);
    if (pids.has(p.id)) fail(`${at}: duplicate id`);
    pids.add(p.id);
    if (!(typeof p.label === 'string' && p.label.length)) fail(`${at}: label must be text`);
    if (!(typeof p.description === 'string' && p.description.length)) fail(`${at}: description must be text`);
    if (typeof p.values !== 'object' || p.values === null || Array.isArray(p.values)) fail(`${at}: values must map slider ids to values`);
    for (const [id, v] of Object.entries(p.values)) {
      const s = ids.get(id);
      if (!s) fail(`${at}: unknown slider ${id}`);
      const { min, max } = rangeOf(s);
      if (!(isNum(v) && v >= min && v <= max)) fail(`${at}: ${id} must be in [${min}, ${max}]`);
      if (Number(formatValue(s, v)) !== v) fail(`${at}: ${id} ${v} is not on a step`);
    }
    if (i === 0 && (p.id !== 'default' || Object.keys(p.values).length)) fail('the first preset must be default, with no values');
    const key = encodeSettings(data, p.values);
    if (seenValues.has(key)) fail(`${at}: the same values as preset ${seenValues.get(key)}`);
    seenValues.set(key, p.id);
  });
  return data;
}

/** The canonical encoding of values (slider id → value): the sliders off their defaults, in file order. */
export function encodeSettings(data, values) {
  const parts = [];
  for (const s of data.sliders) {
    if (!(s.id in values)) continue;
    const t = formatValue(s, values[s.id]);
    if (Number(t) !== s.default) parts.push(`${s.id}:${t}`);
  }
  return parts.join(',');
}

const rustNum = (v) => {
  const t = String(v);
  return /[.e]/.test(t) ? t : `${t}.0`;
};

/** The Rust tables for validated settings. */
export function settingsRust(data) {
  const rs = [`// ${settingsHeader}`, '', 'use crate::settings::{Category, Drive, Op, Preset, Slider, Target};', ''];
  rs.push('/// The sliders\' categories, in order (shared/worldgen/settings.json).');
  rs.push(`pub static CATEGORIES: [Category; ${data.categories.length}] = [`);
  for (const c of data.categories) rs.push(`    Category { id: ${JSON.stringify(c.id)}, label: ${JSON.stringify(c.label)} },`);
  rs.push('];');
  rs.push('');
  rs.push('/// The sliders, in their file order: the encoding\'s order.');
  rs.push(`pub static SLIDERS: [Slider; ${data.sliders.length}] = [`);
  for (const s of data.sliders) {
    const r = rangeOf(s);
    const drives = s.drives.map((d) => {
      const op =
        d.op === 'set'
          ? `Op::Set(${rustNum(d.factor ?? 1)})`
          : d.op === 'choose'
            ? `Op::Choose([${d.values.map(rustNum).join(', ')}])`
            : `Op::${d.op[0].toUpperCase()}${d.op.slice(1)}`;
      return `Drive { target: Target::${TARGETS[d.target].rust}, op: ${op} }`;
    });
    rs.push('    Slider {');
    rs.push(`        id: ${JSON.stringify(s.id)},`);
    rs.push(`        label: ${JSON.stringify(s.label)},`);
    rs.push(`        category: ${JSON.stringify(s.category)},`);
    rs.push(`        toggle: ${Boolean(s.toggle)},`);
    rs.push(`        min: ${rustNum(r.min)},`);
    rs.push(`        max: ${rustNum(r.max)},`);
    rs.push(`        step: ${rustNum(r.step)},`);
    rs.push(`        decimals: ${decimalsOf(r.step)},`);
    rs.push(`        default: ${rustNum(s.default)},`);
    rs.push(`        drives: &[${drives.join(', ')}],`);
    rs.push('    },');
  }
  rs.push('];');
  rs.push('');
  rs.push('/// The named presets, in their file order (the first is the default).');
  rs.push(`pub static PRESETS: [Preset; ${data.presets.length}] = [`);
  for (const p of data.presets) {
    const vs = Object.entries(p.values).map(([k, v]) => `(${JSON.stringify(k)}, ${rustNum(v)})`);
    rs.push(`    Preset { id: ${JSON.stringify(p.id)}, label: ${JSON.stringify(p.label)}, values: &[${vs.join(', ')}] },`);
  }
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

/** The TypeScript module for validated settings (the create-world screen, the route's encoding). */
export function settingsTs(data) {
  const ts = [`// ${settingsHeader}`, ''];
  ts.push('export interface SettingsCategory {');
  ts.push('  readonly id: string;');
  ts.push('  readonly label: string;');
  ts.push('}');
  ts.push('');
  ts.push('/** A slider (a toggle is 0–1 in steps of 1). `map`: it changes the world map. */');
  ts.push('export interface SettingsSlider {');
  for (const l of [
    'readonly id: string;',
    'readonly label: string;',
    'readonly category: string;',
    'readonly toggle: boolean;',
    'readonly min: number;',
    'readonly max: number;',
    'readonly step: number;',
    'readonly decimals: number;',
    'readonly default: number;',
    'readonly format: string;',
    'readonly labels: readonly string[];',
    'readonly hint: string;',
    'readonly map: boolean;',
  ]) {
    ts.push(`  ${l}`);
  }
  ts.push('}');
  ts.push('');
  ts.push('export interface SettingsPreset {');
  ts.push('  readonly id: string;');
  ts.push('  readonly label: string;');
  ts.push('  readonly description: string;');
  ts.push('  readonly values: Readonly<Record<string, number>>;');
  ts.push('}');
  ts.push('');
  ts.push(`export const CATEGORIES: readonly SettingsCategory[] = ${JSON.stringify(data.categories.map((c) => ({ id: c.id, label: c.label })), null, 2)};`);
  ts.push('');
  const sliders = data.sliders.map((s) => {
    const r = rangeOf(s);
    return {
      id: s.id,
      label: s.label,
      category: s.category,
      toggle: Boolean(s.toggle),
      min: r.min,
      max: r.max,
      step: r.step,
      decimals: decimalsOf(r.step),
      default: s.default,
      format: s.format,
      labels: s.labels ?? [],
      hint: s.hint ?? '',
      map: s.drives.some((d) => TARGETS[d.target].stage === 'map'),
    };
  });
  ts.push(`export const SLIDERS: readonly SettingsSlider[] = ${JSON.stringify(sliders, null, 2)};`);
  ts.push('');
  const presets = data.presets.map((p) => ({ id: p.id, label: p.label, description: p.description, values: p.values }));
  ts.push(`export const PRESETS: readonly SettingsPreset[] = ${JSON.stringify(presets, null, 2)};`);
  ts.push('');
  return ts.join('\n');
}

