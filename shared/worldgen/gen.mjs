/** Checks the hydrology profiles; throws naming the profile, group and key. */
export function validateHydrology(data) {
  const fail = (m) => {
    throw new Error(`hydrology.json: ${m}`);
  };
  const checkGroup = (at, g, keys, extraKeys = []) => {
    if (typeof g !== 'object' || g === null || Array.isArray(g)) fail(`${at} must be an object`);
    const ge = Object.keys(g).filter((k) => k !== '$comment' && !(k in keys) && !extraKeys.includes(k));
    if (ge.length) fail(`${at}: unknown ${ge.join(', ')}`);
    for (const [key, [min, max, whole]] of Object.entries(keys)) {
      const v = g[key];
      const low = typeof min === 'object' ? v > min.above : v >= min;
      const lo = typeof min === 'object' ? `(${min.above}` : `[${min}`;
      if (!(isNum(v) && low && v <= max && (!whole || Number.isInteger(v)))) {
        fail(`${at}.${key} must be ${whole ? 'a whole number ' : ''}in ${lo}, ${max}]`);
      }
    }
  };
  if (typeof data !== 'object' || data === null) fail('must be an object');
  const top = Object.keys(data).filter((k) => !['$comment', 'default', 'profiles'].includes(k));
  if (top.length) fail(`unknown ${top.join(', ')}`);
  if (!(Array.isArray(data.profiles) && data.profiles.length)) fail('profiles must be a non-empty list');
  const names = new Set();
  for (const p of data.profiles) {
    if (typeof p !== 'object' || p === null) fail('a profile must be an object');
    const at = p.name ?? '(unnamed)';
    const extra = Object.keys(p).filter((k) => !PROFILE_KEYS.includes(k));
    if (extra.length) fail(`${at}: unknown ${extra.join(', ')}`);
    if (!(typeof p.name === 'string' && NAME.test(p.name))) fail(`${at}: name must be [a-z0-9_]+`);
    if (names.has(p.name)) fail(`${at}: duplicate name`);
    names.add(p.name);
    checkGroup(`${at}: grid`, p.grid, HYDROLOGY.grid);
    if (p.grid.cell % 2 !== 0) fail(`${at}: grid.cell must be an even number of metres (cells are sampled at their centres)`);
    checkGroup(`${at}: erosion`, p.erosion, HYDROLOGY.erosion, ['talus']);
    checkGroup(`${at}: erosion.talus`, p.erosion.talus, HYDROLOGY.talus);
    if (!RAIN_MODELS.includes(p.rain?.model)) fail(`${at}: rain.model must be one of ${RAIN_MODELS.join(', ')}`);
    if (p.rain.model === 'orographic') {
      checkGroup(`${at}: rain`, p.rain, { ...HYDROLOGY.rain, ...HYDROLOGY.orographic }, ['model']);
      if (!(p.rain.min <= p.rain.max)) fail(`${at}: rain.min must not exceed rain.max`);
    } else {
      checkGroup(`${at}: rain`, p.rain, HYDROLOGY.rain, ['model']);
    }
    if (p.uplift !== undefined) {
      const u = p.uplift;
      checkGroup(`${at}: uplift`, u, HYDROLOGY.uplift, ['shelf', 'apron', 'ranges', 'highlands', 'plates']);
      if (u.apron !== undefined) checkGroup(`${at}: uplift.apron`, u.apron, HYDROLOGY.apron);
      checkGroup(`${at}: uplift.shelf`, u.shelf, HYDROLOGY.shelf);
      if (!(u.shelf.min <= u.shelf.max)) fail(`${at}: uplift.shelf.min must not exceed uplift.shelf.max`);
      if (u.ranges !== undefined) {
        checkGroup(`${at}: uplift.ranges`, u.ranges, HYDROLOGY.ranges, ['length', 'warp']);
        checkGroup(`${at}: uplift.ranges.length`, u.ranges.length, HYDROLOGY.length);
        if (!(u.ranges.length.min <= u.ranges.length.max)) fail(`${at}: uplift.ranges.length.min must not exceed its max`);
        if (!(u.ranges.minCoast <= u.ranges.maxCoast)) fail(`${at}: uplift.ranges.minCoast must not exceed maxCoast`);
        checkGroup(`${at}: uplift.ranges.warp`, u.ranges.warp, HYDROLOGY.warp);
      }
      if (u.highlands !== undefined) checkGroup(`${at}: uplift.highlands`, u.highlands, HYDROLOGY.highlands);
      if (u.plates !== undefined) {
        checkGroup(`${at}: uplift.plates`, u.plates, HYDROLOGY.plates, ['warp']);
        checkGroup(`${at}: uplift.plates.warp`, u.plates.warp, HYDROLOGY.warp);
        if (u.plates.count === 1) fail(`${at}: uplift.plates.count must be 0 or at least 2 (a boundary needs two)`);
      }
    }
    if (p.rockBands !== undefined) {
      checkGroup(`${at}: rockBands`, p.rockBands, HYDROLOGY.rockBands, ['warp']);
      checkGroup(`${at}: rockBands.warp`, p.rockBands.warp, HYDROLOGY.warp);
    }
    checkGroup(`${at}: lakes`, p.lakes, HYDROLOGY.lakes, ['smallPits']);
    if (!SMALL_PITS.includes(p.lakes.smallPits)) fail(`${at}: lakes.smallPits must be one of ${SMALL_PITS.join(', ')}`);
    checkGroup(`${at}: rivers`, p.rivers, HYDROLOGY.rivers, ['geometry', 'mouths']);
    checkGroup(`${at}: rivers.mouths`, p.rivers.mouths, HYDROLOGY.mouths, ['rule']);
    if (!MOUTH_RULES.includes(p.rivers.mouths.rule)) fail(`${at}: rivers.mouths.rule must be one of ${MOUTH_RULES.join(', ')}`);
    const g = p.rivers.geometry;
    if (!(Array.isArray(g) && g.length >= 1)) fail(`${at}: rivers.geometry must be a non-empty list`);
    g.forEach((pt, i) => checkGroup(`${at}: rivers.geometry[${i}]`, pt, HYDROLOGY.geometry));
    for (let i = 1; i < g.length; i++) {
      if (!(g[i].discharge > g[i - 1].discharge)) fail(`${at}: rivers.geometry discharges must increase`);
      if (g[i].width < g[i - 1].width || g[i].depth < g[i - 1].depth) {
        fail(`${at}: rivers.geometry widths and depths must not decrease with discharge`);
      }
    }
  }
  if (!names.has(data.default)) fail(`default names no profile (${data.default})`);
  return data;
}

/** A profile's `tectonics` field (the uplift layer; absent parts are off). */
function tectonicsRust(u) {
  if (u === undefined) return ['        tectonics: None,'];
  const r = u.ranges ?? {
    count: 0, length: { min: 1, max: 1 }, width: 1, strength: 0, wander: 0, warp: { amplitude: 0, wavelength: 100 }, minCoast: 0, maxCoast: 0, align: 0,
  };
  const h = u.highlands ?? { strength: 0, wavelength: 100, cover: 0 };
  const pl = u.plates ?? { count: 0, width: 1, strength: 0, rift: 0, warp: { amplitude: 0, wavelength: 100 } };
  return [
    '        tectonics: Some(Tectonics {',
    `            rate: ${rf(u.rate)},`,
    `            base_height: ${rf(u.baseHeight)},`,
    `            keep_relief: ${rf(u.keepRelief)},`,
    `            plains: ${rf(u.plains)},`,
    `            shelf_min: ${rf(u.shelf.min)},`,
    `            shelf_max: ${rf(u.shelf.max)},`,
    `            shelf_wavelength: ${u.shelf.wavelength},`,
    `            apron_strength: ${rf(u.apron?.strength ?? 0)},`,
    `            apron_width: ${rf(u.apron?.width ?? 1)},`,
    '            ranges: Ranges {',
    `                count: ${r.count},`,
    `                length_min: ${rf(r.length.min)},`,
    `                length_max: ${rf(r.length.max)},`,
    `                width: ${rf(r.width)},`,
    `                strength: ${rf(r.strength)},`,
    `                wander: ${rf(r.wander)},`,
    `                warp: ${rf(r.warp.amplitude)},`,
    `                warp_wavelength: ${r.warp.wavelength},`,
    `                min_coast: ${rf(r.minCoast)},`,
    `                max_coast: ${rf(r.maxCoast)},`,
    `                align: ${rf(r.align)},`,
    '            },',
    '            highlands: Highlands {',
    `                strength: ${rf(h.strength)},`,
    `                wavelength: ${h.wavelength},`,
    `                cover: ${rf(h.cover)},`,
    '            },',
    '            plates: Plates {',
    `                count: ${pl.count},`,
    `                width: ${rf(pl.width)},`,
    `                strength: ${rf(pl.strength)},`,
    `                rift: ${rf(pl.rift)},`,
    `                warp: ${rf(pl.warp.amplitude)},`,
    `                warp_wavelength: ${pl.warp.wavelength},`,
    '            },',
    '        }),',
  ];
}

/** The Rust table for validated hydrology profiles. */
export function hydrologyRust(data) {
  const rs = [
    `// ${hydrologyHeader}`,
    '',
    '#[allow(unused_imports)]',
    'use super::{',
    '    Highlands, HydrologyParams, MouthRule, Orographic, Plates, Rain, Ranges, RiverPoint, RockBands, SmallPits,',
    '    Tectonics,',
    '};',
    '',
  ];
  rs.push('/// The profile tools use when none is named (hydrology.json `default`).');
  rs.push(`pub const DEFAULT: &str = ${JSON.stringify(data.default)};`);
  rs.push('');
  rs.push('/// The hydrology profiles (shared/worldgen/hydrology.json), in their file order.');
  rs.push(`pub static PROFILES: [HydrologyParams; ${data.profiles.length}] = [`);
  const pascal = (s) => s[0].toUpperCase() + s.slice(1);
  for (const p of data.profiles) {
    const e = p.erosion;
    rs.push('    HydrologyParams {');
    rs.push(`        name: ${JSON.stringify(p.name)},`);
    rs.push(`        cell: ${p.grid.cell},`);
    rs.push(`        iterations: ${e.iterations},`);
    rs.push(`        time_step: ${rf(e.timeStep)},`);
    rs.push(`        erodibility: ${rf(e.erodibility)},`);
    rs.push(`        area_exponent: ${rf(e.areaExponent)},`);
    rs.push(`        slope_exponent: ${rf(e.slopeExponent)},`);
    rs.push(`        uplift: ${rf(e.uplift)},`);
    rs.push(`        uplift_reference: ${rf(e.upliftReference)},`);
    rs.push(...tectonicsRust(p.uplift));
    if (p.rockBands === undefined) {
      rs.push('        rock_bands: None,');
    } else {
      const b = p.rockBands;
      rs.push('        rock_bands: Some(RockBands {');
      rs.push(`            contrast: ${rf(b.contrast)},`);
      rs.push(`            wavelength: ${rf(b.wavelength)},`);
      rs.push(`            hard_share: ${rf(b.hardShare)},`);
      rs.push(`            warp: ${rf(b.warp.amplitude)},`);
      rs.push(`            warp_wavelength: ${b.warp.wavelength},`);
      rs.push('        }),');
    }
    rs.push(`        talus_slope: ${rf(e.talus.maxSlope)},`);
    rs.push(`        talus_passes: ${e.talus.passes},`);
    rs.push(`        lake_fill: ${rf(e.lakeFill)},`);
    if (p.rain.model === 'orographic') {
      const r = p.rain;
      rs.push('        rain: Rain::Orographic(Orographic {');
      for (const [k, v] of [
        ['direction', r.direction],
        ['spread', r.spread],
        ['upslope', r.upslope],
        ['fetch', r.fetch],
        ['shadow', r.shadow],
        ['shadow_height', r.shadowHeight],
        ['min', r.min],
        ['max', r.max],
      ]) {
        rs.push(`            ${k}: ${rf(v)},`);
      }
      rs.push('        }),');
    } else {
      rs.push(`        rain: Rain::${pascal(p.rain.model)},`);
    }
    rs.push(`        rainfall: ${rf(p.rain.amount)},`);
    rs.push(`        lake_min_area: ${rf(p.lakes.minArea * 1e6)},`);
    rs.push(`        lake_min_depth: ${rf(p.lakes.minDepth)},`);
    rs.push(`        small_pits: SmallPits::${pascal(p.lakes.smallPits)},`);
    rs.push(`        max_breach_depth: ${rf(p.lakes.maxBreachDepth)},`);
    rs.push(`        river_threshold: ${rf(p.rivers.threshold)},`);
    rs.push('        river_geometry: &[');
    for (const g of p.rivers.geometry) {
      rs.push(`            RiverPoint { discharge: ${rf(g.discharge)}, width: ${rf(g.width)}, depth: ${rf(g.depth)} },`);
    }
    rs.push('        ],');
    rs.push(`        mouth_min_discharge: ${rf(p.rivers.mouths.minDischarge)},`);
    rs.push(`        mouth_rule: MouthRule::${pascal(p.rivers.mouths.rule)},`);
    rs.push(`        mouth_reach: ${rf(p.rivers.mouths.reach)},`);
    rs.push(`        delta_max_slope: ${rf(p.rivers.mouths.deltaMaxSlope)},`);
    rs.push('    },');
  }
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

// ---- Between the faces: the bedrock and the portals (midplane.json) ------------------------------

const midplaneHeader = 'Generated by shared/worldgen/gen.mjs from shared/worldgen/midplane.json. Do not edit.';
/** The walls a portal's ladder may be fixed to, and the ladder's facing on each (away from it). */
export const LADDER_WALLS = { north: 'south', east: 'west', south: 'north', west: 'east' };
const MIDPLANE = {
  bedrock: { thickness: [0, 10] },
  portals: {
    spacing: [0, 100_000],
    within: [{ above: 0 }, 100_000],
    attempts: [1, 100_000, true],
    inland: [0, 10_000],
    maxHeight: [0, 10_000],
    radius: [1, 16],
    clear: [0, 64],
  },
  rim: { width: [0, 8], height: [0, 8] },
};

/** Checks the bedrock and portals against `blocks` (id → block data); throws naming the key. */
export function validateMidplane(data, blocks) {
  const fail = (m) => {
    throw new Error(`midplane.json: ${m}`);
  };
  const constants = JSON.parse(readFileSync(join(here, '../protocol/constants.json'), 'utf8'));
  const cell = constants.cellHeight;
  const checkGroup = (at, g, keys, extraKeys) => {
    if (typeof g !== 'object' || g === null || Array.isArray(g)) fail(`${at} must be an object`);
    const ge = Object.keys(g).filter((k) => k !== '$comment' && !(k in keys) && !extraKeys.includes(k));
    if (ge.length) fail(`${at}: unknown ${ge.join(', ')}`);
    for (const [key, [min, max, whole]] of Object.entries(keys)) {
      const v = g[key];
      const low = typeof min === 'object' ? v > min.above : v >= min;
      const lo = typeof min === 'object' ? `(${min.above}` : `[${min}`;
      if (!(isNum(v) && low && v <= max && (!whole || Number.isInteger(v)))) {
        fail(`${at}.${key} must be ${whole ? 'a whole number ' : ''}in ${lo}, ${max}]`);
      }
    }
  };
  const block = (at, id) => {
    const b = blocks.get(id);
    if (!b) fail(`${at} ${id} is not in the registry`);
    return b;
  };
  if (typeof data !== 'object' || data === null) fail('must be an object');
  const top = Object.keys(data).filter((k) => !['$comment', 'bedrock', 'portals'].includes(k));
  if (top.length) fail(`unknown ${top.join(', ')}`);
  checkGroup('bedrock', data.bedrock, MIDPLANE.bedrock, ['block']);
  const bedrock = block('bedrock.block', data.bedrock.block);
  if (bedrock.shape !== 'full') fail(`bedrock.block ${data.bedrock.block} must be a full block`);
  if (bedrock.indestructible !== true) fail(`bedrock.block ${data.bedrock.block} must be indestructible`);
  if (!Number.isInteger(data.bedrock.thickness / cell)) fail(`bedrock.thickness must be a whole number of cells (${cell} m)`);
  if (data.bedrock.thickness / cell > constants.world.coreLayers) {
    fail(`bedrock.thickness must lie inside the core (${constants.world.coreLayers * cell} m)`);
  }
  const p = data.portals;
  checkGroup('portals', p, MIDPLANE.portals, ['count', 'rim', 'ladder', 'motes']);
  if (!moteNames(loadMotes()).includes(p.motes)) fail(`portals.motes ${JSON.stringify(p.motes)} is not a look in shared/look/motes.json`);
  const c = p.count;
  if (!(Array.isArray(c) && c.length === 2 && c.every((n) => Number.isInteger(n) && n >= 0 && n <= 64) && c[0] <= c[1])) {
    fail('portals.count must be [min, max], whole numbers 0–64 with min ≤ max');
  }
  checkGroup('portals.rim', p.rim, MIDPLANE.rim, ['block']);
  if (block('portals.rim.block', p.rim.block).shape !== 'full') fail(`portals.rim.block ${p.rim.block} must be a full block`);
  if (!Number.isInteger(p.rim.height / cell)) fail(`portals.rim.height must be a whole number of cells (${cell} m)`);
  if (typeof p.ladder !== 'object' || p.ladder === null) fail('portals.ladder must be an object');
  const le = Object.keys(p.ladder).filter((k) => !['$comment', 'block', 'wall'].includes(k));
  if (le.length) fail(`portals.ladder: unknown ${le.join(', ')}`);
  const ladder = block('portals.ladder.block', p.ladder.block);
  if (ladder.climbable !== true) fail(`portals.ladder.block ${p.ladder.block} must be climbable`);
  if (!(p.ladder.wall in LADDER_WALLS)) fail(`portals.ladder.wall must be one of ${Object.keys(LADDER_WALLS).join(', ')}`);
  const facing = ladder.facingProperty;
  if (!(facing && ladder.properties?.[facing]?.includes(LADDER_WALLS[p.ladder.wall]))) {
    fail(`portals.ladder.block ${p.ladder.block} has no ${facing ?? 'facing'}=${LADDER_WALLS[p.ladder.wall]} state`);
  }
  return data;
}

/** The Rust constant for validated midplane data. */
export function midplaneRust(data) {
  const cell = JSON.parse(readFileSync(join(here, '../protocol/constants.json'), 'utf8')).cellHeight;
  const p = data.portals;
  const ladder = registryBlocks().get(p.ladder.block);
  const state = `${p.ladder.block}[${ladder.facingProperty}=${LADDER_WALLS[p.ladder.wall]}]`;
  const rs = [`// ${midplaneHeader}`, '', 'use crate::portals::{Midplane, PortalRules};', ''];
  rs.push('/// The bedrock and the portals (shared/worldgen/midplane.json).');
  rs.push('pub const MIDPLANE: Midplane = Midplane {');
  rs.push(`    bedrock: ${JSON.stringify(data.bedrock.block)},`);
  rs.push(`    bedrock_rows: ${data.bedrock.thickness / cell},`);
  rs.push('    portals: PortalRules {');
  const fields = [
    ['count_min', `${p.count[0]}`],
    ['count_max', `${p.count[1]}`],
    ['spacing', rf(p.spacing)],
    ['within', rf(p.within)],
    ['attempts', `${p.attempts}`],
    ['inland', rf(p.inland)],
    ['max_height', rf(p.maxHeight)],
    ['radius', rf(p.radius)],
    ['rim_block', JSON.stringify(p.rim.block)],
    ['rim_width', rf(p.rim.width)],
    ['rim_rows', `${p.rim.height / cell}`],
    ['ladder', JSON.stringify(state)],
    ['wall', `[${{ north: '0, -1', east: '1, 0', south: '0, 1', west: '-1, 0' }[p.ladder.wall]}]`],
    ['clear', rf(p.clear)],
    ['motes', JSON.stringify(p.motes)],
  ];
  for (const [k, v] of fields) rs.push(`        ${k}: ${v},`);
  rs.push('    },');
  rs.push('};');
  rs.push('');
  return rs.join('\n');
}

