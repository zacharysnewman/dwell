#!/usr/bin/env node
// Generates the on-screen interface's parts that Settings can show or hide (client/src/ui/hud.gen.ts,
// and the rules that hide them, client/src/ui/hud.gen.css: the page's CSP takes stylesheets from
// files only) from shared/ui/hud.json, after validating them: an unknown, missing or malformed entry fails with
// its path named. The output is checked in; CI regenerates it and fails on any diff.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/ui/gen.mjs from shared/ui/hud.json. Do not edit.';

const FIELDS = { id: 'id', label: 'text', hint: 'text', selector: 'selector', shown: 'bool', phone: 'bool' };

const fail = (m) => {
  throw new Error(`hud.json: ${m}`);
};

function check(where, kind, v) {
  switch (kind) {
    case 'id':
      if (typeof v !== 'string' || !/^[a-z]+(-[a-z]+)*$/.test(v)) fail(`${where} must be lowercase words joined by dashes, got ${JSON.stringify(v)}`);
      return;
    case 'text':
      if (typeof v !== 'string' || v.trim() === '') fail(`${where} must be some text`);
      return;
    case 'selector':
      // An id or class selector, so it can't reach the menu or the page itself by accident.
      if (typeof v !== 'string' || !/^[#.][A-Za-z][\w-]*$/.test(v)) fail(`${where} must be one #id or .class selector, got ${JSON.stringify(v)}`);
      return;
    case 'bool':
      if (typeof v !== 'boolean') fail(`${where} must be true or false, got ${JSON.stringify(v)}`);
      return;
  }
}

/** Checks the parts; returns them. Throws naming the entry. */
export function validateHud(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  for (const k of Object.keys(data)) if (k !== '$comment' && k !== 'elements') fail(`unknown entry ${k}`);
  if (!Array.isArray(data.elements) || data.elements.length === 0) fail('elements must be a list of parts');
  const ids = new Set();
  data.elements.forEach((e, i) => {
    const where = `elements[${i}]`;
    if (typeof e !== 'object' || e === null || Array.isArray(e)) fail(`${where} must be an object`);
    for (const k of Object.keys(e)) if (k !== '$comment' && !(k in FIELDS)) fail(`unknown entry ${where}.${k}`);
    for (const [k, kind] of Object.entries(FIELDS)) {
      if (!(k in e)) fail(`missing entry ${where}.${k}`);
      check(`${where}.${k}`, kind, e[k]);
    }
    if (ids.has(e.id)) fail(`${where}.id: "${e.id}" is listed twice`);
    ids.add(e.id);
  });
  return data;
}

/** The TypeScript for validated parts. */
export function hudTs(data) {
  const ts = [`// ${header}`, ''];
  ts.push('/** A part of the on-screen interface Settings can show or hide (shared/ui/hud.json). */');
  ts.push('export interface HudElement {');
  ts.push('  id: string;');
  ts.push('  label: string;');
  ts.push('  hint: string;');
  ts.push('  selector: string;');
  ts.push('  shown: boolean;');
  ts.push('  phone: boolean;');
  ts.push('}');
  ts.push('');
  ts.push('export const HUD_ELEMENTS: readonly HudElement[] = [');
  for (const e of data.elements) {
    const o = Object.fromEntries(Object.keys(FIELDS).map((k) => [k, e[k]]));
    ts.push(`  ${JSON.stringify(o)},`);
  }
  ts.push('];');
  ts.push('');
  return ts.join('\n');
}

/** The CSS for validated parts: each hidden while its class is on the body. */
export function hudCss(data) {
  const css = [`/* ${header} */`, ''];
  for (const e of data.elements) {
    css.push(`body.hud-hide-${e.id} ${e.selector} {`);
    css.push('  display: none !important;');
    css.push('}');
    css.push('');
  }
  return css.join('\n');
}

