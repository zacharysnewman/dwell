#!/usr/bin/env node
// Generates the on-screen interface's parts that Settings can show or hide (client/src/ui/hud.gen.ts,
// and the rules that hide them, client/src/ui/hud.gen.css: the page's CSP takes stylesheets from
// files only) from shared/ui/hud.json, after validating them: an unknown, missing or malformed entry fails with
// its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/ui/gen.mjs from shared/ui/hud.json. Do not edit.';

const FIELDS = { id: 'id', label: 'text', hint: 'text', selector: 'selector', shown: 'bool', phone: 'bool' };

const fail = (m) => {
  throw new Error(`hud.json: ${m}`);
};

function check(where, kind, v) {
  switch (kind) {
    case 'id':
      if (typeof v !== 'string' || !/^[a-z]+(-[a-z]+)*$/.test(v)) fail(`${where} must be lowercase words joined by dashes, got ${JSON.stringify(v)}`);
      return;
    case 'text':
      if (typeof v !== 'string' || v.trim() === '') fail(`${where} must be some text`);
      return;
    case 'selector':
      // An id or class selector, so it can't reach the menu or the page itself by accident.
      if (typeof v !== 'string' || !/^[#.][A-Za-z][\w-]*$/.test(v)) fail(`${where} must be one #id or .class selector, got ${JSON.stringify(v)}`);
      return;
    case 'bool':
      if (typeof v !== 'boolean') fail(`${where} must be true or false, got ${JSON.stringify(v)}`);
      return;
  }
}

/** Checks the parts; returns them. Throws naming the entry. */
export function validateHud(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  for (const k of Object.keys(data)) if (k !== '$comment' && k !== 'elements') fail(`unknown entry ${k}`);
  if (!Array.isArray(data.elements) || data.elements.length === 0) fail('elements must be a list of parts');
  const ids = new Set();
  data.elements.forEach((e, i) => {
    const where = `elements[${i}]`;
    if (typeof e !== 'object' || e === null || Array.isArray(e)) fail(`${where} must be an object`);
    for (const k of Object.keys(e)) if (k !== '$comment' && !(k in FIELDS)) fail(`unknown entry ${where}.${k}`);
    for (const [k, kind] of Object.entries(FIELDS)) {
      if (!(k in e)) fail(`missing entry ${where}.${k}`);
      check(`${where}.${k}`, kind, e[k]);
    }
    if (ids.has(e.id)) fail(`${where}.id: "${e.id}" is listed twice`);
    ids.add(e.id);
  });
  return data;
}

/** The TypeScript for validated parts. */
export function hudTs(data) {
  const ts = [`// ${header}`, ''];
  ts.push('/** A part of the on-screen interface Settings can show or hide (shared/ui/hud.json). */');
  ts.push('export interface HudElement {');
  ts.push('  id: string;');
  ts.push('  label: string;');
  ts.push('  hint: string;');
  ts.push('  selector: string;');
  ts.push('  shown: boolean;');
  ts.push('  phone: boolean;');
  ts.push('}');
  ts.push('');
  ts.push('export const HUD_ELEMENTS: readonly HudElement[] = [');
  for (const e of data.elements) {
    const o = Object.fromEntries(Object.keys(FIELDS).map((k) => [k, e[k]]));
    ts.push(`  ${JSON.stringify(o)},`);
  }
  ts.push('];');
  ts.push('');
  return ts.join('\n');
}

/** The CSS for validated parts: each hidden while its class is on the body. */
export function hudCss(data) {
  const css = [`/* ${header} */`, ''];
  for (const e of data.elements) {
    css.push(`body.hud-hide-${e.id} ${e.selector} {`);
    css.push('  display: none !important;');
    css.push('}');
    css.push('');
  }
  return css.join('\n');
}

// The minimap and the explored map (shared/ui/map.json; docs/adr/0068-minimap-and-explored-map.md):
// numbers in a range, colours as #rrggbb; emitted for the client crate (`dwell-game` `minimap.rs`
// reads `MAP`) and the shell (`ui/map.gen.ts`).
const mapHeader = 'Generated by shared/ui/gen.mjs from shared/ui/map.json. Do not edit.';

/** Each section's fields: [kind, min, max]. Kinds: num, int, color, bool. */
export const MAP_FIELDS = {
  minimap: {
    radiusM: ['int', 8, 256],
    texelM: ['num', 0.25, 8],
    sizePx: ['int', 64, 512],
    moveTexels: ['num', 0.25, 16],
    turnDegrees: ['num', 0.1, 45],
    refreshSeconds: ['num', 0.1, 60],
    scanUpM: ['num', 0, 256],
    scanDownM: ['num', 1, 512],
    playerColor: ['color'],
    otherColor: ['color'],
    dotPx: ['num', 1, 32],
    edgeColor: ['color'],
    cpuUpdateMs: ['int', 0, 10000],
  },
  heightShading: {
    default: ['bool'],
    rangeM: ['num', 1, 512],
    darkest: ['num', 0, 1],
    brightest: ['num', 1, 3],
    slope: ['num', 0, 4],
    waterDepthM: ['num', 0.5, 128],
  },
  explored: { cellM: ['int', 1, 128] },
  bigMap: {
    startPxPerCell: ['num', 0.1, 256],
    minPxPerCell: ['num', 0.1, 256],
    maxPxPerCell: ['num', 0.1, 256],
    zoomStep: ['num', 1.01, 4],
    fogColor: ['color'],
  },
};

const mapFail = (m) => {
  throw new Error(`map.json: ${m}`);
};

/** Checks the map's data; returns it. Throws naming the entry. */
export function validateMap(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) mapFail('(root) must be an object');
  for (const k of Object.keys(data)) if (k !== '$comment' && !(k in MAP_FIELDS)) mapFail(`unknown entry ${k}`);
  for (const [section, fields] of Object.entries(MAP_FIELDS)) {
    const sec = data[section];
    if (typeof sec !== 'object' || sec === null || Array.isArray(sec)) mapFail(`${section} must be an object`);
    for (const k of Object.keys(sec)) if (k !== '$comment' && !(k in fields)) mapFail(`unknown entry ${section}.${k}`);
    for (const [k, [kind, lo, hi]] of Object.entries(fields)) {
      const where = `${section}.${k}`;
      const v = sec[k];
      if (v === undefined) mapFail(`missing entry ${where}`);
      if (kind === 'bool') {
        if (typeof v !== 'boolean') mapFail(`${where} must be true or false`);
      } else if (kind === 'color') {
        if (typeof v !== 'string' || !/^#[0-9a-f]{6}$/i.test(v)) mapFail(`${where} must be a #rrggbb colour, got ${JSON.stringify(v)}`);
      } else {
        if (typeof v !== 'number' || !Number.isFinite(v)) mapFail(`${where} must be a number`);
        if (kind === 'int' && !Number.isInteger(v)) mapFail(`${where} must be a whole number`);
        if (v < lo || v > hi) mapFail(`${where} must be within ${lo}–${hi}, got ${v}`);
      }
    }
  }
  const b = data.bigMap;
  if (!(b.minPxPerCell <= b.startPxPerCell && b.startPxPerCell <= b.maxPxPerCell)) {
    mapFail('bigMap: minPxPerCell ≤ startPxPerCell ≤ maxPxPerCell');
  }
  if (data.minimap.radiusM % data.explored.cellM !== 0) mapFail('explored.cellM must divide minimap.radiusM');
  return data;
}

const snake = (k) => k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rsNum = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

/** The Rust for the client crate: the tunables `dwell-game` `minimap.rs` declares. */
export function mapRs(data) {
  const rs = [`// ${mapHeader}`, '', '/// The minimap and the explored map (shared/ui/map.json).', 'pub const MAP: MapTunables = MapTunables {'];
  for (const [section, fields] of Object.entries(MAP_FIELDS)) {
    for (const [k, [kind]] of Object.entries(fields)) {
      const v = data[section][k];
      const name = `${snake(section)}_${snake(k)}`;
      const val = kind === 'bool' ? String(v) : kind === 'color' ? `0x${v.slice(1).toLowerCase()}` : rsNum(v);
      rs.push(`    ${name}: ${val},`);
    }
  }
  rs.push('};', '');
  return rs.join('\n');
}

/** The TypeScript for the shell (written as Prettier writes it: CI checks both). */
export function mapTs(data) {
  const ts = [`// ${mapHeader}`, '', '/** The minimap and the explored map (shared/ui/map.json). */', 'export const MAP = {'];
  for (const [section, fields] of Object.entries(MAP_FIELDS)) {
    ts.push(`  ${section}: {`);
    for (const k of Object.keys(fields)) {
      const v = data[section][k];
      ts.push(`    ${k}: ${typeof v === 'string' ? `'${v}'` : String(v)},`);
    }
    ts.push('  },');
  }
  ts.push('} as const;', '');
  return ts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateHud(JSON.parse(readFileSync(join(here, 'hud.json'), 'utf8')));
  writeFileSync(join(root, 'client/src/ui/hud.gen.ts'), hudTs(data));
  writeFileSync(join(root, 'client/src/ui/hud.gen.css'), hudCss(data));
  const map = validateMap(JSON.parse(readFileSync(join(here, 'map.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-game/src/map.gen.rs'), mapRs(map));
  writeFileSync(join(root, 'client/src/ui/map.gen.ts'), mapTs(map));
  console.log('ui: HUD parts and the map generated');
}

