/** The most zoom levels the big map has (owner, 2026-11-09: "at most 5 zoom levels"). */
export const MAX_LEVELS = 5;

/**
 * The world disc's radius (m; shared/protocol/constants.json's worldRadius), the widest zoom
 * level's half span: the whole world, its sea included (owner, 2026-11-09), not the island.
 */
export const WORLD_RADIUS_M = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '../protocol/constants.json'), 'utf8')).world.worldRadius;

const isPow2 = (v) => Number.isInteger(v) && v > 0 && (v & (v - 1)) === 0;

/**
 * Each level's span across the panel's short side (m, whole metres): the closest the minimap's
 * diameter, the widest the world disc's, the levels between spaced geometrically.
 */
export function levelSpans(data, worldRadiusM = WORLD_RADIUS_M) {
  const n = data.bigMap.levels.length;
  const near = 2 * data.minimap.radiusM;
  const far = 2 * worldRadiusM;
  return data.bigMap.levels.map((_, i) => Math.round(near * (far / near) ** (i / (n - 1))));
}

/** The controller's button names (shared/input/gamepad.json), for the map's controller buttons. */
const PAD_BUTTONS = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '../input/gamepad.json'), 'utf8')).buttons.map((b) => b.name);

/**
 * Where the background builds a level's tiles (ADR 0068; owner, 2026-11-10): `player` round the
 * player (revealed.prebuildSpans of its span), `island` every tile touching the island
 * (constants.json's islandRadius), `disc` every tile touching the world disc.
 */
export const REACHES = ['player', 'island', 'disc'];

const mapFail = (m) => {
  throw new Error(`map.json: ${m}`);
};

/** Checks the map's data; returns it. Throws naming the entry. */
export function validateMap(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) mapFail('(root) must be an object');
  for (const k of Object.keys(data)) if (k !== '$comment' && !(k in MAP_FIELDS)) mapFail(`unknown entry ${k}`);
  for (const [section, fields] of Object.entries(MAP_FIELDS)) {
    const sec = data[section];
    if (typeof sec !== 'object' || sec === null || Array.isArray(sec)) mapFail(`${section} must be an object`);
    for (const k of Object.keys(sec)) if (k !== '$comment' && !(k in fields)) mapFail(`unknown entry ${section}.${k}`);
    for (const [k, [kind, lo, hi]] of Object.entries(fields)) {
      const where = `${section}.${k}`;
      const v = sec[k];
      if (v === undefined) mapFail(`missing entry ${where}`);
      if (kind === 'bool') {
        if (typeof v !== 'boolean') mapFail(`${where} must be true or false`);
      } else if (kind === 'button') {
        if (!PAD_BUTTONS.includes(v)) mapFail(`${where} must be a controller button (${PAD_BUTTONS.join(', ')}), got ${JSON.stringify(v)}`);
      } else if (kind === 'levels') {
        if (!Array.isArray(v) || v.length < 2 || v.length > MAX_LEVELS) mapFail(`${where} must be a list of 2 to ${MAX_LEVELS} levels, closest first`);
        v.forEach((lv, i) => {
          const at = `${where}[${i}]`;
          if (typeof lv !== 'object' || lv === null || Array.isArray(lv)) mapFail(`${at} must be an object`);
          for (const lk of Object.keys(lv)) if (lk !== '$comment' && lk !== 'cellM' && lk !== 'reach') mapFail(`unknown entry ${at}.${lk}`);
          if (!REACHES.includes(lv.reach)) mapFail(`${at}.reach must be one of ${REACHES.join(', ')}, got ${JSON.stringify(lv.reach)}`);
          if (!isPow2(lv.cellM) || lv.cellM > 1024) mapFail(`${at}.cellM must be a whole power of two within 1–1024, got ${JSON.stringify(lv.cellM)}`);
          if (i > 0 && !(lv.cellM > v[i - 1].cellM)) mapFail(`${at}.cellM must be above the level before it (${v[i - 1].cellM})`);
        });
      } else if (kind === 'stops') {
        const [, key, from, to] = fields[k];
        if (!Array.isArray(v) || v.length === 0) mapFail(`${where} must be a list of at least one { ${key}, color }`);
        v.forEach((stop, i) => {
          const at = `${where}[${i}]`;
          if (typeof stop !== 'object' || stop === null || Array.isArray(stop)) mapFail(`${at} must be an object`);
          for (const sk of Object.keys(stop)) if (sk !== '$comment' && sk !== key && sk !== 'color') mapFail(`unknown entry ${at}.${sk}`);
          const n = stop[key];
          if (typeof n !== 'number' || !Number.isFinite(n) || n < from || n > to) mapFail(`${at}.${key} must be a number within ${from}–${to}, got ${JSON.stringify(n)}`);
          if (typeof stop.color !== 'string' || !/^#[0-9a-f]{6}$/i.test(stop.color)) mapFail(`${at}.color must be a #rrggbb colour, got ${JSON.stringify(stop.color)}`);
          if (i > 0 && !(n > v[i - 1][key])) mapFail(`${at}.${key} must be above the stop before it (${v[i - 1][key]})`);
        });
      } else if (kind === 'color') {
        if (typeof v !== 'string' || !/^#[0-9a-f]{6}$/i.test(v)) mapFail(`${where} must be a #rrggbb colour, got ${JSON.stringify(v)}`);
      } else {
        if (typeof v !== 'number' || !Number.isFinite(v)) mapFail(`${where} must be a number`);
        if (kind === 'int' && !Number.isInteger(v)) mapFail(`${where} must be a whole number`);
        if (v < lo || v > hi) mapFail(`${where} must be within ${lo}–${hi}, got ${v}`);
      }
    }
  }
  const b = data.bigMap;
  if (b.startLevel >= b.levels.length) mapFail(`bigMap.startLevel must name a level (0–${b.levels.length - 1})`);
  if (!(data.heightTint.lowM < data.heightTint.highM)) mapFail('heightTint: lowM must be below highM');
  if (!(data.heightTint.highM < data.heightTint.peakM)) mapFail('heightTint: highM must be below peakM');
  if (data.minimap.radiusM % data.explored.cellM !== 0) mapFail('explored.cellM must divide minimap.radiusM');
  // The zoom levels' cells and the explored cells nest (fog per level).
  if (!isPow2(data.explored.cellM)) mapFail('explored.cellM must be a whole power of two');
  const pad = ['padZoomIn', 'padZoomInAlt', 'padZoomOut', 'padZoomOutAlt', 'padCenter', 'padClose'].map((k) => b[k]);
  if (new Set(pad).size !== pad.length || pad.includes('view')) mapFail('bigMap: the controller buttons must differ (View closes the map)');
  return data;
}

// The big map's debug layers (shared/ui/mapLayers.json; REALISTIC_WORLD.md R6): read as JSON by
// the shell (`ui/mapLayers.ts`), checked here. The fields are the generator's fixed vocabulary
// (`dwell-worldgen` `map_layers.rs` `MapField`, whose test reads the same file).
export const LAYER_FIELDS = { plates: 'category', uplift: 'value', rain: 'value', rocks: 'category' };

const layersFail = (m) => {
  throw new Error(`mapLayers.json: ${m}`);
};
const isColor = (v) => typeof v === 'string' && /^#[0-9a-f]{6}$/i.test(v);

/** Checks the debug layers' data; returns it. Throws naming the entry. */
export function validateMapLayers(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) layersFail('(root) must be an object');
  for (const k of Object.keys(data)) if (!['$comment', 'key', 'samples', 'layers'].includes(k)) layersFail(`unknown entry ${k}`);
  if (typeof data.key !== 'string' || !/^Key[A-Z]$/.test(data.key)) layersFail(`key must be a letter key's code (KeyA–KeyZ), got ${JSON.stringify(data.key)}`);
  if (!Number.isInteger(data.samples) || data.samples < 16 || data.samples > 512) layersFail(`samples must be a whole number within 16–512, got ${JSON.stringify(data.samples)}`);
  if (!Array.isArray(data.layers) || data.layers.length === 0) layersFail('layers must be a list of at least one layer');
  const names = new Set();
  data.layers.forEach((l, i) => {
    const at = `layers[${i}]`;
    if (typeof l !== 'object' || l === null || Array.isArray(l)) layersFail(`${at} must be an object`);
    for (const k of Object.keys(l)) if (!['$comment', 'name', 'label', 'field', 'opacity', 'colors', 'outlineColor', 'ramp'].includes(k)) layersFail(`unknown entry ${at}.${k}`);
    if (typeof l.name !== 'string' || !/^[a-z][a-z0-9_]*$/.test(l.name)) layersFail(`${at}.name must be a lower-case name, got ${JSON.stringify(l.name)}`);
    if (names.has(l.name)) layersFail(`${at}.name ${l.name} is used twice`);
    names.add(l.name);
    if (typeof l.label !== 'string' || l.label.length < 1 || l.label.length > 24) layersFail(`${at}.label must be 1 to 24 characters`);
    const kind = LAYER_FIELDS[l.field];
    if (!kind) layersFail(`${at}.field must be one of ${Object.keys(LAYER_FIELDS).join(', ')}, got ${JSON.stringify(l.field)}`);
    if (typeof l.opacity !== 'number' || !(l.opacity > 0 && l.opacity <= 1)) layersFail(`${at}.opacity must be a number within 0 (exclusive) and 1`);
    if (kind === 'category') {
      if (l.ramp !== undefined) layersFail(`${at}.ramp: a ${l.field} layer is coloured by category (colors), not a ramp`);
      if (typeof l.colors !== 'object' || l.colors === null || Array.isArray(l.colors)) layersFail(`${at}.colors must be an object of category → #rrggbb`);
      for (const [c, v] of Object.entries(l.colors)) if (!isColor(v)) layersFail(`${at}.colors.${c} must be a #rrggbb colour, got ${JSON.stringify(v)}`);
      if (l.outlineColor !== undefined && !isColor(l.outlineColor)) layersFail(`${at}.outlineColor must be a #rrggbb colour`);
    } else {
      if (l.colors !== undefined || l.outlineColor !== undefined) layersFail(`${at}: a ${l.field} layer is coloured by a ramp, not colors`);
      if (!Array.isArray(l.ramp) || l.ramp.length < 2) layersFail(`${at}.ramp must be a list of at least two { at, color } stops`);
      l.ramp.forEach((s, k) => {
        const where = `${at}.ramp[${k}]`;
        if (typeof s !== 'object' || s === null || Array.isArray(s)) layersFail(`${where} must be an object`);
        for (const sk of Object.keys(s)) if (sk !== 'at' && sk !== 'color') layersFail(`unknown entry ${where}.${sk}`);
        if (typeof s.at !== 'number' || !Number.isFinite(s.at)) layersFail(`${where}.at must be a number`);
        if (k > 0 && !(s.at > l.ramp[k - 1].at)) layersFail(`${where}.at must be above the stop before it (${l.ramp[k - 1].at})`);
        if (!isColor(s.color)) layersFail(`${where}.color must be a #rrggbb colour, got ${JSON.stringify(s.color)}`);
      });
    }
  });
  return data;
}

const snake = (k) => k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rsNum = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

/** The Rust for the client crate: the tunables `dwell-game` `minimap.rs` declares. */
export function mapRs(data) {
  const rs = [`// ${mapHeader}`, '', '/// The minimap and the explored map (shared/ui/map.json).', 'pub const MAP: MapTunables = MapTunables {'];
  for (const [section, fields] of Object.entries(MAP_FIELDS)) {
    for (const [k, [kind]] of Object.entries(fields)) {
      const v = data[section][k];
      const name = `${snake(section)}_${snake(k)}`;
      const val =
        kind === 'bool'
          ? String(v)
          : kind === 'color'
            ? `0x${v.slice(1).toLowerCase()}`
            : kind === 'button'
              ? JSON.stringify(v)
              : kind === 'levels'
                ? `&[${v.map((lv, i) => `(${rsNum(lv.cellM)}, ${rsNum(levelSpans(data)[i])})`).join(', ')}]`
                : kind === 'stops'
                ? `&[${v.map((s) => `(${rsNum(s[fields[k][1]])}, 0x${s.color.slice(1).toLowerCase()})`).join(', ')}]`
                : rsNum(v);
      rs.push(`    ${name}: ${val},`);
    }
  }
  rs.push('};', '');
  return rs.join('\n');
}

const kind0 = ([kind]) => kind;

/** The TypeScript for the shell (written as Prettier writes it: CI checks both). */
export function mapTs(data) {
  const ts = [`// ${mapHeader}`, '', '/** The minimap and the explored map (shared/ui/map.json). */', 'export const MAP = {'];
  for (const [section, fields] of Object.entries(MAP_FIELDS)) {
    ts.push(`  ${section}: {`);
    for (const k of Object.keys(fields)) {
      const v = data[section][k];
      if (kind0(fields[k]) === 'levels') {
        const spans = levelSpans(data);
        ts.push(`    ${k}: [`, ...v.map((lv, i) => `      { cellM: ${lv.cellM}, spanM: ${spans[i]}, reach: '${lv.reach}' },`), '    ],');
      } else if (Array.isArray(v)) {
        const key = fields[k][1];
        ts.push(`    ${k}: [`, ...v.map((s) => `      { ${key}: ${s[key]}, color: '${s.color}' },`), '    ],');
      } else {
        ts.push(`    ${k}: ${typeof v === 'string' ? `'${v}'` : String(v)},`);
      }
    }
    ts.push('  },');
  }
  ts.push('} as const;', '');
  return ts.join('\n');
}

// The HUD's layout (shared/ui/layout.json; client/src/ui/hudLayout.ts places the parts): anchored
// parts with priorities and the regions kept clear, emitted for the shell (`ui/layout.gen.ts`).
const layoutHeader = 'Generated by shared/ui/gen.mjs from shared/ui/layout.json. Do not edit.';
export const ANCHORS = ['top-left', 'top', 'top-right', 'bottom-left', 'bottom', 'bottom-right'];
const PLACEMENT = ['anchor', 'flush', 'after', 'minWidthPx'];
/** Placement used instead on a touch screen, then on a screen wider than tall or taller than wide. */
const OVERRIDES = ['touch', 'landscape', 'portrait'];
const PART_FIELDS = ['id', 'selector', 'anchor', 'priority', 'flush', 'after', 'minWidthPx', 'fixed', 'clearPx', ...OVERRIDES];
const CLEAR_FIELDS = ['id', 'x', 'y', 'touch', 'orientation'];

const layoutFail = (m) => {
  throw new Error(`layout.json: ${m}`);
};

function placement(where, o, ids) {
  if ('anchor' in o && !ANCHORS.includes(o.anchor)) layoutFail(`${where}.anchor must be one of ${ANCHORS.join(', ')}, got ${JSON.stringify(o.anchor)}`);
  if ('flush' in o && typeof o.flush !== 'boolean') layoutFail(`${where}.flush must be true or false`);
  if ('after' in o && !ids.has(o.after)) layoutFail(`${where}.after must name a part listed before it, got ${JSON.stringify(o.after)}`);
  if ('minWidthPx' in o && !(Number.isInteger(o.minWidthPx) && o.minWidthPx >= 0 && o.minWidthPx <= 2000)) layoutFail(`${where}.minWidthPx must be a whole number within 0–2000`);
}

/** Checks the layout; returns it. Throws naming the entry. */
export function validateLayout(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) layoutFail('(root) must be an object');
  for (const k of Object.keys(data)) if (!['$comment', 'gapPx', 'keepClear', 'parts'].includes(k)) layoutFail(`unknown entry ${k}`);
  if (!(Number.isInteger(data.gapPx) && data.gapPx >= 0 && data.gapPx <= 64)) layoutFail('gapPx must be a whole number within 0–64');
  if (!Array.isArray(data.keepClear)) layoutFail('keepClear must be a list');
  data.keepClear.forEach((c, i) => {
    const where = `keepClear[${i}]`;
    if (typeof c !== 'object' || c === null || Array.isArray(c)) layoutFail(`${where} must be an object`);
    for (const k of Object.keys(c)) if (k !== '$comment' && !CLEAR_FIELDS.includes(k)) layoutFail(`unknown entry ${where}.${k}`);
    if (typeof c.id !== 'string' || !/^[a-z]+(-[a-z]+)*$/.test(c.id)) layoutFail(`${where}.id must be lowercase words joined by dashes`);
    for (const axis of ['x', 'y']) {
      const r = c[axis];
      if (!Array.isArray(r) || r.length !== 2 || !r.every((v) => typeof v === 'number' && v >= 0 && v <= 1) || !(r[0] < r[1])) {
        layoutFail(`${where}.${axis} must be [from, to], fractions of the screen with from < to`);
      }
    }
    if (typeof c.touch !== 'boolean') layoutFail(`${where}.touch must be true or false`);
    if (!['landscape', 'portrait', 'any'].includes(c.orientation)) layoutFail(`${where}.orientation must be landscape, portrait or any`);
  });
  if (!Array.isArray(data.parts) || data.parts.length === 0) layoutFail('parts must be a list of parts');
  const ids = new Set();
  data.parts.forEach((p, i) => {
    const where = `parts[${i}]`;
    if (typeof p !== 'object' || p === null || Array.isArray(p)) layoutFail(`${where} must be an object`);
    for (const k of Object.keys(p)) if (k !== '$comment' && !PART_FIELDS.includes(k)) layoutFail(`unknown entry ${where}.${k}`);
    if (typeof p.id !== 'string' || !/^[a-z]+(-[a-z]+)*$/.test(p.id)) layoutFail(`${where}.id must be lowercase words joined by dashes, got ${JSON.stringify(p.id)}`);
    if (ids.has(p.id)) layoutFail(`${where}.id: "${p.id}" is listed twice`);
    if (typeof p.selector !== 'string' || !/^[#.][A-Za-z][\w-]*$/.test(p.selector)) layoutFail(`${where}.selector must be one #id or .class selector, got ${JSON.stringify(p.selector)}`);
    if ('fixed' in p && typeof p.fixed !== 'boolean') layoutFail(`${where}.fixed must be true or false`);
    if (p.fixed) {
      for (const k of [...PLACEMENT, 'priority', ...OVERRIDES]) if (k in p) layoutFail(`${where}.${k}: a fixed part isn't placed`);
      if (!(Number.isInteger(p.clearPx) && p.clearPx >= 0 && p.clearPx <= 400)) layoutFail(`${where}.clearPx must be a whole number within 0–400`);
    } else {
      if ('clearPx' in p) layoutFail(`${where}.clearPx is a fixed part's`);
      if (!('anchor' in p)) layoutFail(`missing entry ${where}.anchor`);
      if (!(Number.isInteger(p.priority) && p.priority >= 0 && p.priority <= 99)) layoutFail(`${where}.priority must be a whole number within 0–99`);
      placement(where, p, ids);
      for (const o of OVERRIDES) {
        if (!(o in p)) continue;
        const t = p[o];
        if (typeof t !== 'object' || t === null || Array.isArray(t)) layoutFail(`${where}.${o} must be an object`);
        for (const k of Object.keys(t)) if (!PLACEMENT.includes(k)) layoutFail(`unknown entry ${where}.${o}.${k}`);
        placement(`${where}.${o}`, t, ids);
      }
    }
    ids.add(p.id);
  });
  return data;
}

