#!/usr/bin/env node
// Generates controller support's data (docs/GAMEPAD.md) for Rust (crates/dwell-game/src/
// gamepad.gen.rs) and the TS shell (client/src/input/gamepad.gen.ts) from shared/input/gamepad.json,
// after validating it: an unknown, missing or out-of-range entry fails with its path named. The
// outputs are checked in; CI regenerates them and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/input/gen.mjs from shared/input/gamepad.json. Do not edit.';

/** The play actions the engine knows (crates/dwell-game/src/gamepad.rs `PlayAction`), in its order. */
export const PLAY_ACTIONS = [
  'jump',
  'crouch',
  'run',
  'break',
  'place',
  'hotbarNext',
  'hotbarPrev',
  'fly',
  'flyFaster',
  'flySlower',
  'spyglass',
  'map',
  'pause',
];
/** The menu actions the shell knows (client/src/input/gamepadMenu.ts). */
export const MENU_ACTIONS = ['up', 'down', 'left', 'right', 'confirm', 'back', 'close'];
const STICKS = ['moveX', 'moveY', 'lookX', 'lookY'];
const TUNABLES = {
  deadzone: [0, 0.9],
  lookDegPerS: [1, 2000],
  lookCurve: [0.5, 4],
  triggerThreshold: [0.05, 0.95],
  menuRepeatMs: [20, 2000],
  menuRepeatDelayMs: [20, 5000],
};
/** The standard mapping has 17 buttons (0–16) and 4 axes. */
const MAX_BUTTON = 16;
const MAX_AXIS = 3;

const fail = (m) => {
  throw new Error(`gamepad.json: ${m}`);
};
const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);
const keysOf = (o) => Object.keys(o).filter((k) => k !== '$comment');

/** Checks the data; returns it. Throws naming the entry. */
export function validateGamepad(data) {
  if (!isObject(data)) fail('must be an object');
  const extra = keysOf(data).filter((k) => !['buttons', 'sticks', 'play', 'menu', 'tunables'].includes(k));
  if (extra.length) fail(`unknown ${extra.join(', ')}`);
  if (!Array.isArray(data.buttons) || data.buttons.length === 0) fail('buttons must be a list');
  const names = new Set();
  const indices = new Set();
  data.buttons.forEach((b, i) => {
    const at = `buttons[${i}]`;
    if (!isObject(b)) fail(`${at} must be an object`);
    const e = keysOf(b).filter((k) => !['name', 'label', 'index'].includes(k));
    if (e.length) fail(`${at}: unknown ${e.join(', ')}`);
    if (typeof b.name !== 'string' || !/^[a-z][a-z0-9]*$/.test(b.name)) fail(`${at}.name must be lowercase letters and digits`);
    if (typeof b.label !== 'string' || b.label === '') fail(`${at}.label must be a name to show`);
    if (!Number.isInteger(b.index) || b.index < 0 || b.index > MAX_BUTTON) fail(`${at}.index must be a whole number in [0, ${MAX_BUTTON}]`);
    if (names.has(b.name)) fail(`${at}.name ${b.name} is listed twice`);
    if (indices.has(b.index)) fail(`${at}.index ${b.index} is listed twice`);
    names.add(b.name);
    indices.add(b.index);
  });
  if (!isObject(data.sticks)) fail('sticks must be an object');
  for (const k of keysOf(data.sticks)) if (!STICKS.includes(k)) fail(`sticks: unknown ${k}`);
  for (const k of STICKS) {
    const v = data.sticks[k];
    if (!Number.isInteger(v) || v < 0 || v > MAX_AXIS) fail(`sticks.${k} must be an axis in [0, ${MAX_AXIS}]`);
  }
  const bindings = (group, actions) => {
    const g = data[group];
    if (!isObject(g)) fail(`${group} must be an object`);
    for (const k of keysOf(g)) if (!actions.includes(k)) fail(`${group}: unknown action ${k} (known: ${actions.join(', ')})`);
    const used = new Map();
    for (const a of actions) {
      const b = g[a];
      if (typeof b !== 'string') fail(`${group}.${a} must name a button`);
      if (!names.has(b)) fail(`${group}.${a}: ${JSON.stringify(b)} is not in buttons`);
      if (used.has(b)) fail(`${group}.${a}: ${b} is already ${group}.${used.get(b)}`);
      used.set(b, a);
    }
  };
  bindings('play', PLAY_ACTIONS);
  bindings('menu', MENU_ACTIONS);
  if (!isObject(data.tunables)) fail('tunables must be an object');
  for (const k of keysOf(data.tunables)) if (!(k in TUNABLES)) fail(`tunables: unknown ${k}`);
  for (const [k, [min, max]] of Object.entries(TUNABLES)) {
    const v = data.tunables[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < min || v > max) fail(`tunables.${k} must be in [${min}, ${max}]`);
  }
  return data;
}

const rf = (n) => (Number.isInteger(n) ? `${n}.0` : `${n}`);
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

/** The Rust tables. */
export function gamepadRust(data) {
  const t = data.tunables;
  const rs = [`// ${header}`, '', 'use crate::gamepad::{Button, GamepadTunables, Sticks};', ''];
  rs.push('/// The standard mapping\'s buttons: name, label, index.');
  rs.push(`pub const BUTTONS: [Button; ${data.buttons.length}] = [`);
  for (const b of data.buttons) rs.push(`    Button { name: ${JSON.stringify(b.name)}, label: ${JSON.stringify(b.label)}, index: ${b.index} },`);
  rs.push('];', '');
  rs.push('/// The play actions\' default buttons, in `PlayAction` order (by name).');
  rs.push(`pub const PLAY: [(&str, &str); ${PLAY_ACTIONS.length}] = [`);
  for (const a of PLAY_ACTIONS) rs.push(`    (${JSON.stringify(a)}, ${JSON.stringify(data.play[a])}),`);
  rs.push('];', '');
  const s = data.sticks;
  rs.push(`pub const STICKS: Sticks = Sticks { move_x: ${s.moveX}, move_y: ${s.moveY}, look_x: ${s.lookX}, look_y: ${s.lookY} };`, '');
  rs.push('pub const TUNABLES: GamepadTunables = GamepadTunables {');
  for (const k of Object.keys(TUNABLES)) rs.push(`    ${snake(k)}: ${rf(t[k])},`);
  rs.push('};', '');
  return rs.join('\n');
}

/** The TS module. */
export function gamepadTs(data) {
  const plain = {
    buttons: data.buttons,
    sticks: data.sticks,
    play: Object.fromEntries(PLAY_ACTIONS.map((a) => [a, data.play[a]])),
    menu: Object.fromEntries(MENU_ACTIONS.map((a) => [a, data.menu[a]])),
    tunables: Object.fromEntries(Object.keys(TUNABLES).map((k) => [k, data.tunables[k]])),
  };
  return [
    `// ${header}`,
    '',
    `export const PLAY_ACTIONS = ${JSON.stringify(PLAY_ACTIONS)} as const;`,
    'export type PlayAction = (typeof PLAY_ACTIONS)[number];',
    `export const MENU_ACTIONS = ${JSON.stringify(MENU_ACTIONS)} as const;`,
    'export type MenuAction = (typeof MENU_ACTIONS)[number];',
    '',
    `export const GAMEPAD = ${JSON.stringify(plain, null, 2)} as const;`,
    '',
  ].join('\n');
}

export function loadGamepad() {
  return JSON.parse(readFileSync(join(here, 'gamepad.json'), 'utf8'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateGamepad(loadGamepad());
  writeFileSync(join(root, 'crates/dwell-game/src/gamepad.gen.rs'), gamepadRust(data));
  writeFileSync(join(root, 'client/src/input/gamepad.gen.ts'), gamepadTs(data));
  console.log(`input: ${data.buttons.length} buttons, ${PLAY_ACTIONS.length} play and ${MENU_ACTIONS.length} menu actions generated`);
}
