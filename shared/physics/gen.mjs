#!/usr/bin/env node
// Generates the felling tunables (docs/FELLING.md §5) for Rust (crates/dwell-sim/src/felling.gen.rs)
// from shared/physics/felling.json, after validating them: an unknown, missing or out-of-range
// entry fails with its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/physics/gen.mjs from shared/physics/felling.json. Do not edit.';

/** Field → [min, max, integer?]. */
export const FELLING_RANGES = {
  riderReach: [0, 64, true],
  maxSystemCells: [1, 1 << 20, true],
  maxPieceCells: [1, 4096, true],
  toppleSpin: [0, 10, false],
  toppleTipSpeed: [0, 100, false],
  sleepLinear: [0, 10, false],
  sleepAngular: [0, 10, false],
  sleepSeconds: [0, 60, false],
  maxSeconds: [1, 600, false],
  maxSettles: [1, 255, true],
  hitSpeed: [0, 100, false],
  hitDamagePerSpeed: [0, 100, false],
  holdSpeed: [0, 100, false],
  pushHoldSeconds: [0, 10, false],
  settleGlideSeconds: [0, 2, false],
  settleBounce: [0, 1, false],
  terrainChunksPerTick: [1, 4096, true],
};

const fail = (m) => {
  throw new Error(`felling.json: ${m}`);
};

/** Checks the tunables; returns them. Throws naming the entry. */
export function validateFelling(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  const keys = Object.keys(FELLING_RANGES);
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry (root).${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry (root).${k}`);
  for (const [k, [lo, hi, int]] of Object.entries(FELLING_RANGES)) {
    const v = data[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi || (int && !Number.isInteger(v))) {
      fail(`${k} must be ${int ? 'a whole number' : 'a number'} in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  }
  return data;
}

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

/** The Rust source for validated tunables. */
export function fellingRust(data) {
  const lines = [`// ${header}`, '', 'use crate::felling::FellingData;', ''];
  lines.push('/// The felling tunables (shared/physics/felling.json).');
  lines.push('pub const FELLING: FellingData = FellingData {');
  for (const [k, [, , int]] of Object.entries(FELLING_RANGES)) {
    lines.push(`    ${snake(k)}: ${int ? String(data[k]) : rf(data[k])},`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

/** The registry's block names (`dwell:stone`), from shared/blocks/dwell.json. */
export function registryBlockNames() {
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  return new Set(ns.blocks.map((b) => `${ns.namespace}:${b.name}`));
}

/** A body kind's rules (docs/BUILT_BODIES.md §2): the engine's vocabulary. */
export const KIND_RULES = ['place', 'break', 'split', 'settles', 'saved'];
const bodiesHeader = 'Generated by shared/physics/gen.mjs from shared/physics/bodies.json. Do not edit.';

/** Checks the body kinds; returns them. Throws naming the entry. */
export function validateBodies(data, blocks = registryBlockNames()) {
  const bad = (m) => {
    throw new Error(`bodies.json: ${m}`);
  };
  if (typeof data !== 'object' || data === null || Array.isArray(data)) bad('(root) must be an object');
  for (const k of Object.keys(data)) if (!['$comment', 'kinds', 'water'].includes(k)) bad(`unknown entry (root).${k}`);
  const w = data.water;
  if (typeof w !== 'object' || w === null || Array.isArray(w)) bad('water must be an object');
  for (const k of Object.keys(w)) if (!['drag', 'angularDrag'].includes(k)) bad(`water: unknown ${k}`);
  for (const k of ['drag', 'angularDrag']) {
    if (typeof w[k] !== 'number' || !(w[k] >= 0 && w[k] <= 50)) bad(`water.${k} must be a number in [0, 50] (/s)`);
  }
  if (!Array.isArray(data.kinds) || data.kinds.length === 0) bad('kinds must be a non-empty list');
  if (data.kinds.length > 256) bad('kinds: at most 256 (the wire has a byte)');
  const names = new Set();
  const starters = new Map();
  data.kinds.forEach((k, i) => {
    const at = `kinds[${i}]`;
    if (typeof k !== 'object' || k === null || Array.isArray(k)) bad(`${at} must be an object`);
    for (const key of Object.keys(k)) if (!['$comment', 'name', 'builtOn', ...KIND_RULES].includes(key)) bad(`${at}: unknown ${key}`);
    if (typeof k.name !== 'string' || !/^[a-z][a-z0-9_]*$/.test(k.name)) bad(`${at}.name must be a lower-case name`);
    if (names.has(k.name)) bad(`${at}.name ${k.name} is listed twice`);
    names.add(k.name);
    for (const r of KIND_RULES) if (typeof k[r] !== 'boolean') bad(`${at}.${r} must be true or false`);
    const started = k.builtOn ?? [];
    if (!Array.isArray(started)) bad(`${at}.builtOn must be a list of block names`);
    for (const b of started) {
      if (!blocks.has(b)) bad(`${at}.builtOn: ${JSON.stringify(b)} is not a block of the registry`);
      if (starters.has(b)) bad(`${at}.builtOn: ${b} already builds ${starters.get(b)}`);
      starters.set(b, k.name);
    }
  });
  if (data.kinds[0].name !== 'natural') bad('kinds[0] must be natural (the pieces felling makes; kind 0 on the wire)');
  return data;
}

/** The Rust source for validated body kinds. */
export function bodiesRust(data) {
  const lines = [`// ${bodiesHeader}`, '', 'use crate::felling::{BodyKind, WaterRules};', ''];
  const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
  lines.push('/// How bodies float (shared/physics/bodies.json `water`).');
  lines.push(`pub const WATER: WaterRules = WaterRules { drag: ${rf(data.water.drag)}, angular_drag: ${rf(data.water.angularDrag)} };`, '');
  lines.push('/// The body kinds, in wire order (shared/physics/bodies.json).');
  lines.push(`pub const BODY_KINDS: [BodyKind; ${data.kinds.length}] = [`);
  for (const k of data.kinds) {
    const started = `&[${(k.builtOn ?? []).map((b) => JSON.stringify(b)).join(', ')}]`;
    lines.push(`    BodyKind { name: ${JSON.stringify(k.name)}, ${KIND_RULES.map((r) => `${r === 'break' ? 'breaks' : r}: ${k[r]}`).join(', ')}, built_on: ${started} },`);
  }
  lines.push('];', '');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateFelling(JSON.parse(readFileSync(join(here, 'felling.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-sim/src/felling.gen.rs'), fellingRust(data));
  const bodies = validateBodies(JSON.parse(readFileSync(join(here, 'bodies.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-sim/src/bodies.gen.rs'), bodiesRust(bodies));
  console.log('physics: felling tunables and body kinds generated');
}
