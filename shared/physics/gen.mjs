#!/usr/bin/env node
// Generates the felling tunables (docs/FELLING.md §5) for Rust (crates/dwell-sim/src/felling.gen.rs)
// from shared/physics/felling.json, after validating them: an unknown, missing or out-of-range
// entry fails with its path named. The output is checked in; CI regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/physics/gen.mjs from shared/physics/felling.json. Do not edit.';

/** Field → [min, max, integer?]. */
export const FELLING_RANGES = {
  riderReach: [0, 64, true],
  maxSystemCells: [1, 1 << 20, true],
  maxPieceCells: [1, 4096, true],
  toppleSpin: [0, 10, false],
  sleepLinear: [0, 10, false],
  sleepAngular: [0, 10, false],
  sleepSeconds: [0, 60, false],
  maxSeconds: [1, 600, false],
  maxSettles: [1, 255, true],
  hitSpeed: [0, 100, false],
  hitDamagePerSpeed: [0, 100, false],
  pushableMass: [0, 1e7, false],
  heavyHoldSpeed: [0, 100, false],
  settleGlideSeconds: [0, 2, false],
  settleBounce: [0, 1, false],
  terrainChunksPerTick: [1, 4096, true],
};

const fail = (m) => {
  throw new Error(`felling.json: ${m}`);
};

/** Checks the tunables; returns them. Throws naming the entry. */
export function validateFelling(data) {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) fail('(root) must be an object');
  const keys = Object.keys(FELLING_RANGES);
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) fail(`unknown entry (root).${k}`);
  for (const k of keys) if (!(k in data)) fail(`missing entry (root).${k}`);
  for (const [k, [lo, hi, int]] of Object.entries(FELLING_RANGES)) {
    const v = data[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi || (int && !Number.isInteger(v))) {
      fail(`${k} must be ${int ? 'a whole number' : 'a number'} in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  }
  return data;
}

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

/** The Rust source for validated tunables. */
export function fellingRust(data) {
  const lines = [`// ${header}`, '', 'use crate::felling::FellingData;', ''];
  lines.push('/// The felling tunables (shared/physics/felling.json).');
  lines.push('pub const FELLING: FellingData = FellingData {');
  for (const [k, [, , int]] of Object.entries(FELLING_RANGES)) {
    lines.push(`    ${snake(k)}: ${int ? String(data[k]) : rf(data[k])},`);
  }
  lines.push('};', '');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateFelling(JSON.parse(readFileSync(join(here, 'felling.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-sim/src/felling.gen.rs'), fellingRust(data));
  console.log('physics: felling tunables generated');
}
