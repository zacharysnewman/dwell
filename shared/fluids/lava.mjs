#!/usr/bin/env node
// Generates lava's data (docs/proposals/VOLCANOES.md §6, phase V1) for Rust from shared/fluids/lava.json:
// `crates/dwell-lava/src/lava.gen.rs` (the hot fluids' surface grid), and from
// shared/fluids/fixtures/lava.json `lava_fixture.gen.rs` (tests only: a fluid and vents added by data
// alone). Fluids and vents are named (`ns:name`); a vent names its fluid, a fluid its rocks (blocks of
// the registry, shared/blocks/dwell.json). The output is checked in; CI regenerates it and fails on any
// diff (`--check` fails here without writing). A bad entry fails with a message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = (src) => `Generated by shared/fluids/lava.mjs from ${src}. Do not edit.`;

/** Top field → [min, max, integer?]. */
export const TOP_RANGES = {
  speed: [0.01, 100, false],
  tickEvery: [1, 600, true],
  nearRadiusM: [1, 4096, false],
  farEverySeconds: [0.1, 3600, false],
  cfl: [0.05, 1, false],
  maxSubsteps: [1, 1000000, true],
  stepDepthM: [0.1, 1000, false],
  maxTiles: [1, 65536, true],
};
/** Fluid field → [min, max, integer?]. */
export const FLUID_RANGES = {
  viscosityM2s: [0.01, 1000, false],
  yieldDepthM: [0, 2, false],
  coolingSeconds: [1, 86400, false],
  edgeCooling: [0, 20, false],
  thinDepthM: [0, 4, false],
  tubeSpeedMs: [0.0001, 1000, false],
  breakoutDepthM: [0, 100, false],
  light: [0, 15, true],
  damagePerSecond: [0, 1000, false],
  burnSeconds: [0, 60, false],
  burnDamagePerSecond: [0, 1000, false],
};
/** What a vent does: the engine's fixed vocabulary (`dwell_lava::VentKind`). */
export const VENT_KINDS = ['lake', 'river'];
const VENT_FIELDS = ['name', 'fluid', 'kind', 'x', 'z', 'rateM3s', 'levelM'];
const NAMESPACED = /^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$/;
const COLOR = /^#[0-9a-f]{6}$/;
/** The clients' looks (VOLCANOES.md §6.3), optional (a fixture takes these): steam's puffs where
 * lava boils water away, and the screen's edge while a player burns. */
export const LOOK_DEFAULTS = {
  steam: { color: '#f2f4f6', seconds: 1.6, riseMs: 1.6, sizeM: [0.4, 1.6], opacity: 0.75 },
  burnEdge: { color: '#ff5a1e', opacity: 0.6, seconds: 0.9 },
  heat: [{ name: 'hot', above: 0, color: '#ff5a14', core: '#ffa030', intensity: 1.6, crust: 0.5 }],
  heatHysteresis: 0.03,
};
/** A heat stop's name: the value of lava's `heat` block property it would be written as. */
const STOP_NAME = /^[a-z][a-z0-9_]*$/;

/** The registry's block names, from shared/blocks/dwell.json. */
export function registryBlocks() {
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  return new Set(ns.blocks.map((b) => `${ns.namespace}:${b.name}`));
}

/** Each registry block's `heat` property values (lava's look by heat), by block name. */
export function registryHeat() {
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  return new Map(ns.blocks.filter((b) => b.properties?.heat).map((b) => [`${ns.namespace}:${b.name}`, b.properties.heat]));
}

const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);

/**
 * Checks lava data; returns it. `known` names fluids a vent may name besides the file's own (a
 * fixture's vents may use the build's lava). Throws naming the entry.
 */
export function validateLava(data, { blocks = registryBlocks(), heatProps = registryHeat(), known = [], file = 'lava.json' } = {}) {
  const bad = (m) => {
    throw new Error(`${file}: ${m}`);
  };
  const keys = (o, at, allowed) => {
    if (!isObject(o)) bad(`${at} must be an object`);
    for (const k of Object.keys(o)) if (k[0] !== '$' && !allowed.includes(k)) bad(`${at}: unknown field ${k} (${allowed.join(', ')})`);
  };
  const range = (o, at, k, [lo, hi, int]) => {
    const v = o[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi || (int && !Number.isInteger(v))) {
      bad(`${at}.${k} must be ${int ? 'a whole number' : 'a number'} in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  };
  const block = (at, v) => {
    if (!blocks.has(v)) bad(`${at}: ${JSON.stringify(v)} is not a block of the registry`);
  };
  keys(data, '(root)', ['formatVersion', ...Object.keys(TOP_RANGES), 'fluids', 'vents', 'steam', 'burnEdge', 'heat', 'heatHysteresis']);
  const color = (at, v) => {
    if (typeof v !== 'string' || !COLOR.test(v)) bad(`${at} must be a colour #rrggbb, got ${JSON.stringify(v)}`);
  };
  if (data.steam !== undefined) {
    keys(data.steam, 'steam', ['color', 'seconds', 'riseMs', 'sizeM', 'opacity']);
    color('steam.color', data.steam.color);
    range(data.steam, 'steam', 'seconds', [0.1, 20, false]);
    range(data.steam, 'steam', 'riseMs', [0, 20, false]);
    range(data.steam, 'steam', 'opacity', [0, 1, false]);
    const z = data.steam.sizeM;
    if (!Array.isArray(z) || z.length !== 2 || !z.every((v) => typeof v === 'number' && v > 0 && v <= 10) || z[0] > z[1]) {
      bad(`steam.sizeM must be [birth, end] metres (0, 10], birth ≤ end, got ${JSON.stringify(z)}`);
    }
  }
  if (data.burnEdge !== undefined) {
    keys(data.burnEdge, 'burnEdge', ['color', 'opacity', 'seconds']);
    color('burnEdge.color', data.burnEdge.color);
    range(data.burnEdge, 'burnEdge', 'opacity', [0, 1, false]);
    range(data.burnEdge, 'burnEdge', 'seconds', [0.05, 10, false]);
  }
  if (data.heat !== undefined) {
    if (!Array.isArray(data.heat) || data.heat.length === 0) bad('heat must be a non-empty list of stops, hottest first');
    const seen = new Set();
    data.heat.forEach((h, i) => {
      const at = typeof h?.name === 'string' ? `heat.${h.name}` : `heat[${i}]`;
      keys(h, at, ['name', 'above', 'color', 'core', 'intensity', 'crust']);
      if (typeof h.name !== 'string' || !STOP_NAME.test(h.name)) bad(`${at}.name must be lower_snake_case`);
      if (seen.has(h.name)) bad(`${at}: listed twice`);
      seen.add(h.name);
      range(h, at, 'above', [0, 1, false]);
      color(`${at}.color`, h.color);
      color(`${at}.core`, h.core);
      range(h, at, 'intensity', [0, 16, false]);
      range(h, at, 'crust', [0, 1, false]);
      if (i > 0 && !(h.above < data.heat[i - 1].above)) bad(`${at}.above must be below the hotter stop's (${data.heat[i - 1].above}): stops run hottest first`);
    });
    if (data.heat[data.heat.length - 1].above !== 0) bad(`heat: the coolest stop's above must be 0 (every molten column has a stop)`);
  }
  if (data.heatHysteresis !== undefined) range(data, '(root)', 'heatHysteresis', [0, 0.5, false]);
  if (data.formatVersion !== 1) bad(`formatVersion must be 1, not ${JSON.stringify(data.formatVersion)}`);
  for (const [k, r] of Object.entries(TOP_RANGES)) range(data, '(root)', k, r);
  if (!Array.isArray(data.fluids) || data.fluids.length === 0) bad('fluids must be a non-empty list');
  const names = new Set();
  data.fluids.forEach((l, i) => {
    const at = typeof l?.name === 'string' ? `fluids.${l.name}` : `fluids[${i}]`;
    keys(l, at, ['name', ...Object.keys(FLUID_RANGES), 'rock', 'quench']);
    if (typeof l.name !== 'string' || !NAMESPACED.test(l.name)) bad(`${at}.name must be namespaced (ns:name)`);
    if (names.has(l.name)) bad(`${at}: listed twice`);
    names.add(l.name);
    for (const [k, r] of Object.entries(FLUID_RANGES)) range(l, at, k, r);
    block(`${at}.rock`, l.rock);
    keys(l.quench, `${at}.quench`, ['rock', 'steamWaterM']);
    block(`${at}.quench.rock`, l.quench.rock);
    range(l.quench, `${at}.quench`, 'steamWaterM', [0, 16, false]);
  });
  // A fluid's block with a `heat` property is written by stop name: its values are the stops'.
  const stops = (data.heat ?? LOOK_DEFAULTS.heat).map((h) => h.name);
  for (const l of data.fluids) {
    const vals = heatProps.get(l.name);
    if (vals && JSON.stringify(vals) !== JSON.stringify(stops)) {
      bad(`fluids.${l.name}: its block's heat property ${JSON.stringify(vals)} must be the heat stops' names in order ${JSON.stringify(stops)}`);
    }
  }
  const fluids = new Set([...known, ...names]);
  const vents = data.vents ?? [];
  if (!Array.isArray(vents)) bad('vents must be a list');
  const ventNames = new Set();
  vents.forEach((v, i) => {
    const at = typeof v?.name === 'string' ? `vents.${v.name}` : `vents[${i}]`;
    keys(v, at, VENT_FIELDS);
    if (typeof v.name !== 'string' || !NAMESPACED.test(v.name)) bad(`${at}.name must be namespaced (ns:name)`);
    if (ventNames.has(v.name)) bad(`${at}: listed twice`);
    ventNames.add(v.name);
    if (!fluids.has(v.fluid)) bad(`${at}.fluid: ${JSON.stringify(v.fluid)} is not a hot fluid (${[...fluids].join(', ')})`);
    if (!VENT_KINDS.includes(v.kind)) bad(`${at}.kind: ${JSON.stringify(v.kind)} is not one of ${VENT_KINDS.join(', ')}`);
    range(v, at, 'x', [0, 65535, true]);
    range(v, at, 'z', [0, 65535, true]);
    range(v, at, 'rateM3s', [0.001, 1000, false]);
    if (v.kind === 'lake') range(v, at, 'levelM', [-4096, 4096, false]);
    else if (v.levelM !== undefined) bad(`${at}.levelM: only a lake vent holds a level`);
  });
  return data;
}

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
const kind = (k) => k[0].toUpperCase() + k.slice(1);

/** The Rust source for validated lava data, as the constant `name`. */
export function lavaRust(data, { name = 'DATA', src = 'shared/fluids/lava.json' } = {}) {
  const lines = [`// ${header(src)}`, '', '#[allow(unused_imports)]', 'use crate::data::{BurnEdge, HeatStop, HotFluid, LavaData, Quench, SteamLook, VentDef, VentKind};', ''];
  lines.push(`/// Lava's data (${src}).`);
  lines.push(`pub const ${name}: LavaData = LavaData {`);
  for (const [k, [, , int]] of Object.entries(TOP_RANGES)) lines.push(`    ${snake(k)}: ${int ? String(data[k]) : rf(data[k])},`);
  lines.push('    fluids: &[');
  for (const l of data.fluids) {
    lines.push('        HotFluid {');
    lines.push(`            name: ${JSON.stringify(l.name)},`);
    for (const [k, [, , int]] of Object.entries(FLUID_RANGES)) lines.push(`            ${snake(k)}: ${int ? String(l[k]) : rf(l[k])},`);
    lines.push(`            rock: ${JSON.stringify(l.rock)},`);
    lines.push(`            quench: Quench { rock: ${JSON.stringify(l.quench.rock)}, steam_water_m: ${rf(l.quench.steamWaterM)} },`);
    lines.push('        },');
  }
  lines.push('    ],');
  lines.push('    vents: &[');
  for (const v of data.vents ?? []) {
    lines.push(
      `        VentDef { name: ${JSON.stringify(v.name)}, fluid: ${JSON.stringify(v.fluid)}, kind: VentKind::${kind(v.kind)}, x: ${v.x}, z: ${v.z}, rate_m3s: ${rf(v.rateM3s)}, level_m: ${rf(v.levelM ?? 0)} },`,
    );
  }
  lines.push('    ],');
  const st = data.steam ?? LOOK_DEFAULTS.steam;
  const be = data.burnEdge ?? LOOK_DEFAULTS.burnEdge;
  lines.push(
    `    steam: SteamLook { color: ${JSON.stringify(st.color)}, seconds: ${rf(st.seconds)}, rise_ms: ${rf(st.riseMs)}, size_m: [${rf(st.sizeM[0])}, ${rf(st.sizeM[1])}], opacity: ${rf(st.opacity)} },`,
  );
  lines.push(`    burn_edge: BurnEdge { color: ${JSON.stringify(be.color)}, opacity: ${rf(be.opacity)}, seconds: ${rf(be.seconds)} },`);
  lines.push('    heat: &[');
  for (const h of data.heat ?? LOOK_DEFAULTS.heat) {
    lines.push(`        HeatStop { name: ${JSON.stringify(h.name)}, above: ${rf(h.above)}, color: ${JSON.stringify(h.color)}, core: ${JSON.stringify(h.core)}, intensity: ${rf(h.intensity)}, crust: ${rf(h.crust)} },`);
  }
  lines.push('    ],');
  lines.push(`    heat_hysteresis: ${rf(data.heatHysteresis ?? LOOK_DEFAULTS.heatHysteresis)},`);
  lines.push('};', '');
  return lines.join('\n');
}

/** Both outputs: [path relative to the repository, source]. */
export function outputs() {
  const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
  const data = validateLava(read('shared/fluids/lava.json'));
  const fixture = validateLava(read('shared/fluids/fixtures/lava.json'), {
    known: data.fluids.map((l) => l.name),
    file: 'fixtures/lava.json',
  });
  return [
    ['crates/dwell-lava/src/lava.gen.rs', lavaRust(data)],
    ['crates/dwell-lava/src/lava_fixture.gen.rs', lavaRust(fixture, { name: 'FIXTURE', src: 'shared/fluids/fixtures/lava.json' })],
  ];
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [p, src] of outputs()) {
    const full = join(root, p);
    if (check) {
      let now = '';
      try {
        now = readFileSync(full, 'utf8');
      } catch {}
      if (now !== src) {
        console.error(`lava: ${p} is stale; run node shared/fluids/lava.mjs`);
        stale = true;
      }
    } else writeFileSync(full, src);
  }
  if (stale) process.exit(1);
  console.log(`lava: data ${check ? 'checked' : 'generated'}`);
}
