#!/usr/bin/env node
// Generates the waterfalls' detection and push data (docs/WATER_SURFACE_GRID.md §2e) for Rust
// (crates/dwell-world/src/falls.gen.rs) from shared/fluids/falls.json, after validating it: an unknown,
// missing or out-of-range entry fails with its path named. The output is checked in; CI regenerates it
// and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/fluids/falls.mjs from shared/fluids/falls.json. Do not edit.';

/** Field → [min, max]. */
export const FALLS_RANGES = {
  minSpeedMs: [0, 20],
  minFlowM2s: [0, 20],
  minDropM: [0.1, 64],
  maxDropM: [0.5, 256],
  mergeM: [0, 4],
  reachM: [0.1, 4],
  fullFlowM2s: [0.001, 100],
  pushOutMs: [0, 50],
  pushDownMs: [0, 50],
  pushRate: [0, 100],
};

/** Checks the falls data; returns it. Throws naming the entry. */
export function validateFalls(data) {
  const bad = (m) => {
    throw new Error(`falls.json: ${m}`);
  };
  if (typeof data !== 'object' || data === null || Array.isArray(data)) bad('(root) must be an object');
  for (const k of Object.keys(data)) if (k !== '$comment' && !(k in FALLS_RANGES)) bad(`unknown entry (root).${k}`);
  for (const [k, [lo, hi]] of Object.entries(FALLS_RANGES)) {
    const v = data[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi) {
      bad(`${k} must be a number in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  }
  if (data.maxDropM <= data.minDropM) bad('maxDropM must be above minDropM');
  return data;
}

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

/** The Rust source for validated falls data. */
export function fallsRust(data) {
  const lines = [`// ${header}`, '', 'use crate::falls::FallsData;', ''];
  lines.push("/// The waterfalls' data (shared/fluids/falls.json).");
  lines.push('pub const FALLS: FallsData = FallsData {');
  for (const k of Object.keys(FALLS_RANGES)) lines.push(`    ${snake(k)}: ${rf(data[k])},`);
  lines.push('};', '');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateFalls(JSON.parse(readFileSync(join(here, 'falls.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-world/src/falls.gen.rs'), fallsRust(data));
  console.log('fluids: falls data generated');
}
