#!/usr/bin/env node
// Generates the water grid's data (docs/WATER_SURFACE_GRID.md §4) for Rust (crates/dwell-world/src/flow.gen.rs)
// from shared/fluids/flow.json, after validating it: an unknown, missing or out-of-range entry, or a
// block the registry doesn't have, fails with its path named. The output is checked in; CI
// regenerates it and fails on any diff.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const header = 'Generated by shared/fluids/gen.mjs from shared/fluids/flow.json. Do not edit.';

/** Field → [min, max, integer?]. */
export const FLOW_RANGES = {
  speed: [0, 1000, false],
  tickEvery: [1, 600, true],
  theta: [0.5, 1, false],
  cfl: [0.05, 1, false],
  maxSubsteps: [1, 100000, true],
  stepBudget: [256, 100000000, true],
  threadStepBudget: [256, 1000000000, true],
  maxOwedS: [0, 36000, false],
  sleepBandM: [0.0001, 0.5, false],
  wakeBandM: [0.001, 5, false],
  calmS: [0.1, 3600, false],
  releaseS: [0, 3600, false],
  jumpM2s: [0.001, 100, false],
  releaseM: [0.001, 5, false],
  editReach: [0, 64, true],
  fillHysteresis: [0, 0.5, false],
  currentStillMs: [0, 10, false],
  currentDepthM: [0, 10, false],
  riverCurrentMaxMs: [0, 20, false],
};

/** The registry's blocks (name → liquid?), from shared/blocks/dwell.json. */
export function registryBlocks() {
  const ns = JSON.parse(readFileSync(join(root, 'shared/blocks/dwell.json'), 'utf8'));
  return new Map(ns.blocks.map((b) => [`${ns.namespace}:${b.name}`, b.liquid === true]));
}

/** Checks the flow data; returns it. Throws naming the entry. */
export function validateFlow(data, blocks = registryBlocks()) {
  const bad = (m) => {
    throw new Error(`flow.json: ${m}`);
  };
  if (typeof data !== 'object' || data === null || Array.isArray(data)) bad('(root) must be an object');
  const keys = [...Object.keys(FLOW_RANGES), 'liquids'];
  for (const k of Object.keys(data)) if (k !== '$comment' && !keys.includes(k)) bad(`unknown entry (root).${k}`);
  for (const [k, [lo, hi, int]] of Object.entries(FLOW_RANGES)) {
    const v = data[k];
    if (typeof v !== 'number' || !Number.isFinite(v) || v < lo || v > hi || (int && !Number.isInteger(v))) {
      bad(`${k} must be ${int ? 'a whole number' : 'a number'} in [${lo}, ${hi}], got ${JSON.stringify(v)}`);
    }
  }
  if (!Array.isArray(data.liquids) || data.liquids.length === 0) bad('liquids must be a non-empty list');
  const seen = new Set();
  data.liquids.forEach((l, i) => {
    const at = `liquids[${i}]`;
    if (typeof l !== 'object' || l === null || Array.isArray(l)) bad(`${at} must be an object`);
    for (const k of Object.keys(l)) if (!['$comment', 'block', 'manning', 'weir', 'running'].includes(k)) bad(`${at}: unknown ${k}`);
    if (!blocks.has(l.running)) bad(`${at}.running: ${JSON.stringify(l.running)} is not a block of the registry`);
    if (!blocks.get(l.running)) bad(`${at}.running: ${l.running} is not a liquid`);
    if (l.running === l.block) bad(`${at}.running: must not be the liquid's own block`);
    if (!blocks.has(l.block)) bad(`${at}.block: ${JSON.stringify(l.block)} is not a block of the registry`);
    if (!blocks.get(l.block)) bad(`${at}.block: ${l.block} is not a liquid`);
    if (seen.has(l.block)) bad(`${at}.block: ${l.block} is listed twice`);
    seen.add(l.block);
    if (typeof l.weir !== 'number' || !(l.weir > 0 && l.weir <= 10)) bad(`${at}.weir must be a number in (0, 10]`);
    if (typeof l.manning !== 'number' || !(l.manning >= 0.005 && l.manning <= 0.5)) {
      bad(`${at}.manning must be a number in [0.005, 0.5]`);
    }
  });
  if (data.wakeBandM < data.sleepBandM) bad('wakeBandM must be at least sleepBandM');
  if (data.threadStepBudget < data.stepBudget) bad('threadStepBudget must be at least stepBudget');
  return data;
}

const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const rf = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));

/** The Rust source for validated flow data. */
export function flowRust(data) {
  const lines = [`// ${header}`, '', 'use crate::flow::{FlowData, LiquidFlow};', ''];
  lines.push('/// The water grid\'s data (shared/fluids/flow.json).');
  lines.push('pub const FLOW: FlowData = FlowData {');
  for (const [k, [, , int]] of Object.entries(FLOW_RANGES)) {
    lines.push(`    ${snake(k)}: ${int ? String(data[k]) : rf(data[k])},`);
  }
  lines.push('    liquids: &[');
  for (const l of data.liquids) {
    lines.push(
      `        LiquidFlow { block: ${JSON.stringify(l.block)}, manning: ${rf(l.manning)}, weir: ${rf(l.weir)}, running: ${JSON.stringify(l.running)} },`,
    );
  }
  lines.push('    ],');
  lines.push('};', '');
  return lines.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = validateFlow(JSON.parse(readFileSync(join(here, 'flow.json'), 'utf8')));
  writeFileSync(join(root, 'crates/dwell-world/src/flow.gen.rs'), flowRust(data));
  console.log('fluids: flow data generated');
}
