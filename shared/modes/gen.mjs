#!/usr/bin/env node
// Generates the game modes (docs/adr/0065-game-modes.md) for Rust and TypeScript from
// shared/modes/modes.json: `crates/dwell-protocol/src/modes.gen.rs` (the server, the sim core and the
// client read a world's mode through `dwell_protocol::modes`) and `client/src/ui/modes.gen.ts` (the
// New world form's choices). Outputs are checked in; CI regenerates them and fails on any diff. A bad
// entry fails with a message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const header = 'Generated by shared/modes/gen.mjs from shared/modes/modes.json. Do not edit.';

/**
 * The abilities a mode may grant: the engine's fixed vocabulary (`dwell_protocol::modes::Ability`,
 * one bit each, in this order). A mode is the list of the ones it allows; new modes are data, a new
 * ability is code here and in `modes.rs`.
 */
export const ABILITIES = ['damage', 'flight', 'brushes', 'unlimitedBlocks', 'map', 'mapRevealed', 'stamina', 'oxygen', 'instantBreaks', 'structures', 'theaterViewpoint', 'blueprints'];
const NAME = /^[a-z][a-z0-9_]*$/;
const TOP_FIELDS = ['formatVersion', 'defaultMode', 'modes'];
const MODE_FIELDS = ['name', 'label', 'description', 'experimental', 'abilities'];
/** A mode's name is sent at join and saved with the world (a `WorldSettings` field): kept short. */
const MAX_NAME = 32;

const fail = (m) => {
  throw new Error(`shared/modes: ${m}`);
};

/** Checks the data; returns it with every mode's fields filled. */
export function validateModes(data) {
  if (typeof data !== 'object' || data === null) fail('the file must hold an object');
  for (const k of Object.keys(data)) {
    if (!TOP_FIELDS.includes(k)) fail(`unknown field ${k} (${TOP_FIELDS.join(', ')})`);
  }
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  if (!Array.isArray(data.modes) || data.modes.length === 0) fail('modes: at least one game mode');
  if (data.modes.length > 32) fail('modes: at most 32');
  const seen = new Set();
  const modes = data.modes.map((m, i) => {
    if (typeof m !== 'object' || m === null) fail(`modes[${i}] must be an object`);
    const at = typeof m.name === 'string' ? `modes.${m.name}` : `modes[${i}]`;
    for (const k of Object.keys(m)) {
      if (!MODE_FIELDS.includes(k)) fail(`${at}: unknown field ${k} (${MODE_FIELDS.join(', ')})`);
    }
    if (typeof m.name !== 'string' || !NAME.test(m.name) || m.name.length > MAX_NAME) {
      fail(`${at}: name must be lower case letters, digits and _ (at most ${MAX_NAME})`);
    }
    if (seen.has(m.name)) fail(`${at}: the name is listed twice`);
    seen.add(m.name);
    if (typeof m.label !== 'string' || m.label.trim() === '' || m.label.length > 40) {
      fail(`${at}: label must be 1–40 characters`);
    }
    if (m.description !== undefined && typeof m.description !== 'string') {
      fail(`${at}: description must be text`);
    }
    if (m.experimental !== undefined && typeof m.experimental !== 'boolean') {
      fail(`${at}: experimental must be true or false`);
    }
    if (!Array.isArray(m.abilities)) fail(`${at}: abilities must be a list (${ABILITIES.join(', ')})`);
    const got = new Set();
    for (const a of m.abilities) {
      if (!ABILITIES.includes(a)) fail(`${at}: unknown ability ${a} (${ABILITIES.join(', ')})`);
      if (got.has(a)) fail(`${at}: ability ${a} is listed twice`);
      got.add(a);
    }
    return {
      name: m.name,
      label: m.label,
      description: m.description ?? '',
      experimental: m.experimental ?? false,
      abilities: ABILITIES.filter((a) => got.has(a)),
    };
  });
  if (typeof data.defaultMode !== 'string' || !seen.has(data.defaultMode)) {
    fail(`defaultMode must name one of the modes (${[...seen].join(', ')}), not ${data.defaultMode}`);
  }
  return { formatVersion: data.formatVersion, defaultMode: data.defaultMode, modes };
}

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

export function modesRust(d) {
  const rs = [`// ${header}`, '', 'use crate::modes::{Ability, GameMode};', ''];
  rs.push('/// The mode a new world plays, and a world saved before modes (ADR 0065).');
  rs.push(`pub const DEFAULT_MODE: &str = "${d.defaultMode}";`);
  rs.push('');
  rs.push('pub static MODES: &[GameMode] = &[');
  for (const m of d.modes) {
    rs.push('    GameMode {');
    rs.push(`        name: "${m.name}",`);
    rs.push(`        label: ${JSON.stringify(m.label)},`);
    rs.push(`        experimental: ${m.experimental},`);
    const bits = m.abilities.map((a) => `Ability::${pascal(a)}.bit()`);
    rs.push(`        abilities: ${bits.length ? bits.join(' | ') : '0'},`);
    rs.push('    },');
  }
  rs.push('];');
  rs.push('');
  return rs.join('\n');
}

export function modesTs(d) {
  const ts = [`// ${header}`, ''];
  ts.push(`export const ABILITIES = ${JSON.stringify(ABILITIES)} as const;`);
  ts.push('export type Ability = (typeof ABILITIES)[number];');
  ts.push('');
  ts.push('export interface GameMode {');
  ts.push('  name: string;');
  ts.push('  label: string;');
  ts.push('  description: string;');
  ts.push('  /** Offered, but marked experimental in the New world form. */');
  ts.push('  experimental: boolean;');
  ts.push('  abilities: readonly Ability[];');
  ts.push('}');
  ts.push('');
  ts.push(`export const DEFAULT_MODE = ${JSON.stringify(d.defaultMode)};`);
  ts.push('');
  ts.push('export const GAME_MODES: readonly GameMode[] = [');
  for (const m of d.modes) {
    ts.push('  {');
    ts.push(`    name: ${JSON.stringify(m.name)},`);
    ts.push(`    label: ${JSON.stringify(m.label)},`);
    ts.push(`    description: ${JSON.stringify(m.description)},`);
    ts.push(`    experimental: ${m.experimental},`);
    ts.push(`    abilities: [${m.abilities.map((a) => JSON.stringify(a)).join(', ')}],`);
    ts.push('  },');
  }
  ts.push('];');
  ts.push('');
  return ts.join('\n');
}

export function loadModes() {
  return JSON.parse(readFileSync(join(here, 'modes.json'), 'utf8'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const root = join(here, '..', '..');
  const d = validateModes(loadModes());
  writeFileSync(join(root, 'crates/dwell-protocol/src/modes.gen.rs'), modesRust(d));
  writeFileSync(join(root, 'client/src/ui/modes.gen.ts'), modesTs(d));
}
