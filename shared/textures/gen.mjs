#!/usr/bin/env node
// Bakes the painterly texture set (docs/PAINTERLY_TEXTURES.md, ADR 0040): validates
// shared/textures/palette.json and materials.json against the block registry's texture names
// (shared/blocks/dwell.json), paints every block tile with paint.mjs and writes the texels for the
// atlas (crates/dwell-mesh/src/painterly.rgba) with their tile names (painterly.gen.rs). The output
// is checked in; CI regenerates it and fails on any diff.
//
//   node shared/textures/gen.mjs                 regenerate
//   node shared/textures/gen.mjs --png out.png   also write a preview sheet of every material
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { deflateSync } from 'node:zlib';
import { TILE, imageRows, paintMaterial, validateMaterials, validatePalette } from './paint.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

/** The texture names the registry's blocks draw with. */
export function registryTiles(blocks) {
  const out = new Set();
  for (const b of blocks.blocks) {
    const t = b.textures;
    if (t === undefined) continue;
    for (const name of typeof t === 'string' ? [t] : [t.top, t.side, t.bottom]) out.add(name);
  }
  return [...out];
}

/** Validates and paints: the block tiles in `tiles` order, as { names, texels }. */
export function bake(materials, palette, tiles) {
  validatePalette(palette);
  validateMaterials(materials, palette, tiles);
  const names = Object.keys(materials.tiles);
  const texels = new Uint8Array(names.length * TILE * TILE * 4);
  names.forEach((name, i) => texels.set(paintMaterial(materials.tiles[name], materials, palette), i * TILE * TILE * 4));
  return { names, texels };
}

export function rustSource(names) {
  return `// Generated by shared/textures/gen.mjs from shared/textures/materials.json and palette.json. Do not edit.

/// Texels per tile edge the painterly set is painted at.
pub const PAINTERLY_TILE: usize = ${TILE};

/// The atlas tiles the painterly set paints, in the order of their texels in [\`PAINTERLY_TEXELS\`].
pub const PAINTERLY_TILES: [&str; ${names.length}] = [${names.map((n) => JSON.stringify(n)).join(', ')}];

/// Each painterly tile's RGBA8 texels (sRGB), row y = 0 (the tile's bottom) first.
pub static PAINTERLY_TEXELS: &[u8; ${names.length * TILE * TILE * 4}] = include_bytes!("painterly.rgba");
`;
}

function crc32(buf) {
  let c = ~0;
  for (const b of buf) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}

/** A PNG (RGBA8) of `rgba`, `w` × `h`, first row the top. */
export function png(rgba, w, h) {
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(td));
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) raw.set(rgba.subarray(y * w * 4, (y + 1) * w * 4), y * (w * 4 + 1) + 1);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/** Every material, each tile repeated 2 × 2 (to show it tiles) at `scale`, in rows of `per`. */
export function sheet(materials, palette, scale = 4, per = 6) {
  const names = Object.keys(materials.materials);
  const cell = TILE * 2 * scale + 8;
  const w = per * cell;
  const h = Math.ceil(names.length / per) * cell;
  const out = new Uint8Array(w * h * 4).fill(255);
  names.forEach((name, i) => {
    const tile = imageRows(paintMaterial(name, materials, palette));
    const ox = (i % per) * cell + 4;
    const oy = Math.floor(i / per) * cell + 4;
    for (let y = 0; y < TILE * 2 * scale; y++) {
      for (let x = 0; x < TILE * 2 * scale; x++) {
        const s = ((Math.floor(y / scale) % TILE) * TILE + (Math.floor(x / scale) % TILE)) * 4;
        const o = ((oy + y) * w + ox + x) * 4;
        // Over a light grey checker, so cut-out gaps show.
        const bg = (Math.floor(x / 8) + Math.floor(y / 8)) % 2 ? 236 : 214;
        const a = tile[s + 3] / 255;
        for (let c = 0; c < 3; c++) out[o + c] = Math.round(tile[s + c] * a + bg * (1 - a));
        out[o + 3] = 255;
      }
    }
  });
  return { names, png: png(out, w, h) };
}

const BEGIN = '// BEGIN GENERATED by shared/textures/gen.mjs: paint.mjs and the repo\'s palette and materials. Do not edit here.';
const END = '// END GENERATED';
/** The names paint.mjs exports, which the editor page reads from `PAINT`. */
const EXPORTS = [
  'TILE', 'STROKE_KINDS', 'LAYER_KINDS', 'USES', 'RAMP_STOPS', 'hash', 'validatePalette', 'resolveColor',
  'resolveMaterial', 'validateMaterials', 'paintMaterial', 'imageRows', 'materialRamp',
];

/**
 * The editor page (docs/prototypes/painterly-texture-lab.html) with its generated block replaced:
 * paint.mjs's source as a `PAINT` object, and the repo's palette and materials as its defaults, so
 * the page paints exactly as the build does.
 */
export function labPage(html, paintSource, palette, materials) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('painterly-texture-lab.html: the generated block\'s markers are missing');
  const body = paintSource.replace(/^export /gm, '');
  const block = [
    BEGIN,
    'const PAINT = (() => {',
    body.trimEnd(),
    `return { ${EXPORTS.join(', ')} };`,
    '})();',
    `const REPO_PALETTE = ${JSON.stringify(palette)};`,
    `const REPO_MATERIALS = ${JSON.stringify(materials)};`,
    '',
  ].join('\n');
  return html.slice(0, a) + block + html.slice(b);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const palette = readJson(join(here, 'palette.json'));
  const materials = readJson(join(here, 'materials.json'));
  const tiles = registryTiles(readJson(join(root, 'shared', 'blocks', 'dwell.json')));
  try {
    const { names, texels } = bake(materials, palette, tiles);
    const out = join(root, 'crates', 'dwell-mesh', 'src');
    writeFileSync(join(out, 'painterly.rgba'), texels);
    writeFileSync(join(out, 'painterly.gen.rs'), rustSource(names));
    const lab = join(root, 'docs', 'prototypes', 'painterly-texture-lab.html');
    writeFileSync(lab, labPage(readFileSync(lab, 'utf8'), readFileSync(join(here, 'paint.mjs'), 'utf8'), palette, materials));
    console.log(`painted ${names.length} block tiles (${Object.keys(materials.materials).length} materials)`);
    const at = process.argv.indexOf('--png');
    if (at > 0) {
      const s = sheet(materials, palette);
      writeFileSync(process.argv[at + 1], s.png);
      console.log(`sheet: ${s.names.join(', ')}`);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
