#!/usr/bin/env node
// Bakes the painterly texture set (docs/PAINTERLY_TEXTURES.md, ADR 0040): validates
// shared/textures/palette.json and materials.json against the block registry's texture names
// (shared/blocks/dwell.json) and the engine's utility tiles, paints every atlas tile with paint.mjs and writes the texels for the
// atlas (crates/dwell-mesh/src/painterly.rgba) with their tile names (painterly.gen.rs); then the cel
// style's tiles from shared/textures/cel.json (cel.mjs) into cel.rgba and cel.gen.rs. The output
// is checked in; CI regenerates it and fails on any diff.
//
//   node shared/textures/gen.mjs                 regenerate
//   node shared/textures/gen.mjs --png out.png   also write a preview sheet of every material
//   node shared/textures/gen.mjs --cel-png out.png   the same in the cel style
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { deflateSync } from 'node:zlib';
import { blockTiles } from '../blocks/faces.mjs';
import { TILE, imageRows, paintMaterial, resolveMaterial, validateMaterials, validatePalette } from './paint.mjs';
import { paintCel, upscaleCel, validateCel } from './cel.mjs';
import { loadPixelArt } from '../look/pixelart.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

/** The texture names the registry's blocks draw with (their `sideUnder` tiles too). */
export function registryTiles(blocks) {
  const out = new Set();
  for (const b of blocks.blocks) for (const name of blockTiles(b)) out.add(name);
  return [...out];
}

/**
 * The atlas's utility tiles, which no block's `textures` name but the engine draws with
 * (crates/dwell-mesh/src/textures.rs `TILE_ORDER`): `plain`, the white tile of an untextured state
 * (tinted by its colour), and `missing`, the fallback look of a state this build can't draw (ADR
 * 0038). The registry's `grid` tile is named by the sandbox floor.
 */
export const ENGINE_TILES = ['plain', 'missing'];

/** Every atlas tile the texture set must paint: the registry's tiles and the engine's. */
export function atlasTiles(blocks) {
  return [...ENGINE_TILES, ...registryTiles(blocks)];
}

/** Validates and paints: every atlas tile (`tiles`), in `materials.tiles` order, as { names, texels }. */
export function bake(materials, palette, tiles) {
  validatePalette(palette);
  validateMaterials(materials, palette, tiles);
  const names = Object.keys(materials.tiles);
  const texels = new Uint8Array(names.length * TILE * TILE * 4);
  names.forEach((name, i) => texels.set(paintMaterial(materials.tiles[name], materials, palette), i * TILE * TILE * 4));
  return { names, texels };
}

/**
 * The cel style's bake (§10): validates shared/textures/cel.json against the materials and the
 * pixel-art palette it names (`pixelPalettes`: name → ramps of sRGB byte triples), then paints every
 * `tiles` entry at the style's own resolution (`tileTexels`), in `materials.tiles` order, as
 * { names, n, texels }.
 */
export function bakeCel(cel, materials, palette, pixelPalettes) {
  const ramps = pixelPalettes[cel.palette];
  if (!ramps) throw new Error(`cel.json: palette "${cel.palette}" is not a pixel-art palette (${Object.keys(pixelPalettes).join(', ')})`);
  validateCel(cel, materials, palette, ramps.flat());
  const names = Object.keys(materials.tiles);
  const n = cel.tileTexels;
  const texels = new Uint8Array(names.length * n * n * 4);
  names.forEach((name, i) => texels.set(paintCel(materials.tiles[name], cel, materials, palette), i * n * n * 4));
  return { names, n, mips: cel.mips, texels };
}

/** The cel style's Rust: its tile names (the painterly set's, in order), mips and texels. */
export function celRustSource(names, n, mips = 'average') {
  const flat = `pub const CEL_TILES: [&str; ${names.length}] = [${names.map((t) => JSON.stringify(t)).join(', ')}];`;
  const list = flat.length <= 100
    ? flat
    : `pub const CEL_TILES: [&str; ${names.length}] = [\n${names.map((t) => `    ${JSON.stringify(t)},\n`).join('')}];`;
  return `// Generated by shared/textures/gen.mjs from shared/textures/cel.json and materials.json. Do not edit.

/// Texels per tile edge the cel style is painted at (each is repeated to fill the atlas's tile).
pub const CEL_TILE: usize = ${n};

/// Whether the atlas halves the opaque cel tiles by their majority tone for the mips (\`mips\`:
/// "mode"), keeping their tones, rather than by the average.
pub const CEL_MODE_MIPS: bool = ${mips === 'mode'};

/// The atlas tiles the cel style paints, in the order of their texels in [\`CEL_TEXELS\`].
${list}

/// Each cel tile's RGBA8 texels (sRGB), row y = 0 (the tile's bottom) first.
pub static CEL_TEXELS: &[u8; ${names.length * n * n * 4}] = include_bytes!("cel.rgba");
`;
}

/** Each atlas tile's glow (its material's `emissive`, docs/LIGHTS.md), in `tiles` order. */
export function tileEmissive(materials, names) {
  return names.map((n) => resolveMaterial(materials, materials.tiles[n]).emissive ?? 0);
}

/**
 * Whether each atlas tile hangs from its block's top edge (its material's `hang`, a skirt), in
 * `tiles` order: such a side shows the tile's top on every block; other tiles run in world metres.
 */
export function tileHang(materials, names) {
  return names.map((n) => resolveMaterial(materials, materials.tiles[n]).hang ?? false);
}

export function rustSource(names, emissive = names.map(() => 0), hang = names.map(() => false)) {
  // As rustfmt lays it out: one line if it fits in 100 columns, else one entry per line.
  const array = (head, items) => {
    const flat = `${head}${items.join(', ')}];`;
    return flat.length <= 100 ? flat : `${head}\n${items.map((n) => `    ${n},\n`).join('')}];`;
  };
  const list = array(`pub const PAINTERLY_TILES: [&str; ${names.length}] = [`, names.map((n) => JSON.stringify(n)));
  // Short numbers, as rustfmt packs them: as many to a line as fit in 100 columns.
  const packed = (head, items) => {
    const flat = `${head}${items.join(', ')}];`;
    if (flat.length <= 100) return flat;
    const lines = [];
    let line = '   ';
    for (const it of items) {
      if (line.length + 1 + it.length + 1 > 100) {
        lines.push(line);
        line = '   ';
      }
      line += ` ${it},`;
    }
    lines.push(line);
    return `${head}\n${lines.join('\n')}\n];`;
  };
  const glow = packed(
    `pub const PAINTERLY_EMISSIVE: [f32; ${names.length}] = [`,
    emissive.map((v) => (Number.isInteger(v) ? `${v}.0` : `${v}`)),
  );
  const hangs = packed(`pub const PAINTERLY_HANG: [bool; ${names.length}] = [`, hang.map(String));
  return `// Generated by shared/textures/gen.mjs from shared/textures/materials.json and palette.json. Do not edit.

/// Texels per tile edge the painterly set is painted at.
pub const PAINTERLY_TILE: usize = ${TILE};

/// The atlas tiles the painterly set paints, in the order of their texels in [\`PAINTERLY_TEXELS\`].
${list}

/// Each tile's glow: how much of its colour it gives off unlit (its material's \`emissive\`).
${glow}

/// Whether each tile hangs from its block's top edge (its material's \`hang\`): a side face shows
/// the tile's top on every block, so it never merges up or down; other tiles run in world metres.
${hangs}

/// Each painterly tile's RGBA8 texels (sRGB), row y = 0 (the tile's bottom) first.
pub static PAINTERLY_TEXELS: &[u8; ${names.length * TILE * TILE * 4}] = include_bytes!("painterly.rgba");
`;
}

function crc32(buf) {
  let c = ~0;
  for (const b of buf) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}

/** A PNG (RGBA8) of `rgba`, `w` × `h`, first row the top. */
export function png(rgba, w, h) {
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(td));
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) raw.set(rgba.subarray(y * w * 4, (y + 1) * w * 4), y * (w * 4 + 1) + 1);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/**
 * Every material, each tile repeated 2 × 2 (to show it tiles) at `scale`, in rows of `per`; with
 * `paint` (name → TILE² RGBA) another style's tiles.
 */
export function sheet(materials, palette, scale = 4, per = 6, paint = (name) => paintMaterial(name, materials, palette)) {
  const names = Object.keys(materials.materials);
  const cell = TILE * 2 * scale + 8;
  const w = per * cell;
  const h = Math.ceil(names.length / per) * cell;
  const out = new Uint8Array(w * h * 4).fill(255);
  names.forEach((name, i) => {
    const tile = imageRows(paint(name));
    const ox = (i % per) * cell + 4;
    const oy = Math.floor(i / per) * cell + 4;
    for (let y = 0; y < TILE * 2 * scale; y++) {
      for (let x = 0; x < TILE * 2 * scale; x++) {
        const s = ((Math.floor(y / scale) % TILE) * TILE + (Math.floor(x / scale) % TILE)) * 4;
        const o = ((oy + y) * w + ox + x) * 4;
        // Over a light grey checker, so cut-out gaps show.
        const bg = (Math.floor(x / 8) + Math.floor(y / 8)) % 2 ? 236 : 214;
        const a = tile[s + 3] / 255;
        for (let c = 0; c < 3; c++) out[o + c] = Math.round(tile[s + c] * a + bg * (1 - a));
        out[o + 3] = 255;
      }
    }
  });
  return { names, png: png(out, w, h) };
}

const BEGIN = '// BEGIN GENERATED by shared/textures/gen.mjs: paint.mjs and the repo\'s palette and materials. Do not edit here.';
const END = '// END GENERATED';
/** The names paint.mjs exports, which the editor page reads from `PAINT`. */
const EXPORTS = [
  'TILE', 'STROKE_KINDS', 'LAYER_KINDS', 'USES', 'RAMP_STOPS', 'hash', 'validatePalette', 'resolveColor',
  'resolveMaterial', 'validateMaterials', 'paintMaterial', 'imageRows', 'materialRamp',
];

/**
 * The editor page (docs/prototypes/painterly-texture-lab.html) with its generated block replaced:
 * paint.mjs's source as a `PAINT` object, and the repo's palette and materials as its defaults, so
 * the page paints exactly as the build does.
 */
export function labPage(html, paintSource, palette, materials) {
  const a = html.indexOf(BEGIN);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('painterly-texture-lab.html: the generated block\'s markers are missing');
  const body = paintSource.replace(/^export /gm, '');
  const block = [
    BEGIN,
    'const PAINT = (() => {',
    body.trimEnd(),
    `return { ${EXPORTS.join(', ')} };`,
    '})();',
    `const REPO_PALETTE = ${JSON.stringify(palette)};`,
    `const REPO_MATERIALS = ${JSON.stringify(materials)};`,
    '',
  ].join('\n');
  return html.slice(0, a) + block + html.slice(b);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const palette = readJson(join(here, 'palette.json'));
  const materials = readJson(join(here, 'materials.json'));
  const tiles = atlasTiles(readJson(join(root, 'shared', 'blocks', 'dwell.json')));
  const cel = readJson(join(here, 'cel.json'));
  try {
    const { names, texels } = bake(materials, palette, tiles);
    const out = join(root, 'crates', 'dwell-mesh', 'src');
    writeFileSync(join(out, 'painterly.rgba'), texels);
    writeFileSync(join(out, 'painterly.gen.rs'), rustSource(names, tileEmissive(materials, names), tileHang(materials, names)));
    const lab = join(root, 'docs', 'prototypes', 'painterly-texture-lab.html');
    writeFileSync(lab, labPage(readFileSync(lab, 'utf8'), readFileSync(join(here, 'paint.mjs'), 'utf8'), palette, materials));
    const c = bakeCel(cel, materials, palette, loadPixelArt().palettes);
    writeFileSync(join(out, 'cel.rgba'), c.texels);
    writeFileSync(join(out, 'cel.gen.rs'), celRustSource(c.names, c.n, cel.mips));
    console.log(`painted ${names.length} atlas tiles (${Object.keys(materials.materials).length} materials), painterly and cel (${c.n} × ${c.n})`);
    const at = process.argv.indexOf('--png');
    if (at > 0) {
      const s = sheet(materials, palette);
      writeFileSync(process.argv[at + 1], s.png);
      console.log(`sheet: ${s.names.join(', ')}`);
    }
    const atCel = process.argv.indexOf('--cel-png');
    if (atCel > 0) {
      const s = sheet(materials, palette, 4, 6, (name) => upscaleCel(paintCel(name, cel, materials, palette), cel.tileTexels));
      writeFileSync(process.argv[atCel + 1], s.png);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
