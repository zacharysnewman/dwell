#!/usr/bin/env node
// Generates defeat's tunables (docs/CHARACTERS.md §11.13, WORK_QUEUE item 55: humans never die, they
// kneel and stand up at a shrine) for Rust from shared/defeat/defeat.json:
// `crates/dwell-protocol/src/defeat.gen.rs` (the server's timing and the client's clips, fade and
// camera read them through `dwell_protocol::defeat`). The output is checked in; CI regenerates it
// and fails on any diff. A bad entry fails with a message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
export const RUST = join(root, 'crates/dwell-protocol/src/defeat.gen.rs');
const header = 'Generated by shared/defeat/gen.mjs from shared/defeat/defeat.json. Do not edit.';

const TOP = ['$comment', 'formatVersion', 'kneelS', 'fadeS', 'standS', 'roles', 'camera', 'characters'];
/** The roles defeat plays: the engine's fixed vocabulary; the clips they name are data. */
export const ROLE_KEYS = ['kneel', 'kneelArmed', 'stand', 'standArmed'];
const CAMERA = ['backM', 'upM', 'pitchDeg', 'easeS'];
const OVERRIDE = ['kneelS', 'fadeS', 'camera'];

const fail = (m) => {
  throw new Error(`shared/defeat: ${m}`);
};

function fields(o, at, allowed) {
  if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`${at} must be an object`);
  for (const k of Object.keys(o)) {
    if (!allowed.includes(k)) fail(`${at}: unknown field ${k} (${allowed.join(', ')})`);
  }
}

function num(o, at, k, lo, hi) {
  const v = o[k];
  if (typeof v !== 'number' || !Number.isFinite(v)) fail(`${at}.${k} must be a number`);
  if (v < lo || v > hi) fail(`${at}.${k} must be at least ${lo} and at most ${hi}, not ${v}`);
  return v;
}

function camera(o, at, base) {
  fields(o, at, CAMERA);
  const out = { ...base };
  const range = { backM: [0.5, 20], upM: [-5, 20], pitchDeg: [-89, 45], easeS: [0, 10] };
  for (const k of CAMERA) {
    if (k in o || !base) out[k] = num(o, at, k, ...range[k]);
  }
  return out;
}

export const loadDefeat = () => JSON.parse(readFileSync(join(here, 'defeat.json'), 'utf8'));
const loadJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

/**
 * Checks the data against the characters (`shared/characters/characters.json`: every role's clip a
 * clip of each biped character) and the creatures (an override's name a character or an NPC kind);
 * returns it resolved: `{ kneelS, fadeS, roles, camera, characters: { name: { kneelS, fadeS, camera } } }`.
 */
export function validateDefeat(data, characters = loadJson('shared/characters/characters.json'), creatures = loadJson('shared/creatures/creatures.json')) {
  fields(data, 'the file', TOP);
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  const kneelS = num(data, 'the file', 'kneelS', 0.5, 60);
  const fadeS = num(data, 'the file', 'fadeS', 0, 10);
  const standS = num(data, 'the file', 'standS', 0.1, 10);
  fields(data.roles, 'roles', ROLE_KEYS);
  const roles = {};
  for (const k of ROLE_KEYS) {
    const r = data.roles[k];
    if (typeof r !== 'string' || !/^[a-z_]+$/.test(r)) fail(`roles.${k} must be a role name (lower case and _), not ${JSON.stringify(r)}`);
    for (const [id, ch] of Object.entries(characters.characters)) {
      if (ch.rig !== 'biped') continue;
      const clip = (ch.clips ?? {})[r];
      if (!clip) fail(`roles.${k}: character "${id}" has no clip for role "${r}" (characters.json clips)`);
      const c = characters.clips[clip];
      if (k.startsWith('kneel') && c.loop) fail(`roles.${k}: clip "${clip}" must not loop (the kneel is held at its end)`);
      if (k.startsWith('stand') && c.duration > standS) fail(`standS (${standS} s) is shorter than ${clip}'s ${c.duration} s`);
    }
    roles[k] = r;
  }
  if (data.camera === undefined) fail('camera is missing');
  const cam = camera(data.camera, 'camera', null);
  const names = new Set([
    ...Object.values(characters.characters).filter((c) => c.rig === 'biped').map((c) => c.name),
    ...creatures.creatures.filter((c) => c.npc).map((c) => c.name),
  ]);
  const out = {};
  for (const [name, o] of Object.entries(data.characters ?? {})) {
    const at = `characters.${name}`;
    if (!names.has(name)) fail(`${at}: not a human character or NPC kind (${[...names].join(', ')})`);
    fields(o, at, OVERRIDE);
    out[name] = {
      kneelS: 'kneelS' in o ? num(o, at, 'kneelS', 0.5, 60) : kneelS,
      fadeS: 'fadeS' in o ? num(o, at, 'fadeS', 0, 10) : fadeS,
      camera: o.camera === undefined ? cam : camera(o.camera, `${at}.camera`, cam),
    };
  }
  return { kneelS, fadeS, standS, roles, camera: cam, characters: out };
}

const f = (v) => (Number.isInteger(v) ? `${v}.0` : `${v}`);
const defeatSrc = (d, pad) =>
  `Defeat {\n${pad}    kneel_s: ${f(d.kneelS)},\n${pad}    fade_s: ${f(d.fadeS)},\n${pad}    camera: DefeatCamera {\n` +
  CAMERA.map((k) => `${pad}        ${k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)}: ${f(d.camera[k])},\n`).join('') +
  `${pad}    },\n${pad}}`;

/** The Rust tables. */
export function defeatRust(d) {
  const roles = ROLE_KEYS.map((k) => `    ${k.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)}: ${JSON.stringify(d.roles[k])},\n`).join('');
  const chars = Object.entries(d.characters)
    .map(([n, o]) => `    (${JSON.stringify(n)}, ${defeatSrc(o, '    ')}),\n`)
    .join('');
  return `// ${header}

// Included by defeat.rs (its types).

/// The defaults.
pub static DEFAULT: Defeat = ${defeatSrc(d, '')};

/// The stand's time at the shrine (s): held still, no harm, the view fading in.
pub const STAND_S: f64 = ${f(d.standS)};

/// The roles the characters play (their clips: shared/characters/characters.json).
pub static ROLES: DefeatRoles = DefeatRoles {
${roles}};

/// Per character (a characters.json name or an NPC kind), resolved over the defaults.
pub static CHARACTERS: &[(&str, Defeat)] = &[
${chars}];
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const d = validateDefeat(loadDefeat());
  const rs = defeatRust(d);
  let old = '';
  try {
    old = readFileSync(RUST, 'utf8');
  } catch {}
  if (old !== rs) writeFileSync(RUST, rs);
  console.log(`shared/defeat: valid; wrote ${RUST.slice(root.length + 1)}`);
}
