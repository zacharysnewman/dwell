#!/usr/bin/env node
// Validates shared/characters/characters.json against the shared style (shared/textures, ADR 0040)
// and writes it, the style, the rig module (rig.mjs) and the painter (shared/textures/paint.mjs)
// into the Character Lab page (docs/prototypes/character-lab.html), between its generated markers
// (docs/CHARACTERS.md §8, ADR 0041). The page is checked in; CI regenerates it and fails on any
// diff. A bad entry fails with a message naming it.
//
// The game doesn't load characters yet (CHARACTERS.md §9): when it does, this generator also writes
// the Rust tables, as shared/look/gen.mjs does.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { validate } from './rig.mjs';
import { resolveMaterial } from '../textures/paint.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
export const PAGE = join(root, 'docs/prototypes/character-lab.html');
const read = (p) => readFileSync(join(root, p), 'utf8');

/** The raw shared palette and materials (shared/textures). */
export const loadTextures = () => ({
  palette: JSON.parse(read('shared/textures/palette.json')),
  materials: JSON.parse(read('shared/textures/materials.json')),
});

/** The style the rig validates against: `{ ramps, swatches, materials: { name: { ramp, overlay } } }`,
 * each material's `like` template resolved. */
export function styleFrom({ palette, materials }) {
  const mats = {};
  for (const name of Object.keys(materials.materials)) {
    const m = resolveMaterial(materials, name);
    mats[name] = { ramp: m.ramp, overlay: m.overlay ?? 0, use: m.use };
  }
  return { ramps: palette.ramps, swatches: palette.swatches ?? {}, materials: mats };
}
export const loadStyle = () => styleFrom(loadTextures());
export const loadData = () => JSON.parse(read('shared/characters/characters.json'));

const BEGIN = (what) => `// <generated by shared/characters/gen.mjs: ${what}>`;
const END = (what) => `// </generated: ${what}>`;

/** A module's source as a scoped object of its exports, for the page's one module script: imports
 * dropped (the page provides them), `export` stripped, the exported names returned. */
export function scoped(name, path) {
  const src = read(path);
  const names = [...src.matchAll(/^export (?:async )?(?:const|let|function\*?|class) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
  const body = src
    .replace(/^import [^;]+;\n/gm, '')
    .replace(/^export /gm, '')
    .trimEnd();
  return `const ${name} = (() => {\n// ${path}\n${body}\nreturn { ${names.join(', ')} };\n})();`;
}

const splice = (page, what, body) => {
  const begin = BEGIN(what);
  const end = END(what);
  const a = page.indexOf(begin);
  const b = page.indexOf(end);
  if (a < 0 || b < a) throw new Error(`shared/characters: ${PAGE}: missing the markers "${begin}" … "${end}"`);
  return `${page.slice(0, a + begin.length)}\n${body}\n${page.slice(b)}`;
};

/** The page with its generated blocks replaced. */
export function renderPage(page, data, textures) {
  let out = splice(page, 'paint.mjs', scoped('Paint', 'shared/textures/paint.mjs'));
  out = splice(out, 'rig.mjs', scoped('Rig', 'shared/characters/rig.mjs'));
  return splice(
    out,
    'data',
    [
      `const PALETTE = ${JSON.stringify(textures.palette)};`,
      `const MATERIALS = ${JSON.stringify(textures.materials)};`,
      `const DATA = ${JSON.stringify(data, null, 1)};`,
    ].join('\n'),
  );
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const textures = loadTextures();
  const data = validate(loadData(), styleFrom(textures));
  const page = readFileSync(PAGE, 'utf8');
  const next = renderPage(page, data, textures);
  if (next !== page) writeFileSync(PAGE, next);
  const n = Object.keys(data.characters).length;
  console.log(`shared/characters: ${n} characters valid; wrote ${PAGE.slice(root.length + 1)}`);
}
