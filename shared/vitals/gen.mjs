#!/usr/bin/env node
// Generates stamina and oxygen's tunables (docs/adr/0069-stamina-and-oxygen.md) for Rust and
// TypeScript from shared/vitals/vitals.json: `crates/dwell-protocol/src/vitals.gen.rs` (the
// controller, the server and the client read them through `dwell_protocol::vitals`) and
// `client/src/ui/vitals.gen.ts` (the HUD). Outputs are checked in; CI regenerates them and fails on
// any diff. A bad entry fails with a message naming it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const header = 'Generated by shared/vitals/gen.mjs from shared/vitals/vitals.json. Do not edit.';

/**
 * What spends stamina: the engine's fixed vocabulary (`dwell_protocol::vitals::Activity`, in this
 * order), each recognised by the controller. Their rates are data; a new activity is code here, in
 * `vitals.rs` and where the controller sees it.
 */
export const ACTIVITIES = ['sprint', 'swim', 'tread'];
const TOP_FIELDS = ['$comment', 'formatVersion', 'stamina', 'oxygen'];
const STAMINA_FIELDS = ['max', 'drains', 'regenPerSecond', 'regenDelaySeconds', 'recoverFraction', 'exhaustedSinkSpeed'];
const OXYGEN_FIELDS = ['capacitySeconds', 'refillPerSecond', 'headFraction', 'drownDamage', 'drownIntervalSeconds'];

const fail = (m) => {
  throw new Error(`shared/vitals: ${m}`);
};

function fields(o, at, allowed) {
  if (typeof o !== 'object' || o === null || Array.isArray(o)) fail(`${at} must be an object`);
  for (const k of Object.keys(o)) {
    if (!allowed.includes(k)) fail(`${at}: unknown field ${k} (${allowed.join(', ')})`);
  }
}

function num(o, at, k, lo, hi, { integer = false, above = false } = {}) {
  const v = o[k];
  if (typeof v !== 'number' || !Number.isFinite(v)) fail(`${at}.${k} must be a number`);
  if (integer && !Number.isInteger(v)) fail(`${at}.${k} must be a whole number, not ${v}`);
  if ((above ? v <= lo : v < lo) || v > hi) {
    fail(`${at}.${k} must be ${above ? 'above' : 'at least'} ${lo} and at most ${hi}, not ${v}`);
  }
  return v;
}

/** Checks the data; returns it with every activity's rate (0 for one not listed). */
export function validateVitals(data) {
  fields(data, 'the file', TOP_FIELDS);
  if (data.formatVersion !== 1) fail(`formatVersion must be 1, not ${data.formatVersion}`);
  const s = data.stamina;
  fields(s, 'stamina', STAMINA_FIELDS);
  const max = num(s, 'stamina', 'max', 0, 10000, { above: true });
  if (!Array.isArray(s.drains)) fail('stamina.drains must be a list of { activity, perSecond }');
  const drains = Object.fromEntries(ACTIVITIES.map((a) => [a, 0]));
  const seen = new Set();
  s.drains.forEach((d, i) => {
    const at = typeof d?.activity === 'string' ? `stamina.drains.${d.activity}` : `stamina.drains[${i}]`;
    fields(d, at, ['activity', 'perSecond']);
    if (!ACTIVITIES.includes(d.activity)) {
      fail(`${at}: unknown activity ${d.activity} (${ACTIVITIES.join(', ')})`);
    }
    if (seen.has(d.activity)) fail(`${at}: the activity is listed twice`);
    seen.add(d.activity);
    drains[d.activity] = num(d, at, 'perSecond', 0, 10000);
  });
  const stamina = {
    max,
    drains,
    regenPerSecond: num(s, 'stamina', 'regenPerSecond', 0, 10000),
    regenDelaySeconds: num(s, 'stamina', 'regenDelaySeconds', 0, 60),
    recoverFraction: num(s, 'stamina', 'recoverFraction', 0, 1, { above: true }),
    exhaustedSinkSpeed: num(s, 'stamina', 'exhaustedSinkSpeed', 0, 20),
  };
  const o = data.oxygen;
  fields(o, 'oxygen', OXYGEN_FIELDS);
  const oxygen = {
    capacitySeconds: num(o, 'oxygen', 'capacitySeconds', 0, 3600, { above: true }),
    refillPerSecond: num(o, 'oxygen', 'refillPerSecond', 0, 3600, { above: true }),
    headFraction: num(o, 'oxygen', 'headFraction', 0, 1, { above: true }),
    drownDamage: num(o, 'oxygen', 'drownDamage', 0, 255, { integer: true }),
    drownIntervalSeconds: num(o, 'oxygen', 'drownIntervalSeconds', 0, 60, { above: true }),
  };
  return { formatVersion: 1, stamina, oxygen };
}

const f32 = (v) => (Number.isInteger(v) ? `${v}.0` : String(v));
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

export function vitalsRust(d) {
  const s = d.stamina;
  const o = d.oxygen;
  const rs = [`// ${header}`, '', 'use crate::vitals::{Activity, VitalsDef};', ''];
  rs.push('pub static VITALS: VitalsDef = VitalsDef {');
  rs.push(`    max_stamina: ${f32(s.max)},`);
  rs.push('    drains: [');
  for (const a of ACTIVITIES) rs.push(`        (Activity::${pascal(a)}, ${f32(s.drains[a])}),`);
  rs.push('    ],');
  rs.push(`    regen_per_second: ${f32(s.regenPerSecond)},`);
  rs.push(`    regen_delay_seconds: ${f32(s.regenDelaySeconds)},`);
  rs.push(`    recover_fraction: ${f32(s.recoverFraction)},`);
  rs.push(`    exhausted_sink_speed: ${f32(s.exhaustedSinkSpeed)},`);
  rs.push(`    oxygen_seconds: ${f32(o.capacitySeconds)},`);
  rs.push(`    oxygen_refill_per_second: ${f32(o.refillPerSecond)},`);
  rs.push(`    head_fraction: ${f32(o.headFraction)},`);
  rs.push(`    drown_damage: ${o.drownDamage},`);
  rs.push(`    drown_interval_seconds: ${f32(o.drownIntervalSeconds)},`);
  rs.push('};');
  rs.push('');
  rs.push(`pub const ACTIVITY_NAMES: [&str; ${ACTIVITIES.length}] = [${ACTIVITIES.map((a) => JSON.stringify(a)).join(', ')}];`);
  rs.push('');
  return rs.join('\n');
}

export function vitalsTs(d) {
  const ts = [`// ${header}`, ''];
  ts.push('/** Stamina and oxygen (docs/adr/0069-stamina-and-oxygen.md). */');
  ts.push('export const VITALS = {');
  ts.push(`  maxStamina: ${d.stamina.max},`);
  ts.push('  /** The share of stamina an exhausted player needs back. */');
  ts.push(`  recoverFraction: ${d.stamina.recoverFraction},`);
  ts.push(`  oxygenSeconds: ${d.oxygen.capacitySeconds},`);
  ts.push('} as const;');
  ts.push('');
  return ts.join('\n');
}

export function loadVitals() {
  return JSON.parse(readFileSync(join(here, 'vitals.json'), 'utf8'));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const root = join(here, '..', '..');
  const d = validateVitals(loadVitals());
  writeFileSync(join(root, 'crates/dwell-protocol/src/vitals.gen.rs'), vitalsRust(d));
  writeFileSync(join(root, 'client/src/ui/vitals.gen.ts'), vitalsTs(d));
}
