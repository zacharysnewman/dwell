//! Chisel in the game (Phase 56 B7, WORK_QUEUE item 34): the host retunes a running world's
//! worldgen config (biome sliders) and the terrain around them regenerates. The config is saved in
//! the world file's settings (`worldgen`) and installed again when the world opens; each face's map
//! is re-wrapped with it (`dwell_worldgen::config::retune_worldgen`: a biome edit, never the ground
//! itself). The chunks within a radius of the host are generated again under the new config with
//! the player's edits kept on top (the cells where the chunk differs from the old config's
//! generation), saved, and sent whole to the clients streaming them; their LOD sections are marked
//! dirty, so the near LOD follows.

use super::*;

/// The world file's settings key holding the world's worldgen config (absent: the build's ground,
/// or a test world whose config came from its launch).
pub const WORLDGEN_SETTING: &str = "worldgen";

/// What a retune did.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Retune {
    /// Chunks generated again (within the radius, loaded or saved).
    pub chunks: usize,
    /// Of those, the chunks that carried edits (kept over the new ground).
    pub edited: usize,
    /// The edited cells kept over the new ground.
    pub kept_cells: usize,
    /// Each face's new map bytes (A, B), for the instances that generate elsewhere (the page's
    /// workers) to install.
    pub maps: Vec<Vec<u8>>,
}

/// Rebases chunk `current` (generated by `old`, then edited) onto `new`'s generation of the same
/// chunk: the cells where `current` differs from `old` kept, the rest `new`'s. Returns the chunk
/// and how many cells were kept.
pub fn rebase_chunk(current: &Chunk, old: &Chunk, new: &Chunk) -> (Chunk, usize) {
    let mut out = new.clone();
    let mut kept = 0;
    let (cur, was) = (current.voxels(), old.voxels());
    let into = out.voxels_mut();
    for i in 0..CHUNK_VOLUME_CELLS {
        if cur[i] != was[i] {
            into[i] = cur[i];
            kept += 1;
        }
    }
    (out, kept)
}

const CHUNK_VOLUME_CELLS: usize = dwell_world::CHUNK_VOLUME;

impl Server {
    /// Installs the worldgen config saved in the world file (`WORLDGEN_SETTING`) before the
    /// generators are made, when it isn't the one installed: re-wrapping the installed maps (no
    /// recompute) when the ground is the same, else computing the config's maps.
    pub(super) fn install_saved_worldgen(config: &ServerConfig) {
        if config.generator_override.is_some()
            || !dwell_world::has_terrain(config.generator_version)
        {
            return;
        }
        let Some(saved) = config
            .store
            .as_ref()
            .and_then(|s| s.db().setting(WORLDGEN_SETTING))
        else {
            return;
        };
        let seed = config.world_seed;
        if dwell_worldgen::config::installed_worldgen(seed) == saved.trim() {
            return;
        }
        if dwell_worldgen::config::retune_worldgen(seed, &saved).is_ok() {
            return;
        }
        for f in [dwell_world::Face::A, dwell_world::Face::B] {
            let face = dwell_worldgen::bifacial::face_seed(seed, f);
            match dwell_worldgen::config::worldgen_map_bytes(face, &saved)
                .and_then(|b| dwell_worldgen::worldmap::cache::install(&b))
            {
                Ok(_) => {}
                Err(e) => eprintln!("dwell: the world's saved worldgen config is refused ({e})"),
            }
        }
    }

    /// Retunes the world to worldgen config `text` (Chisel in the game, host only): the maps
    /// re-wrapped, the generators made again, the config saved with the world, and the chunks
    /// within `radius` chunks (horizontally, every height) of `center` generated again with their
    /// edits kept. Refused for a world without terrain, a fixed generator, while guests are in the
    /// world (their generators would disagree until they join again), or for an edit that moves the
    /// ground (`retune_worldgen`).
    pub fn retune_worldgen(
        &mut self,
        text: &str,
        center: [f64; 3],
        radius: i32,
    ) -> Result<Retune, String> {
        if self.config.generator_override.is_some()
            || !dwell_world::has_terrain(self.config.generator_version)
        {
            return Err("this world has no generated terrain to tune".into());
        }
        if self.sessions.values().filter(|s| s.joined()).count() > 1 {
            return Err(
                "Chisel in the game is for the host alone: not while guests are here".into(),
            );
        }
        let text = text.trim();
        let old = self.generator.clone();
        let maps = dwell_worldgen::config::retune_worldgen(self.config.world_seed, text)?;
        let (version, seed, size) = (
            self.config.generator_version,
            self.config.world_seed,
            self.config.world_size,
        );
        let generator = dwell_worldgen::generator_for_sized(version, seed, size);
        self.world.set_generator(generator.clone());
        self.worldgen = if self.config.jobs_remote {
            WorldgenPool::new_remote(generator.clone())
        } else {
            WorldgenPool::new(generator.clone(), self.config.worldgen_threads)
        };
        self.generator = generator.clone();
        self.lod
            .set_generator(dwell_worldgen::lod_generator_for_sized(version, seed, size));
        self.worldgen_text = text.to_owned();
        // The ground items' and trees' caches are the old ground's.
        self.ground_density = None;
        self.ground_density_chunks.clear();
        self.growers = None;
        if let Some(store) = &self.config.store {
            store.db().set_setting(WORLDGEN_SETTING, text)?;
        }
        // The chunks to generate again: loaded or saved, within the radius.
        let mid = chunk_at(center[0], center[1], center[2]);
        let near = |c: &ChunkCoord| (c.x - mid.x).abs() <= radius && (c.z - mid.z).abs() <= radius;
        let mut coords: Vec<ChunkCoord> =
            self.world.chunks().map(|(c, _)| *c).filter(near).collect();
        coords.extend(
            self.saved
                .lock()
                .expect("saved index")
                .keys()
                .copied()
                .filter(near),
        );
        coords.sort_by_key(|c| (c.x, c.y, c.z));
        coords.dedup();
        let mut report = Retune {
            maps,
            ..Retune::default()
        };
        for c in coords {
            let current = self.world.get_or_create(c).clone();
            let (mut was, mut now) = (Chunk::default(), Chunk::default());
            old(c, &mut was);
            generator(c, &mut now);
            let (mut chunk, kept) = if current.revision() > 0 {
                rebase_chunk(&current, &was, &now)
            } else {
                (now, 0)
            };
            if kept > 0 {
                report.edited += 1;
                report.kept_cells += kept;
            }
            // Saved and sent whole: the clients' own generators are the old config's until their
            // instances install the new maps.
            chunk.set_revision(current.revision().max(1));
            chunk.bump_revision();
            self.world.put(c, chunk);
            self.ground_generated.remove(&c);
            self.growth_scanned.remove(&c);
            self.dirty.insert(c);
            self.lod.mark_chunk(c);
            report.chunks += 1;
            let ids: Vec<SessionId> = self
                .sessions
                .iter()
                .filter(|(_, s)| s.streamed.contains(&c))
                .map(|(&id, _)| id)
                .collect();
            for id in ids {
                if let Some(m) = self.chunk_message(id, c, true) {
                    self.send_reliable(id, &Message::ChunkData(m), Channel::World);
                }
            }
        }
        // The verification chunk is the new generator's (a client joining later checks it).
        let mut v = Chunk::default();
        generator(self.verification_chunk, &mut v);
        self.verification_hash = chunk_hash(&v);
        Ok(report)
    }
}
